using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace ArmoniK.Api.TransportOptionsGenerator
{
  /// <summary>
  ///   Turns the JSON schema of the armonik-transport option vocabulary into a C# options class.
  /// </summary>
  public static class Generator
  {
    /// <summary>
    ///   Namespace of the generated class.
    /// </summary>
    public const string Namespace = "ArmoniK.Api.Client.Native";

    /// <summary>
    ///   Name of the generated class.
    /// </summary>
    public const string ClassName = "TransportOptions";

    private const string Eol = "\n";

