"""The ONE C header backend: `ak_abi.h` of ABI v1, rendered from the PLAN only.

FIX-PLAN WP5 step 6 (R-G14): this module (born `cpp_abi.py`, WP5 step 2) is the single
renderer of the C declaration of the ABI. The C++, Java and Python slices all compile
against what it writes; `java_abi.py`, the second renderer, is gone. C# is not a C host and
renders its own declarations from the same plan (`cs_binding.py`).

Everything comes from `plan.py`:
  * the fixed ABI (R-G13): error codes and details, the vocabulary structs, the function
    types, the constants, every fixed entry point, the packed-run symbols, the lifecycle's
    flag values -- `plan.FIXED`, `plan.lifecycle`;
  * the per-message groups and presence bits -- `group_fields`, `ugroup_fields`,
    `presence_bits`; the vtables in the plan's member order -- `enc_vtable`, `dec_vtable`;
    the entry points -- `vtable_messages`, `element_types`, `direct_fields`;
  * the RPC half -- `plan.rpc`, and its counting surface -- `plan.FIXED.rpc_counting`;
  * the layout facts -- `cpp_layout.facts`, the enumeration the core's export uses.
It adds no member, reorders none and derives no layout. A host that wants the C compiler
to check ITS OWN numbers (the Java binding computes offsets in Java) passes
`extra_asserts`, lines appended inside the header's assertion section.

C99/C++11 clean: nothing here depends on the standard level (README 5.1's hard stop).
"""
import cpp_layout
from plan import (FIXED, abi_order_topo, as_plan, dec_vtable, direct_fields, element_types,
                  enc_vtable, group_fields, loop_slots, presence_bits, slot_elem,
                  ugroup_fields, vtable_messages)

HEAD_FMT = ("/* @generated by ffi/poc/codec/gen/c_abi.py (plan from %s)."
            " Do not edit. */\n")

C_OF = {"i32": "int32_t", "i64": "int64_t", "u8": "uint8_t", "f64": "double",
        "u32": "uint32_t", "u64": "uint64_t", "usize": "size_t", "isize": "intptr_t",
        "void": "void", "char": "char"}
# Types that are C structs (typedef'd to their own name below) or typedef'd handles.
STRUCTS = set(n for n, _d, _m in FIXED.structs) | {"ak_bytes", "ak_completion",
                                                   "ak_client_opts", "ak_rpc_counters"}


def cty(t):
    """The C spelling of one type of the plan's vocabulary."""
    t = t.strip()
    if t.endswith("?"):
        return cty(t[:-1])               # a nullable function pointer is a plain pointer in C
    if t.startswith("*const "):
        return "const %s *" % cty(t[len("*const "):])
    if t.startswith("*mut "):
        return "%s *" % cty(t[len("*mut "):])
    if t in C_OF:
        return C_OF[t]
    if t.startswith(("ak_efix_", "ak_dfix_", "ak_ufix_")) or t in STRUCTS:
        return "struct " + t
    return t                              # a typedef'd handle or function type


def _join(ty, name):
    """`int32_t x`, `void *x`: a pointer declarator binds to the name."""
    return "%s%s%s" % (ty, "" if ty.endswith("*") else " ", name)


def _decl(name, params, ret):
    args = ", ".join(_join(cty(t), a) for a, t in params) or "void"
    return "%s(%s);" % (_join(cty(ret) if ret else "void", name), args)


def _lifecycle(p):
    """ABI v1 section 3, from `plan.lifecycle` (R-G7): the prototype and the success
    rule. The flag values, `ak_err`, `ak_init_opts` and `ak_log_fn` are plan.FIXED's and
    are already declared above."""
    lc = p.lifecycle
    o = ["/* ---- section 3: the lifecycle (plan.lifecycle, R-G7) ----------------------------",
         " * Every binding rendered from this plan calls `%s` before its first codec or RPC" % lc.init[0],
         " * call and treats %s and %s as success. A core built with `%s`" % (lc.success + (lc.gate_feature,)),
         " * refuses every entry point with AK_ERR_UNINITIALIZED until it has. The prototype",
         " * is among the fixed entry points below. */", ""]
    return o


def _param(a, t):
    if t == "fn(u64)->u64":
        return "uint64_t (*%s)(uint64_t)" % a
    return _join(cty(t), a)


def _decl(name, params, ret):
    args = ", ".join(_param(a, t) for a, t in params) or "void"
    return "%s(%s);" % (_join(cty(ret) if ret else "void", name), args)


def _cval(ty, v):
    if ty == "*const void":
        return "((const void *)(uintptr_t)%d)" % v
    if ty == "i64":
        return "((int64_t)%d)" % v
    if ty in ("u32", "usize"):
        return "%du" % v
    return "(%d)" % v if v < 0 else "%d" % v


def _struct(name, doc, members, typedef=True):
    o = ["/* %s */" % doc, "struct %s {" % name]
    for fn, ty, *rest in members:
        mdoc = rest[0] if rest and rest[0] else ""
        o.append("  %s;%s" % (_join(cty(ty), fn), ("  /* %s */" % mdoc) if mdoc else ""))
    o.append("};")
    if typedef:
        o.append("typedef struct %s %s;" % (name, name))
    return o


def _fixed_top(p):
    F = FIXED
    lc = p.lifecycle
    o = ["",
         "/* The C ABI of ffi/design/ABI-v1.md, version %d. Fixed part (sections 3, 4, 5, 7.1," % F.abi_version,
         " * 9, 10) from plan.FIXED; per-message part (section 6's groups and vtables, section",
         " * 7's fixes) from the plan's layout. C99/C++11 clean. */",
         "#ifndef AK_ABI_H", "#define AK_ABI_H", "",
         "#include <stddef.h>", "#include <stdint.h>", "",
         "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
         "/* ---- section 5: errors (plan.FIXED.codes) ------------------------------------- */"]
    for n, v, doc in F.codes:
        o.append("#define %-24s %-6s /* %s */" % (n, "(%d)" % v if v < 0 else str(v), doc))
    for n, v in F.details:
        o.append("#define %-24s %du" % (n, v))
    o.append("")
    o.append("#define AK_ABI_VERSION %du" % F.abi_version)
    o.append("")
    o.append("/* ---- section 3: lifecycle flags (plan.lifecycle.flag_values) ------------------- */")
    for n, v in lc.flag_values:
        o.append("#define %-22s %du" % (n, v))
    o.append("")
    o.append("/* ---- section 4: common vocabulary (plan.FIXED) --------------------------------- */")
    for h in F.handles:
        o.append("typedef struct %s %s;" % (h, h))
    # the uspan is needed by ak_unk_f: declare structs before function types that use them.
    o.append("typedef struct ak_uspan ak_uspan;")
    for name, params, ret, doc in F.fn_types:
        o.append("/* %s */" % doc)
        o.append("typedef %s (*%s)(%s);" % (cty(ret) if ret else "void", name,
                                            ", ".join(_param(a, t) for a, t in params)))
    for name, doc, members in F.structs:
        o += _struct(name, doc, members)
    for n, ty, v, doc in F.constants:
        o.append("#define %s %s  /* %s */" % (n, _cval(ty, v), doc))
    o.append("")
    return o


def _fixed_exports(p):
    o = ["/* ---- the fixed entry points (plan.FIXED.functions) ----------------------------- */"]
    group = None
    for g, name, params, ret, doc in FIXED.functions:
        if g != group:
            o.append("/* %s */" % g)
            group = g
        if doc:
            o.append("/* %s */" % doc)
        o.append(_decl(name, params, ret))
    o.append("")
    return o


def _rpc(p):
    """ABI v1 section 9, from `plan.rpc` (R-G5), and its counting surface
    (`plan.FIXED.rpc_counting`, R-G13): handles, structs, the callback type, the constants
    and every prototype, once."""
    r = p.rpc
    o = ["/* ---- section 9: the RPC half (plan.rpc, R-G5) -----------------------------------",
         " * Declared only here. A host never hand-declares one of these: R-D2 was a 3-field",
         " * copy of a 6-field struct, R-G5 a `u64` timeout declared `i32` on one side. */"]
    for h in r.handles:
        o.append("typedef struct %s %s;" % (h, h))
    for name, doc, fields in r.structs:
        o += _struct(name, doc, fields)
        o.append("#define %s_FIELDS %d" % (name.upper(), len(fields)))
    for name, params, ret, doc in r.callbacks:
        o.append("/* %s */" % doc)
        o.append("typedef %s (*%s)(%s);" % (cty(ret) if ret else "void", name,
                                            ", ".join(_param(a, t) for a, t in params)))
    for name, ty, val, doc in r.constants:
        o.append("#define %s %d  /* %s */" % (name, val, doc))
    for name, params, ret, doc in r.functions:
        if doc:
            o.append("/* %s */" % doc)
        o.append(_decl(name, params, ret))
    cname, cdoc, cmembers = FIXED.rpc_counters_struct
    # No typedef: the struct shares its name with the function that fills it, which C
    # allows for a struct TAG only.
    o += _struct(cname, cdoc + " Exported by a core built with `rpc`.", cmembers, typedef=False)
    for _g, name, params, ret, doc in FIXED.rpc_counting:
        if doc:
            o.append("/* %s */" % doc)
        o.append(_decl(name, params, ret))
    o.append("")
    return o


SASSERT = """
/* ABI v1 section 10 and obligation 12.3: layouts asserted, not assumed. */
#ifdef __cplusplus
#define AK_SASSERT(c, m) static_assert(c, m)
#else
#define AK_SASSERT_CAT2(a, b) a##b
#define AK_SASSERT_CAT(a, b) AK_SASSERT_CAT2(a, b)
#define AK_SASSERT(c, m) typedef char AK_SASSERT_CAT(ak_sa_, __LINE__)[(c) ? 1 : -1]
#endif
""".strip("\n")


def _asserts(p):
    o = ["/* The fixed structs' sizes on a 64-bit host (plan.FIXED.sizes). */",
         "#if UINTPTR_MAX == 0xFFFFFFFFFFFFFFFFu"]
    for name, size in FIXED.sizes.items():
        o.append("AK_SASSERT(sizeof(struct %s) == %d, \"sizeof %s\");" % (name, size, name))
    o.append("AK_SASSERT(offsetof(struct ak_bdr_rec, token) == 8, \"ak_bdr_rec.token\");")
    o.append("#endif")
    # Every RPC struct made of 4-byte scalars only (ak_client_opts, R-D2): size and every
    # member offset pinned as numbers.
    for name, _doc, fields in p.rpc.structs:
        if all(ty in ("u32", "i32") for _f, ty, _d in fields):
            o.append("AK_SASSERT(sizeof(struct %s) == %d, \"sizeof %s\");"
                     % (name, 4 * len(fields), name))
            for i, (fn, _ty, _d) in enumerate(fields):
                o.append("AK_SASSERT(offsetof(struct %s, %s) == %d, \"%s.%s\");"
                         % (name, fn, 4 * i, name, fn))
    o.append("")
    return o


def emit(x, extra_asserts=()):
    """(ak_abi.h, ak_layout.h, ak_layout_names.h) for a plan."""
    p = as_plan(x)
    head = HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")
    o = [head]
    o += _fixed_top(p)
    o += _lifecycle(p)

    # ---- per-message groups (plan.group_fields / ugroup_fields / presence_bits) --------
    layout_asserts = cpp_layout.facts(p)
    for name in abi_order_topo(p):
        m = p.msg(name)
        bits = presence_bits(m)
        for pre in ("e", "d", "u"):
            sname = "ak_%sfix_%s" % (pre, name)
            fields = ugroup_fields(m) if pre == "u" else group_fields(m, pre != "d")
            o.append("/* %s group for `%s`.%s */" % (
                "Decode" if pre == "d" else "Encode", name,
                "  With the unknown-field bag (decision 11 candidate)." if pre == "u" else ""))
            o.append("struct %s {" % sname)
            for fname, ty in fields:
                o.append("  %s %s;" % (cty(ty), fname))
            o.append("  uint32_t presence;")
            o.append("};")
            for fname, b in bits.items():
                o.append("#define %s_PRESENT_%s (1u << %d)" % (sname.upper(), fname.upper(), b))
            o.append("")

    # ---- vtables, in the plan's member order (plan.enc_vtable / dec_vtable) -------------
    for name in vtable_messages(p):
        slots = {"_".join(path): f for path, f in loop_slots(p, name)}
        o.append("/* Encode vtable for `%s`. */" % name)
        o.append("struct ak_evt_%s {" % name)
        for kind, sn, et in enc_vtable(p, name):
            if kind == "reserved":
                o.append("  const void *_reserved;  /* an empty struct has no defined size in C */")
            elif kind == "loop":
                o.append("  ak_loop_f loop_%s;" % sn)
            else:
                o.append("  const struct ak_evt_%s *elem_%s;" % (et, sn))
        o.append("};")
        o.append("")
        o.append("/* Decode vtable for `%s` (the push family, ABI v1 section 7.1). */" % name)
        o.append("struct ak_dvt_%s {" % name)
        for kind, sn, x in dec_vtable(p, name):
            if kind == "apply":
                o.append("  void (*apply)(ak_dec_ctx *, void *, const struct ak_dfix_%s *);" % name)
            elif kind == "unknown":
                o.append("  ak_unk_f unknown;")
            elif kind == "unk":
                o.append("  ak_unk_f unk_%s;" % sn)
            elif kind == "add":
                dty, _ = slot_elem(slots[sn])
                o.append("  void (*add_%s)(ak_dec_ctx *, void *, int64_t, const %s *, int32_t);"
                         % (sn, cty(dty)))
            elif kind == "new":
                o.append("  int64_t (*new_%s)(ak_dec_ctx *, void *);" % sn)
            elif kind == "applyelem":
                o.append("  void (*apply_%s)(ak_dec_ctx *, void *, int64_t, const struct ak_dfix_%s *);"
                         % (sn, x))
            else:
                idty, _ = slot_elem(x)
                o.append("  void (*add_%s)(ak_dec_ctx *, void *, int64_t, const %s *, int32_t);"
                         % (sn, cty(idty)))
        o.append("};")
        o.append("")

    # ---- entry points --------------------------------------------------------------
    o.append("/* ABI v1 section 6: what the host calls are PLAIN EXPORTS, not a table. */")
    for root in p.roots:
        dargs = ", const uint8_t *direct, size_t direct_len" if direct_fields(p, root) else ""
        o.append("intptr_t ak_encode_%s(const void *obj, ak_enc_ctx *ctx,"
                 " const struct ak_evt_%s *vt, const struct ak_efix_%s *fix%s);"
                 % (root, root, root, dargs))
        o.append("intptr_t ak_uencode_%s(const void *obj, ak_enc_ctx *ctx,"
                 " const struct ak_evt_%s *vt, const struct ak_ufix_%s *fix%s);"
                 % (root, root, root, dargs))
        o.append("int32_t ak_decode_%s(ak_dec_ctx *ctx, void *obj, const uint8_t *buf,"
                 " size_t len, const struct ak_dvt_%s *vt);" % (root, root))
        o.append("int32_t ak_parse_%s(ak_dec_ctx *ctx, const uint8_t *buf, size_t len);" % root)
    for et in sorted(element_types(p)):
        if p.msg(et).leaf:
            o.append("int32_t ak_elem_%s(ak_enc_ctx *ctx, const struct ak_efix_%s *elems, int32_t n);"
                     % (et, et))
            o.append("int32_t ak_uelem_%s(ak_enc_ctx *ctx, const struct ak_ufix_%s *elems, int32_t n);"
                     % (et, et))
        else:
            o.append("int32_t ak_elemu_%s(ak_enc_ctx *ctx, const struct ak_efix_%s *elems,"
                     " int32_t n, int64_t tok0);" % (et, et))
            o.append("int32_t ak_uelemu_%s(ak_enc_ctx *ctx, const struct ak_ufix_%s *elems,"
                     " int32_t n, int64_t tok0);" % (et, et))
    for _g, name, params, ret, doc in FIXED.run_functions():
        o.append(_decl(name, params, ret))
    o.append("")
    o += _fixed_exports(p)
    o += _rpc(p)

    # ---- section 10: group layouts exported and asserted ---------------------------
    o.append(SASSERT)
    o.append("")
    o += _asserts(p)
    o += list(extra_asserts)
    o.append("/* Number of (struct, member) layout facts this header pins. */")
    n = sum(1 + len(ms) for _, ms in layout_asserts)
    o.append("#define AK_LAYOUT_FACTS %d" % n)
    o.append("")
    o.append("#ifdef __cplusplus")
    o.append("} /* extern \"C\" */")
    o.append("#endif")
    o.append("#endif /* AK_ABI_H */")
    o.append("")

    # The host-side compile-time table lives in its own header so ak_abi.h stays C.
    tbl = [head, "/* The layout facts, in the order ak_layout_facts() writes them. */",
           "#ifndef AK_LAYOUT_H", "#define AK_LAYOUT_H", "#include <cstddef>",
           "#include <cstdint>", "#include \"ak_abi.h\"", "",
           "static const uint32_t AK_LAYOUT_HOST[AK_LAYOUT_FACTS] = {"]
    names = [head,
             "/* One name per fact, in the same order, so a disagreement can be NAMED and",
             " * not merely counted. */",
             "#ifndef AK_LAYOUT_NAMES_H", "#define AK_LAYOUT_NAMES_H",
             "static const char *const AK_LAYOUT_NAMES[AK_LAYOUT_FACTS] = {"]
    for sname, members in layout_asserts:
        tbl.append("  (uint32_t)sizeof(struct %s)," % sname)
        names.append("  \"sizeof %s\"," % sname)
        for mem in members:
            tbl.append("  (uint32_t)offsetof(struct %s, %s)," % (sname, mem))
            names.append("  \"%s.%s\"," % (sname, mem))
    tbl.append("};")
    tbl.append("#endif")
    tbl.append("")
    names.append("};")
    names.append("#endif")
    names.append("")
    return "\n".join(o), "\n".join(tbl), "\n".join(names)
