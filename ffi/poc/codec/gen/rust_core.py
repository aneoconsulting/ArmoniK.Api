"""The core's codec: ONE traversal emitter, two backends.

ABI v1 section 7.1 makes this a condition rather than a preference: "one traversal emitter
parameterised by where values are deposited, not two emitters that have to agree. Two
emitters is a fork at the generator level and it is the most likely place for the two
families to drift apart on a shape nobody tested."

So `walk_encode` and `walk_decode` below decide the field order, the wire types and the
skip rules once, and a Backend object decides only where a value comes from (encode) or
goes to (decode):

  NativeEnc / NativeDec   the `core-native` arm: the same traversal emitted into the host,
                          reading and writing facade objects directly. No boundary at all.
  GroupEnc  / FixDec      the core behind the C ABI: reading an `ak_efix_*` group the host
                          filled, and depositing into an `ak_dfix_*` arena it hands back.

What that buys, and what it does not: the two arms cannot disagree about the WIRE, because
the field walk is one function. They can and do differ in what a field access costs, which
is the whole measurement. It also means the two are NOT independent encoders, so neither
validates the other; both are checked against the manifest instead.
"""
from rustnames import SCALAR, variant

HEAD = "// @generated by ffi/poc/rust/gen/generate.py from ffi/schema/shapes.json. Do not edit.\n"

W_VARINT, W_I64, W_LEN = 0, 1, 2


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


class Sites:
    """Length-prefix sites. One slot per site in the encode context, never process-global
    (ABI v1 section 6). Allocated per backend, because the native backend has fewer: it
    knows a string's length before it writes it and the core does not."""

    def __init__(self):
        self.ids = {}

    def id(self, key):
        return self.ids.setdefault(key, len(self.ids))

    def __len__(self):
        return len(self.ids)


# ============================================================== the traversal, once

def walk_encode(ir, m, b, o):
    """Emit the body of one message's encoder. `b` is the backend.

    A oneof is emitted through `b.oneof`, NOT skipped. It was skipped once, silently,
    because `Message.plain` excludes oneof members and every backend iterated that: the
    generator produced a codec that ignored `Probe.body` entirely and said nothing. A
    backend that cannot do a shape raises here.
    """
    for f in m.plain:
        if f.oneof:
            continue
        if f.card == "singular" and f.kind == "message":
            b.child(m, f, o)
        elif f.card == "repeated" and f.kind == "message":
            b.repeated_message(m, f, o)
        elif f.card == "singular" and f.kind in ("string", "bytes"):
            b.blob(m, f, o)
        elif f.card == "singular" and f.kind in ("int32", "int64", "bool", "enum"):
            b.scalar(m, f, o)
        elif f.card == "singular" and f.kind == "double":
            b.double(m, f, o)
        elif f.card == "repeated" and f.kind in ("string", "bytes"):
            b.repeated_blob(m, f, o)
        elif f.card == "packed":
            b.packed(m, f, o)
        elif f.card == "map":
            b.map(m, f, o)
        else:
            raise NotImplementedError("encode %s.%s (%s %s): stage 3"
                                      % (m.name, f.name, f.card, f.kind))
    for oname, members in m.oneofs.items():
        b.oneof(m, oname, members, o)


def walk_decode(ir, m, b, o):
    """Emit the tag dispatch of one message's decoder."""
    for f in m.plain:
        if f.oneof:
            continue
        if f.card == "singular" and f.kind == "message":
            b.child(m, f, o)
        elif f.card == "repeated" and f.kind == "message":
            b.repeated_message(m, f, o)
        elif f.card == "singular" and f.kind in ("string", "bytes"):
            b.blob(m, f, o)
        elif f.card == "singular" and f.kind in ("int32", "int64", "bool", "enum"):
            b.scalar(m, f, o)
        elif f.card == "singular" and f.kind == "double":
            b.double(m, f, o)
        elif f.card == "repeated" and f.kind in ("string", "bytes"):
            b.repeated_blob(m, f, o)
        elif f.card == "packed":
            b.packed(m, f, o)
        elif f.card == "map":
            b.map(m, f, o)
        else:
            raise NotImplementedError("decode %s.%s (%s %s): stage 3"
                                      % (m.name, f.name, f.card, f.kind))
    for oname, members in m.oneofs.items():
        b.oneof(m, oname, members, o)


# ============================================================== backend: core-native

class NativeEnc:
    def __init__(self, sites):
        self.sites = sites

    def child(self, m, f, o):
        s = self.sites.id((m.name, f.name))
        o.append("    if let Some(c) = &o.%s {" % f.name)
        o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
        o.append("        enc_%s(c, e);" % snake(f.of))
        o.append("        e.end(mk);")
        o.append("    }")

    def repeated_message(self, m, f, o):
        s = self.sites.id((m.name, f.name))
        o.append("    for c in &o.%s {" % f.name)
        o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
        o.append("        enc_%s(c, e);" % snake(f.of))
        o.append("        e.end(mk);")
        o.append("    }")

    def blob(self, m, f, o):
        if f.explicit:
            # Explicit presence: written when SET, zero or not. Present-and-empty is a
            # different thing from absent, and this is the field shape that difference is
            # for (design/SHAPES.md, M3).
            acc = "v.as_bytes()" if f.kind == "string" else "&v[..]"
            o.append("    if let Some(v) = &o.%s { e.blob_field(%d, %s); }" % (f.name, f.tag, acc))
            return
        acc = "o.%s.as_bytes()" % f.name if f.kind == "string" else "&o.%s" % f.name
        o.append("    if !o.%s.is_empty() { e.blob_field(%d, %s); }" % (f.name, f.tag, acc))

    def scalar(self, m, f, o):
        if f.explicit:
            conv = {"bool": "*v as u64", "int32": "*v as i64 as u64", "int64": "*v as u64",
                    "enum": "v.to_i32() as i64 as u64"}[f.kind]
            o.append("    if let Some(v) = &o.%s { e.varint_field(%d, %s); }" % (f.name, f.tag, conv))
            return
        n = "o.%s" % f.name
        if f.kind == "enum":
            o.append("    { let v = %s.to_i32(); if v != 0 { e.varint_field(%d, v as i64 as u64); } }"
                     % (n, f.tag))
        elif f.kind == "bool":
            o.append("    if %s { e.varint_field(%d, 1); }" % (n, f.tag))
        elif f.kind == "int32":
            o.append("    if %s != 0 { e.varint_field(%d, %s as i64 as u64); }" % (n, f.tag, n))
        else:
            o.append("    if %s != 0 { e.varint_field(%d, %s as u64); }" % (n, f.tag, n))

    def double(self, m, f, o):
        o.append("    if o.%s != 0.0 { e.f64_field(%d, o.%s); }" % (f.name, f.tag, f.name))

    def repeated_blob(self, m, f, o):
        acc = "s.as_bytes()" if f.kind == "string" else "&s[..]"
        o.append("    for s in &o.%s { e.blob_field(%d, %s); }" % (f.name, f.tag, acc))

    def packed(self, m, f, o):
        # Repeated scalars are always packed in the canonical form, and an empty one is
        # written as nothing rather than as a zero-length field.
        o.append("    if !o.%s.is_empty() {" % f.name)
        s_ = self.sites.id(("packed", m.name, f.name))
        o.append("        let mk = e.begin(%d, %d);" % (f.tag, s_))
        if f.kind == "double":
            o.append("        for v in &o.%s { e.buf.extend_from_slice(&v.to_le_bytes()); }" % f.name)
        elif f.kind == "bool":
            o.append("        for v in &o.%s { e.varint(*v as u64); }" % f.name)
        elif f.kind == "enum":
            # The one packed shape the real schema has: 3 packed fields, all enums.
            o.append("        for v in &o.%s { e.varint(v.to_i32() as i64 as u64); }" % f.name)
        elif f.kind == "int32":
            o.append("        for v in &o.%s { e.varint(*v as i64 as u64); }" % f.name)
        else:
            o.append("        for v in &o.%s { e.varint(*v as u64); }" % f.name)
        o.append("        e.end(mk);")
        o.append("    }")

    def oneof(self, m, oname, members, o):
        from rustnames import camel, oneof_type
        ty = oneof_type(m.name, oname)
        o.append("    if let Some(v) = &o.%s {" % oname)
        o.append("        match v {")
        for g in members:
            v = camel(g.name)
            if g.kind == "string":
                o.append("            %s::%s(x) => e.blob_field(%d, x.as_bytes())," % (ty, v, g.tag))
            elif g.kind == "bytes":
                o.append("            %s::%s(x) => e.blob_field(%d, x)," % (ty, v, g.tag))
            elif g.kind == "message":
                s_ = self.sites.id(("oneof", m.name, oname, g.name))
                o.append("            %s::%s(x) => {" % (ty, v))
                o.append("                let mk = e.begin(%d, %d);" % (g.tag, s_))
                o.append("                enc_%s(x, e);" % snake(g.of))
                o.append("                e.end(mk);")
                o.append("            }")
            elif g.kind == "double":
                o.append("            %s::%s(x) => e.f64_field(%d, *x)," % (ty, v, g.tag))
            elif g.kind == "bool":
                o.append("            %s::%s(x) => e.varint_field(%d, *x as u64)," % (ty, v, g.tag))
            elif g.kind == "int32":
                o.append("            %s::%s(x) => e.varint_field(%d, *x as i64 as u64)," % (ty, v, g.tag))
            else:
                o.append("            %s::%s(x) => e.varint_field(%d, *x as u64)," % (ty, v, g.tag))
        o.append("        }")
        o.append("    }")

    def map(self, m, f, o):
        # No map case: a pair message, written through the same length-prefixed path as any
        # other repeated message (ABI v1 section 11). BTreeMap iterates in key order, which
        # is the canonical form ffi/schema/README.md fixes.
        s_ = self.sites.id(("map", m.name, f.name))
        o.append("    for (k, val) in &o.%s {" % f.name)
        o.append("        let mk = e.begin(%d, %d);" % (f.tag, s_))
        o.append("        if !k.is_empty() { e.blob_field(1, k.as_bytes()); }")
        o.append("        if !val.is_empty() { e.blob_field(2, val.as_bytes()); }")
        o.append("        e.end(mk);")
        o.append("    }")


class NativeDec:
    def __init__(self, sites=None):
        self.sites = sites

    def child(self, m, f, o):
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        o.append("                let mut c = %s::default();" % f.of)
        o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
        o.append("                dec_%s(&mut sub, &mut c);" % snake(f.of))
        o.append("                if sub.err != 0 { d.err = sub.err; }")
        o.append("                out.%s = Some(c);" % f.name)
        o.append("            }")

    def repeated_message(self, m, f, o):
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        o.append("                let mut c = %s::default();" % f.of)
        o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
        o.append("                dec_%s(&mut sub, &mut c);" % snake(f.of))
        o.append("                if sub.err != 0 { d.err = sub.err; }")
        o.append("                out.%s.push(c);" % f.name)
        o.append("            }")

    def blob(self, m, f, o):
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        if f.explicit:
            if f.kind == "string":
                o.append("                match ak_rt::strings::decode_str(&buf[off..off + n]) {")
                o.append("                    Ok(s) => out.%s = Some(s)," % f.name)
                o.append("                    Err(e) => { d.err = e; return; }")
                o.append("                }")
            else:
                o.append("                out.%s = Some(::bytes::Bytes::copy_from_slice(&buf[off..off + n]));"
                         % f.name)
            o.append("            }")
            return
        if f.kind == "string":
            o.append("                // ABI v1 open decision 3: the decoder carries the UTF-8")
            o.append("                // guarantee, because the encoder's check bought nothing and")
            o.append("                // the parser cannot trust the wire. The policy is one")
            o.append("                // build-time choice in ak_rt::strings, not a per-site one.")
            o.append("                match ak_rt::strings::decode_str(&buf[off..off + n]) {")
            o.append("                    Ok(s) => out.%s = s," % f.name)
            o.append("                    Err(e) => { d.err = e; return; }")
            o.append("                }")
        else:
            o.append("                out.%s = ::bytes::Bytes::copy_from_slice(&buf[off..off + n]);" % f.name)
        o.append("            }")

    def scalar(self, m, f, o):
        cast = {"int32": "as i32", "int64": "as i64", "bool": "!= 0", "enum": "as i32"}[f.kind]
        if f.explicit:
            v = ("%s::from_i32(d.varint() as i32)" % f.of if f.kind == "enum"
                 else "d.varint() %s" % cast)
            o.append("            %d if wire == 0 => out.%s = Some(%s)," % (f.tag, f.name, v))
            return
        if f.kind == "enum":
            o.append("            %d if wire == 0 => out.%s = %s::from_i32(d.varint() as i32),"
                     % (f.tag, f.name, f.of))
        else:
            o.append("            %d if wire == 0 => out.%s = d.varint() %s," % (f.tag, f.name, cast))

    def double(self, m, f, o):
        o.append("            %d if wire == 1 => out.%s = d.f64()," % (f.tag, f.name))

    def repeated_blob(self, m, f, o):
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        if f.kind == "string":
            o.append("                match ak_rt::strings::decode_str(&buf[off..off + n]) {")
            o.append("                    Ok(s) => out.%s.push(s)," % f.name)
            o.append("                    Err(e) => { d.err = e; return; }")
            o.append("                }")
        else:
            o.append("                out.%s.push(::bytes::Bytes::copy_from_slice(&buf[off..off + n]));"
                     % f.name)
        o.append("            }")

    def packed(self, m, f, o):
        # A decoder must accept both forms whatever the writer emits: proto3 makes packed
        # the default, it does not make the unpacked form illegal.
        rd = {"double": "sub.f64()", "bool": "sub.varint() != 0",
              "int32": "sub.varint() as i32", "int64": "sub.varint() as i64",
              "enum": "%s::from_i32(sub.varint() as i32)" % f.of}[f.kind]
        rd1 = {"double": "d.f64()", "bool": "d.varint() != 0",
               "int32": "d.varint() as i32", "int64": "d.varint() as i64",
               "enum": "%s::from_i32(d.varint() as i32)" % f.of}[f.kind]
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
        o.append("                while !sub.at_end() { out.%s.push(%s); }" % (f.name, rd))
        o.append("                if sub.err != 0 { d.err = sub.err; }")
        o.append("            }")
        o.append("            %d => out.%s.push(%s)," % (f.tag, f.name, rd1))

    def oneof(self, m, oname, members, o):
        from rustnames import camel, oneof_type
        ty = oneof_type(m.name, oname)
        for g in members:
            v = camel(g.name)
            if g.kind in ("string", "bytes"):
                o.append("            %d if wire == 2 => {" % g.tag)
                o.append("                let (off, n) = d.len_body();")
                if g.kind == "string":
                    o.append("                match ak_rt::strings::decode_str(&buf[off..off + n]) {")
                    o.append("                    Ok(s) => out.%s = Some(%s::%s(s))," % (oname, ty, v))
                    o.append("                    Err(e) => { d.err = e; return; }")
                    o.append("                }")
                else:
                    o.append("                out.%s = Some(%s::%s(::bytes::Bytes::copy_from_slice(&buf[off..off + n])));"
                             % (oname, ty, v))
                o.append("            }")
            elif g.kind == "message":
                o.append("            %d if wire == 2 => {" % g.tag)
                o.append("                let (off, n) = d.len_body();")
                o.append("                let mut c = %s::default();" % g.of)
                o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
                o.append("                dec_%s(&mut sub, &mut c);" % snake(g.of))
                o.append("                if sub.err != 0 { d.err = sub.err; }")
                o.append("                out.%s = Some(%s::%s(c));" % (oname, ty, v))
                o.append("            }")
            elif g.kind == "double":
                o.append("            %d if wire == 1 => out.%s = Some(%s::%s(d.f64()))," % (g.tag, oname, ty, v))
            else:
                cast = {"int32": "as i32", "int64": "as i64", "bool": "!= 0"}[g.kind]
                o.append("            %d if wire == 0 => out.%s = Some(%s::%s(d.varint() %s)),"
                         % (g.tag, oname, ty, v, cast))

    def map(self, m, f, o):
        o.append("            %d if wire == 2 => {" % f.tag)
        o.append("                let (off, n) = d.len_body();")
        o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
        o.append("                let (mut k, mut val) = (String::new(), String::new());")
        o.append("                let eb = sub.buf;")
        o.append("                while !sub.at_end() {")
        o.append("                    let kk = sub.varint();")
        o.append("                    let (et, ew) = ((kk >> 3) as u32, (kk & 7) as u32);")
        o.append("                    match et {")
        o.append("                        1 if ew == 2 => { let (a, b) = sub.len_body();")
        o.append("                            match ak_rt::strings::decode_str(&eb[a..a + b]) {")
        o.append("                                Ok(s) => k = s, Err(e) => { d.err = e; return; } } }")
        o.append("                        2 if ew == 2 => { let (a, b) = sub.len_body();")
        o.append("                            match ak_rt::strings::decode_str(&eb[a..a + b]) {")
        o.append("                                Ok(s) => val = s, Err(e) => { d.err = e; return; } } }")
        o.append("                        _ => sub.skip(ew),")
        o.append("                    }")
        o.append("                }")
        o.append("                if sub.err != 0 { d.err = sub.err; }")
        o.append("                out.%s.insert(k, val);" % f.name)
        o.append("            }")


def emit_core_native(ir):
    sites = Sites()
    body = []
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("#[inline]")
        body.append("fn enc_%s(o: &%s, e: &mut Enc) {" % (snake(name), name))
        walk_encode(ir, m, NativeEnc(sites), body)
        body.append("}")
        body.append("")
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("#[inline]")
        body.append("fn dec_%s(d: &mut Dec, out: &mut %s) {" % (snake(name), name))
        body.append("    #[allow(unused_variables)]\n    let buf = d.buf;")
        body.append("    while !d.at_end() {")
        body.append("        let k = d.varint();")
        body.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        body.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; return; }")
        body.append("        match tag {")
        walk_decode(ir, m, NativeDec(), body)
        body.append("            _ => d.skip(wire),")
        body.append("        }")
        body.append("    }")
        body.append("}")
        body.append("")

    o = [HEAD,
         "//! Arm `core-native`: the generated codec emitted into the host language, over the",
         "//! same facade objects, with no boundary at all. README R3 calls this the",
         "//! no-boundary control and says it is not optional: on Java it is the arm that",
         "//! changed the recommendation.",
         "//!",
         "//! Same traversal emitter as the core behind the C ABI, so the two cannot disagree",
         "//! about the wire. What differs is only where a field value comes from.",
         "#![allow(clippy::all)]",
         "use super::types::*;",
         "use ak_rt::dec::Dec;",
         "use ak_rt::Enc;",
         "",
         "/// One learned length-prefix slot per site in this file (ABI v1 section 6).",
         "pub const SITES: usize = %d;" % len(sites),
         ""]
    o += body
    for root in ir.roots:
        o.append("pub fn encode_%s(o: &%s) -> Vec<u8> {" % (snake(root), root))
        o.append("    let mut e = Enc::new(SITES);")
        o.append("    enc_%s(o, &mut e);" % snake(root))
        o.append("    e.buf")
        o.append("}")
        o.append("")
        o.append("/// Encode into a context that is reused, so the learned widths survive and the")
        o.append("/// allocation is not part of what is timed. This is the shape a real host uses.")
        o.append("pub fn encode_into_%s(o: &%s, e: &mut Enc) {" % (snake(root), root))
        o.append("    e.reset();")
        o.append("    enc_%s(o, e);" % snake(root))
        o.append("}")
        o.append("")
        o.append("pub fn decode_%s(b: &[u8]) -> Result<%s, i32> {" % (snake(root), root))
        o.append("    let mut d = Dec::new(b);")
        o.append("    let mut out = %s::default();" % root)
        o.append("    dec_%s(&mut d, &mut out);" % snake(root))
        o.append("    if d.err != 0 { Err(d.err) } else { Ok(out) }")
        o.append("}")
        o.append("")
    return "\n".join(o)
