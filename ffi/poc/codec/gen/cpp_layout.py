"""ABI v1 section 10 and obligation 12.3: group layouts exported and asserted at load.

The rust slice records this as "specified and not built", and for a good reason: both of
its sides compiled against one generated header, so there was nothing to disagree. Here the
two sides genuinely restate the layout -- `#[repr(C)]` in Rust and a `struct` in a C header
-- which is exactly the case the specification names, and whose failure mode is "a wrong
value in a field, the worst way to find it".

So the core exports its own view of every group's `sizeof` and every member's `offsetof`,
in one fixed order, and the host compares it with the numbers its own compiler produced.
Four lines of insurance, as section 10 says, and a positive control in `gen/boundary.sh`.
"""
from plan import abi_order_topo, as_plan, group_fields, ugroup_fields, unknown_compiled_out

HEAD_FMT = "// @generated by ffi/poc/codec/gen/generate.py from %s. Do not edit.\n"
HEAD = HEAD_FMT % "ffi/schema/shapes.json"


def facts(ir):
    """The ONE enumeration of the layout facts, in order.

    Both the host's compile-time table (`c_abi`'s ak_layout.h) and the core's run-time export are
    built from this list, so a permutation at constant count -- which is what defect C5
    was, and which a count check cannot see -- is impossible by construction rather than by
    two backends agreeing. Before this each side rebuilt the enumeration separately.
    """
    ir = as_plan(ir)
    out = []
    for name in abi_order_topo(ir):
        m = ir.msg(name)
        # WP5 step 10: the no-unknown variant has no u-groups (and no `unknown` member in
        # a d-group, which `group_fields` already omits), so its facts are its own.
        pres = ("e", "d") if unknown_compiled_out(ir) else ("e", "d", "u")
        for pre in pres:
            sname = "ak_%sfix_%s" % (pre, name)
            fields = ugroup_fields(m) if pre == "u" else group_fields(m, pre != "d")
            out.append((sname, [fn for fn, _ in fields] + ["presence"]))
    return out


def emit(ir):
    ir = as_plan(ir)
    o = [HEAD_FMT % getattr(ir, "source", "ffi/schema/shapes.json"),
         "//! The core's own view of every group layout, in the order the host's",
         "//! `AK_LAYOUT_HOST` table lists them.",
         "#![allow(non_snake_case)]",
         "use ak_abi::*;",
         ""]
    rows = []
    for sname, members in facts(ir):
        rows.append("core::mem::size_of::<%s>() as u32" % sname)
        for mem in members:
            rows.append("core::mem::offset_of!(%s, %s) as u32" % (sname, mem))
    o.append("pub const AK_LAYOUT_FACTS: usize = %d;" % len(rows))
    o.append("")
    o.append("/// Writes at most `cap` facts and returns how many exist.")
    o.append("#[no_mangle]")
    o.append("pub unsafe extern \"C\" fn ak_layout_facts(out: *mut u32, cap: usize) -> usize {")
    o.append("    let v: [u32; AK_LAYOUT_FACTS] = [")
    for r in rows:
        o.append("        %s," % r)
    o.append("    ];")
    o.append("    let n = if cap < AK_LAYOUT_FACTS { cap } else { AK_LAYOUT_FACTS };")
    o.append("    core::ptr::copy_nonoverlapping(v.as_ptr(), out, n);")
    o.append("    AK_LAYOUT_FACTS")
    o.append("}")
    o.append("")
    return "\n".join(o)
