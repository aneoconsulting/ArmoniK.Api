def _canon_types(p):
    """Every decode group a pull record or an FSM event can carry, and the groups they nest."""
    todo = list(p.roots)
    for root in p.roots:
        for _path, f in loop_slots(p, root):
            et = elem_type(f)
            if et:
                todo.append(et)
                for _ip, iff in loop_slots(p, et):
                    if elem_type(iff):
                        todo.append(elem_type(iff))
    seen = []
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.append(n)
        for _mn, ty in group_fields(p.msg(n), False):
            if ty.startswith("ak_dfix_"):
                todo.append(ty[len("ak_dfix_"):])
    return sorted(seen)


def _canon_fns(p):
    """A group's bytes with its PADDING zeroed (member by member, nested groups recursively):
    a group built in a stack local (pull's record) carries whatever its padding held, so the
    differential compares members, not padding."""
    o = []
    for n in _canon_types(p):
        o.append("unsafe fn fsm_canon_%s(s: *const u8, d: *mut u8) {" % _snake(n))
        for mn, ty in group_fields(p.msg(n), False) + [("presence", "u32")]:
            off = "::core::mem::offset_of!(ak_dfix_%s, %s)" % (n, _rmember(mn))
            if ty.startswith("ak_dfix_"):
                o.append("    fsm_canon_%s(s.add(%s), d.add(%s));" % (_snake(ty[len("ak_dfix_"):]), off, off))
            else:
                o.append("    ::core::ptr::copy_nonoverlapping(s.add(%s), d.add(%s), ::core::mem::size_of::<%s>());" % (off, off, ty))
        o.append("}")
        o.append("")
    o.append("/// `n` groups of `size` bytes at `body`, padding zeroed by `f`; the rest of `body` as is.")
    o.append("fn fsm_canon_run(body: &[u8], n: usize, size: usize, f: unsafe fn(*const u8, *mut u8)) -> Vec<u8> {")
    o.append("    let mut out = vec![0u8; body.len()];")
    o.append("    let k = n * size;")
    o.append("    if k <= body.len() {")
    o.append("        for i in 0..n { unsafe { f(body.as_ptr().add(i * size), out.as_mut_ptr().add(i * size)); } }")
    o.append("        out[k..].copy_from_slice(&body[k..]);")
    o.append("        out")
    o.append("    } else {")
    o.append("        body.to_vec()")
    o.append("    }")
    o.append("}")
    o.append("")
    return o


def _canon_root(p, root):
    """(op, slot) -> the payload with group padding zeroed."""
    rs = _snake(root)
    o = ["/// D23 check: a record's or an event's payload with group padding zeroed.",
         "fn fsm_canon_rec_%s(op: u32, slot: u32, n: u32, body: &[u8]) -> Vec<u8> {" % rs,
         "    match (op, slot) {",
         "        (AK_BDR_APPLY, 0) => fsm_canon_run(body, 1, ::core::mem::size_of::<ak_dfix_%s>(), fsm_canon_%s)," % (root, rs)]
    for i, (path, f) in enumerate(loop_slots(p, root)):
        et = elem_type(f)
        if et and not p.msg(et).leaf:
            o.append("        (AK_BDR_APPLY_ELEM, %d) => fsm_canon_run(body, 1, ::core::mem::size_of::<ak_dfix_%s>(), fsm_canon_%s)," % (pull_slot(i, -1), et, _snake(et)))
            for k, (_ip, iff) in enumerate(loop_slots(p, et)):
                ie = elem_type(iff)
                if ie:
                    o.append("        (AK_BDR_ADD, %d) => fsm_canon_run(body, n as usize, ::core::mem::size_of::<ak_dfix_%s>(), fsm_canon_%s)," % (pull_slot(i, k), ie, _snake(ie)))
        elif et:
            o.append("        (AK_BDR_ADD, %d) => fsm_canon_run(body, n as usize, ::core::mem::size_of::<ak_dfix_%s>(), fsm_canon_%s)," % (i + 1, et, _snake(et)))
    o.append("        // spans and scalars have no padding")
    o.append("        _ => body.to_vec(),")
    o.append("    }")
    o.append("}")
    o.append("")
    return o


def _binding_root(p, root):
    rs = _snake(root)
    o = _canon_root(p, root)
    rslots = loop_slots(p, root)
    # ---- the dispatch of one event to the push vtable's host functions
    o.append("/// D23: one FSM event to the host functions the push vtable registers.")
    o.append("#[inline(always)]")
    o.append("unsafe fn fsm_feed_%s(ctx: *mut ak_dec_ctx, sink: *mut c_void, op: u32, ev: &ak_fsm_ev, toks: &mut Vec<i64>) {" % rs)
    o.append("    match (op, ev.slot) {")
    o.append("        (AK_BDR_APPLY, 0) => apply_%s(ctx, sink, ev.data as *const ak_dfix_%s)," % (rs, root))
    for i, (path, f) in enumerate(rslots):
        sn = slot_name(path)
        et = elem_type(f)
        dty = slot_elem(f)[0]
        if et and not p.msg(et).leaf:
            o.append("        (AK_BDR_NEW, %d) => toks.push(new_%s_%s(ctx, sink))," % (pull_slot(i, -1), rs, sn))
            o.append("        (AK_BDR_APPLY_ELEM, %d) => apply_%s_%s(ctx, sink, toks[ev.token as usize], ev.data as *const ak_dfix_%s),"
                     % (pull_slot(i, -1), rs, sn, et))
            for k, (ipath, iff) in enumerate(loop_slots(p, et)):
                isn = slot_name(ipath)
                o.append("        (AK_BDR_ADD, %d) => add_%s_%s_%s(ctx, sink, toks[ev.token as usize], ev.data as *const %s, ev.n as i32),"
                         % (pull_slot(i, k), rs, sn, isn, slot_elem(iff)[0]))
        else:
            o.append("        (AK_BDR_ADD, %d) => add_%s_%s(ctx, sink, ev.token, ev.data as *const %s, ev.n as i32),"
                     % (i + 1, rs, sn, dty))
    o.append("        // An event for a slot this host does not know is a generator disagreement.")
    o.append("        _ => ak_fail(ctx as *mut c_void, AK_ERR_ABI, ::core::ptr::null(), 0),")
    o.append("    }")
    o.append("}")
    o.append("")
    # ---- the consumer
    o.append("/// D23: decode `%s` with the FSM family: begin (the first event), then next until the" % root)
    o.append("/// end event; each event is fed to the push vtable's host functions as it arrives.")
    o.append("#[inline(always)]")
    o.append("fn fsm_with_%s_armed(ctxs: DecCtxs, b: &[u8], toks: &mut Vec<i64>) -> Result<%s, i32> {" % (rs, root))
    o.append("    let ctx = ctxs.%s;" % rs)
    o.append("    let mut out = %s::default();" % root)
    o.append("    toks.clear();")
    o.append("    let rc = unsafe {")
    o.append("        let mut sink = Sink%s { out: &mut out, base: b.as_ptr() };" % root)
    o.append("        let obj = &mut sink as *mut _ as *mut c_void;")
    o.append("        let mut ev = ak_fsm_ev::default();")
    o.append("        let mut rc = ak_fsm_begin_%s(ctx, b.as_ptr(), b.len(), &mut ev);" % root)
    o.append("        // The return value is the event's op; the root group (APPLY) is the last.")
    o.append("        loop {")
    o.append("            if rc <= 0 { if rc == 0 { rc = AK_ERR_ABI; } break; }")
    o.append("            fsm_feed_%s(ctx, obj, rc as u32, &ev, toks);" % rs)
    o.append("            if rc == AK_BDR_APPLY as i32 { rc = AK_OK; break; }")
    o.append("            rc = ak_fsm_next_%s(ctx, &mut ev);" % root)
    o.append("        }")
    o.append("        if rc < 0 { rc } else { host_call(); ak_dec_err(ctx) }")
    o.append("    };")
    o.append("    if rc < 0 { Err(rc) } else { Ok(out) }")
    o.append("}")
    o.append("")
    o.append("/// D23: the FSM family, unknown fields dropped.")
    o.append("pub fn fsm_with_%s(ctxs: DecCtxs, b: &[u8], toks: &mut Vec<i64>) -> Result<%s, i32> {" % (rs, root))
    if not NOUNK:
        o.append("    disarm_%s(ctxs);" % rs)
    o.append("    fsm_with_%s_armed(ctxs, b, toks)" % rs)
    o.append("}")
    o.append("")
    if not NOUNK:
        o.append("/// D23: the FSM family with every unknown-field position retained.")
        o.append("pub fn fsm_with_%s_unk(ctxs: DecCtxs, b: &[u8], toks: &mut Vec<i64>) -> Result<%s, i32> {" % (rs, root))
        o.append("    let rc = arm_%s(ctxs);" % rs)
        o.append("    if rc != AK_OK { return Err(rc); }")
        o.append("    let r = fsm_with_%s_armed(ctxs, b, toks);" % rs)
        o.append("    unk_reclaim();")
        o.append("    r")
        o.append("}")
        o.append("")
    # ---- attribution probe (D23 attribution, coordinator 2026-10-09): the FSM's events
    # COLLECTED into a pull-format record buffer by the host, then replayed with the pull
    # family's own host replay after the decode. Separates "decode and facade construction
    # interleaved per event" from "decode first, facade after". Not an arm of the campaign.
    o.append("/// D23 attribution probe: FSM decode with every event copied into a pull-format record")
    o.append("/// buffer (`buf`), then the pull family's replay over it. Drop mode.")
    o.append("pub fn fsm_collect_with_%s(ctxs: DecCtxs, b: &[u8], toks: &mut Vec<i64>, buf: &mut Vec<u64>) -> Result<%s, i32> {" % (rs, root))
    if not NOUNK:
        o.append("    disarm_%s(ctxs);" % rs)
    o.append("    let ctx = ctxs.%s;" % rs)
    o.append("    let mut out = %s::default();" % root)
    o.append("    toks.clear();")
    o.append("    buf.clear();")
    o.append("    let rc = unsafe {")
    o.append("        let mut ev = ak_fsm_ev::default();")
    o.append("        let mut rc = ak_fsm_begin_%s(ctx, b.as_ptr(), b.len(), &mut ev);" % root)
    o.append("        while rc > 0 {")
    o.append("            let pad = ((ev.bytes as usize) + 7) / 8;")
    o.append("            let h = ak_bdr_rec { op: rc as u32, slot: ev.slot, token: ev.token, n: ev.n, bytes: (pad * 8) as u32 };")
    o.append("            let at = buf.len();")
    o.append("            buf.resize(at + 3 + pad, 0);")
    o.append("            ::core::ptr::write(buf.as_mut_ptr().add(at) as *mut ak_bdr_rec, h);")
    o.append("            if ev.bytes != 0 { ::core::ptr::copy_nonoverlapping(ev.data as *const u8, buf.as_mut_ptr().add(at + 3) as *mut u8, ev.bytes as usize); }")
    o.append("            if rc == AK_BDR_APPLY as i32 { rc = AK_OK; break; }")
    o.append("            rc = ak_fsm_next_%s(ctx, &mut ev);" % root)
    o.append("        }")
    o.append("        if rc < 0 { rc } else {")
    o.append("            let mut sink = Sink%s { out: &mut out, base: b.as_ptr() };" % root)
    o.append("            let obj = &mut sink as *mut _ as *mut c_void;")
    o.append("            replay_%s(ctx, obj, buf, toks);" % rs)
    o.append("            host_call(); ak_dec_err(ctx)")
    o.append("        }")
    o.append("    };")
    o.append("    if rc < 0 { Err(rc) } else { Ok(out) }")
    o.append("}")
    o.append("")
    # ---- the graph check: FSM consumer against push, same mode
    o.append("/// D23 check: the FSM consumer's graph against push's (same mode), or the same error.")
    o.append("pub fn fsm_graph_%s(ctxs: DecCtxs, b: &[u8], retain: bool) -> Result<(), String> {" % rs)
    o.append("    let mut toks = Vec::new();")
    if NOUNK:
        o.append("    let _ = retain;")
        o.append("    let (a, c) = (decode_with_%s(ctxs, b), fsm_with_%s(ctxs, b, &mut toks));" % (rs, rs))
    else:
        o.append("    let (a, c) = if retain {")
        o.append("        (decode_with_%s_unk(ctxs, b), fsm_with_%s_unk(ctxs, b, &mut toks))" % (rs, rs))
        o.append("    } else {")
        o.append("        (decode_with_%s(ctxs, b), fsm_with_%s(ctxs, b, &mut toks))" % (rs, rs))
        o.append("    };")
    o.append("    match (&a, &c) {")
    o.append("        (Ok(x), Ok(y)) if format!(\"{x:?}\") == format!(\"{y:?}\") => Ok(()),")
    o.append("        (Err(x), Err(y)) if x == y => Ok(()),")
    o.append("        _ => Err(format!(\"push {:?} / fsm {:?}\", a.as_ref().map(|_| \"ok\"), c.as_ref().map(|_| \"ok\"))),")
    o.append("    }")
    o.append("}")
    o.append("")
    # ---- the differential: pull's log against the FSM's events
    o.append("/// D23 check: decode `b` with pull and with the FSM on the same context and mode; compare")
    o.append("/// pull's records with the FSM's events, record for record, the return codes, and (retain)")
    o.append("/// the unknown-field buffers (a bump arena reset before each family: same grows, same bytes).")
    o.append("/// `sk`: the D20 mask given to BOTH families (pull's `ak_dec_set_pvt_*`, the FSM's")
    o.append("/// `ak_fsm_set_pvt_*`) for this comparison; both are reset to NULL after it.")
    o.append("pub fn fsm_diff_%s(ctxs: DecCtxs, b: &[u8], retain: bool, sk: u64) -> FsmDiff {" % rs)
    o.append("    let ctx = ctxs.%s;" % rs)
    o.append("    let mut d = FsmDiff::default();")
    o.append("    unsafe {")
    o.append("        let pvt = %s { %s: sk };" % (pvt_name(root), UTF8_MEMBER))
    o.append("        ak_dec_set_pvt_%s(ctx, &pvt);" % root)
    o.append("        ak_fsm_set_pvt_%s(ctx, &pvt);" % root)
    if not NOUNK:
        o.append("        let arm = |opts: &mut %s| -> i32 {" % unk_opts_name(root))
        for mn, _m, _ty in unk_opts_layout(p, root):
            o.append("            opts.%s.grow = Some(fsm_bump_grow);" % _rmember(mn))
        o.append("            if retain { ak_dec_reset_%s(ctx, opts) } else { ak_dec_reset_%s(ctx, ::core::ptr::null_mut()) }" % (root, root))
        o.append("        };")
        o.append("        let mut o1 = unk_opts_%s(None);" % rs)
        o.append("        let _ = arm(&mut o1);")
        o.append("        fsm_bump_reset();")
    else:
        o.append("        let _ = retain;")
    o.append("        ak_dec_counters_reset(ctx);")
    o.append("        d.pull_rc = ak_parse_%s(ctx, b.as_ptr(), b.len());" % root)
    o.append("        (d.pull_fwd, d.pull_rev) = fsm_counters(ctx);")
    o.append("        let mut p: *const u8 = ::core::ptr::null();")
    o.append("        let mut n: usize = 0;")
    o.append("        let mut pull: Vec<FsmRow> = Vec::new();")
    o.append("        if ak_bdr_ptr(ctx, &mut p, &mut n) == AK_OK && n > 0 {")
    o.append("            let recs = ::core::slice::from_raw_parts(p as *const u64, n / 8);")
    o.append("            for (h, body) in ak_rt::bdr::RecIter::new(recs) {")
    o.append("                pull.push((h.op, h.slot, h.token, h.n, fsm_canon_rec_%s(h.op, h.slot, h.n, ::core::slice::from_raw_parts(body, h.bytes as usize))));" % rs)
    o.append("            }")
    o.append("        }")
    if not NOUNK:
        o.append("        let snap = fsm_bump_snapshot();")
        o.append("        let mut o2 = unk_opts_%s(None);" % rs)
        o.append("        let _ = arm(&mut o2);")
        o.append("        fsm_bump_reset();")
    o.append("        ak_dec_counters_reset(ctx);")
    o.append("        let mut fsm: Vec<FsmRow> = Vec::new();")
    o.append("        let mut ev = ak_fsm_ev::default();")
    o.append("        let mut rc = ak_fsm_begin_%s(ctx, b.as_ptr(), b.len(), &mut ev);" % root)
    o.append("        d.calls = 1;")
    o.append("        let mut bad: Option<String> = None;")
    o.append("        while rc > 0 {")
    o.append("            let body = if ev.bytes == 0 { Vec::new() } else { ::core::slice::from_raw_parts(ev.data as *const u8, ev.bytes as usize).to_vec() };")
    o.append("            // The op is the return value (D23 as amended 2026-10-09).")
    o.append("            fsm.push((rc as u32, ev.slot, ev.token, ev.n, fsm_canon_rec_%s(rc as u32, ev.slot, ev.n, &body)));" % rs)
    o.append("            if rc == AK_BDR_APPLY as i32 { break; }")
    o.append("            if fsm.len() > 4 * b.len() + 16 { bad = Some(\"runaway: more events than the input allows\".into()); break; }")
    o.append("            rc = ak_fsm_next_%s(ctx, &mut ev);" % root)
    o.append("            d.calls += 1;")
    o.append("        }")
    o.append("        if rc == 0 { bad = Some(\"begin/next returned 0 (neither an op nor an error)\".into()); }")
    o.append("        d.fsm_rc = rc;")
    o.append("        (d.fsm_fwd, d.fsm_rev) = fsm_counters(ctx);")
    o.append("        // A call after the end or an error is refused.")
    o.append("        let mut ev2 = ak_fsm_ev::default();")
    o.append("        let after = ak_fsm_next_%s(ctx, &mut ev2);" % root)
    o.append("        if bad.is_none() && after != AK_ERR_INVALID_STATE { bad = Some(format!(\"a call after the end returned {after}\")); }")
    if not NOUNK:
        o.append("        let snap2 = fsm_bump_snapshot();")
        o.append("        ak_dec_reset_%s(ctx, ::core::ptr::null_mut());" % root)
        o.append("        (*ctxs.unk).%s_armed.set(false);" % rs)
        o.append("        if bad.is_none() && snap != snap2 { bad = Some(format!(\"unknown-field buffers differ ({} / {} words)\", snap.len(), snap2.len())); }")
    o.append("        ak_dec_set_pvt_%s(ctx, ::core::ptr::null());" % root)
    o.append("        ak_fsm_set_pvt_%s(ctx, ::core::ptr::null());" % root)
    o.append("        d.records = pull.len();")
    o.append("        d.events = fsm.len();")
    o.append("        let want = if d.pull_rc < 0 { d.pull_rc } else { AK_BDR_APPLY as i32 };")
    o.append("        if bad.is_none() && d.fsm_rc != want { bad = Some(format!(\"pull returned {}, the FSM ended with {}\", d.pull_rc, d.fsm_rc)); }")
    o.append("        if bad.is_none() { bad = fsm_rows_cmp(&pull, &fsm); }")
    o.append("        d.mismatch = bad;")
    o.append("    }")
    o.append("    d")
    o.append("}")
    o.append("")
    return o


