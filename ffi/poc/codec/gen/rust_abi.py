def head_of(p):
    return HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")


ZERO = {"i32": "0", "i64": "0", "u8": "0", "f64": "0.0", "u32": "0"}


def _rty(t):
    """A type of the plan's vocabulary in Rust (fixed ABI and RPC)."""
    t = t.strip()
    if t.endswith("?"):
        return "Option<%s>" % _rty(t[:-1])
    if t == "fn(u64)->u64":
        return "unsafe extern \"C\" fn(u64) -> u64"
    if t.startswith("*const "):
        return "*const %s" % _rty(t[len("*const "):])
    if t.startswith("*mut "):
        return "*mut %s" % _rty(t[len("*mut "):])
    return {"void": "c_void", "char": "core::ffi::c_char"}.get(t, t)


RUST_KEYWORDS = {"self", "Self", "type", "match", "ref", "move", "fn", "impl", "loop", "mod",
                 "use", "where", "struct", "enum", "trait", "crate", "super", "box", "in"}


def rust_member(n):
    """A plan member name as a Rust field name (syntax only): a keyword gets a trailing `_`."""
    return n + "_" if n in RUST_KEYWORDS else n


def _rsig(name, params, ret):
    return "%s(%s)%s" % (name, ", ".join("%s: %s" % (a, _rty(t)) for a, t in params),
                         " -> %s" % _rty(ret) if ret else "")


def _camel(snake_name):
    return "".join(p.capitalize() for p in snake_name.split("_"))


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def _zero_of(ty):
    if ty == "ak_str":
        return "ak_str { data: ::core::ptr::null(), len: 0, tc: None }"
    if ty == "ak_span":
        return "ak_span { off: 0, len: 0, coder: 0 }"
    if ty == "ak_blob":
        return "ak_blob { data: ::core::ptr::null(), len: 0 }"
    if ty == "ak_unk_buf":
        return "ak_unk_buf { data: ::core::ptr::null_mut(), len: 0, cap: 0 }"
    if ty in ZERO:
        return ZERO[ty]
    return "%s::ZERO" % ty


