def _init_guard(body):
    """ABI v1 section 3: "Every other entry point requires `ak_init` to have returned
    successfully, the codec included, and returns AK_ERR_UNINITIALIZED if it has not."

    Emitted as a post-pass over the finished body rather than at each of the ten places an
    entry point is written, because the rule is about the SET of entry points and a rule
    applied at nine of ten sites is the defect class this generator keeps finding (D12,
    D13): a walker that misses a case and reports nothing.  Here the pass finds every
    `extern "C" fn ak_*` in the emitted text, so a new entry point gets the guard by
    existing rather than by someone remembering.

    Behind `init-guard`, off by default.  That is a measurement decision and not a design
    one: the claim has a price on the hot path -- `ak_elem_*` runs once per chunk and
    `ak_encode_*` once per message -- and no slice in this branch has quoted it.  With the
    feature off the emitted entry points are byte-for-byte what they were.
    """
    out = []
    i = 0
    n = len(body)
    while i < n:
        ln = body[i]
        out.append(ln)
        if not (ln.startswith("pub unsafe extern \"C\" fn ak_")
                or ln.startswith("pub extern \"C\" fn ak_")):
            i += 1
            continue
        # Walk to the end of the signature, which is the first line ending in `{`.
        j = i
        while j < n and not body[j].rstrip().endswith("{"):
            j += 1
            out.append(body[j])
        if j >= n:
            i = j + 1
            continue
        sig = " ".join(body[i:j + 1])
        if "-> isize" in sig:
            bad = "return AK_ERR_UNINITIALIZED as isize;"
        elif "->" in sig:
            bad = "return AK_ERR_UNINITIALIZED;"
        else:
            bad = "return;"
        out.append("    // ABI v1 section 3: every entry point requires `ak_init`.")
        out.append("    #[cfg(feature = \"init-guard\")]")
        out.append("    if !crate::ak_init_ok() {")
        out.append("        %s" % bad)
        out.append("    }")
        i = j + 1
    return out


class Sites:
    """Length-prefix sites. One learned-width slot per site in the encode context, never
    process-global (ABI v1 section 6). A buffer strategy, so it is the backend's."""

    def __init__(self):
        self.ids = {}

    def id(self, key):
        return self.ids.setdefault(key, len(self.ids))

    def __len__(self):
        return len(self.ids)


def emit_codec(ir):
    ir = as_plan(ir)
    if ir.options.unknown != "both":
        # The C ABI carries BOTH unknown-field behaviours and the host picks per call
        # (`ak_encode_*` / `ak_uencode_*`; `ak_decode_*` with or without the `unknown`
        # slots). A single-mode rendering would be a different ABI, so it is refused
        # rather than emitted with a `u` family that silently drops the bag.
        raise NotImplementedError("the C ABI core renders unknown='both'; got %r" % ir.options.unknown)
    # Refused at generator time, never emitted wrong: a root the ABI cannot carry.
    for root in ir.roots:
        check_expressible(ir, root)
    sites = Sites()
    body = []

    # ---------- encode: one group encoder per message that is a root or an element type.
    # A singular message child is walked INLINE rather than through a call of its own,
    # because "the group carries the whole singular subtree" and because a loop slot living
    # on an inlined child is reached through the parent's vtable: a standalone encoder for
    # the child would have no way to name it.
    def enc_walk(owner, name, gexpr, prefix, o, fail="false", bag=False):
        """Render one message's ENCODE PLAN (`plan.MessagePlan.encode`) over a group.

        The list order is the write order and every presence test is the step's; this
        function chooses only how a group member is read. The `u` family is the same walk
        with the bag: presence constants of the `u` group, and the plan's `unknown_tail`
        step rendered."""
        m = ir.msg(name)
        vt_owner = has_slots(ir, owner)
        pfx = "AK_UFIX_" if bag else "AK_EFIX_"

        def bit(fname):
            return pfx + "%s_PRESENT_%s" % (name.upper(), fname.upper())

        for oname, tags in m.oneof_checks:
            o.append("    // A case this build does not know -- a host generated against a newer")
            o.append("    // descriptor -- is refused before anything is written (plan rule).")
            o.append("    match %s.%s_case {" % (gexpr, oname))
            o.append("        %s => {}" % " | ".join(["0"] + [str(t) for t in tags]))
            o.append("        _ => { (*cx).e.fail(AK_ERR_ABI); return %s; }" % fail)
            o.append("    }")
        oneof_sited = set()
        for st in m.encode:
            f = st.field
            if st.op == "unknown_tail":
                if bag:
                    # The captured runs, verbatim, after every known field (plan rule).
                    o.append("    if !enc_raw(cx, &%s.unknown) { return %s; }" % (gexpr, fail))
                continue
            path = prefix + (f.name,)
            sn = slot_name(path)
            if st.op == "child":
                s = _site(sites, ("child", owner, path))
                o.append("    if %s.presence & %s != 0 {" % (gexpr, bit(f.name)))
                o.append("        let mk = (*cx).e.begin(%d, %d);" % (f.tag, s))
                inner = []
                enc_walk(owner, f.of, "%s.%s" % (gexpr, f.name), path, inner, fail, bag)
                o.extend("    " + ln for ln in inner)
                o.append("        (*cx).e.end(mk);")
                o.append("    }")
            elif st.op == "blob":
                s = _site(sites, ("blob", owner, path))
                v = "%s.%s" % (gexpr, f.name)
                if f.presence == "direct":
                    # A direct field carries the sentinel, never a transcoder.
                    cond = "%s.len != 0" % v
                elif f.presence == "explicit":
                    # Carried by the presence WORD: present-and-empty is still written.
                    cond = "%s.presence & %s != 0" % (gexpr, bit(f.name))
                else:
                    cond = "%s.tc.is_some() && %s.len != 0" % (v, v)
                o.append("    if %s {" % cond)
                o.append("        if !enc_blob(cx, %d, %d, &%s) { return %s; }" % (f.tag, s, v, fail))
                o.append("    }")
            elif st.op == "scalar":
                v = "%s.%s" % (gexpr, f.name)
                if f.presence == "explicit":
                    cond = "%s.presence & %s != 0" % (gexpr, bit(f.name))
                else:
                    cond = _implicit_cond(f, v)
                o.append("    if %s { %s }" % (cond, _enc_value(f, v)))
            elif st.op in ("packed", "repeated_blob", "repeated_message", "map"):
                assert vt_owner
                if f.card == "packed" and f.kind not in PACKED_KIND:
                    raise NotImplementedError(
                        "packed %s (%s.%s): the C ABI has no run symbol for this host "
                        "layout" % (f.kind, name, f.name))
                s = _site(sites, ("loop", owner, path))
                et = elem_type(f)
                o.append("    if let Some(lp) = (*vt).loop_%s {" % sn)
                o.append("        (*cx).open_tag = %d;" % f.tag)
                o.append("        (*cx).open_site = %d;" % s)
                o.append("        (*cx).open_kind = %d;" % PACKED_KIND.get(f.kind if f.card == "packed" else "", 0))
                if et and has_slots(ir, et):
                    o.append("        (*cx).open_vt = (*vt).elem_%s as *const c_void;" % sn)
                o.append("        ak_rt::bump!((*cx).e.c, reverse);")
                o.append("        let rc = lp(cx as *mut ak_enc_ctx, obj, token);")
                o.append("        if rc < 0 { (*cx).e.fail(rc); return %s; }" % fail)
                # R-D6 / ABI v1 section 5: the sticky slot is checked after EVERY upcall.
                o.append("        if (*cx).e.err != 0 || (*cx).hdr.err != AK_OK { return %s; }" % fail)
                o.append("    }")
            elif st.op == "oneof_member":
                oname = st.oneof
                members = m.oneofs[oname]
                if oname not in oneof_sited:
                    # One length-prefix site for the oneof's message members, allocated when
                    # the oneof is first met, before any member's own site.
                    oneof_sited.add(oname)
                    if any(g.kind == "message" for g in members):
                        _site(sites, ("oneofmsg", owner, prefix + (oname,)))
                n = "%s.%s_%s" % (gexpr, oname, f.name)
                o.append("    if %s.%s_case == %d {" % (gexpr, oname, f.tag))
                if f.is_blob:
                    s = _site(sites, ("oneofblob", owner, prefix + (oname, f.name)))
                    o.append("        if !enc_blob(cx, %d, %d, &%s) { return %s; }" % (f.tag, s, n, fail))
                elif f.kind == "message":
                    s = _site(sites, ("oneofmsg", owner, prefix + (oname,)))
                    o.append("        let mk = (*cx).e.begin(%d, %d);" % (f.tag, s))
                    o.append("        if !enc_%s_%sgroup(&%s, cx) { return %s; }"
                             % (snake(f.of), "u" if bag else "", n, fail))
                    o.append("        (*cx).e.end(mk);")
                else:
                    o.append("        %s" % _enc_value(f, n))
                o.append("    }")
            else:
                raise NotImplementedError("encode step %r in %s" % (st.op, name))

    for name in ir.abi_order:
        m = ir.msg(name)
        if (name not in vtable_messages(ir)
                and name not in element_types(ir)
                and name not in oneof_message_members(ir)):
            continue
        slots = has_slots(ir, name)
        body.append("#[inline]")
        if slots:
            body.append("unsafe fn enc_%s_group(" % snake(name))
            body.append("    g: &ak_efix_%s," % name)
            body.append("    cx: *mut EncCtxImpl,")
            body.append("    vt: *const ak_evt_%s," % name)
            body.append("    obj: *const c_void,")
            body.append("    token: i64,")
            body.append(") -> bool {")
        else:
            body.append("unsafe fn enc_%s_group(g: &ak_efix_%s, cx: *mut EncCtxImpl) -> bool {"
                        % (snake(name), name))
        enc_walk(name, name, "g", (), body)
        body.append("    true")
        body.append("}")
        body.append("")
        # The same group, walked again with the bag slot. ABI v1 open decision 11
        # candidate; the `e` family above is untouched.
        body.append("#[inline]")
        if slots:
            body.append("unsafe fn enc_%s_ugroup(" % snake(name))
            body.append("    g: &ak_ufix_%s," % name)
            body.append("    cx: *mut EncCtxImpl,")
            body.append("    vt: *const ak_evt_%s," % name)
            body.append("    obj: *const c_void,")
            body.append("    token: i64,")
            body.append(") -> bool {")
        else:
            body.append("unsafe fn enc_%s_ugroup(g: &ak_ufix_%s, cx: *mut EncCtxImpl) -> bool {"
                        % (snake(name), name))
        enc_walk(name, name, "g", (), body, bag=True)
        body.append("    true")
        body.append("}")
        body.append("")

    for et in sorted(element_types(ir)):
        m = ir.msg(et)
        if m.leaf:
            body.append("#[no_mangle]")
            body.append("pub unsafe extern \"C\" fn ak_elem_%s(" % et)
            body.append("    ctx: *mut ak_enc_ctx,")
            body.append("    elems: *const ak_efix_%s," % et)
            body.append("    n: i32,")
            body.append(") -> i32 {")
            body.append("    let cx = ctx as *mut EncCtxImpl;")
            body.append("    ak_rt::bump!((*cx).e.c, forward);")
            body.extend(SAVE_LINES)
            body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
            body.append("    for i in 0..n as usize {")
            body.append("        let mk = (*cx).e.begin(tag, site);")
            body.append("        if !enc_%s_group(&*elems.add(i), cx) { return crate::enc_status(cx); }" % snake(et))
            body.append("        (*cx).e.end(mk);")
            body.append("    }")
            body.extend(RESTORE_LINES)
            body.append("    AK_OK")
            body.append("}")
            body.append("")
            body.append("/// The same run over the group that carries the unknown-field bag.")
            body.append("#[no_mangle]")
            body.append("pub unsafe extern \"C\" fn ak_uelem_%s(" % et)
            body.append("    ctx: *mut ak_enc_ctx,")
            body.append("    elems: *const ak_ufix_%s," % et)
            body.append("    n: i32,")
            body.append(") -> i32 {")
            body.append("    let cx = ctx as *mut EncCtxImpl;")
            body.append("    ak_rt::bump!((*cx).e.c, forward);")
            body.extend(SAVE_LINES)
            body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
            body.append("    for i in 0..n as usize {")
            body.append("        let mk = (*cx).e.begin(tag, site);")
            body.append("        if !enc_%s_ugroup(&*elems.add(i), cx) { return crate::enc_status(cx); }" % snake(et))
            body.append("        (*cx).e.end(mk);")
            body.append("    }")
            body.extend(RESTORE_LINES)
            body.append("    AK_OK")
            body.append("}")
        else:
            body.append("#[no_mangle]")
            body.append("pub unsafe extern \"C\" fn ak_elemu_%s(" % et)
            body.append("    ctx: *mut ak_enc_ctx,")
            body.append("    elems: *const ak_efix_%s," % et)
            body.append("    n: i32,")
            body.append("    tok0: i64,")
            body.append(") -> i32 {")
            body.append("    let cx = ctx as *mut EncCtxImpl;")
            body.append("    ak_rt::bump!((*cx).e.c, forward);")
            body.extend(SAVE_LINES)
            body.append("    // Read the open state into locals BEFORE the run: encoding an")
            body.append("    // element makes reverse calls that open fields of their own.")
            body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
            body.append("    let vt = (*cx).open_vt as *const ak_evt_%s;" % et)
            body.append("    let obj = (*cx).open_obj;")
            body.append("    for i in 0..n as usize {")
            body.append("        let mk = (*cx).e.begin(tag, site);")
            body.append("        if !enc_%s_group(&*elems.add(i), cx, vt, obj, tok0 + i as i64) {"
                        % snake(et))
            body.append("            return crate::enc_status(cx);")
            body.append("        }")
            body.append("        (*cx).e.end(mk);")
            body.append("    }")
            body.extend(RESTORE_LINES)
            body.append("    AK_OK")
            body.append("}")
            body.append("")
            body.append("/// The same unbatched run over the group that carries the bag.")
            body.append("#[no_mangle]")
            body.append("pub unsafe extern \"C\" fn ak_uelemu_%s(" % et)
            body.append("    ctx: *mut ak_enc_ctx,")
            body.append("    elems: *const ak_ufix_%s," % et)
            body.append("    n: i32,")
            body.append("    tok0: i64,")
            body.append(") -> i32 {")
            body.append("    let cx = ctx as *mut EncCtxImpl;")
            body.append("    ak_rt::bump!((*cx).e.c, forward);")
            body.extend(SAVE_LINES)
            body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
            body.append("    let vt = (*cx).open_vt as *const ak_evt_%s;" % et)
            body.append("    let obj = (*cx).open_obj;")
            body.append("    for i in 0..n as usize {")
            body.append("        let mk = (*cx).e.begin(tag, site);")
            body.append("        if !enc_%s_ugroup(&*elems.add(i), cx, vt, obj, tok0 + i as i64) {"
                        % snake(et))
            body.append("            return crate::enc_status(cx);")
            body.append("        }")
            body.append("        (*cx).e.end(mk);")
            body.append("    }")
            body.extend(RESTORE_LINES)
            body.append("    AK_OK")
            body.append("}")
        body.append("")

    for root in ir.roots:
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_encode_%s(" % root)
        body.append("    obj: *const c_void,")
        body.append("    ctx: *mut ak_enc_ctx,")
        body.append("    vt: *const ak_evt_%s," % root)
        body.append("    fix: *const ak_efix_%s," % root)
        if direct_fields(ir, root):
            body.append("    direct: *const u8,")
            body.append("    direct_len: usize,")
        body.append(") -> isize {")
        body.append("    let cx = ctx as *mut EncCtxImpl;")
        body.append("    ak_rt::bump!((*cx).e.c, forward);")
        body.append("    (*cx).open_obj = obj;")
        if direct_fields(ir, root):
            body.append("    (*cx).direct = direct;")
            body.append("    (*cx).direct_len = direct_len;")
        body.append("    let g = &*fix;")
        body.append("    let token = AK_TOKEN_ROOT;")
        body.append("    let _ = token;")
        inner = []
        enc_walk(root, root, "g", (), inner, fail="crate::enc_status(cx) as isize")
        body.extend(inner)
        body.append("    let st = crate::enc_status(cx);")
        body.append("    if st != AK_OK { return st as isize; }")
        body.append("    (*cx).e.buf.len() as isize")
        body.append("}")
        body.append("")
        # The same root entry with the bag. ABI v1 open decision 11 candidate.
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_uencode_%s(" % root)
        body.append("    obj: *const c_void,")
        body.append("    ctx: *mut ak_enc_ctx,")
        body.append("    vt: *const ak_evt_%s," % root)
        body.append("    fix: *const ak_ufix_%s," % root)
        if direct_fields(ir, root):
            body.append("    direct: *const u8,")
            body.append("    direct_len: usize,")
        body.append(") -> isize {")
        body.append("    let cx = ctx as *mut EncCtxImpl;")
        body.append("    ak_rt::bump!((*cx).e.c, forward);")
        body.append("    (*cx).open_obj = obj;")
        if direct_fields(ir, root):
            body.append("    (*cx).direct = direct;")
            body.append("    (*cx).direct_len = direct_len;")
        body.append("    let g = &*fix;")
        body.append("    let token = AK_TOKEN_ROOT;")
        body.append("    let _ = token;")
        inner = []
        enc_walk(root, root, "g", (), inner, fail="crate::enc_status(cx) as isize", bag=True)
        body.extend(inner)
        body.append("    let st = crate::enc_status(cx);")
        body.append("    if st != AK_OK { return st as isize; }")
        body.append("    (*cx).e.buf.len() as isize")
        body.append("}")
        body.append("")

    body.append("#[no_mangle]")
    body.append("pub unsafe extern \"C\" fn ak_blob_run(")
    body.append("    ctx: *mut ak_enc_ctx,")
    body.append("    elems: *const ak_str,")
    body.append("    n: i32,")
    body.append(") -> i32 {")
    body.append("    let cx = ctx as *mut EncCtxImpl;")
    body.append("    ak_rt::bump!((*cx).e.c, forward);")
    body.append("    if crate::enc_status(cx) != AK_OK { return crate::enc_status(cx); }")
    body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
    body.append("    for i in 0..n as usize {")
    body.append("        if !enc_blob(cx, tag, site, &*elems.add(i)) { return crate::enc_status(cx); }")
    body.append("    }")
    body.append("    AK_OK")
    body.append("}")
    body.append("")
    for ty in ("i32", "i64", "f64", "u8"):
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_run_%s(ctx: *mut ak_enc_ctx, p: *const %s, n: usize) -> i32 {"
                    % (ty, ty))
        body.append("    let cx = ctx as *mut EncCtxImpl;")
        body.append("    ak_rt::bump!((*cx).e.c, forward);")
        body.append("    if crate::enc_status(cx) != AK_OK { return crate::enc_status(cx); }")
        body.append("    if n == 0 { return AK_OK; }")
        body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
        body.append("    let mk = (*cx).e.begin(tag, site);")
        body.append("    // The wire encoding comes from the schema and lives in the context,")
        body.append("    // so bool and enum need no symbols of their own.")
        body.append("    for i in 0..n {")
        body.append("        let v = *p.add(i);")
        if ty == "f64":
            body.append("        (*cx).e.buf.extend_from_slice(&v.to_le_bytes());")
        elif ty == "i32":
            body.append("        (*cx).e.varint(v as i64 as u64);")
        else:
            body.append("        (*cx).e.varint(v as u64);")
        body.append("    }")
        body.append("    (*cx).e.end(mk);")
        body.append("    AK_OK")
        body.append("}")
        body.append("")

    body.extend(_emit_decode(ir, sites))
    body = _init_guard(body)

    global SITE_NAMES
    SITE_NAMES = ["/".join(str(x) for x in (k[0], k[1], ".".join(k[2]))) for k in sites.ids]
    o = [head_of(ir),
         "//! The core behind the C ABI, rendered from the plans of `poc/codec/gen/plan.py`.",
         "//! `core-native` is rendered from the SAME plans (`gen/rust_native.py`); the only",
         "//! difference between the two is where a value comes from: a group the host filled",
         "//! here, a facade object there (R-E1).",
         "#![allow(non_snake_case, non_camel_case_types, unused_unsafe, unused_variables,",
         "    unused_assignments, unused_mut, unused_macros, clippy::all)]",
         "use crate::{enc_blob, enc_raw, DecCtxImpl, EncCtxImpl, UnkBuf};",
         "use ak_abi::*;",
         "use ak_rt::dec::Dec;",
         "use core::ffi::c_void;",
         "",
         "/// One learned length-prefix slot per site. Per context, never process-global.",
         "pub const SITES: usize = %d;" % len(sites),
         ""]
    o += body
    return "\n".join(o)


PACKED_KIND = {"int32": 1, "int64": 2, "bool": 3, "double": 4, "enum": 5}


# ============================================================== the core, decode

def _push_elemcall(root, sn, dexpr, baseexpr):
    """The push family's deposit for a non-leaf element: a call that will make reverse
    calls of its own."""
    return "dec_%s_%s_element(ctx, dcx, obj, vt, %s, %s)" % (snake(root), sn, dexpr, baseexpr)


def _pull_elemcall(root, sn, dexpr, baseexpr):
    """The pull family's, into the record buffer. Same arguments, no `obj` and no `vt`,
    because a parse makes no upcall at all -- which is the property the JVM needs and the
    reason section 7.1 carries two families."""
    return "dec_%s_%s_element_pull(dcx, %s, %s)" % (snake(root), sn, dexpr, baseexpr)


def _emit_decode(ir, sites):
    """The push family (ABI v1 section 7.1), with section 7.2's batching predicate.

    Every arena is a local of the entry point or of the element decoder, so it is per decode
    rather than per thread: reentrant by construction, and never a thread-local.

    Every arena is flushed the moment a tag arrives that does not belong to it. That is
    correctness and not tidiness: protobuf permits a repeated field's occurrences to be
    interleaved with other fields', so `A B A B` is legal wire, and prost writing each field
    contiguously is a property of prost rather than of the format.
    """
    out = []

    def dec_walk(root, name, fxexpr, prefix, bufname, basename, depth, slot_id, o,
                 elemcall=None):
        """Render one message's DECODE PLAN (`plan.MessagePlan.decode`) as match arms.

        Every (field number, wire type) pair in the table becomes one arm; a pair that is
        not in the table falls through to the caller's `_` arm, which skips it as an
        unknown field -- so a known field number at the wrong wire type is skipped for
        every kind alike (R-E2), because the table simply has no arm for it. Recurses into
        a singular message child, which the group inlines and whose loop slots are the
        parent's; that recursion is what makes a repeated occurrence MERGE (plan rule).

        The push family and the pull family (ABI v1 section 7.1) share this verbatim; they
        differ in `elemcall` (where a non-leaf element goes), the `flush_*` macros and the
        entry point's epilogue, all emitted around it. Readers are named by depth
        (`d`, `c1`, `c2`, ...) so an error at any depth reaches its parent's reader: the
        previous emitter named every nested reader `cd`, and at depth two its propagation
        line assigned a reader's error to itself."""
        if elemcall is None:
            elemcall = _push_elemcall
        m = ir.msg(name)
        rd = "d" if depth == 0 else "c%d" % depth
        pol_reject = ir.options.utf8 == "reject"

        def utf8_check(f, bufx, off, n, reader):
            # Plan rule: a `string` is validated on decode under utf8="reject".
            if f.utf8 and pol_reject:
                o.append("                if %s != 0 && ak_rt::strings::check_utf8(&%s[%s..%s + %s]).is_err() { %s.err = ak_rt::ERR_TRANSCODE; }"
                         % (n, bufx, off, off, n, reader))

        def rd_expr(read, reader):
            return {"varint_i32": "%s.varint() as i32", "varint_i64": "%s.varint() as i64",
                    "varint_bool": "(%s.varint() != 0) as u8", "fixed64_f64": "%s.f64()",
                    "fixed32_u32": "%s.fixed32()"}[read] % reader

        def dbit(fname):
            return "AK_DFIX_%s_PRESENT_%s" % (name.upper(), fname.upper())

        for (tag, wire), act in sorted(m.decode.items()):
            f = act.field
            path = prefix + (f.name,)
            sn = slot_name(path)
            op = act.op
            if op == "merge_child":
                nd = depth + 1
                crd, nb, nbuf = "c%d" % nd, "base%d" % nd, "buf%d" % nd
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != 0 { flush!(); cur = 0; }")
                o.append("                let (coff, clen) = %s.len_body();" % rd)
                o.append("                let %s = %s + coff;" % (nb, basename))
                o.append("                let %s = &%s[coff..coff + clen];" % (nbuf, bufname))
                o.append("                let mut %s = Dec::new(%s);" % (crd, nbuf))
                o.append("                %s.presence |= %s;" % (fxexpr, dbit(f.name)))
                o.append("                while !%s.at_end() {" % crd)
                o.append("                    let k = %s.varint();" % crd)
                o.append("                    if %s.err != 0 { break; }" % crd)
                o.append("                    let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
                o.append("                    if tag == 0 { %s.err = ak_rt::ERR_MALFORMED; break; }" % crd)
                o.append("                    match tag {")
                sub = []
                dec_walk(root, f.of, "%s.%s" % (fxexpr, f.name), path, nbuf, nb, nd, slot_id,
                         sub, elemcall)
                o.extend("        " + ln for ln in sub)
                o.append("                        _ => %s.skip(tag, wire)," % crd)
                o.append("                    }")
                o.append("                }")
                o.append("                if %s.err != 0 { %s.err = %s.err; }" % (crd, rd, crd))
                o.append("            }")
            elif op == "set_blob":
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != 0 { flush!(); cur = 0; }")
                o.append("                let (off, n) = %s.len_body();" % rd)
                utf8_check(f, bufname, "off", "n", rd)
                o.append("                %s.%s = ak_span { off: (%s + off) as u32, len: n as u32, coder: 0 };"
                         % (fxexpr, f.name, basename))
                if f.explicit:
                    o.append("                %s.presence |= %s;" % (fxexpr, dbit(f.name)))
                o.append("            }")
            elif op == "set_scalar":
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != 0 { flush!(); cur = 0; }")
                o.append("                %s.%s = %s;" % (fxexpr, f.name, rd_expr(act.read, rd)))
                if f.explicit:
                    o.append("                %s.presence |= %s;" % (fxexpr, dbit(f.name)))
                o.append("            }")
            elif op == "append_message" and not ir.msg(f.of).leaf:
                # A non-leaf element: no batching (ABI v1 section 7.2).
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != 0 { flush!(); cur = 0; }")
                o.append("                let (off, n) = %s.len_body();" % rd)
                o.append("                let mut sub = Dec::new(&%s[off..off + n]);" % bufname)
                o.append("                %s;" % elemcall(root, sn, "&mut sub", "%s + off" % basename))
                o.append("                if sub.err != 0 { %s.err = sub.err; }" % rd)
                o.append("            }")
            elif op in ("append_message", "map_entry"):
                sid = slot_id[sn]
                et = elem_type(f)
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != %d { flush!(); cur = %d; }" % (sid, sid))
                o.append("                if n_%s == N_%s { flush_%s!(); }" % (sn, sn.upper(), sn))
                o.append("                let (off, n) = %s.len_body();" % rd)
                o.append("                let mut es = Dec::new(&%s[off..off + n]);" % bufname)
                o.append("                if !uk_%s.is_null() { (*uk_%s).token = (%s + n_%s) as i64; }"
                         % (sn, sn, "done_%s" % sn, sn))
                o.append("                a_%s[n_%s].write(dec_%s_fix(&mut es, %s + off, uk_%s));"
                         % (sn, sn, snake(et), basename, sn))
                o.append("                if es.err != 0 { %s.err = es.err; }" % rd)
                o.append("                n_%s += 1;" % sn)
                o.append("            }")
            elif op == "append_blob":
                sid = slot_id[sn]
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != %d { flush!(); cur = %d; }" % (sid, sid))
                o.append("                if n_%s == N_%s { flush_%s!(); }" % (sn, sn.upper(), sn))
                o.append("                let (off, n) = %s.len_body();" % rd)
                utf8_check(f, bufname, "off", "n", rd)
                o.append("                a_%s[n_%s].write(ak_span { off: (%s + off) as u32, len: n as u32, coder: 0 });"
                         % (sn, sn, basename))
                o.append("                n_%s += 1;" % sn)
                o.append("            }")
            elif op == "packed_run":
                sid = slot_id[sn]
                one = rd_expr(act.read, "ps")
                if f.kind == "bool":
                    one = "(ps.varint() != 0) as u8"
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != %d { flush!(); cur = %d; }" % (sid, sid))
                o.append("                let (off, n) = %s.len_body();" % rd)
                o.append("                let mut ps = Dec::new(&%s[off..off + n]);" % bufname)
                o.append("                while !ps.at_end() {")
                o.append("                    if n_%s == N_%s { flush_%s!(); }" % (sn, sn.upper(), sn))
                o.append("                    let v = %s;" % one)
                o.append("                    if ps.err != 0 { break; }")
                o.append("                    a_%s[n_%s].write(v);" % (sn, sn))
                o.append("                    n_%s += 1;" % sn)
                o.append("                }")
                o.append("                if ps.err != 0 { %s.err = ps.err; }" % rd)
                o.append("            }")
            elif op == "packed_one":
                sid = slot_id[sn]
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != %d { flush!(); cur = %d; }" % (sid, sid))
                o.append("                if n_%s == N_%s { flush_%s!(); }" % (sn, sn.upper(), sn))
                o.append("                let v = %s;" % rd_expr(act.read, rd))
                o.append("                if %s.err == 0 { a_%s[n_%s].write(v); n_%s += 1; }" % (rd, sn, sn, sn))
                o.append("            }")
            elif op == "oneof_set":
                oname = act.oneof
                n = "%s.%s_%s" % (fxexpr, oname, f.name)
                o.append("            %d if wire == %d => {" % (tag, wire))
                o.append("                if cur != 0 { flush!(); cur = 0; }")
                if f.is_blob:
                    o.append("                let (off, n) = %s.len_body();" % rd)
                    utf8_check(f, bufname, "off", "n", rd)
                    o.append("                %s = ak_span { off: (%s + off) as u32, len: n as u32, coder: 0 };"
                             % (n, basename))
                elif f.kind == "message":
                    if not ir.msg(f.of).leaf:
                        raise NotImplementedError(
                            "a non-leaf message as a oneof member (%s.%s): its loop slots "
                            "would have no vtable to reach" % (name, f.name))
                    o.append("                let (off, n) = %s.len_body();" % rd)
                    o.append("                let mut os = Dec::new(&%s[off..off + n]);" % bufname)
                    o.append("                // Plan rule: the SAME member again merges; another member,")
                    o.append("                // or none, starts from empty.")
                    o.append("                if %s.%s_case != %d { %s = ak_dfix_%s::ZERO; }"
                             % (fxexpr, oname, f.tag, n, f.of))
                    # A oneof's message member has no capture of its own in the ABI: its
                    # unknown fields are skipped, in retain mode too (reported, not hidden).
                    o.append("                dec_%s_fix_into(&mut os, %s + off, ::core::ptr::null_mut(), &mut %s);"
                             % (snake(f.of), basename, n))
                    o.append("                if os.err != 0 { %s.err = os.err; }" % rd)
                else:
                    o.append("                %s = %s;" % (n, rd_expr(act.read, rd)))
                o.append("                // Last one wins: a later member replaces the case.")
                o.append("                %s.%s_case = %d;" % (fxexpr, oname, f.tag))
                o.append("            }")
            else:
                raise NotImplementedError("decode action %r (%s.%s)" % (op, name, f.name))

    def arena_decl(sn, dty, o, indent="    ", unkcb=None):
        o.append("%s// ABI v1 7.3: a byte budget divided by the group size, not an element" % indent)
        o.append("%s// count, so the scratch is the same 32 KB whatever the schema does." % indent)
        o.append("%sconst N_%s: usize = ak_rt::arena_n(::core::mem::size_of::<%s>());"
                 % (indent, sn.upper(), dty))
        o.append("%slet mut a_%s: [::core::mem::MaybeUninit<%s>; N_%s] =" % (indent, sn, dty, sn.upper()))
        o.append("%s    [const { ::core::mem::MaybeUninit::uninit() }; N_%s];" % (indent, sn.upper()))
        o.append("%slet mut n_%s: usize = 0;" % (indent, sn))
        o.append("%s// How many elements of this slot have already been handed over, so an" % indent)
        o.append("%s// unknown run can name its element as an INDEX (decision 11 candidate)." % indent)
        o.append("%slet mut done_%s: usize = 0;" % (indent, sn))
        o.append("%slet _ = done_%s;" % (indent, sn))
        if unkcb:
            o.append("%slet mut ub_%s = UnkBuf::new((*vt).%s, ctx, obj);" % (indent, sn, unkcb))
            o.append("%slet uk_%s: *mut UnkBuf = if ub_%s.cb.is_some() { &mut ub_%s } else { ::core::ptr::null_mut() };"
                     % (indent, sn, sn, sn))
        else:
            o.append("%slet uk_%s: *mut UnkBuf = ::core::ptr::null_mut();" % (indent, sn))

    def flush_macros(slots, tokarg, o, family="push"):
        """One macro per slot, and one that flushes them all.

        **The deposit point.** For `push` a flush is a reverse call into the host; for
        `pull` it is a record appended to the host-owned buffer of section 7.1. Everything
        that decides WHEN a flush happens -- 7.2's batching predicate, 7.3's flush on a tag
        that does not belong to the open batch, the arena filling up -- is emitted by
        `dec_walk` and `arena_decl` and is identical in both families. This is the only
        place the two differ, and `slots` carries per-family what it needs: the vtable
        member for push, the record's slot id for pull."""
        for sn, dty, extra in slots:
            o.append("    macro_rules! flush_%s {" % sn)
            o.append("        () => {")
            o.append("            if n_%s > 0 {" % sn)
            if family == "push":
                # R-D6 / ABI v1 section 5: no upcall once the host has failed the
                # operation, and the slot is read after every upcall so the reader stops.
                o.append("                if let Some(add) = (*vt).%s {" % extra)
                o.append("                    if (*dcx).hdr.err == AK_OK {")
                o.append("                        ak_rt::bump!((*dcx).c, reverse);")
                o.append("                        add(ctx, obj, %s, a_%s.as_ptr() as *const %s, n_%s as i32);"
                         % (tokarg, sn, dty, sn))
                o.append("                    }")
                o.append("                }")
            else:
                o.append("                // No call: the run is copied into the record buffer and the")
                o.append("                // host reads it after `ak_parse_*` returns.")
                o.append("                (*dcx).bdr.push(")
                o.append("                    ak_rt::bdr::OP_ADD,")
                o.append("                    %d," % extra)
                o.append("                    %s," % tokarg)
                o.append("                    n_%s as u32," % sn)
                o.append("                    a_%s.as_ptr() as *const u8," % sn)
                o.append("                    n_%s * ::core::mem::size_of::<%s>()," % (sn, dty))
                o.append("                );")
            o.append("                done_%s += n_%s;" % (sn, sn))
            o.append("                n_%s = 0;" % sn)
            o.append("                if !uk_%s.is_null() { (*uk_%s).flush(); }" % (sn, sn))
            if family == "push":
                o.append("                if (*dcx).hdr.err != AK_OK && d.err == 0 { d.err = (*dcx).hdr.err; }")
            o.append("            }")
            o.append("        };")
            o.append("    }")
        o.append("    macro_rules! flush {")
        o.append("        () => {")
        for sn, _, _ in slots:
            o.append("            flush_%s!();" % sn)
        o.append("        };")
        o.append("    }")

    # ---- leaf fix decoders: element types, and the message members of a oneof
    for name in sorted(element_types(ir) | oneof_message_members(ir)):
        if not ir.msg(name).leaf:
            continue
        out.append("#[inline]")
        out.append("unsafe fn dec_%s_fix(d: &mut Dec, base: usize, unk: *mut UnkBuf) -> ak_dfix_%s {" % (snake(name), name))
        out.append("    let mut out = ak_dfix_%s::ZERO;" % name)
        out.append("    dec_%s_fix_into(d, base, unk, &mut out);" % snake(name))
        out.append("    out")
        out.append("}")
        out.append("")
        out.append("/// Decode INTO an existing group: what a oneof's message member needs to merge a")
        out.append("/// repeated occurrence (plan rule), and what `dec_%s_fix` wraps." % snake(name))
        out.append("#[inline]")
        out.append("unsafe fn dec_%s_fix_into(d: &mut Dec, base: usize, unk: *mut UnkBuf, out: &mut ak_dfix_%s) {" % (snake(name), name))
        out.append("    #[allow(unused_variables)]")
        out.append("    let buf0 = d.buf;")
        out.append("    let base0 = base;")
        out.append("    let mut cur = 0u32;")
        out.append("    macro_rules! flush { () => { }; }")
        out.append("    while !d.at_end() {")
        out.append("        // Decision 11 candidate: where this field's tag-and-value run starts,")
        out.append("        // so an unknown one can be handed over as a span rather than dropped.")
        out.append("        let s0 = d.pos;")
        out.append("        let k = d.varint();")
        out.append("        if d.err != 0 { break; }")
        out.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        out.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
        out.append("        match tag {")
        dec_walk(name, name, "out", (), "buf0", "base0", 0, {}, out)
        out.append("            _ => {")
        out.append("                d.skip(tag, wire);")
        out.append("                if !unk.is_null() {")
        out.append("                    (*unk).push(base0 + s0, d.pos - s0);")
        out.append("                    // R-D6: the push may have delivered a chunk; stop if the host failed.")
        out.append("                    let he = (*unk).host_err();")
        out.append("                    if he != AK_OK && d.err == 0 { d.err = he; }")
        out.append("                }")
        out.append("            }")
        out.append("        }")
        out.append("    }")
        out.append("}")
        out.append("")

    # ---- non-leaf element decoders, one per (root, slot)
    for root in ir.roots:
        for path, f in loop_slots(ir, root):
            et = elem_type(f)
            if not et or ir.msg(et).leaf:
                continue
            sn = slot_name(path)
            inner_slots = loop_slots(ir, et)
            sid = {slot_name(p): i + 1 for i, (p, _) in enumerate(inner_slots)}
            out.append("/// `%s` is not batchable: it carries repeated or map fields of its own," % et)
            out.append("/// so there would be nothing to attach the inner elements to. Two calls")
            out.append("/// per element -- `new` then `apply` -- plus one run per inner field that")
            out.append("/// occurred (ABI v1 section 7.2).")
            out.append("unsafe fn dec_%s_%s_element(" % (snake(root), sn))
            out.append("    ctx: *mut ak_dec_ctx,")
            out.append("    dcx: *mut DecCtxImpl,")
            out.append("    obj: *mut c_void,")
            out.append("    vt: *const ak_dvt_%s," % root)
            out.append("    d: &mut Dec,")
            out.append("    base: usize,")
            out.append(") {")
            out.append("    let tok = match (*vt).new_%s {" % sn)
            out.append("        Some(f) => {")
            out.append("            ak_rt::bump!((*dcx).c, reverse);")
            out.append("            f(ctx, obj)")
            out.append("        }")
            out.append("        None => return,")
            out.append("    };")
            # R-D6: the host failed the operation (or could not make the element: a
            # negative token is a refusal, not "skip this one"). Stop the reader, so the
            # root loop makes no further upcall; before this the element was silently
            # dropped and the next element called `new` again.
            out.append("    if (*dcx).hdr.err != AK_OK { d.err = (*dcx).hdr.err; return; }")
            out.append("    if tok < 0 { crate::ak_fail(ctx as *mut c_void, AK_ERR_HOST, ::core::ptr::null(), 0); d.err = AK_ERR_HOST; return; }")
            out.append("    let mut out = ak_dfix_%s::ZERO;" % et)
            out.append("    #[allow(unused_variables)]")
            out.append("    let buf0 = d.buf;")
            out.append("    let base0 = base;")
            out.append("    // Retain (plan rule): the element's OWN unknown fields, keyed by its token,")
            out.append("    // through the slot's `unk_` callback. Before WP5 a non-leaf element captured")
            out.append("    // nothing, so retain mode dropped them (`U-element-*`, `U-chunkelem-*`).")
            out.append("    let mut ub_el = UnkBuf::new((*vt).unk_%s, ctx, obj);" % sn)
            out.append("    ub_el.token = tok;")
            out.append("    let uk_el: *mut UnkBuf = if ub_el.cb.is_some() { &mut ub_el } else { ::core::ptr::null_mut() };")
            slots = []
            for ipath, iff in inner_slots:
                isn = slot_name(ipath)
                idty, _ = slot_elem_rust(iff)
                arena_decl(isn, idty, out)
                slots.append((isn, idty, "add_%s_%s" % (sn, isn)))
            flush_macros(slots, "tok", out)
            out.append("    let mut cur = 0u32;")
            out.append("    while !d.at_end() {")
            out.append("        let s0 = d.pos;")
            out.append("        let k = d.varint();")
            out.append("        if d.err != 0 { break; }")
            out.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
            out.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
            out.append("        match tag {")
            dec_walk(root, et, "out", (), "buf0", "base0", 0, sid, out)
            out.append("            _ => {")
            out.append("                if cur != 0 { flush!(); cur = 0; }")
            out.append("                d.skip(tag, wire);")
            out.append("                if !uk_el.is_null() {")
            out.append("                    (*uk_el).push(base0 + s0, d.pos - s0);")
            out.append("                    if (*dcx).hdr.err != AK_OK && d.err == 0 { d.err = (*dcx).hdr.err; }")
            out.append("                }")
            out.append("            }")
            out.append("        }")
            out.append("    }")
            # R-D1: do NOT deliver this element after a decode error. On malformed wire
            # `d.err` is set and the collected spans point at nothing valid; delivering
            # them (flush!()/apply) is what let a host read out of bounds. On valid input
            # `d.err == 0`, so the output is byte-identical.
            out.append("    if d.err == 0 {")
            out.append("        flush!();")
            out.append("    }")
            out.append("    if d.err == 0 && !uk_el.is_null() {")
            out.append("        (*uk_el).flush();")
            out.append("        if (*dcx).hdr.err != AK_OK { d.err = (*dcx).hdr.err; }")
            out.append("    }")
            out.append("    if d.err == 0 {")
            out.append("        if let Some(ap) = (*vt).apply_%s {" % sn)
            out.append("            ak_rt::bump!((*dcx).c, reverse);")
            out.append("            ap(ctx, obj, tok, &out);")
            out.append("            if (*dcx).hdr.err != AK_OK { d.err = (*dcx).hdr.err; }")
            out.append("        }")
            out.append("    }")
            out.append("}")
            out.append("")

    # ---- root decode entry points
    for root in ir.roots:
        rslots = loop_slots(ir, root)
        sid = {slot_name(p): i + 1 for i, (p, _) in enumerate(rslots)}
        out.append("#[no_mangle]")
        out.append("pub unsafe extern \"C\" fn ak_decode_%s(" % root)
        out.append("    ctx: *mut ak_dec_ctx,")
        out.append("    obj: *mut c_void,")
        out.append("    buf: *const u8,")
        out.append("    len: usize,")
        out.append("    vt: *const ak_dvt_%s," % root)
        out.append(") -> i32 {")
        out.append("    let dcx = ctx as *mut DecCtxImpl;")
        out.append("    ak_rt::bump!((*dcx).c, forward);")
        out.append("    // ABI v1 section 5: the slot is sticky and the FIRST error wins, which is a rule")
        out.append("    // about ONE operation. A new decode starts here, so nothing can be lost by")
        out.append("    // clearing it and a context that carried a failure would otherwise poison every")
        out.append("    // later decode. Doing it here rather than in the host costs no extra crossing")
        out.append("    // and takes the obligation off the binding author.")
        out.append("    (*dcx).hdr.err = AK_OK;")
        out.append("    // R-D9: spans are (u32, u32) into this buffer, so a buffer longer than")
        out.append("    // u32::MAX would alias offsets and lengths. Reject at entry rather than")
        out.append("    // truncate. `usize` is 64-bit on every host this ships to.")
        out.append("    if len > u32::MAX as usize {")
        out.append("        (*dcx).hdr.err = AK_ERR_LIMIT;")
        out.append("        return AK_ERR_LIMIT;")
        out.append("    }")
        out.append("    let buf0 = ::core::slice::from_raw_parts(buf, len);")
        out.append("    let base0 = 0usize;")
        out.append("    let mut d = Dec::new(buf0);")
        out.append("    let mut out = ak_dfix_%s::ZERO;" % root)
        slots = []
        for path, f in rslots:
            et = elem_type(f)
            if et and not ir.msg(et).leaf:
                continue
            sn = slot_name(path)
            dty, _ = slot_elem_rust(f)
            arena_decl(sn, dty, out, unkcb=("unk_%s" % sn) if elem_type(f) else None)
            slots.append((sn, dty, "add_%s" % sn))
        flush_macros(slots, "AK_TOKEN_ROOT", out)
        out.append("    // Decision 11 candidate: the ROOT message's own unknown fields.")
        out.append("    let mut ub_root = UnkBuf::new((*vt).unknown, ctx, obj);")
        out.append("    let uk_root: *mut UnkBuf = if ub_root.cb.is_some() { &mut ub_root } else { ::core::ptr::null_mut() };")
        out.append("    let mut cur = 0u32;")
        out.append("    while !d.at_end() {")
        out.append("        let s0 = d.pos;")
        out.append("        let k = d.varint();")
        out.append("        if d.err != 0 { break; }")
        out.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        out.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
        out.append("        match tag {")
        dec_walk(root, root, "out", (), "buf0", "base0", 0, sid, out)
        out.append("            _ => {")
        out.append("                if cur != 0 { flush!(); cur = 0; }")
        out.append("                d.skip(tag, wire);")
        out.append("                if !uk_root.is_null() {")
        out.append("                    (*uk_root).push(base0 + s0, d.pos - s0);")
        out.append("                    if (*dcx).hdr.err != AK_OK && d.err == 0 { d.err = (*dcx).hdr.err; }")
        out.append("                }")
        out.append("            }")
        out.append("        }")
        out.append("    }")
        # R-D1: on a decode error, deliver nothing. The trailing flush!()/apply after the
        # loop is exactly what handed a host the group it then read out of bounds. On valid
        # input `d.err == 0`, so the delivered bytes are byte-identical.
        out.append("    if d.err == 0 {")
        out.append("        flush!();")
        out.append("    }")
        out.append("    if d.err == 0 && !uk_root.is_null() {")
        out.append("        (*uk_root).flush();")
        out.append("        if (*dcx).hdr.err != AK_OK { d.err = (*dcx).hdr.err; }")
        out.append("    }")
        out.append("    // R-D6: `apply` only if nothing -- the reader or the host -- failed.")
        out.append("    if d.err == 0 && (*dcx).hdr.err == AK_OK {")
        out.append("        if let Some(apply) = (*vt).apply {")
        out.append("            ak_rt::bump!((*dcx).c, reverse);")
        out.append("            apply(ctx, obj, &out);")
        out.append("        }")
        out.append("    }")
        out.append("    // The host may have failed the operation from inside a reverse call; the")
        out.append("    // sticky slot in the context is where it said so (ABI v1 section 5).")
        out.append("    if (*dcx).hdr.err != AK_OK { (*dcx).hdr.err } else if d.err != 0 { d.err } else { AK_OK }")
        out.append("}")
        out.append("")

    # ================================================== the pull family (ABI v1 7.1)
    #
    # The same `dec_walk` above, the same `arena_decl` above, the same `flush_macros`
    # above with its family switch flipped. What is written here is the entry point and
    # the element decoder around them -- the prologue, the epilogue and the deposit -- and
    # that is the measured answer to open decision 2's second half.
    out.append("// " + "=" * 84)
    out.append("// The PULL family (ABI v1 section 7.1). `ak_parse_*` makes NO reverse call:")
    out.append("// it deposits into the host-owned context's record buffer, and the host reads")
    out.append("// it afterwards with `ak_bdr_drain` or `ak_bdr_ptr`. On the JVM that is what")
    out.append("// lets a parse run inside a critical section without first copying the wire")
    out.append("// buffer into native scratch; on a host whose reverse call is cheap it is a")
    out.append("// materialisation nobody needs, and the measurement says which is which.")
    out.append("//")
    out.append("// The traversal is `dec_walk`, shared verbatim with the push family above.")
    out.append("// " + "=" * 84)
    out.append("")

    for root in ir.roots:
        rslots = loop_slots(ir, root)
        for j, (path, f) in enumerate(rslots):
            et = elem_type(f)
            if not et or ir.msg(et).leaf:
                continue
            sn = slot_name(path)
            inner_slots = loop_slots(ir, et)
            sid = {slot_name(p): k + 1 for k, (p, _) in enumerate(inner_slots)}
            out.append("/// Pull form of the non-leaf element run. `new` becomes a minted token and")
            out.append("/// an OP_NEW record, `apply` becomes an OP_APPLY_ELEM record; the host's")
            out.append("/// replay does what its `new_%s`/`apply_%s` would have done." % (sn, sn))
            out.append("unsafe fn dec_%s_%s_element_pull(" % (snake(root), sn))
            out.append("    dcx: *mut DecCtxImpl,")
            out.append("    d: &mut Dec,")
            out.append("    base: usize,")
            out.append(") {")
            out.append("    // The codec MINTS the token because there is nobody to ask during a parse.")
            out.append("    // A token is an index (ABI v1 section 10), and the host's replay pushes its")
            out.append("    // elements in the order the records arrive, so index i names the same object")
            out.append("    // on both sides without either holding an address.")
            out.append("    let tok = (*dcx).bdr.mint();")
            out.append("    (*dcx).bdr.push(ak_rt::bdr::OP_NEW, %d, tok, 0, ::core::ptr::null(), 0);"
                       % ((j + 1) << 16))
            out.append("    let mut out = ak_dfix_%s::ZERO;" % et)
            out.append("    #[allow(unused_variables)]")
            out.append("    let buf0 = d.buf;")
            out.append("    let base0 = base;")
            slots = []
            for k, (ipath, iff) in enumerate(inner_slots):
                isn = slot_name(ipath)
                idty, _ = slot_elem_rust(iff)
                arena_decl(isn, idty, out)
                slots.append((isn, idty, ((j + 1) << 16) | (k + 1)))
            flush_macros(slots, "tok", out, family="pull")
            out.append("    let mut cur = 0u32;")
            out.append("    while !d.at_end() {")
            out.append("        let k = d.varint();")
            out.append("        if d.err != 0 { break; }")
            out.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
            out.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
            out.append("        match tag {")
            dec_walk(root, et, "out", (), "buf0", "base0", 0, sid, out,
                     elemcall=_pull_elemcall)
            out.append("            _ => { if cur != 0 { flush!(); cur = 0; } d.skip(tag, wire); }")
            out.append("        }")
            out.append("    }")
            # R-D1: no OP_APPLY_ELEM record after a decode error -- the host's replay must
            # not apply a group built over a hostile length. Byte-identical on valid input.
            out.append("    if d.err == 0 {")
            out.append("        flush!();")
            out.append("        (*dcx).bdr.push(")
            out.append("            ak_rt::bdr::OP_APPLY_ELEM,")
            out.append("            %d," % ((j + 1) << 16))
            out.append("            tok,")
            out.append("            1,")
            out.append("            &out as *const _ as *const u8,")
            out.append("            ::core::mem::size_of::<ak_dfix_%s>()," % et)
            out.append("        );")
            out.append("    }")
            out.append("}")
            out.append("")

    for root in ir.roots:
        rslots = loop_slots(ir, root)
        sid = {slot_name(p): i + 1 for i, (p, _) in enumerate(rslots)}
        out.append("/// Pull family (ABI v1 section 7.1): parse into the context, zero upcalls.")
        out.append("///")
        out.append("/// The host then calls `ak_bdr_footprint` and either `ak_bdr_drain` (copy the")
        out.append("/// records into its own memory, which is what a managed host must do) or")
        out.append("/// `ak_bdr_ptr` (walk them in place, which is what a native host does).")
        out.append("#[no_mangle]")
        out.append("pub unsafe extern \"C\" fn ak_parse_%s(" % root)
        out.append("    ctx: *mut ak_dec_ctx,")
        out.append("    buf: *const u8,")
        out.append("    len: usize,")
        out.append(") -> i32 {")
        out.append("    let dcx = ctx as *mut DecCtxImpl;")
        out.append("    ak_rt::bump!((*dcx).c, forward);")
        out.append("    // Same rule as `ak_decode_*` (D17): a new operation clears the sticky slot,")
        out.append("    // so a rejected parse cannot poison every later one on this context.")
        out.append("    (*dcx).hdr.err = AK_OK;")
        out.append("    (*dcx).bdr.reset();")
        out.append("    // R-D9: reject a buffer longer than u32::MAX before it can alias a span.")
        out.append("    if len > u32::MAX as usize {")
        out.append("        (*dcx).hdr.err = AK_ERR_LIMIT;")
        out.append("        return AK_ERR_LIMIT;")
        out.append("    }")
        out.append("    let buf0 = ::core::slice::from_raw_parts(buf, len);")
        out.append("    let base0 = 0usize;")
        out.append("    let mut d = Dec::new(buf0);")
        out.append("    let mut out = ak_dfix_%s::ZERO;" % root)
        slots = []
        for i, (path, f) in enumerate(rslots):
            et = elem_type(f)
            if et and not ir.msg(et).leaf:
                continue
            sn = slot_name(path)
            dty, _ = slot_elem_rust(f)
            arena_decl(sn, dty, out)
            slots.append((sn, dty, i + 1))
        flush_macros(slots, "AK_TOKEN_ROOT", out, family="pull")
        out.append("    let mut cur = 0u32;")
        out.append("    while !d.at_end() {")
        out.append("        let k = d.varint();")
        out.append("        if d.err != 0 { break; }")
        out.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        out.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
        out.append("        match tag {")
        dec_walk(root, root, "out", (), "buf0", "base0", 0, sid, out, elemcall=_pull_elemcall)
        out.append("            // Decision 11's capture is NOT built for this family: the bag is a")
        out.append("            // candidate and pull is a family, and pricing one through the other")
        out.append("            // would make neither answerable. Unknown fields are skipped here,")
        out.append("            // which is what the default push path does too.")
        out.append("            _ => { if cur != 0 { flush!(); cur = 0; } d.skip(tag, wire); }")
        out.append("        }")
        out.append("    }")
        # R-D1: no OP_APPLY record after a decode error, so the host's replay applies
        # nothing built over a hostile length. Byte-identical on valid input.
        out.append("    if d.err == 0 {")
        out.append("        flush!();")
        out.append("        // The root group LAST, exactly where the push family calls `apply`, so the")
        out.append("        // record stream is the call sequence push would have made, in its order.")
        out.append("        (*dcx).bdr.push(")
        out.append("            ak_rt::bdr::OP_APPLY,")
        out.append("            0,")
        out.append("            AK_TOKEN_ROOT,")
        out.append("            1,")
        out.append("            &out as *const _ as *const u8,")
        out.append("            ::core::mem::size_of::<ak_dfix_%s>()," % root)
        out.append("        );")
        out.append("    }")
        out.append("    if (*dcx).hdr.err != AK_OK { (*dcx).hdr.err } else if d.err != 0 { d.err } else { AK_OK }")
        out.append("}")
        out.append("")
    return out


# ============================================================== the RPC half (R-G5)

def _rty(t):
    """The plan's RPC type vocabulary, spelled in Rust."""
    return t.replace("*mut void", "*mut c_void").replace("*const void", "*const c_void")


REGION_BEGIN = "// @generated-begin plan.rpc"
REGION_END = "// @generated-end plan.rpc"


def emit_rpc_abi(p):
    """`ak-abi`'s declaration of section 9, rendered from `plan.rpc`: the handles, the
    structs, the callback type, the constants and the prototypes, once. Before this they
    were declared by hand in `ak-abi` and defined again in `ak-core/src/rpc.rs`, with an
    offset check for one struct and none for the prototypes -- and `ak_queue_next`'s
    timeout was `i32` here and `u64` there (R-G5).

    Returns the text of the marked REGION of `ak-abi/src/lib.rs` (the file imports
    `c_void` and allows non-camel-case names already), because the cpp slice's header
    generator reads `ak_client_opts` from that file until it renders plans."""
    p = as_plan(p)
    r = p.rpc
    o = [REGION_BEGIN,
         "// Rendered by poc/codec/gen/generate.py from plan.py (RpcAbi). Do not edit by hand.",
         ""]
    for h in r.handles:
        o.append("/// An opaque handle; the host holds a pointer and never looks inside.")
        o.append("pub enum %s {}" % h)
    o.append("")
    for name, doc, fields in r.structs:
        o.append("/// %s" % doc)
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct %s {" % name)
        for fn, ty, fdoc in fields:
            if fdoc:
                o.append("    /// %s" % fdoc)
            o.append("    pub %s: %s," % (fn, _rty(ty)))
        o.append("}")
        o.append("")
        o.append("impl Default for %s {" % name)
        o.append("    fn default() -> Self {")
        o.append("        %s {" % name)
        for fn, ty, _ in fields:
            o.append("            %s: %s," % (fn, _rdefault(ty)))
        o.append("        }")
        o.append("    }")
        o.append("}")
        o.append("")
    for name, params, ret, doc in r.callbacks:
        o.append("/// %s" % doc)
        o.append("pub type %s = extern \"C\" fn(%s)%s;" % (
            name, ", ".join("%s: %s" % (a, _rty(t)) for a, t in params),
            " -> %s" % _rty(ret) if ret else ""))
    o.append("")
    for name, ty, val, doc in r.constants:
        o.append("/// %s" % doc)
        o.append("pub const %s: %s = %d;" % (name, ty, val))
    o.append("")
    o.append("unsafe extern \"C\" {")
    for name, params, ret, doc in r.functions:
        if doc:
            o.append("    /// %s" % doc)
        o.append("    pub fn %s(%s)%s;" % (
            name, ", ".join("%s: %s" % (a, _rty(t)) for a, t in params),
            " -> %s" % _rty(ret) if ret else ""))
    o.append("}")
    o.append(REGION_END)
    return "\n".join(o)


def splice_region(text, region):
    """`text` with its marked region replaced by `region` (which carries the markers)."""
    i = text.index(REGION_BEGIN)
    j = text.index(REGION_END, i) + len(REGION_END)
    return text[:i] + region + text[j:]


def r_fields(fields):
    return fields


def _rdefault(ty):
    if ty.startswith("*const"):
        return "::core::ptr::null()"
    if ty.startswith("*mut"):
        return "::core::ptr::null_mut()"
    if ty in ("u8", "u32", "i32", "u64", "i64", "usize"):
        return "0"
    return "%s::default()" % ty


def emit_rpc_check(p):
    """Compile-time proof, inside the core, that every RPC definition has exactly the
    signature `plan.rpc` declares: a function item coerces to the declared function-pointer
    type or the build fails. And the core USES `ak_abi`'s structs rather than defining its
    own, so a struct layout exists once and cannot disagree with itself."""
    p = as_plan(p)
    o = [HEAD_FMT % "poc/codec/gen/plan.py (RpcAbi)",
         "//! R-G5: every RPC entry point the core defines, checked against the ONE declaration",
         "//! (`plan.rpc`, rendered into `ak-abi`). A signature that drifts is a compile error.",
         "#![allow(non_upper_case_globals, dead_code)]",
         "use ak_abi::*;",
         "use core::ffi::c_void;",
         ""]
    for name, params, ret, doc in p.rpc.functions:
        o.append("const _%s: unsafe extern \"C\" fn(%s)%s = crate::rpc::%s;" % (
            name, ", ".join(_rty(t) for _, t in params),
            " -> %s" % _rty(ret) if ret else "", name))
    o.append("")
    return "\n".join(o)
