"""Rust backend: the C ABI of design/ABI-v1.md and the core behind it, rendered from PLANS.

FIX-PLAN WP5 step 1. This module renders `plan.py`'s output and decides nothing about the
wire: the order of the writes, every presence test, which (field number, wire type) pairs
a field accepts, merge semantics, the unknown-field behaviour, the UTF-8 policy and every
layout member come from the plan (see its contract). What is decided here is Rust: how a
group is read, how a run is batched across the boundary, the learned-width length prefix,
the arenas, the names.

Four emitted files, from one plan:
  crates/ak-abi/src/generated/abi.rs     the per-message ABI: groups, vtables, prototypes
  crates/ak-abi/src/lib.rs (a marked region)  the RPC half's structs and prototypes (R-G5)
  crates/ak-core/src/generated/codec.rs  the codec behind the C ABI (push and pull families)
  crates/ak-core/src/generated/rpc_check.rs  compile-time proof that the core's RPC
                                         definitions have exactly the declared signatures

ABI v1 section 6's layout rules and section 7.2's batching predicate are the plan's; the
group carries the whole singular subtree, a string rides in the group as `ak_str`, a
repeated or map field keeps a loop slot (including one on an inlined child), a map is a
repeated field of its pair message, and a repeated field is a batched run on decode iff
its element type is a leaf.
"""
from plan import (ABI_SCALAR, CSCALAR, LEN, as_plan, check_expressible,  # noqa: F401
                  direct_fields, elem_type, element_types, group_fields, loop_slots,
                  oneof_message_members, presence_bits, slot_elem, slot_name, ugroup_fields,
                  vtable_messages)
from rustnames import SCALAR  # noqa: F401

# Historical name, imported by the cpp and java generators until they are ported.
slot_elem_rust = slot_elem

HEAD_FMT = "// @generated by ffi/poc/codec/gen/generate.py from %s. Do not edit.\n"
HEAD = HEAD_FMT % "ffi/schema/shapes.json"


def head_of(p):
    return HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")


ZERO = {"i32": "0", "i64": "0", "u8": "0", "f64": "0.0", "u32": "0"}


def _camel(snake_name):
    return "".join(p.capitalize() for p in snake_name.split("_"))


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def _zero_of(ty):
    if ty == "ak_str":
        return "ak_str { data: ::core::ptr::null(), len: 0, tc: None }"
    if ty == "ak_span":
        return "ak_span { off: 0, len: 0, coder: 0 }"
    if ty == "ak_blob":
        return "ak_blob { data: ::core::ptr::null(), len: 0 }"
    if ty in ZERO:
        return ZERO[ty]
    return "%s::ZERO" % ty


