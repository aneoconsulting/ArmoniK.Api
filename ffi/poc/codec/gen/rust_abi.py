def emit_abi(ir):
    ir = as_plan(ir)
    # WP5 step 10: the no-unknown variant has no u-groups, no options, no u-family.
    nounk = unknown_compiled_out(ir)
    o = [head_of(ir),
         "//! The per-message part of the C ABI: section 6's groups and vtables, section 7's",
         "//! decode fixes. Both the core and the host binding compile against this file.",
         "#![allow(non_camel_case_types, non_upper_case_globals)]",
         "// The fixed vocabulary (ak_str, ak_span, ak_blob, ak_unk_buf, ak_unk_opts, ak_loop_f,",
         "// AK_TOKEN_ROOT) is plan.FIXED's, rendered into ak-abi's lib.rs (WP5 step 6).",
         ("use super::super::{ak_dec_ctx, ak_enc_ctx, ak_loop_f, ak_span, ak_str};" if nounk else
          "use super::super::{ak_blob, ak_dec_ctx, ak_enc_ctx, ak_loop_f, ak_span, ak_str, ak_unk_buf,\n"
          "    ak_unk_opts, ak_unk_pool};"),
         "use core::ffi::c_void;",
         ""]

    for name in ir.abi_order:
        m = ir.msg(name)
        bits = presence_bits(m)
        # "u" is the ABI v1 open decision 11 candidate: the same ENCODE group with one
        # more slot, an opaque bag of unknown fields the host hands back verbatim. It is a
        # single `ak_str`, NOT a repeated field, and that is load-bearing: run
        # `gen/unknown_predicate.py` -- a repeated bag takes the schema from 9 leaf messages
        # to 0 and the batched run of section 7.2 fails everywhere.
        for pre in (("e", "d") if nounk else ("e", "d", "u")):
            enc = pre != "d"
            sname = "ak_%sfix_%s" % (pre, name)
            o.append("/// %s group for `%s`.%s" % (
                "Encode" if enc else "Decode", name,
                "  With the unknown-field bag (decision 11 candidate)." if pre == "u" else ""))
            o.append("#[repr(C)]")
            o.append("#[derive(Clone, Copy)]")
            o.append("pub struct %s {" % sname)
            # The plan's layout, rendered: `u` is the e-group with each child's u-group and
            # a trailing bag (a nested message needs its OWN bag).
            fields = ugroup_fields(m) if pre == "u" else group_fields(m, enc)
            for fname, ty in fields:
                o.append("    pub %s: %s," % (fname, ty))
            o.append("    pub presence: u32,")
            o.append("}")
            o.append("impl %s {" % sname)
            o.append("    pub const ZERO: Self = %s {" % sname)
            for fname, ty in fields:
                o.append("        %s: %s," % (fname, _zero_of(ty)))
            o.append("        presence: 0,")
            o.append("    };")
            o.append("}")
            for fname, b in bits.items():
                o.append("pub const %s_PRESENT_%s: u32 = 1 << %d;" % (sname.upper(), fname.upper(), b))
            o.append("")

    for name in vtable_messages(ir):
        # The plan's member order and shape (plan.enc_vtable / dec_vtable, WP5 step 6).
        slots = {slot_name(path): f for path, f in loop_slots(ir, name)}
        o.append("/// Encode vtable for `%s`." % name)
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_evt_%s {" % name)
        for kind, sn, et in enc_vtable(ir, name):
            if kind == "reserved":
                o.append("    /// Reserved: an empty struct has no defined size in C.")
                o.append("    pub _reserved: *const c_void,")
            elif kind == "loop":
                o.append("    pub loop_%s: Option<ak_loop_f>," % sn)
            else:
                o.append("    /// The element type has loop slots of its own (ABI v1 section 6).")
                o.append("    pub elem_%s: *const ak_evt_%s," % (sn, et))
        o.append("}")
        o.append("")
        o.append("/// Decode vtable for `%s` (the push family, ABI v1 section 7.1)." % name)
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_dvt_%s {" % name)
        for kind, sn, x in dec_vtable(ir, name):
            if kind == "apply":
                o.append("    pub apply: Option<")
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, *const ak_dfix_%s)," % name)
                o.append("    >,")
            elif kind == "add":
                dty, _ = slot_elem(slots[sn])
                o.append("    pub add_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const %s, i32)," % dty)
                o.append("    >,")
            elif kind == "new":
                o.append("    pub new_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void) -> i64,")
                o.append("    >,")
            elif kind == "applyelem":
                o.append("    pub apply_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const ak_dfix_%s)," % x)
                o.append("    >,")
            else:
                idty, _ = slot_elem(x)
                o.append("    pub add_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const %s, i32)," % idty)
                o.append("    >,")
        o.append("}")
        o.append("")

    # Decision 11 (WP5 step 7): the per-root unknown-field options, from the plan.
    for root in ([] if nounk else ir.roots):
        o.append("/// Decision 11: `%s`'s unknown-field options, one entry per message position" % root)
        o.append("/// (plan.unk_positions order). All zero = drop mode.")
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct %s {" % unk_opts_name(root))
        o.append("    /// ONE per struct: passed as `sink` to whichever position's grow is called.")
        o.append("    pub host: *mut c_void,")
        for mn, m, ty in unk_opts_layout(ir, root):
            o.append("    /// `%s`%s" % (m, " (a repeated position: a pool, rule 1)" if ty == "ak_unk_pool" else ""))
            o.append("    pub %s: %s," % (rust_member(mn), ty))
        o.append("}")
        o.append("pub const %s_N: usize = %d;" % (unk_opts_name(root).upper(), len(unk_opts_members(ir, root))))
        o.append("")

    o.append("// ABI v1 section 6: what a host calls in the codec are PLAIN EXPORTS, not a")
    o.append("// table, so a missing symbol is a load failure, which is loud.")
    o.append("unsafe extern \"C\" {")
    for root in ir.roots:
        o.append("    pub fn ak_encode_%s(" % root)
        o.append("        obj: *const c_void,")
        o.append("        ctx: *mut ak_enc_ctx,")
        o.append("        vt: *const ak_evt_%s," % root)
        o.append("        fix: *const ak_efix_%s," % root)
        if direct_fields(ir, root):
            o.append("        // ABI v1 section 8: the one direct-argument field of this tree.")
            o.append("        direct: *const u8,")
            o.append("        direct_len: usize,")
        o.append("    ) -> isize;")
        ustart = len(o)
        o.append("    /// ABI v1 open decision 11 candidate: the same entry over the group that")
        o.append("    /// carries the unknown-field bag.")
        o.append("    pub fn ak_uencode_%s(" % root)
        o.append("        obj: *const c_void,")
        o.append("        ctx: *mut ak_enc_ctx,")
        o.append("        vt: *const ak_evt_%s," % root)
        o.append("        fix: *const ak_ufix_%s," % root)
        if direct_fields(ir, root):
            o.append("        direct: *const u8,")
            o.append("        direct_len: usize,")
        o.append("    ) -> isize;")
        if nounk:
            del o[ustart:]
        o.append("    pub fn ak_decode_%s(" % root)
        o.append("        ctx: *mut ak_dec_ctx,")
        o.append("        obj: *mut c_void,")
        o.append("        buf: *const u8,")
        o.append("        len: usize,")
        o.append("        vt: *const ak_dvt_%s," % root)
        o.append("    ) -> i32;")
        for fname, params, ret, doc in unk_entry_points(ir, root):
            o.append("    /// %s" % doc)
            o.append("    pub fn %s;" % _rsig(fname, params, ret))
        o.append("    /// ABI v1 section 7.1's PULL family: no `obj`, no vtable and no reverse")
        o.append("    /// call. The decoded values land in the context's record buffer and the")
        o.append("    /// host reads them with `ak_bdr_drain` or `ak_bdr_ptr`.")
        o.append("    pub fn ak_parse_%s(" % root)
        o.append("        ctx: *mut ak_dec_ctx,")
        o.append("        buf: *const u8,")
        o.append("        len: usize,")
        o.append("    ) -> i32;")
    for et in sorted(element_types(ir)):
        leaf = ir.msg(et).leaf
        if leaf:
            o.append("    /// Leaf form: `%s` is transitively free of repeated and map fields," % et)
            o.append("    /// so the codec makes no reverse call during a run.")
            o.append("    pub fn ak_elem_%s(ctx: *mut ak_enc_ctx, elems: *const ak_efix_%s, n: i32) -> i32;"
                     % (et, et))
            if not nounk:
                o.append("    pub fn ak_uelem_%s(ctx: *mut ak_enc_ctx, elems: *const ak_ufix_%s, n: i32) -> i32;"
                         % (et, et))
        else:
            o.append("    /// Unrestricted form: names element i as `tok0 + i` from a contiguous")
            o.append("    /// token range the host allocated, because the codec has to call back")
            o.append("    /// into the host mid-run for `%s`'s own repeated fields." % et)
            o.append("    pub fn ak_elemu_%s(" % et)
            o.append("        ctx: *mut ak_enc_ctx,")
            o.append("        elems: *const ak_efix_%s," % et)
            o.append("        n: i32,")
            o.append("        tok0: i64,")
            o.append("    ) -> i32;")
            if not nounk:
                o.append("    pub fn ak_uelemu_%s(" % et)
                o.append("        ctx: *mut ak_enc_ctx,")
                o.append("        elems: *const ak_ufix_%s," % et)
                o.append("        n: i32,")
                o.append("        tok0: i64,")
                o.append("    ) -> i32;")
    # The run symbols: fixed names, from plan.FIXED.run_functions (WP5 step 6).
    for _g, fname, params, ret, doc in FIXED.run_functions():
        o.append("    /// %s" % doc)
        o.append("    pub fn %s;" % _rsig(fname, params, ret))
    o.append("}")
    o.append("")
    o.append("/// What each length-prefix site of the core is, in site order, so a miss count")
    o.append("/// can name the field it came from (ABI v1 open decision 5). A descriptor fact,")
    o.append("/// so it lives in the header both sides compile against.")
    o.append("pub const SITE_NAMES: [&str; %d] = [" % len(SITE_NAMES))
    for n in SITE_NAMES:
        o.append("    \"%s\"," % n)
    o.append("];")
    o.append("")
    return "\n".join(o)


