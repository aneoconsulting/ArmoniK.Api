def has_slots(ir, name):
    return bool(loop_slots(ir, name))


def _site(sites, key):
    return sites.id(key)


def _enc_value(f, v):
    """The Rust spelling of the plan's value codec for one write (no presence test)."""
    return {
        "varint_i32": "(*cx).e.varint_field(%d, %s as i64 as u64);",
        "varint_i64": "(*cx).e.varint_field(%d, %s as u64);",
        "varint_bool": "(*cx).e.varint_field(%d, (%s != 0) as u64);",
        "fixed64_f64": "(*cx).e.f64_field(%d, %s);",
        "fixed32_u32": "(*cx).e.fixed32_field(%d, %s);",
    }[f.value] % (f.tag, v)


def _implicit_cond(f, v):
    """The plan's implicit-presence test, spelled in Rust: a double by its BIT PATTERN."""
    if f.value == "fixed64_f64":
        return "%s.to_bits() != 0" % v
    return "%s != 0" % v


