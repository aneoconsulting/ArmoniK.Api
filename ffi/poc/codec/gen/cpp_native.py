"""C++ backend: arm `core-native-cpp`, the codec rendered into the host from the PLANS.

FIX-PLAN WP5 step 2, R-E1's C++ half. The cpp slice's `cpp_core.py` rendered its codec
through `rust_core.py`'s legacy walk and carried its own copy of every decode decision:
a known field at a foreign wire type was read anyway for a packed field (`else` read a
varint whatever the wire type), a repeated singular message REPLACED the one decoded
instead of merging (R-E4), a repeated oneof message member likewise, a double was
written with `!= 0.0` (so `-0.0` was dropped, R-E3), a tag 0 inside a map entry was
skipped, there was no message depth limit and no `fixed32`. Here the encoder renders
`MessagePlan.encode` step by step and the decoder renders `MessagePlan.decode` -- the
table of (field number, wire type) -> action that `rust_abi.py` renders for the core and
`rust_native.py` for the Rust control -- so the three differ only in where a value comes
from or goes to.

One output per unknown-field mode (owner position 6), from one renderer:
`emit(plan, unknown="drop")` and `emit(plan, unknown="retain")`, in namespaces
`<ns>::native` and `<ns>::native_retain`.

What this module decides (the contract's "may"): the facade spelling of each access
(`ak::Optional`, `ak::Box`, the oneof class, `std::map`), `switch` on the key as the
dispatch, the raw-cursor `ak::Enc` with learned length widths, `reserve` on packed runs,
and the C++11/C++17 split (`#if AK_CXX17`: `emplace_back`'s reference and
`insert_or_assign`), which changes no byte and no installed type. What it may not decide,
it does not: every write, presence test, accepted wire type, merge, the unknown-field
behaviour, the UTF-8 policy and the depth limit are the plan's. A plan option it cannot
render (utf8="lossy": `std::string` has no substituting decode here yet) RAISES.
"""
from plan import as_plan, relower
from cpp_names import camel, oneof_type, snake

HEAD_FMT = ("// @generated by ffi/poc/codec/gen/cpp_native.py (plan from %s). Do not edit.\n")


class Sites:
    """Length-prefix sites, one learned-width slot each (ABI v1 section 6)."""

    def __init__(self):
        self.ids = {}

    def id(self, key):
        return self.ids.setdefault(key, len(self.ids))

    def __len__(self):
        return len(self.ids)


# -------------------------------------------------------------------- value spellings

def _wire_value(f, v):
    """The facade value `v` of field `f` as the uint64 / double / uint32 its codec writes."""
    if f.kind == "enum":
        v = "(%s).v" % v
    return {
        "varint_i32": "(uint64_t)(int64_t)(%s)",
        "varint_i64": "(uint64_t)(%s)",
        "varint_bool": "(uint64_t)((%s) ? 1 : 0)",
        "fixed64_f64": "%s",
        "fixed32_u32": "%s",
    }[f.value] % v


def _write(f, v, ind):
    """Write one value of `f` as a field (key + value), no presence test."""
    w = _wire_value(f, v)
    if f.value == "fixed64_f64":
        return "%se->f64_field(%d, %s);" % (ind, f.tag, w)
    if f.value == "fixed32_u32":
        return "%se->fixed32_field(%d, %s);" % (ind, f.tag, w)
    return "%se->varint_field(%d, %s);" % (ind, f.tag, w)


def _write_elem(f, v, ind):
    """Write one element of a packed run (value only)."""
    w = _wire_value(f, v)
    if f.value == "fixed64_f64":
        return "%se->f64_raw(%s);" % (ind, w)
    if f.value == "fixed32_u32":
        return "%se->u32_raw(%s);" % (ind, w)
    return "%se->varint(%s);" % (ind, w)


def _implicit(f, v):
    """The plan's implicit-presence test (ENCODE RULES)."""
    if f.value == "fixed64_f64":
        return "ak::f64_bits(%s) != 0" % v          # R-E3: -0.0 is written
    if f.value == "varint_bool":
        return v
    if f.kind == "enum":
        return "(%s).v != 0" % v
    return "(%s) != 0" % v


def _read(f, rd):
    """Read one value of `f` from `ak::Dec *` expression `rd`, as the facade type."""
    r = {"varint_i32": "(int32_t)%s->varint()", "varint_i64": "(int64_t)%s->varint()",
         "varint_bool": "(%s->varint() != 0)", "fixed64_f64": "%s->f64()",
         "fixed32_u32": "%s->fixed32()"}[f.value] % rd
    if f.kind == "enum":
        return "%s(%s)" % (f.of, r)
    return r


def _elem_type(f):
    return {"int32": "int32_t", "int64": "int64_t", "bool": "bool", "double": "double",
            "fixed32": "uint32_t"}.get(f.kind, f.of)


def _str_fn(p):
    if p.options.utf8 != "reject":
        raise NotImplementedError(
            "REFUSED: the C++ native backend has no rendering of utf8=%r (a U+FFFD "
            "substituting decode into std::string); it raises rather than emitting the "
            "reject policy under another name" % p.options.utf8)
    return "ak::decode_str_checked"


def _blob_into(f, p, src, n, dst, ind, on_err):
    """Materialise one blob of `f` from (src, n) into `dst` (a std::string lvalue)."""
    if f.kind == "string":
        return ["%s{ int32_t rc = %s(%s, %s, &%s);" % (ind, _str_fn(p), src, n, dst),
                "%s  if (rc != 0) { %s } }" % (ind, on_err)]
    return ["%s%s.assign((const char *)(%s), %s);" % (ind, dst, src, n)]


# -------------------------------------------------------------------- encode

def _enc_message(p, m, o, sites, retain):
    for st in m.encode:
        f = st.field
        if st.op == "unknown_tail":
            if retain:
                o.append("  // Plan rule (retain): the captured unknown runs, verbatim, AFTER")
                o.append("  // every known field.")
                o.append("  if (!o.unknown_fields.empty())")
                o.append("    e->raw((const uint8_t *)o.unknown_fields.data(), o.unknown_fields.size());")
            continue
        v = "o.%s" % f.name
        if st.op == "child":
            s = sites.id((m.name, f.name))
            o.append("  if (%s.has_value()) {" % v)
            o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
            o.append("    enc_%s(*%s, e);" % (snake(f.of), v))
            o.append("    e->end(mk);")
            o.append("  }")
        elif st.op == "blob":
            if f.presence == "explicit":
                o.append("  if (%s.has_value()) e->blob_field(%d, *%s);" % (v, f.tag, v))
            elif f.presence in ("implicit", "direct"):
                o.append("  if (!%s.empty()) e->blob_field(%d, %s);" % (v, f.tag, v))
            else:
                raise NotImplementedError("blob presence %r (%s.%s)" % (f.presence, m.name, f.name))
        elif st.op == "scalar":
            if f.presence == "explicit":
                o.append("  if (%s.has_value()) {" % v)
                o.append(_write(f, "*%s" % v, "    "))
                o.append("  }")
            elif f.presence == "implicit":
                o.append("  if (%s) {" % _implicit(f, v))
                o.append(_write(f, v, "    "))
                o.append("  }")
            else:
                raise NotImplementedError("scalar presence %r (%s.%s)" % (f.presence, m.name, f.name))
        elif st.op == "packed":
            s = sites.id(("packed", m.name, f.name))
            o.append("  if (!%s.empty()) {" % v)
            o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
            o.append("    for (size_t i = 0; i < %s.size(); ++i) {" % v)
            o.append(_write_elem(f, "%s[i]" % v, "      "))
            o.append("    }")
            o.append("    e->end(mk);")
            o.append("  }")
        elif st.op == "repeated_blob":
            o.append("  for (size_t i = 0; i < %s.size(); ++i) e->blob_field(%d, %s[i]);"
                     % (v, f.tag, v))
        elif st.op == "repeated_message":
            s = sites.id((m.name, f.name))
            o.append("  for (size_t i = 0; i < %s.size(); ++i) {" % v)
            o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
            o.append("    enc_%s(%s[i], e);" % (snake(f.of), v))
            o.append("    e->end(mk);")
            o.append("  }")
        elif st.op == "map":
            s = sites.id(("map", m.name, f.name))
            entry = p.msg(f.entry)
            o.append("  for (std::map<std::string, std::string>::const_iterator it = %s.begin();" % v)
            o.append("       it != %s.end(); ++it) {" % v)
            o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
            # The pair message's OWN encode plan, over (key, value).
            for est in entry.encode:
                if est.op == "unknown_tail":
                    continue                 # a facade map entry has no bag
                ef = est.field
                if est.op != "blob" or not ef.is_blob or ef.presence != "implicit":
                    raise NotImplementedError("REFUSED: map %s.%s: a map half that is not an "
                                              "implicit blob (%s %s)" % (m.name, f.name,
                                                                         est.op, ef.kind))
                x = "it->first" if ef.name == "key" else "it->second"
                o.append("    if (!%s.empty()) e->blob_field(%d, %s);" % (x, ef.tag, x))
            o.append("    e->end(mk);")
            o.append("  }")
        elif st.op == "oneof_member":
            ty = oneof_type(m.name, st.oneof)
            acc = "o.%s.%s()" % (st.oneof, f.name)
            o.append("  if (o.%s.which() == %s::k%s) {" % (st.oneof, ty, camel(f.name)))
            o.append("    // Plan rule: a oneof member is written whatever its value.")
            if f.is_blob:
                o.append("    e->blob_field(%d, %s);" % (f.tag, acc))
            elif f.kind == "message":
                s = sites.id(("oneof", m.name, st.oneof, f.name))
                o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
                o.append("    enc_%s(%s, e);" % (snake(f.of), acc))
                o.append("    e->end(mk);")
            else:
                o.append(_write(f, acc, "    "))
            o.append("  }")
        else:
            raise NotImplementedError("encode step %r (%s)" % (st.op, m.name))
    # oneof_checks need no rendering: the facade's oneof class cannot hold an unknown case.


# -------------------------------------------------------------------- decode

def _dec_message(p, m, o):
    """Render `m.decode` as the cases of one `switch` on the (number, wire) key."""
    err = "d->err = rc; return;"
    for (tag, wire), act in sorted(m.decode.items()):
        f = act.field
        op = act.op
        o.append("      case %dull: {  // field %d, wire type %d: %s" % ((tag << 3) | wire, tag, wire, op))
        dst = "out->%s" % f.name
        if op == "set_scalar":
            val = _read(f, "d")
            if f.explicit:
                o.append("        %s.set(%s);" % (dst, val))
            else:
                o.append("        %s = %s;" % (dst, val))
        elif op == "set_blob":
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            if f.explicit:
                o.append("        std::string &s_ = %s.emplace();" % dst)
                tgt = "s_"
            else:
                tgt = dst
            o.extend(_blob_into(f, p, "d->buf + off", "n", tgt, "        ", err))
        elif op == "merge_child":
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            o.append("        ak::Dec sub(d->buf + off, n);")
            o.append("        // Plan rule: a repeated occurrence MERGES into the one decoded (R-E4).")
            o.append("        dec_%s(&sub, &%s.get_or_insert(), depth + 1);" % (snake(f.of), dst))
            o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        elif op == "append_message":
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            o.append("        ak::Dec sub(d->buf + off, n);")
            o.append("        %s.push_back(%s());" % (dst, f.of))
            o.append("        dec_%s(&sub, &%s.back(), depth + 1);" % (snake(f.of), dst))
            o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        elif op == "append_blob":
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            o.append("#if AK_CXX17")
            o.append("        std::string &b_ = %s.emplace_back();" % dst)
            o.append("#else")
            o.append("        %s.push_back(std::string());" % dst)
            o.append("        std::string &b_ = %s.back();" % dst)
            o.append("#endif")
            o.extend(_blob_into(f, p, "d->buf + off", "n", "b_", "        ", err))
        elif op == "packed_run":
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            o.append("        ak::Dec sub(d->buf + off, n);")
            if f.value == "fixed64_f64":
                o.append("        %s.reserve(%s.size() + n / 8);" % (dst, dst))
            elif f.value == "fixed32_u32":
                o.append("        %s.reserve(%s.size() + n / 4);" % (dst, dst))
            else:
                o.append("        %s.reserve(%s.size() + n);  // n bytes of varints: at most n elements" % (dst, dst))
            o.append("        while (!sub.at_end()) {")
            o.append("          %s v_ = %s;" % (_elem_type(f), _read(f, "(&sub)")))
            o.append("          if (sub.err != 0) break;")
            o.append("          %s.push_back(v_);" % dst)
            o.append("        }")
            o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        elif op == "packed_one":
            o.append("        // The unpacked form, at the kind's own wire type only (R-E2).")
            o.append("        %s v_ = %s;" % (_elem_type(f), _read(f, "d")))
            o.append("        if (d->err != 0) return;")
            o.append("        %s.push_back(v_);" % dst)
        elif op == "map_entry":
            entry = p.msg(f.entry)
            o.append("        size_t off, n; d->len_body(&off, &n);")
            o.append("        if (d->err != 0) return;")
            o.append("        if (depth + 1 > kLimit) { d->err = ak::ERR_DEPTH; return; }")
            o.append("        ak::Dec sub(d->buf + off, n);")
            o.append("        std::string k_, v_;")
            o.append("        while (!sub.at_end()) {")
            o.append("          uint64_t kk = sub.varint();")
            o.append("          if (sub.err != 0) break;")
            o.append("          uint32_t et = (uint32_t)(kk >> 3), ew = (uint32_t)(kk & 7);")
            o.append("          if (et == 0) { sub.err = ak::ERR_MALFORMED; break; }")
            o.append("          switch (((uint64_t)et << 3) | ew) {")
            # The pair message's OWN decode plan.
            for (etag, ewire), eact in sorted(entry.decode.items()):
                ef = eact.field
                if eact.op != "set_blob":
                    raise NotImplementedError("REFUSED: map %s.%s: a map half that is not a "
                                              "blob (%s)" % (m.name, f.name, ef.kind))
                x = "k_" if ef.name == "key" else "v_"
                o.append("            case %dull: {" % ((etag << 3) | ewire))
                o.append("              size_t a, b; sub.len_body(&a, &b);")
                o.append("              if (sub.err != 0) break;")
                o.extend(_blob_into(ef, p, "sub.buf + a", "b", x, "              ", err))
                o.append("              break;")
                o.append("            }")
            o.append("            // A facade map entry has no bag: an unknown field inside an")
            o.append("            // entry is skipped in both modes (`U-map-entry`).")
            o.append("            default: sub.skip(et, ew); break;")
            o.append("          }")
            o.append("        }")
            o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
            o.append("        // Plan rule: a duplicate key replaces the earlier value.")
            o.append("#if AK_CXX17")
            o.append("        %s.insert_or_assign(std::move(k_), std::move(v_));" % dst)
            o.append("#else")
            o.append("        %s[k_] = v_;" % dst)
            o.append("#endif")
        elif op == "oneof_set":
            ty = oneof_type(m.name, act.oneof)
            od = "out->%s" % act.oneof
            if f.is_blob:
                o.append("        size_t off, n; d->len_body(&off, &n);")
                o.append("        if (d->err != 0) return;")
                o.append("        std::string &s_ = %s.set_%s();" % (od, f.name))
                o.extend(_blob_into(f, p, "d->buf + off", "n", "s_", "        ", err))
            elif f.kind == "message":
                o.append("        size_t off, n; d->len_body(&off, &n);")
                o.append("        if (d->err != 0) return;")
                o.append("        ak::Dec sub(d->buf + off, n);")
                o.append("        // Plan rule: the SAME member merges; another one starts empty (R-E4).")
                o.append("        %s &c_ = %s.which() == %s::k%s ? %s.mutable_%s() : %s.set_%s();"
                         % (f.of, od, ty, camel(f.name), od, f.name, od, f.name))
                o.append("        dec_%s(&sub, &c_, depth + 1);" % snake(f.of))
                o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
            else:
                o.append("        %s v_ = %s;" % (_elem_type(f), _read(f, "d")))
                o.append("        if (d->err != 0) return;")
                o.append("        %s.set_%s() = v_;" % (od, f.name))
        else:
            raise NotImplementedError("decode action %r (%s.%s)" % (op, m.name, f.name))
        o.append("        break;")
        o.append("      }")


def emit(x, unknown="drop", ns="shapes", types_h="generated/types.h", stem="core_native"):
    """(header, source) of one `core-native` codec for one unknown-field mode."""
    p = as_plan(x)
    if unknown not in ("drop", "retain"):
        raise ValueError("a facade codec is one mode; render both for both")
    if p.options.unknown != unknown:
        p = relower(p, p.options.with_unknown(unknown))
    retain = unknown == "retain"
    sub_ns = "native_retain" if retain else "native"
    guard = "AK_%s_H" % stem.upper()
    head = HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")
    sites = Sites()
    body = []
    msgs = [n for n in p.order if not p.msg(n).synthetic]
    for name in msgs:
        m = p.msg(name)
        body.append("static void enc_%s(const %s &o, ak::Enc *e) {" % (snake(name), name))
        body.append("  (void)o; (void)e;")
        _enc_message(p, m, body, sites, retain)
        body.append("}")
        body.append("")
    for name in msgs:
        m = p.msg(name)
        body.append("static void dec_%s(ak::Dec *d, %s *out, uint32_t depth) {" % (snake(name), name))
        body.append("  (void)out;")
        body.append("  // Plan rule: a message more than kLimit levels below the root is refused.")
        body.append("  if (depth > kLimit) { d->err = ak::ERR_DEPTH; return; }")
        body.append("  while (!d->at_end()) {")
        body.append("    size_t s0 = d->pos;")
        body.append("    (void)s0;")
        body.append("    uint64_t k = d->varint();")
        body.append("    if (d->err != 0) return;")
        body.append("    uint32_t tag = (uint32_t)(k >> 3), wire = (uint32_t)(k & 7);")
        body.append("    if (tag == 0) { d->err = ak::ERR_MALFORMED; return; }")
        body.append("    switch (((uint64_t)tag << 3) | wire) {")
        _dec_message(p, m, body)
        if retain:
            body.append("      // Plan rule (retain): an unknown field is captured verbatim, key")
            body.append("      // included, and re-emitted after the known fields on encode.")
            body.append("      default:")
            body.append("        d->skip(tag, wire);")
            body.append("        if (d->err == 0) out->unknown_fields.append((const char *)(d->buf + s0), d->pos - s0);")
            body.append("        break;")
        else:
            body.append("      // Plan rule (drop): an unknown field -- including a known number at")
            body.append("      // a wire type the table has no case for (R-E2) -- is skipped.")
            body.append("      default: d->skip(tag, wire); break;")
        body.append("    }")
        body.append("  }")
        body.append("}")
        body.append("")

    fwd = []
    for name in msgs:
        fwd.append("static void enc_%s(const %s &o, ak::Enc *e);" % (snake(name), name))
        fwd.append("static void dec_%s(ak::Dec *d, %s *out, uint32_t depth);" % (snake(name), name))
    fwd.append("")

    hdr = [head, "#ifndef %s" % guard, "#define %s" % guard,
           '#include "ak/rt.h"', '#include "%s"' % types_h, "",
           "namespace %s {" % ns, "namespace %s {" % sub_ns, "",
           "// One learned length-prefix slot per site in this file (ABI v1 section 6).",
           "extern const size_t kSites;",
           "// The plan's options this module renders, for a log to name.",
           "extern const char *const kUnknownFields;",
           "extern const char *const kUtf8Policy;",
           "extern const uint32_t kRecursionLimit;", ""]
    for root in p.roots:
        hdr.append("void encode_into_%s(const %s &o, ak::Enc *e);" % (snake(root), root))
        hdr.append("// After an error the object is UNSPECIFIED and the host discards it (R-G6).")
        hdr.append("int32_t decode_%s(const uint8_t *b, size_t n, %s *out);" % (snake(root), root))
    hdr += ["", "}  // namespace %s" % sub_ns, "}  // namespace %s" % ns, "#endif", ""]

    o = [head, """
// Arm `core-native-cpp` (unknown fields: %(MODE)s): the codec rendered from the SAME plans
// as the core behind the C ABI (`poc/codec/gen/plan.py`), over the facade objects, with no
// boundary at all. README R3's no-boundary control; R-E1: the arms differ only in where a
// value comes from.
//
// R5's second half: an arm named "no boundary" is only a control if it is not FUSED INTO
// THE BENCHMARK LOOP. In C++ that question is `-flto` over this file, and the slice's
// `gen/boundary.sh` answers it from the built artifact.
#include "generated/%(STEM)s.h"

#include <cstring>

namespace %(NS)s {
namespace %(SUB)s {

static const uint32_t kLimit = %(LIMIT)d;
""".lstrip("\n") % {"MODE": unknown.upper(), "STEM": stem, "NS": ns, "SUB": sub_ns,
                     "LIMIT": p.options.recursion_limit}]
    o += fwd
    o += body
    for root in p.roots:
        o.append("void encode_into_%s(const %s &o, ak::Enc *e) {" % (snake(root), root))
        o.append("  e->reset();")
        o.append("  enc_%s(o, e);" % snake(root))
        o.append("}")
        o.append("")
        o.append("int32_t decode_%s(const uint8_t *b, size_t n, %s *out) {" % (snake(root), root))
        o.append("  ak::Dec d(b, n);")
        o.append("  dec_%s(&d, out, 0);" % snake(root))
        o.append("  return d.err;")
        o.append("}")
        o.append("")
    o.append("const size_t kSites = %d;" % len(sites))
    o.append("const char *const kUnknownFields = \"%s\";" % unknown)
    o.append("const char *const kUtf8Policy = \"%s\";" % p.options.utf8)
    o.append("const uint32_t kRecursionLimit = kLimit;")
    o.append("")
    o.append("}  // namespace %s" % sub_ns)
    o.append("}  // namespace %s" % ns)
    o.append("")
    return "\n".join(hdr), "\n".join(o)
