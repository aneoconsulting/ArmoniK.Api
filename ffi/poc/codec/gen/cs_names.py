"""C# spellings shared by every C# backend, so two backends cannot disagree on a name.

FIX-PLAN WP5 step 4. Naming only: no wire rule, no layout, no description. Moved here out of
`poc/csharp/gen/csnames.py` together with the backends that use it.
"""
import textwrap

# A word the C# compiler will not accept as an identifier.
KEYWORDS = {
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
    "checked", "class", "const", "continue", "decimal", "default", "delegate",
    "do", "double", "else", "enum", "event", "explicit", "extern", "false",
    "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit",
    "in", "int", "interface", "internal", "is", "lock", "long", "namespace",
    "new", "null", "object", "operator", "out", "override", "params",
    "private", "protected", "public", "readonly", "ref", "return", "sbyte",
    "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct",
    "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
    "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile",
    "while",
}

# The facade's scalar types (the host representation, not the ABI's).
SCALAR = {"int32": "int", "int64": "long", "bool": "bool", "double": "double", "fixed32": "uint"}

# The ABI vocabulary of plan.py (group members, slot elements, RPC types) in C#.
ABI = {"i32": "int", "i64": "long", "u8": "byte", "u32": "uint", "f64": "double",
       "u64": "ulong", "usize": "nuint", "ak_str": "ak_str", "ak_span": "ak_span",
       "ak_blob": "ak_blob"}


def pascal(snake):
    return "".join(p[:1].upper() + p[1:] for p in snake.split("_") if p)


def camel(snake):
    p = pascal(snake)
    return p[:1].lower() + p[1:]


def field(name):
    """A facade member name. Escaped rather than renamed, so it still matches the
    description."""
    n = pascal(name)
    return "@" + n if n in KEYWORDS else n


def enum_member(enum_name, value_name):
    """`RESULT_STATUS_NOTFOUND` in enum `ResultStatus` -> `Notfound` (protoc's C# rule)."""
    prefix = ""
    for ch in enum_name:
        prefix += ("_" if ch.isupper() and prefix else "") + ch
    prefix = prefix.upper() + "_"
    v = value_name[len(prefix):] if value_name.startswith(prefix) else value_name
    out = pascal(v.lower())
    if not out or out[0].isdigit():
        out = pascal(value_name.lower())
    return "@" + out if out in KEYWORDS else out


def oneof_case_type(msg_name, oneof_name):
    return "%s%sCase" % (msg_name, pascal(oneof_name))


def oneof_case_field(oneof_name):
    return "%sCase" % pascal(oneof_name)


def abi_type(t):
    """plan.py's ABI vocabulary in C#. A nested group keeps its ABI name."""
    if t in ABI:
        return ABI[t]
    if t.startswith(("ak_efix_", "ak_dfix_", "ak_ufix_")):
        return t
    raise KeyError("no C# spelling for ABI type %r" % t)


class Head:
    """A line buffer carrying the generated-file banner."""

    def __init__(self, what, source="ffi/schema/shapes.json", backend="cs_backend"):
        self.lines = [
            "// @generated by ffi/poc/codec/gen/%s.py (driven by ffi/poc/csharp/gen/generate.py)" % backend,
            "// from %s. Do not edit: `gen/generate.py --check` fails if this file is not" % source,
            "// what the generator writes today.",
            "//",
            "// " + what,
            "",
        ]

    def __iadd__(self, line):
        self.lines.append(line)
        return self

    def extend(self, lines):
        self.lines.extend(lines)

    def doc(self, text, indent=""):
        for ln in textwrap.wrap(text, 88 - len(indent) - 4):
            self.lines.append("%s/// %s" % (indent, ln))

    def __str__(self):
        return "\n".join(self.lines).rstrip() + "\n"
