"""The C# slice's layout probe: a Rust program printing the RUST declaration's layout.

FIX-PLAN WP5 step 4, R-E6. The finding was that the C# layout probe was emitted from the
same field list the C# declaration was emitted from, so a member missing from both, or the
same wrong order in both, could not be seen; and that it checked sizes only. This emitter
therefore reads NO plan and NO description: it parses the struct declarations out of the
Rust source text of `ak-abi` (`src/lib.rs` and `src/generated/abi.rs`, or
`src/generated_corpus/abi.rs` for the corpus build) -- the text `rust_abi` rendered and the
core compiles against -- and emits a program that prints, for every `#[repr(C)]` struct with
named public members, its size and alignment and every member's name, offset and size as
the Rust compiler computes them (`offset_of!`, `size_of`). The C# side compares that with its
own declaration by NAME, both ways (`poc/csharp/src/Harness/LayoutCheck.cs`): a member one
side has and the other lacks, a different order (a different offset), a different width,
a different total size -- each is a failure.

Imports nothing from the generator.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ABI = os.path.join(HERE, "..", "crates", "ak-abi", "src")

STRUCT = re.compile(r"#\[repr\(C\)\]\s*(?:#\[[^\]]*\]\s*)*pub struct (\w+)\s*\{(.*?)\n\}", re.S)
MEMBER = re.compile(r"^    pub (\w+)\s*:", re.M)


def parse(path):
    """[(struct, [member, ...])] in declaration order, for every repr(C) struct with named
    public members (an opaque handle has none and is skipped)."""
    with open(path) as f:
        src = f.read()
    out = []
    for mt in STRUCT.finditer(src):
        members = MEMBER.findall(mt.group(2))
        if members:
            out.append((mt.group(1), members))
    return out


def sources(corpus):
    gen = "generated_corpus" if corpus else "generated"
    return [os.path.join(ABI, "lib.rs"), os.path.join(ABI, gen, "abi.rs")]


def structs(corpus):
    seen, out = set(), []
    for path in sources(corpus):
        for name, members in parse(path):
            if name in seen:
                raise AssertionError("%s declared twice in ak-abi" % name)
            seen.add(name)
            out.append((name, members))
    return out


HEAD = '''//! @generated by ffi/poc/codec/gen/cs_layout_probe.py (driven by ffi/poc/csharp/gen/generate.py).
//! Do not edit.
//!
//! The layout of every `#[repr(C)]` struct in ak-abi's RUST declaration, as the Rust compiler
//! lays it out: size, alignment, and every member's name, offset and size, as JSON on stdout.
//! The struct and member lists were parsed out of the Rust source text, not taken from any
//! plan, so this is not derived from the list the C# declaration was rendered from (R-E6).
//! Build with `--features corpus` for the corpus-schema ABI.
#![allow(unused_unsafe)]
use ak_abi::*;
use core::mem::{align_of, offset_of, size_of, MaybeUninit};

fn fsz<F>(_: *const F) -> usize {
    size_of::<F>()
}

macro_rules! lay {
    ($out:expr, $t:ident, [$($f:ident),* $(,)?]) => {{
        let u = MaybeUninit::<$t>::uninit();
        let p = u.as_ptr();
        let mut fields: Vec<String> = Vec::new();
        $(
            fields.push(format!("{{\\"name\\": \\"{}\\", \\"offset\\": {}, \\"size\\": {}}}",
                stringify!($f), offset_of!($t, $f), fsz(unsafe { core::ptr::addr_of!((*p).$f) })));
        )*
        $out.push(format!("  \\"{}\\": {{\\"size\\": {}, \\"align\\": {}, \\"fields\\": [{}]}}",
            stringify!($t), size_of::<$t>(), align_of::<$t>(), fields.join(", ")));
    }};
}
'''


def emit():
    o = [HEAD]
    for corpus in (False, True):
        o.append('#[cfg(%sfeature = "corpus")]' % ("" if corpus else "not("))
        if not corpus:
            o[-1] = '#[cfg(not(feature = "corpus"))]'
        o.append("fn all(out: &mut Vec<String>) {")
        for name, members in structs(corpus):
            o.append("    lay!(out, %s, [%s]);" % (name, ", ".join(members)))
        o.append("}")
        o.append("")
    o.append("fn main() {")
    o.append("    let mut out = Vec::new();")
    o.append("    all(&mut out);")
    o.append('    println!("{{\\n{}\\n}}", out.join(",\\n"));')
    o.append("}")
    return "\n".join(o) + "\n"
