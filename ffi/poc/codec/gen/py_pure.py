"""Python backend, part 1: the facade and the pure-Python codec, rendered from PLANS.

FIX-PLAN WP5 step 5. This module replaces `poc/python/gen/py_facade.py` and
`poc/python/gen/py_codec.py`, which walked the description through the python slice's own
`walk.py` and wrote their own wire rules (review finding R-E5: no wire-type check, negative
int32/int64 decoded as unsigned, tag 0 accepted). Here every write, presence test, accepted
(field number, wire type) pair, merge, the unknown-field behaviour, the UTF-8 policy and the
depth limit are the plan's (`plan.py`, the contract in its docstring); this module decides
only how a plan step is spelled in Python.

Two outputs per plan, as `rust_native.py` does for Rust:

  emit_facade(p)                 the facade: `Plain*` (instance dict) and `Slots*`
                                 (`__slots__`) classes, the oneof member tables, and a
                                 metadata table (`MESSAGES`) the slice's harness glue reads
                                 instead of re-deriving anything from the description
  emit_pycodec(p, "drop"|"retain")   README R3's no-boundary control: encode and decode over
                                 the facade objects, one module per unknown-field mode (a
                                 facade codec has no per-call switch the way the C ABI has
                                 two entry-point families)

What this module decides (the contract's "may"): Python spelling; that a dispatch is an
if/elif chain on the whole key (`(number << 3) | wire`, which IS the plan's (number, wire)
pair); that a decoded message is filled into the object it merges into; buffer strategy
(bytearray, struct). What it may not decide, it does not.

A backend: imports `plan` only (FIX-PLAN WP5 item 7).
"""
from plan import GROUP_DEPTH_LIMIT, MAX_FIELD_NUMBER, as_plan, relower, unknown_compiled_out

HEAD = '"""GENERATED by ffi/poc/codec/gen/%s from %s (plan: %r). Do not edit.'

ERR = {"MALFORMED": -2, "TRUNCATED": -3, "DEPTH": -4, "TRANSCODE": -6, "ABI": -11}

ZERO = {"string": '""', "bytes": 'b""', "int32": "0", "int64": "0", "bool": "False",
        "enum": "0", "double": "0.0", "fixed32": "0", "message": "None"}


def _varint_bytes(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def _key_lit(tag, wire):
    """The key of (tag, wire) as a Python bytes literal: a constant, so a write is one
    `+=` rather than a varint call."""
    return repr(_varint_bytes((tag << 3) | wire))


def _key_int(tag, wire):
    return (tag << 3) | wire


def real_messages(p):
    """Every message that has a facade class: the plan's messages minus the synthetic map
    pairs (ABI v1 section 11: a map is a `dict` on the facade and never an object)."""
    return [n for n in p.order if not p.msg(n).synthetic]


def attrs(m, nounk=False):
    """The facade attributes, in constructor order: the fields in tag order, one
    `<oneof>_case` per oneof, and `_unknown` (retain mode's captured runs, `b""` otherwise).
    `nounk` (the plan's unknown fields compiled out, WP5 step 10): no `_unknown` at all."""
    return [f.name for f in m.fields] + ["%s_case" % o for o in m.oneofs] + ([] if nounk else ["_unknown"])


def default(f):
    if f.card in ("repeated", "packed", "map"):
        return "None"
    if f.presence == "explicit":
        return "None"
    if f.kind not in ZERO:
        raise NotImplementedError("no facade default for %s.%s (%s)" % (f.owner, f.name, f.kind))
    return ZERO[f.kind]


# =================================================================== the facade

def emit_facade(x):
    """From a plan whose unknown fields are compiled out (THE NO-UNKNOWN VARIANT) the facade
    carries no `_unknown`: no attribute, no `__slots__` entry, no constructor argument."""
    p = as_plan(x)
    nounk = unknown_compiled_out(p)
    names = real_messages(p)
    L = [HEAD % ("py_pure.py", p.source, p.options) + "\n",
         "The facade, in two storages, so README 9.1's choice is a measured one:",
         "",
         "*   `Plain*`  -- a plain class. Attributes live in an instance __dict__.",
         "*   `Slots*`  -- `__slots__`. A descriptor with a fixed offset, no dict.",
         "",
         "The third storage, a C extension type, is in the generated C shim (`binding.c`),",
         "because its point is that a field read from C is a struct member.",
         "",
         "A oneof is `<oneof>_case`, holding the ACTIVE MEMBER'S TAG (0 = none), as the",
         "ABI's discriminant does (ABI v1 section 6); the names are in `<M>_<oneof>_MEMBERS`.",
         ("Unknown fields are compiled out of this plan: no facade class has `_unknown`." if nounk else
          "`_unknown` holds the unknown-field runs a retain-mode codec captured, verbatim."),
         '"""', "", ""]
    # The metadata table: what the slice's harness glue (projection, field walk, payload
    # builder) reads instead of the description. Facts only, no rule.
    L.append("# name -> {'fields': [(name, tag, kind, card, of, presence, oneof), ...],")
    L.append("#          'oneofs': {oneof: [(tag, member name), ...]}, 'entry': (key kind, value kind)}")
    L.append("ROOTS = %r" % (list(p.roots),))
    L.append("MESSAGES = {")
    for n in names:
        m = p.msg(n)
        L.append("    %r: {" % n)
        L.append("        'fields': [")
        for f in m.fields:
            entry = None
            if f.card == "map":
                em = p.msg(f.entry)
                entry = tuple(g.kind for g in em.fields)
            L.append("            (%r, %d, %r, %r, %r, %r, %r, %r)," % (
                f.name, f.tag, f.kind, f.card, f.of, f.presence, f.oneof, entry))
        L.append("        ],")
        L.append("        'oneofs': {%s}," % ", ".join(
            "%r: [%s]" % (o, ", ".join("(%d, %r)" % (g.tag, g.name) for g in ms))
            for o, ms in m.oneofs.items()))
        L.append("    },")
    L.append("}")
    L.append("")
    for n in names:
        for o, ms in p.msg(n).oneofs.items():
            L.append("%s_%s_MEMBERS = {%s}" % (n, o, ", ".join("%d: %r" % (g.tag, g.name) for g in ms)))
    L.append("")
    L.append("")
    for variant, slots in (("Plain", False), ("Slots", True)):
        for n in names:
            m = p.msg(n)
            at = attrs(m, nounk)
            L.append("class %s%s:" % (variant, n))
            if slots:
                L.append("    __slots__ = (%s)" % "".join('"%s", ' % a for a in at))
            args = (["%s=%s" % (f.name, default(f)) for f in m.fields]
                    + ["%s_case=0" % o for o in m.oneofs] + ([] if nounk else ['_unknown=b""']))
            L.append("    def __init__(self, %s):" % ", ".join(args))
            for f in m.fields:
                if f.card in ("repeated", "packed", "map"):
                    empty = "{}" if f.card == "map" else "[]"
                    L.append("        self.%s = %s if %s is None else %s" % (f.name, empty, f.name, f.name))
                else:
                    L.append("        self.%s = %s" % (f.name, f.name))
            for o in m.oneofs:
                L.append("        self.%s_case = %s_case" % (o, o))
            if not nounk:
                L.append("        self._unknown = _unknown")
            elif not m.fields and not m.oneofs:
                L.append("        pass   # no attribute at all: unknown fields are compiled out")
            L.append("")
            # __eq__: plain fields, discriminants and ONLY the selected member of each
            # oneof (a member nobody selects is not on the wire). `_unknown` is not
            # compared: in drop mode it is always empty, and retain mode is checked on bytes.
            keys = [f.name for f in m.plain] + ["%s_case" % o for o in m.oneofs]
            if m.oneofs:
                L.append("    def _sel(self):")
                for o in m.oneofs:
                    L.append("        n_%s = %s_%s_MEMBERS.get(self.%s_case)" % (o, n, o, o))
                L.append("        return (%s)" % "".join(
                    "getattr(self, n_%s) if n_%s else None, " % (o, o) for o in m.oneofs))
                L.append("")
            sel = " + (self._sel(), )" if m.oneofs else ""
            osel = " + (o._sel(), )" if m.oneofs else ""
            L.append("    def __eq__(self, o):")
            L.append("        return type(o) is type(self) and (%s)%s == (%s)%s"
                     % ("".join("self.%s, " % a for a in keys), sel,
                        "".join("o.%s, " % a for a in keys), osel))
            L.append("")
            L.append("")
    return "\n".join(L)


# =================================================================== the codec

PRELUDE = '''
import struct as _struct
from math import copysign as _copysign

LIMIT = %(limit)d                # Options.recursion_limit
UTF8_POLICY = %(utf8)r
UNKNOWN_FIELDS = %(unknown)r

ERR_MALFORMED, ERR_TRUNCATED, ERR_DEPTH, ERR_TRANSCODE, ERR_ABI = -2, -3, -4, -6, -11
_M64 = (1 << 64) - 1
_GROUP_LIMIT = %(glimit)d               # plan.GROUP_DEPTH_LIMIT: nested groups, per skip


class DecodeError(ValueError):
    """A refused input. `code` is the ABI v1 section 5 code the core returns for the same
    input, so a harness compares refusals across arms by code, not by message."""

    def __init__(self, code, what=""):
        ValueError.__init__(self, "%%d %%s" %% (code, what))
        self.code = code


_pack_d = _struct.Struct("<d").pack
_unpack_d = _struct.Struct("<d").unpack_from
_pack_I = _struct.Struct("<I").pack
_unpack_I = _struct.Struct("<I").unpack_from
_VARINT = [bytes([i]) for i in range(128)]


def _varint(n, out):
    if n < 128:
        out += _VARINT[n]
        return
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return


def _vr(b, i, end):
    """A varint: truncated -> ERR_TRUNCATED, more than 10 bytes -> ERR_MALFORMED, bits
    past 64 dropped (plan DECODE RULES)."""
    if i >= end:
        raise DecodeError(ERR_TRUNCATED, "varint")
    c = b[i]
    i += 1
    if c < 128:
        return c, i
    n = c & 0x7F
    s = 7
    while True:
        if i >= end:
            raise DecodeError(ERR_TRUNCATED, "varint")
        c = b[i]
        i += 1
        n |= (c & 0x7F) << s
        if c < 128:
            return n & _M64, i
        s += 7
        if s > 63:
            raise DecodeError(ERR_MALFORMED, "varint longer than 10 bytes")


def _len(b, i, end):
    """A length prefix: the full unsigned 64-bit varint, accepted only if `n <= end - i`
    (plan rule R-D1/R-G8: never tested as `i + n > end`)."""
    n, i = _vr(b, i, end)
    if n > end - i:
        raise DecodeError(ERR_TRUNCATED, "length %%d overruns %%d remaining" %% (n, end - i))
    return n, i


def _i32(v):
    v &= 0xFFFFFFFF
    return v - 0x100000000 if v >= 0x80000000 else v


def _i64(v):
    return v - (1 << 64) if v >= (1 << 63) else v


def _f64(b, i, end):
    if end - i < 8:
        raise DecodeError(ERR_TRUNCATED, "fixed64")
    return _unpack_d(b, i)[0], i + 8


def _u32(b, i, end):
    if end - i < 4:
        raise DecodeError(ERR_TRUNCATED, "fixed32")
    return _unpack_I(b, i)[0], i + 4


def _str(b, i, n):
    try:
        return b[i:i + n].decode("utf-8"%(utf8_arg)s)
    except UnicodeDecodeError:
        raise DecodeError(ERR_TRANSCODE, "invalid UTF-8") from None


def _skip(b, i, end, t, w):
    """An unknown field (plan DECODE RULES): wire types 0, 1, 2, 5 skipped; 3 opens a
    group skipped to the END_GROUP of the same number; 4 with no group open, 6 and 7 are
    ERR_MALFORMED."""
    if w == 0:
        return _vr(b, i, end)[1]
    if w == 2:
        n, i = _len(b, i, end)
        return i + n
    if w == 1:
        if end - i < 8:
            raise DecodeError(ERR_TRUNCATED, "fixed64")
        return i + 8
    if w == 5:
        if end - i < 4:
            raise DecodeError(ERR_TRUNCATED, "fixed32")
        return i + 4
    if w == 3:
        return _skip_group(b, i, end, t, 0)
    raise DecodeError(ERR_MALFORMED, "wire type %%d" %% w)


def _skip_group(b, i, end, tag, depth):
    if depth >= _GROUP_LIMIT:
        raise DecodeError(ERR_DEPTH, "groups nested past the limit")
    while True:
        if i >= end:
            raise DecodeError(ERR_TRUNCATED, "unterminated group %%d" %% tag)
        k, i = _vr(b, i, end)
        t, w = k >> 3, k & 7
        if t == 0 or t > %(maxfield)d:
            raise DecodeError(ERR_MALFORMED, "field number 0 or above 2^29-1")
        if w == 4:
            if t != tag:
                raise DecodeError(ERR_MALFORMED, "END_GROUP %%d closes group %%d" %% (t, tag))
            return i
        if w == 3:
            i = _skip_group(b, i, end, t, depth + 1)
            continue
        i = _skip(b, i, end, t, w)
'''


class _Out:
    def __init__(self):
        self.L = []

    def __call__(self, ind, s):
        self.L.append("    " * ind + s)


def _enc_value(o, ind, f, v):
    """The write of ONE value of `f` with its key, no presence test (the plan's value codec)."""
    k = _key_lit(f.tag, f.wire)
    c = f.value
    if c in ("varint_i32", "varint_i64"):
        o(ind, "out += %s" % k)
        o(ind, "_varint(%s & _M64 if %s < 0 else %s, out)" % (v, v, v))
    elif c == "varint_bool":
        o(ind, "out += %s" % k)
        o(ind, "out.append(1 if %s else 0)" % v)
    elif c == "fixed64_f64":
        o(ind, "out += %s" % k)
        o(ind, "out += _pack_d(%s)" % v)
    elif c == "fixed32_u32":
        o(ind, "out += %s" % k)
        o(ind, "out += _pack_I(%s)" % v)
    else:
        raise NotImplementedError("value codec %r (%s.%s)" % (c, f.owner, f.name))


def _implicit(f, v):
    """The plan's implicit-presence test: != 0, bool when true, double by BIT PATTERN
    (-0.0 is written, +0.0 is not; R-E3), string/bytes when non-empty."""
    if f.value == "fixed64_f64":
        return "%s or _copysign(1.0, %s) < 0" % (v, v)
    return v


def _enc_blob(o, ind, f, v):
    k = _key_lit(f.tag, 2)
    if f.kind == "string":
        o(ind, "_b = %s.encode('utf-8')" % v)
        o(ind, "out += %s" % k)
        o(ind, "_varint(len(_b), out)")
        o(ind, "out += _b")
    else:
        o(ind, "out += %s" % k)
        o(ind, "_varint(len(%s), out)" % v)
        o(ind, "out += %s" % v)


def _enc_child(o, ind, f, v):
    o(ind, "_s = bytearray()")
    o(ind, "_e_%s(%s, _s)" % (f.of, v))
    o(ind, "out += %s" % _key_lit(f.tag, 2))
    o(ind, "_varint(len(_s), out)")
    o(ind, "out += _s")


def _enc_message(p, m, o, retain):
    o(0, "def _e_%s(o, out):" % m.name)
    start = len(o.L)
    for oname, tags in m.oneof_checks:
        # Plan rule: a case that is neither 0 nor a member tag is REFUSED before any write.
        o(1, "_c = o.%s_case" % oname)
        o(1, "if _c and _c not in %r:" % (tuple(tags),))
        o(2, "raise ValueError('%s.%s_case = %%r is not a member tag' %% (_c,))" % (m.name, oname))
    for st in m.encode:
        f = st.field
        if st.op == "unknown_tail":
            if retain:
                o(1, "_u = o._unknown")
                o(1, "if _u:")
                o(2, "out += _u")
            continue
        v = "o.%s" % f.name
        if st.op == "scalar":
            o(1, "_v = %s" % v)
            if f.presence == "explicit":
                o(1, "if _v is not None:")
            elif f.presence == "implicit":
                o(1, "if %s:" % _implicit(f, "_v"))
            else:
                raise NotImplementedError("scalar presence %r (%s.%s)" % (f.presence, m.name, f.name))
            _enc_value(o, 2, f, "_v")
        elif st.op == "blob":
            o(1, "_v = %s" % v)
            if f.presence == "explicit":
                o(1, "if _v is not None:")
            elif f.presence in ("implicit", "direct"):
                # `direct` is ABI v1 section 8's crossing strategy, not a presence rule: on
                # the wire it is an implicit-presence bytes field (the core tests len != 0).
                o(1, "if _v:")
            else:
                raise NotImplementedError("blob presence %r (%s.%s)" % (f.presence, m.name, f.name))
            _enc_blob(o, 2, f, "_v")
        elif st.op == "child":
            o(1, "_v = %s" % v)
            o(1, "if _v is not None:")
            _enc_child(o, 2, f, "_v")
        elif st.op == "packed":
            o(1, "_v = %s" % v)
            o(1, "if _v:")
            if f.value == "fixed64_f64":
                o(2, "_s = _struct.pack('<%dd' % len(_v), *_v)")
            elif f.value == "fixed32_u32":
                o(2, "_s = _struct.pack('<%dI' % len(_v), *_v)")
            else:
                o(2, "_s = bytearray()")
                if f.value == "varint_bool":
                    o(2, "for _x in _v:")
                    o(3, "_s.append(1 if _x else 0)")
                else:
                    o(2, "for _x in _v:")
                    o(3, "_varint(_x & _M64 if _x < 0 else _x, _s)")
            o(2, "out += %s" % _key_lit(f.tag, 2))
            o(2, "_varint(len(_s), out)")
            o(2, "out += _s")
        elif st.op == "repeated_blob":
            o(1, "for _v in %s:" % v)
            _enc_blob(o, 2, f, "_v")
        elif st.op == "repeated_message":
            o(1, "for _v in %s:" % v)
            _enc_child(o, 2, f, "_v")
        elif st.op == "map":
            em = p.msg(f.entry)
            # Entry ORDER: ascending by key. The plan states each entry's own encode plan and
            # not the order of the entries; ascending by key is the manifest's canonical form
            # (ffi/schema/README.md) and what the core-native Rust control gets from BTreeMap.
            o(1, "_d = %s" % v)
            o(1, "for _k in sorted(_d):")
            o(2, "_mv = _d[_k]")
            o(2, "_s = bytearray()")
            for est in em.encode:
                if est.op == "unknown_tail":
                    continue            # a facade map entry has no bag (U-map-entry)
                ef = est.field
                if est.op != "blob" or ef.presence != "implicit":
                    raise NotImplementedError("map %s.%s: entry step %s %s" % (m.name, f.name, est.op, ef.kind))
                x = "_k" if ef.name == "key" else "_mv"
                o(2, "if %s:" % x)
                kk = _key_lit(ef.tag, 2)
                if ef.kind == "string":
                    o(3, "_b = %s.encode('utf-8')" % x)
                    o(3, "_s += %s; _varint(len(_b), _s); _s += _b" % kk)
                else:
                    o(3, "_s += %s; _varint(len(%s), _s); _s += %s" % (kk, x, x))
            o(2, "out += %s" % _key_lit(f.tag, 2))
            o(2, "_varint(len(_s), out)")
            o(2, "out += _s")
        elif st.op == "oneof_member":
            o(1, "if o.%s_case == %d:" % (st.oneof, f.tag))
            o(2, "_v = %s" % v)
            if f.is_blob:
                _enc_blob(o, 2, f, "_v")
            elif f.kind == "message":
                o(2, "if _v is None:")
                o(3, "raise ValueError('%s.%s is selected but None')" % (m.name, f.name))
                _enc_child(o, 2, f, "_v")
            else:
                _enc_value(o, 2, f, "_v")
        else:
            raise NotImplementedError("encode step %r (%s)" % (st.op, m.name))
    if len(o.L) == start:
        o(1, "pass")
    o(0, "")
    o(0, "")


def _read_scalar(o, ind, f, var):
    """`var, i = <one value of f>` per the plan's value codec, sign-extended (R-E5)."""
    c = f.value
    if c == "varint_i32":
        o(ind, "%s, i = _vr(b, i, end)" % var)
        o(ind, "%s = _i32(%s)" % (var, var))
    elif c == "varint_i64":
        o(ind, "%s, i = _vr(b, i, end)" % var)
        o(ind, "%s = _i64(%s)" % (var, var))
    elif c == "varint_bool":
        o(ind, "%s, i = _vr(b, i, end)" % var)
        o(ind, "%s = %s != 0" % (var, var))
    elif c == "fixed64_f64":
        o(ind, "%s, i = _f64(b, i, end)" % var)
    elif c == "fixed32_u32":
        o(ind, "%s, i = _u32(b, i, end)" % var)
    else:
        raise NotImplementedError("value codec %r (%s.%s)" % (c, f.owner, f.name))


def _read_blob(o, ind, f, var):
    o(ind, "_n, i = _len(b, i, end)")
    if f.kind == "string":
        o(ind, "%s = _str(b, i, _n)" % var)
    else:
        o(ind, "%s = b[i:i + _n]" % var)
    o(ind, "i += _n")


def _dec_message(p, m, o, retain):
    o(0, "def _d_%s(b, i, end, C, depth, o=None):" % m.name)
    o(1, "if depth > LIMIT:")
    o(2, "raise DecodeError(ERR_DEPTH, 'nesting')")
    o(1, "if o is None:")
    o(2, "o = C[%r]()" % m.name)
    if retain:
        o(1, "_u = None")
    o(1, "while i < end:")
    o(2, "_s0 = i")
    o(2, "_k = b[i]")
    o(2, "if _k < 128:")
    o(3, "i += 1")
    o(2, "else:")
    o(3, "_k, i = _vr(b, i, end)")
    o(2, "if _k < 8 or _k >> 3 > %d:" % MAX_FIELD_NUMBER)
    o(3, "raise DecodeError(ERR_MALFORMED, 'field number 0 or above 2^29-1')")
    first = True
    for (tag, wire), act in sorted(m.decode.items()):
        f = act.field
        o(2, "%s _k == %d:" % ("if" if first else "elif", _key_int(tag, wire)))
        first = False
        op = act.op
        if op == "set_scalar":
            _read_scalar(o, 3, f, "_v")
            o(3, "o.%s = _v" % f.name)
        elif op == "set_blob":
            _read_blob(o, 3, f, "o.%s" % f.name)
        elif op == "merge_child":
            # Plan rule: a repeated occurrence MERGES into the one already decoded (R-E4).
            o(3, "_n, i = _len(b, i, end)")
            o(3, "o.%s = _d_%s(b, i, i + _n, C, depth + 1, o.%s)" % (f.name, f.of, f.name))
            o(3, "i += _n")
        elif op == "append_message" and f.card != "map":
            o(3, "_n, i = _len(b, i, end)")
            o(3, "o.%s.append(_d_%s(b, i, i + _n, C, depth + 1))" % (f.name, f.of))
            o(3, "i += _n")
        elif op == "append_blob":
            _read_blob(o, 3, f, "_v")
            o(3, "o.%s.append(_v)" % f.name)
        elif op == "packed_run":
            o(3, "_n, i = _len(b, i, end)")
            o(3, "_l = o.%s" % f.name)
            o(3, "_e = end")
            o(3, "end = i + _n")
            o(3, "while i < end:")
            _read_scalar(o, 4, f, "_v")
            o(4, "_l.append(_v)")
            o(3, "end = _e")
        elif op == "packed_one":
            # The unpacked form, at the kind's own wire type only (R-E2).
            _read_scalar(o, 3, f, "_v")
            o(3, "o.%s.append(_v)" % f.name)
        # WP5 step 7: to the decode plan a map IS a repeated pair message (decision 11).
        elif op == "append_message" and f.card == "map":
            _dec_map_entry(p, m, f, o, 3)
        elif op == "oneof_set":
            if f.kind == "message":
                # Plan rule: the SAME member merges; another member starts from empty (R-E4).
                o(3, "_n, i = _len(b, i, end)")
                o(3, "_c = o.%s if o.%s_case == %d else None" % (f.name, act.oneof, f.tag))
                o(3, "o.%s = _d_%s(b, i, i + _n, C, depth + 1, _c)" % (f.name, f.of))
                o(3, "i += _n")
            elif f.is_blob:
                _read_blob(o, 3, f, "o.%s" % f.name)
            else:
                _read_scalar(o, 3, f, "_v")
                o(3, "o.%s = _v" % f.name)
            o(3, "o.%s_case = %d" % (act.oneof, f.tag))
        else:
            raise NotImplementedError("decode action %r (%s.%s)" % (op, m.name, f.name))
    o(2, "%s:" % ("else" if not first else "if True"))
    # Plan rule: a pair not in the table is UNKNOWN -- including a known field number at a
    # wire type the table has no entry for (R-E2) -- skipped (drop) or captured (retain).
    o(3, "i = _skip(b, i, end, _k >> 3, _k & 7)")
    if retain:
        o(3, "if _u is None:")
        o(4, "_u = bytearray()")
        o(3, "_u += b[_s0:i]")
    if retain:
        o(1, "if _u:")
        o(2, "o._unknown = o._unknown + bytes(_u) if o._unknown else bytes(_u)")
    o(1, "return o")
    o(0, "")
    o(0, "")


def _dec_map_entry(p, m, f, o, ind):
    em = p.msg(f.entry)
    o(ind, "_n, i = _len(b, i, end)")
    o(ind, "if depth + 1 > LIMIT:")
    o(ind + 1, "raise DecodeError(ERR_DEPTH, 'nesting')")
    defaults = {}
    for g in em.fields:
        if not g.is_blob:
            raise NotImplementedError("map %s.%s: a %s entry member" % (m.name, f.name, g.kind))
        defaults[g.name] = ZERO[g.kind]
    o(ind, "_mk, _mv = %s, %s" % (defaults["key"], defaults["value"]))
    o(ind, "_me = i + _n")
    o(ind, "while i < _me:")
    o(ind + 1, "_ek, i = _vr(b, i, _me)")
    o(ind + 1, "if _ek < 8 or _ek >> 3 > %d:" % MAX_FIELD_NUMBER)
    o(ind + 2, "raise DecodeError(ERR_MALFORMED, 'field number 0 or above 2^29-1')")
    first = True
    for (tag, wire), act in sorted(em.decode.items()):
        g = act.field
        if act.op != "set_blob":
            raise NotImplementedError("map %s.%s: entry action %s" % (m.name, f.name, act.op))
        x = "_mk" if g.name == "key" else "_mv"
        o(ind + 1, "%s _ek == %d:" % ("if" if first else "elif", _key_int(tag, wire)))
        first = False
        o(ind + 2, "_en, i = _len(b, i, _me)")
        if g.kind == "string":
            o(ind + 2, "%s = _str(b, i, _en)" % x)
        else:
            o(ind + 2, "%s = b[i:i + _en]" % x)
        o(ind + 2, "i += _en")
    o(ind + 1, "else:")
    # A facade map entry has no bag: an unknown field inside an entry is skipped in both
    # modes (`U-map-entry`, a disputed row; the core-native Rust control does the same).
    o(ind + 2, "i = _skip(b, i, _me, _ek >> 3, _ek & 7)")
    # Plan rule: a duplicate key replaces the earlier value (the host's map insert).
    o(ind, "o.%s[_mk] = _mv" % f.name)


def emit_pycodec(x, unknown="drop"):
    p = as_plan(x)
    if unknown not in ("drop", "retain"):
        raise ValueError("a facade codec is one mode; render both for both")
    if p.options.unknown != unknown:
        p = relower(p, p.options.with_unknown(unknown))
    retain = unknown == "retain"
    L = [HEAD % ("py_pure.py", p.source, p.options) + "\n",
         "README R3's no-boundary control, unknown fields %s: the plan's encode and decode" % unknown.upper(),
         "rendered into Python over the facade objects, with no crossing at all.",
         "",
         "Entry points, per root R:  encode_root_R(obj) -> bytes;  decode_root_R(buf, C) -> obj,",
         "where C maps a message name to its facade constructor (one decoder serves every",
         "storage). A refused input raises DecodeError, whose `code` is the core's code for it;",
         "after an error nothing is returned (plan rule, R-G6).",
         '"""']
    utf8_arg = "" if p.options.utf8 == "reject" else ', "replace"'
    L.append(PRELUDE % {"limit": p.options.recursion_limit, "utf8": p.options.utf8,
                        "unknown": unknown, "utf8_arg": utf8_arg,
                        "maxfield": MAX_FIELD_NUMBER, "glimit": GROUP_DEPTH_LIMIT})
    o = _Out()
    names = real_messages(p)
    for n in names:
        _enc_message(p, p.msg(n), o, retain)
    for n in names:
        _dec_message(p, p.msg(n), o, retain)
    L += o.L
    for r in p.roots:
        L += ["def encode_root_%s(o):" % r,
              "    out = bytearray()",
              "    _e_%s(o, out)" % r,
              "    return bytes(out)",
              "",
              "",
              "def decode_root_%s(b, C):" % r,
              "    b = bytes(b)",
              "    return _d_%s(b, 0, len(b), C, 0)" % r,
              "",
              ""]
    return "\n".join(L)
