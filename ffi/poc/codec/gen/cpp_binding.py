def _velem(ir, f):
    from cpp_names import FSCALAR
    if f.kind in ("string", "bytes"):
        return cppnames.string_type()
    if f.kind in ("message", "enum"):
        return f.of
    if f.kind in FSCALAR:
        return FSCALAR[f.kind]
    raise NotImplementedError("REFUSED: no C++ element type for kind %r" % f.kind)


def _run_call(ir, f, et, n, unk=False):
    if f.card == "map":
        return "ak_elem_%s(ctx, chunk, %s)" % (f.entry, n)
    if f.kind in ("string", "bytes"):
        return "ak_blob_run(ctx, chunk, %s)" % n
    if f.kind != "message" or et is None:
        raise NotImplementedError("REFUSED: no run entry point for %s %s" % (f.card, f.kind))
    u = "u" if unk else ""
    if ir.msg(et).leaf:
        return "ak_%selem_%s(ctx, chunk, %s)" % (u, et, n)
    return "ak_%selemu_%s(ctx, chunk, %s, (int64_t)done)" % (u, et, n)


def _lifecycle(p):
    """R-G7: `ak_init` rendered from `plan.lifecycle`, once, with a C++11 function-local
    static (thread-safe initialisation) so the call happens exactly once per process.
    `AK_BINDING_SKIP_INIT` is the PLANTED control only: the binding skips the call, and
    against a core built with `init-guard` every codec call must then fail."""
    lc = p.lifecycle
    name, _params, _ret = lc.init
    oname, ofields = lc.opts_struct
    names = [fn for fn, _ in ofields]
    if names != ["abi_version", "flags", "log", "log_ctx"]:
        raise NotImplementedError("REFUSED: plan.lifecycle's %s members changed (%s); the "
                                  "binding's fill must be re-rendered" % (oname, names))
    return [
        "// ABI v1 section 3, rendered from plan.lifecycle (R-G7).",
        "static int32_t ak_init_impl() {",
        "  struct %s o;" % oname,
        "  std::memset(&o, 0, sizeof o);",
        "  o.abi_version = AK_ABI_VERSION;",
        "  o.flags = %s;" % " | ".join(lc.default_flags),
        "  o.log = NULL;",
        "  o.log_ctx = NULL;",
        "  struct ak_err e;",
        "  std::memset(&e, 0, sizeof e);",
        "  int32_t rc = %s(&o, &e);" % name,
        "  return (rc == %s || rc == %s) ? AK_OK : rc;" % lc.success,
        "}",
        "",
        "int32_t ak_init_once() {",
        "#ifdef AK_BINDING_SKIP_INIT",
        "  // PLANTED control: the binding skips ak_init. Must fail against init-guard.",
        "  return AK_OK;",
        "#else",
        "  static const int32_t rc = ak_init_impl();",
        "  return rc;",
        "#endif",
        "}",
        "",
        "#define AK_INIT_OR_RETURN() \\",
        "  do { int32_t irc_ = ak_init_once(); if (irc_ != AK_OK) return irc_; } while (0)",
        "",
    ]


