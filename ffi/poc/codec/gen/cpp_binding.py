"""C++ backend: arm `core-ffi`, the C++ host binding over the C ABI, rendered from the PLAN.

FIX-PLAN WP5 step 2: moved from `poc/cpp/gen/cpp_binding.py` into the shared generator. It
takes a `plan.Plan` and reads only the plan's ABI LAYOUT functions (`presence_bits`,
`loop_slots`, `elem_type`, `direct_fields`, `abi_order_topo`) and descriptor view; it
renders `ak_init` from `plan.lifecycle` (R-G7) as `ak_init_once()`, which every entry
point of this binding calls before its first codec call. It decides no wire rule: the core
does the encoding and decoding, this file fills groups and materialises spans.

Two invariants from the specification are load-bearing here and both are GENERATED rather
than left to a binding author's discipline.

Section 6, "the fill must be total": every scalar and all three words of every `ak_str`
are assigned unconditionally, and the presence word is assigned rather than OR-ed. In
exchange the codec resets nothing between elements. A partial fill does not fail, it
silently inherits the previous element's value.

Section 5, the guard: every reverse-call accessor is wrapped so a host exception becomes
`ak_fail` plus a return. In C++ the hazard is not a managed exception but the same thing
one level down -- an exception crossing `extern "C"` into Rust is undefined behaviour --
so the guard is a `try/catch(...)`. Every published managed figure was taken WITHOUT the
guard, so this slice measures with it on and prices it separately.

One rule the decode side cannot do without: a message whose type carries a repeated or map
field is filled IN PLACE, never constructed, because `apply` arrives after the runs that
populated those fields (ABI v1 section 7.1).

Three arms are emitted per root, which is what ABI v1 open decision 1 needs:
  <root>            total fill, batched runs           the specified path
  <root>_zeroed     bulk clear + sparse fill, batched  decision 9's candidate
  <root>_nobatch    total fill, one element per call   "a host may decline to batch"
The transcoder is a parameter, so string-as-DATA (a core transcoder, zero crossings) and
string-as-a-CALL (a host transcoder, one reverse crossing per string) are the same code
with a different `Tcs`. That is the third mechanism decision 1 asks the price of.
"""
from plan import (abi_order_topo, as_plan, direct_fields, elem_type, loop_slots,
                  presence_bits, slot_name)
import cpp_names as cppnames
from cpp_names import camel, oneof_type, snake

HEAD_FMT = ("// @generated by ffi/poc/codec/gen/cpp_binding.py (plan from %s)."
            " Do not edit.\n")


def _head(p):
    return HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")

# The facade this binding is emitted against. `shapes` with `std::string` is the shipping
# one; `shapes_borrow` with `ak::StringView` is bench's measurement arm, which borrows
# every string from the input buffer instead of copying it. ABI v1 needs no change for it
# (section 4's `ak_span` is an offset into the host's own buffer, and 7.4 says to resolve
# it against the base pointer the host already holds), and it is exactly upb's aliasing
# contract. It is NOT what a facade ships by default: the strings are valid only while the
# input buffer lives.
NS = ["shapes"]


def _ns():
    return NS[0]


class _S(object):
    """The facade's string type, as a token usable in `%` formatting."""
    def __str__(self):
        return cppnames.string_type()
    def __mod__(self, other):
        return str(self) % other


S = _S()

NULLSTR = "ak_str_absent()"


def DIRECT(ir, root):
    """The one direct-argument field of this tree, as a C++ expression on the root object.

    ABI v1 section 8 builds the path for ONE field of one root message and the generator
    refuses anything else (`ir.check_direct`), so there is at most one.
    """
    ds = direct_fields(ir, root)
    if not ds:
        return None
    path, _f = ds[0]
    cur = root
    expr = "o"
    for comp in path[:-1]:
        fld = next(x for x in ir.msg(cur).plain if x.name == comp)
        expr = "(*%s.%s)" % (expr, comp)
        cur = fld.of
    return "%s.%s" % (expr, path[-1])


def has_slots(ir, name):
    return bool(loop_slots(ir, name))


def _str_arg(expr, tc):
    return "ak_str_of(%s, %s)" % (expr, tc)


SCALARS = ("int32", "int64", "double", "fixed32")


def map_kinds(ir, f):
    """The DECLARED key and value kinds of a map field's synthetic pair message.

    Every other blob site in this file derives its transcoder and its decode materialiser
    from the field's kind; the map path hardcoded `t.utf8` and the validating reader for
    both halves. `map<string, bytes>` is legal protobuf and would silently have had UTF-8
    validation applied to its value. A codegen rule discovered in one path is swept across
    the generator (README R10), so it is derived here and nowhere restated.
    """
    e = ir.msg(f.entry)
    k = next(x for x in e.plain if x.name == "key")
    v = next(x for x in e.plain if x.name == "value")
    return k.kind, v.kind


def map_tc(kind):
    if kind == "bytes":
        return "t.bytes"
    if kind == "string":
        return "t.utf8"
    raise NotImplementedError("REFUSED: a map half of kind %r is not a blob" % kind)


def map_reader(kind, base, span, ctx, dst):
    if kind == "string":
        return "s_of(%s, %s, %s, &%s);" % (base, span, ctx, dst)
    if kind == "bytes":
        return "b_of(%s, %s, &%s);" % (base, span, dst)
    raise NotImplementedError("REFUSED: a map half of kind %r is not a blob" % kind)


def _refuse(where, m, f):
    """R1's second half: a backend that has no case for a shape RAISES; it does not skip.

    Every dispatch in this file used to end in an unconditional scalar assignment, so a
    shape nobody thought of would have been EMITTED as a scalar store rather than refused.
    That is the class of defect that cost the rust slice a silently-missing oneof, and the
    only difference here is that no instance exists in `shapes.json` today. `gen/refusal_test.py`
    adds one and asserts every backend raises.
    """
    raise NotImplementedError(
        "REFUSED: %s has no case for %s.%s (card=%s kind=%s explicit=%s oneof=%s). "
        "A backend that cannot do a shape raises rather than emitting something plausible "
        "(README R1)." % (where, m.name if m is not None else "?", f.name, f.card, f.kind,
                          f.explicit, f.oneof))


# ---------------------------------------------------------------- encode groups

def _make_field(ir, m, f, o, unk=False):
    """One group member of the TOTAL fill. Assigned unconditionally, always. `unk`: the
    `ak_ufix_*` form (decision 11's bag), whose child slots are the children's u-groups."""
    n = f.name
    sfx, pre = ("_unk", "ak_ufix_") if unk else ("", "ak_efix_")
    if f.card != "singular":
        _refuse("the encode group fill", m, f)
    if f.kind in ("string", "bytes"):
        tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
        if f.direct:
            # ABI v1 section 8: the sentinel says the bytes are an ARGUMENT of the call,
            # not a pointer into staging. C++ never needs it -- there is nothing to pin --
            # and pays nothing for it; it is built so the path is exercised.
            o.append("  g.%s = ak_str_direct(o.%s.size());" % (n, n))
        elif f.explicit:
            o.append("  g.%s = o.%s.has_value() ? %s : %s;"
                     % (n, n, _str_arg("*o." + n, tc), NULLSTR))
        else:
            o.append("  g.%s = %s;" % (n, _str_arg("o." + n, tc)))
    elif f.kind == "message":
        o.append("  g.%s = o.%s.has_value() ? make_%s%s(*o.%s, t) : %s%s();"
                 % (n, n, snake(f.of), sfx, n, pre, f.of))
    elif f.kind == "enum":
        o.append("  g.%s = o.%s.v;" % (n, n))
    elif f.kind == "bool":
        if f.explicit:
            o.append("  g.%s = (uint8_t)(o.%s.has_value() && *o.%s);" % (n, n, n))
        else:
            o.append("  g.%s = (uint8_t)(o.%s ? 1 : 0);" % (n, n))
    elif f.kind in SCALARS:
        if f.explicit:
            o.append("  g.%s = o.%s.has_value() ? *o.%s : 0;" % (n, n, n))
        else:
            o.append("  g.%s = o.%s;" % (n, n))
    else:
        _refuse("the encode group fill", m, f)


def _oneof_make(ir, m, oname, members, o, unk=False):
    ty = oneof_type(m.name, oname)
    sfx, pre = ("_unk", "ak_ufix_") if unk else ("", "ak_efix_")
    o.append("  g.%s_case = (uint32_t)o.%s.which();" % (oname, oname))
    for gm in members:
        slot = "%s_%s" % (oname, gm.name)
        acc = "o.%s.%s()" % (oname, gm.name)
        cond = "o.%s.which() == %s::%s::k%s" % (oname, _ns(), ty, camel(gm.name))
        if gm.kind in ("string", "bytes"):
            tc = "t.bytes" if gm.kind == "bytes" else "t.utf8"
            o.append("  g.%s = %s ? %s : %s;" % (slot, cond, _str_arg(acc, tc), NULLSTR))
        elif gm.kind == "message":
            o.append("  g.%s = %s ? make_%s%s(%s, t) : %s%s();"
                     % (slot, cond, snake(gm.of), sfx, acc, pre, gm.of))
        elif gm.kind == "bool":
            o.append("  g.%s = (uint8_t)(%s ? (%s ? 1 : 0) : 0);" % (slot, cond, acc))
        elif gm.kind in SCALARS or gm.kind == "enum":
            o.append("  g.%s = %s ? %s : 0;" % (slot, cond, acc))
        else:
            _refuse("the encode group's oneof fill", m, gm)


def _sparse_field(ir, m, f, o, bits):
    """Decision 9's candidate: the host bulk-clears the chunk and assigns only what differs
    from the default. The codec still resets nothing between elements; only the host's fill
    changes."""
    n = f.name
    if f.card != "singular":
        _refuse("the sparse encode group fill", m, f)
    if f.kind in ("string", "bytes"):
        tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
        if f.direct:
            o.append("  if (!o.%s.empty()) d->%s = ak_str_direct(o.%s.size());" % (n, n, n))
        elif f.explicit:
            o.append("  if (o.%s.has_value()) { d->%s = %s; d->presence |= 1u << %d; }"
                     % (n, n, _str_arg("*o." + n, tc), bits[n]))
        else:
            o.append("  if (!o.%s.empty()) d->%s = %s;" % (n, n, _str_arg("o." + n, tc)))
    elif f.kind == "message":
        o.append("  if (o.%s.has_value()) { fill_%s_sparse(&d->%s, *o.%s, t);"
                 " d->presence |= 1u << %d; }" % (n, snake(f.of), n, n, bits[n]))
    elif f.kind == "enum":
        o.append("  if (o.%s.v != 0) d->%s = o.%s.v;" % (n, n, n))
    elif f.explicit:
        if f.kind == "bool":
            o.append("  if (o.%s.has_value()) { d->%s = (uint8_t)(*o.%s ? 1 : 0);"
                     " d->presence |= 1u << %d; }" % (n, n, n, bits[n]))
        else:
            o.append("  if (o.%s.has_value()) { d->%s = *o.%s;"
                     " d->presence |= 1u << %d; }" % (n, n, n, bits[n]))
    elif f.kind == "bool":
        o.append("  if (o.%s) d->%s = 1;" % (n, n))
    elif f.kind in SCALARS:
        o.append("  if (o.%s != 0) d->%s = o.%s;" % (n, n, n))
    else:
        _refuse("the sparse encode group fill", m, f)


def _oneof_sparse(ir, m, oname, members, o):
    ty = oneof_type(m.name, oname)
    o.append("  if (o.%s.which() != %s::%s::kNotSet) {" % (oname, _ns(), ty))
    o.append("    d->%s_case = (uint32_t)o.%s.which();" % (oname, oname))
    o.append("    switch (o.%s.which()) {" % oname)
    for gm in members:
        acc = "o.%s.%s()" % (oname, gm.name)
        slot = "%s_%s" % (oname, gm.name)
        o.append("      case %s::%s::k%s:" % (_ns(), ty, camel(gm.name)))
        if gm.kind in ("string", "bytes"):
            tc = "t.bytes" if gm.kind == "bytes" else "t.utf8"
            o.append("        d->%s = %s; break;" % (slot, _str_arg(acc, tc)))
        elif gm.kind == "message":
            o.append("        fill_%s_sparse(&d->%s, %s, t); break;"
                     % (snake(gm.of), slot, acc))
        elif gm.kind == "bool":
            o.append("        d->%s = (uint8_t)(%s ? 1 : 0); break;" % (slot, acc))
        elif gm.kind in SCALARS or gm.kind == "enum":
            o.append("        d->%s = %s; break;" % (slot, acc))
        else:
            _refuse("the sparse encode group's oneof fill", m, gm)
    o.append("      default: break;")
    o.append("    }")
    o.append("  }")


# ---------------------------------------------------------------- decode


def _decode_field(ir, m, f, o, bits, dst):
    n = f.name
    if f.card != "singular":
        _refuse("the decode group read", m, f)
    if f.kind == "string":
        if f.explicit:
            o.append("  if (f.presence & (1u << %d)) s_of(base, f.%s, ctx, &%s.emplace());"
                     % (bits[n], n, dst + n))
        else:
            o.append("  s_of(base, f.%s, ctx, &%s);" % (n, dst + n))
    elif f.kind == "bytes":
        if f.explicit:
            o.append("  if (f.presence & (1u << %d)) b_of(base, f.%s, &%s.emplace());"
                     % (bits[n], n, dst + n))
        else:
            o.append("  b_of(base, f.%s, &%s);" % (n, dst + n))
    elif f.kind == "message":
        if has_slots(ir, f.of):
            o.append("  if (f.presence & (1u << %d)) fill_%s(&%s.get_or_insert(), f.%s, base, ctx);"
                     % (bits[n], snake(f.of), dst + n, n))
            o.append("  else %s.reset();" % (dst + n))
        else:
            o.append("  if (f.presence & (1u << %d)) %s.set(from_%s(f.%s, base, ctx));"
                     % (bits[n], dst + n, snake(f.of), n))
            o.append("  else %s.reset();" % (dst + n))
    elif f.kind == "enum":
        o.append("  %s = %s::%s(f.%s);" % (dst + n, _ns(), f.of, n))
    elif f.explicit:
        conv = "(f.%s != 0)" % n if f.kind == "bool" else "f.%s" % n
        o.append("  if (f.presence & (1u << %d)) %s.set(%s);" % (bits[n], dst + n, conv))
        o.append("  else %s.reset();" % (dst + n))
    elif f.kind == "bool":
        o.append("  %s = (f.%s != 0);" % (dst + n, n))
    elif f.kind in SCALARS:
        o.append("  %s = f.%s;" % (dst + n, n))
    else:
        _refuse("the decode group read", m, f)


def _decode_oneof(ir, m, oname, members, o, dst):
    ty = oneof_type(m.name, oname)
    o.append("  switch (f.%s_case) {" % oname)
    for gm in members:
        slot = "%s_%s" % (oname, gm.name)
        o.append("    case %d: {" % gm.tag)
        if gm.kind == "string":
            o.append("      s_of(base, f.%s, ctx, &%s.set_%s()); break; }"
                     % (slot, dst + oname, gm.name))
        elif gm.kind == "bytes":
            o.append("      b_of(base, f.%s, &%s.set_%s()); break; }"
                     % (slot, dst + oname, gm.name))
        elif gm.kind == "message":
            if has_slots(ir, gm.of):
                raise NotImplementedError("a oneof member with loop slots (%s.%s)"
                                          % (m.name, gm.name))
            o.append("      %s.set_%s() = from_%s(f.%s, base, ctx); break; }"
                     % (dst + oname, gm.name, snake(gm.of), slot))
        elif gm.kind == "bool":
            o.append("      %s.set_%s() = (f.%s != 0); break; }" % (dst + oname, gm.name, slot))
        elif gm.kind in SCALARS or gm.kind == "enum":
            o.append("      %s.set_%s() = f.%s; break; }" % (dst + oname, gm.name, slot))
        else:
            _refuse("the decode group's oneof read", m, gm)
    o.append("    default: %s.clear(); break;" % (dst + oname))
    o.append("  }")


# ---------------------------------------------------------------- loops


def _nav(ir, start, prefix, var, o, src_name):
    """Walk a loop slot's prefix of singular message children from `var`."""
    cur = start
    expr = var
    for i, comp in enumerate(prefix):
        fld = next(f for f in ir.msg(cur).plain if f.name == comp)
        o.append("    if (!%s.%s.has_value()) return AK_OK;" % (expr, comp))
        expr = "(*%s.%s)" % (expr, comp)
        cur = fld.of
    o.append("    const %s &%s_owner = %s;" % (cur, src_name, expr))
    return cur


def _emit_loop(ir, o, root, path, f, fname, elem_of=None, batch=True, zeroed=False, unk=False):
    """One reverse-call loop over a host container. Chunked at ABI v1 7.3's 32 KB arena, or
    one element per call when `batch` is false -- "a host may decline to batch at all and
    loses only what its own crossing costs", which is the arm that prices the predicate."""
    et = elem_type(f)
    if f.card == "packed":
        cty = {"int32": "int32_t", "int64": "int64_t", "double": "double",
               "bool": "uint8_t", "enum": "int32_t"}[f.kind]
        run = {"int32": "ak_run_i32", "int64": "ak_run_i64", "double": "ak_run_f64",
               "bool": "ak_run_u8", "enum": "ak_run_i32"}[f.kind]
    elif f.card == "map":
        cty = "struct ak_efix_%s" % f.entry
    elif f.card == "repeated" and f.kind in ("string", "bytes"):
        cty = "struct ak_str"
    elif f.card == "repeated" and f.kind == "message":
        if et is None:
            _refuse("the encode loop", ir.msg(root), f)
        cty = "struct %s_%s" % ("ak_ufix" if unk else "ak_efix", et)
    else:
        _refuse("the encode loop", ir.msg(root), f)

    o.append("static int32_t %s(ak_enc_ctx *ctx, const void *obj, int64_t token) {" % fname)
    o.append("  AK_GUARD_BEGIN")
    o.append("    const EncObj_%s *h = (const EncObj_%s *)obj;" % (root, root))
    o.append("    const Tcs &t = h->t;")
    o.append("    (void)t; (void)token;")
    if elem_of is None:
        owner = _nav(ir, root, path[:-1], "(*h->o)", o, "src")
    else:
        # A slot that lives on the ELEMENT of a top-level repeated field: the codec names
        # the element by token, and a token is an INDEX, never an address (section 10).
        o.append("    const %s &el = (*h->o).%s[(size_t)token];" % (elem_of[1], elem_of[0]))
        owner = _nav(ir, elem_of[1], path[:-1], "el", o, "src")
    last = path[-1]
    srcty = ("std::map<%s, %s>" % (S, S) if f.card == "map"
             else "std::vector<%s>" % _velem(ir, f))
    o.append("    const %s &src = src_owner.%s;" % (srcty, last))
    if f.card == "packed" and f.kind in ("bool", "enum"):
        # "Its own array" is doing work in that sentence: a vector<bool> or a vector<Enum>
        # is not the wire layout, so the binding materialises a contiguous array first and
        # part of the crossing saved is paid back as a copy. The cost is the host's to
        # avoid by choosing its storage, and this arm shows what it is.
        o.append("    std::vector<%s> flat;" % cty)
        o.append("    flat.reserve(src.size());")
        if f.kind == "bool":
            o.append("    for (size_t i = 0; i < src.size(); ++i) flat.push_back(src[i] ? 1 : 0);")
        else:
            o.append("    for (size_t i = 0; i < src.size(); ++i) flat.push_back(src[i].v);")
        o.append("    if (!flat.empty()) { AK_TAX(); int32_t rc = %s(ctx, &flat[0], flat.size());"
                 " if (rc < 0) return rc; }" % run)
        o.append("  AK_GUARD_END")
        o.append("}")
        o.append("")
        return
    if f.card == "packed":
        o.append("    if (!src.empty()) { AK_TAX(); int32_t rc = %s(ctx, &src[0], src.size());"
                 " if (rc < 0) return rc; }" % run)
        o.append("  AK_GUARD_END")
        o.append("}")
        o.append("")
        return

    sparse = zeroed and f.card == "repeated" and f.kind == "message"
    if batch:
        o.append("    constexpr size_t kChunk = ak::arena_n(sizeof(%s));" % cty)
    else:
        o.append("    constexpr size_t kChunk = 1;  // the host declines to batch")
    o.append("    %s chunk[kChunk];" % cty)
    if sparse:
        o.append("    // Clear only what will be USED, never the whole 32 KB arena: the clear")
        o.append("    // is otherwise O(arena) where the fill is O(elements), so on a 1- or")
        o.append("    // 4-element payload the candidate inverts. Measured with the whole-chunk")
        o.append("    // clear (which is what the rust slice built): P1.1 +156 ns/element and")
        o.append("    // P2.1 +550, against protobuf encodes of 165 and 1205 ns/element.")
        o.append("    const size_t kClear = src.size() < kChunk ? src.size() : kChunk;")
        o.append("    // All-zero is a valid group, and the bulk clear is what lets the")
        o.append("    // fill below be sparse (ABI v1 open decision 9's candidate). Only an")
        o.append("    // ELEMENT GROUP is filled sparsely: a blob run and a map entry are")
        o.append("    // assigned in full, so clearing their chunk would be pure waste -- and")
        o.append("    // an inner loop runs once per element, so that waste would be paid 500")
        o.append("    // times per encode. Measured: P2.2 encode 1.94 of protobuf before this")
        o.append("    // and 0.6x after, which is the whole arm rather than a detail.")
        o.append("    if (kClear) std::memset(chunk, 0, kClear * sizeof(%s));" % cty)
    o.append("    size_t i = 0, done = 0;")
    o.append("    (void)done;")
    if f.card == "map":
        o.append("    for (std::map<%s, %s>::const_iterator it = src.begin();" % (S, S) +
                 " it != src.end(); ++it) {")
        kk, vk = map_kinds(ir, f)
        o.append("      chunk[i].key = ak_str_of(it->first, %s);" % map_tc(kk))
        o.append("      chunk[i].value = ak_str_of(it->second, %s);" % map_tc(vk))
        o.append("      chunk[i].presence = 0;")
    else:
        o.append("    for (size_t k = 0; k < src.size(); ++k) {")
        if f.kind in ("string", "bytes"):
            tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
            o.append("      chunk[i] = ak_str_of(src[k], %s);" % tc)
        elif sparse:
            o.append("      fill_%s_sparse(&chunk[i], src[k], t);" % snake(et))
        else:
            o.append("      chunk[i] = make_%s%s(src[k], t);" % (snake(et), "_unk" if unk else ""))
    o.append("      ++i;")
    o.append("      if (i == kChunk) {")
    o.append("        AK_TAX();")
    o.append("        int32_t rc = %s;" % _run_call(ir, f, et, "(int32_t)i", unk))
    o.append("        if (rc < 0) return rc;")
    o.append("        done += i;")
    if sparse:
        o.append("        // Only what was dirtied is put back.")
        o.append("        std::memset(chunk, 0, i * sizeof(%s));" % cty)
    o.append("        i = 0;")
