"""C++ backend: the C header of ABI v1 (`ak_abi.h`), rendered from the PLAN only.

FIX-PLAN WP5 step 2 (R-E6, R-G5, R-G7). Before this the header was emitted by the cpp
slice's `cpp_header.py` from the IR and `rust_abi`'s helpers, and `ak_client_opts` was
parsed out of `ak-abi/src/lib.rs` with a regular expression, while the rest of the RPC
half (`ak_bytes`, `ak_completion`, every RPC prototype) was hand-declared in the cpp
slice's `src/rpc_common.h` -- a third copy of a declaration the core had twice (R-G5).

Everything per-message here comes from `plan.py`'s ABI LAYOUT functions (`group_fields`,
`ugroup_fields`, `presence_bits`, `loop_slots`, `slot_elem`, `vtable_messages`,
`element_types`, `abi_order_topo`, `direct_fields`) and the layout facts from
`cpp_layout.facts`, the same enumeration the core's run-time export is generated from;
the RPC half from `plan.rpc`; the lifecycle from `plan.lifecycle`. This module adds no
member, reorders none and derives no layout (the plan contract's "may not").

What it states as FIXED TEXT, because the plan does not carry it (reported to the
aggregating session, see `poc/cpp/STATE.md`): section 5's error codes and section 4's
common vocabulary (`ak_str`, `ak_span`, `ak_blob`, `ak_uspan`, the callback types), the
fixed exports of sections 3 to 5 (context lifetime, `ak_enc_take`, transcoders, counters),
and three lifecycle facts `plan.lifecycle` names but does not define: the `ak_err` layout,
the `ak_log_fn` signature and the numeric values of the `AK_INIT_*` flags. Those three are
written to match `poc/codec/crates/ak-abi/src/lib.rs` and pinned by `AK_SASSERT` below, so
a change there that this text does not follow is at least a size mismatch the host sees.

C99/C++11 clean: nothing here depends on the standard level (README 5.1's hard stop).
"""
from plan import (abi_order_topo, as_plan, direct_fields, element_types, elem_type,
                  group_fields, loop_slots, presence_bits, slot_elem, slot_name,
                  ugroup_fields, vtable_messages)
from cpp_names import C_OF, cty
import cpp_layout

HEAD_FMT = ("/* @generated by ffi/poc/codec/gen/cpp_abi.py (plan from %s)."
            " Do not edit. */\n")

# The packed-run symbols: one per host array layout. The core renders the same four
# (`rust_abi.emit_codec`); a packed field's element type is `plan.slot_elem(f)`.
RUN_TYPES = ("i32", "i64", "f64", "u8")

FIXED_TOP = """
/* The C ABI of ffi/design/ABI-v1.md, version 1.
 *
 * Fixed part (sections 3, 4, 5, 9, 10) and per-message part (section 6's groups and
 * vtables, section 7's fixes). C99/C++11 clean: nothing here depends on the standard
 * level, which is the hard stop README section 5.1 puts on the cpp host.
 */
#ifndef AK_ABI_H
#define AK_ABI_H

#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

/* ---- section 5: errors ---------------------------------------------------------- */
#define AK_OK                   0
#define AK_ALREADY_INITIALIZED  1
#define AK_ERR_HOST            (-1)
#define AK_ERR_MALFORMED       (-2)
#define AK_ERR_TRUNCATED       (-3)
#define AK_ERR_DEPTH           (-4)
#define AK_ERR_LIMIT           (-5)
#define AK_ERR_TRANSCODE       (-6)
#define AK_ERR_CAPACITY        (-7)
#define AK_ERR_INVALID_STATE   (-8)
#define AK_ERR_PANIC           (-9)
#define AK_ERR_UNINITIALIZED  (-10)
#define AK_ERR_ABI            (-11)

#define AK_ABI_VERSION 1u

/* ---- section 4: common vocabulary ------------------------------------------------ */

typedef int32_t (*ak_grow_fn)(void *sink, int32_t want, uint8_t **dst, int32_t *cap);
typedef int32_t (*ak_transcode_fn)(const void *src, size_t len,
                                   uint8_t *dst, int32_t cap,
                                   ak_grow_fn grow, void *sink);

/* Encode: a string or bytes field as DATA inside the group, never a call. `len` counts
 * SOURCE code units; for a C++ host holding std::string that is bytes. `tc == NULL` means
 * the field is ABSENT, which is how a group tells absent from present-and-empty. */
struct ak_str { const void *data; size_t len; ak_transcode_fn tc; };

/* ABI v1 section 8: a reserved `data` value meaning "this field is a direct argument of
 * the call". C++ never needs it (there is nothing to pin) and pays nothing for it. */
#define AK_STR_DIRECT ((const void *)(uintptr_t)1)

/* Decode: an OFFSET into the buffer the host handed in, plus a byte length. */
struct ak_span { uint32_t off, len, coder; };

/* Decision 11's unknown-field bag: two words, not three. */
struct ak_blob { const void *data; size_t len; };

/* An unknown-field run delivered on decode: which object (a token: AK_TOKEN_ROOT or the
 * element index the codec minted), and where in the input buffer. */
struct ak_uspan { int64_t token; uint32_t off, len; };

#define AK_TOKEN_ROOT ((int64_t)-1)

typedef struct ak_enc_ctx ak_enc_ctx;
typedef struct ak_dec_ctx ak_dec_ctx;

typedef int32_t (*ak_loop_f)(ak_enc_ctx *ctx, const void *obj, int64_t token);
typedef void (*ak_unk_f)(ak_dec_ctx *ctx, void *obj, const struct ak_uspan *spans, int32_t n);
""".lstrip("\n")

FIXED_EXPORTS = """
/* ---- the fixed exports (sections 3, 4, 5) ---------------------------------------- */
uint32_t ak_abi_version(void);
ak_enc_ctx *ak_enc_ctx_new(void);
void ak_enc_ctx_free(ak_enc_ctx *);
void ak_enc_reset(ak_enc_ctx *);
int32_t ak_enc_take(ak_enc_ctx *, const uint8_t **ptr, size_t *len);
int32_t ak_enc_err(const ak_enc_ctx *);
ak_dec_ctx *ak_dec_ctx_new(void);
void ak_dec_ctx_free(ak_dec_ctx *);
void ak_fail(void *ctx, int32_t code, const uint8_t *msg, uint32_t msg_len);
int32_t ak_dec_err(const ak_dec_ctx *);
void ak_dec_err_reset(ak_dec_ctx *);
ak_transcode_fn ak_tc_utf8(void);
ak_transcode_fn ak_tc_utf8_trusted(void);
ak_transcode_fn ak_tc_utf8_simd(void);
ak_transcode_fn ak_tc_bytes(void);

/* README R5: counted in the CORE, so a call the optimiser removed is not counted. */
struct AkCounters {
  uint64_t forward, reverse, transcode, prefix_moves, prefix_bytes, grows;
};
void ak_enc_counters(const ak_enc_ctx *, struct AkCounters *out);
/* Counting build only: the HOST reports a reverse crossing the core cannot see, because
 * `ak_str.tc` may point into either image and the counter lives in the core. */
void ak_enc_count_reverse(ak_enc_ctx *);
void ak_enc_counters_reset(ak_enc_ctx *);
void ak_dec_counters(const ak_dec_ctx *, struct AkCounters *out);
void ak_dec_counters_reset(ak_dec_ctx *);
size_t ak_enc_site_moves(const ak_enc_ctx *, uint32_t *out, size_t cap);

/* The boundary priced on its own, in the same process and build as the arms. */
uint64_t ak_noop(uint64_t x);
uint64_t ak_noop_reverse(uint64_t (*f)(uint64_t), uint64_t x);
""".strip("\n")

SASSERT = """
/* ABI v1 section 10 and obligation 12.3: layouts asserted, not assumed. */
#ifdef __cplusplus
#define AK_SASSERT(c, m) static_assert(c, m)
#else
#define AK_SASSERT_CAT2(a, b) a##b
#define AK_SASSERT_CAT(a, b) AK_SASSERT_CAT2(a, b)
#define AK_SASSERT(c, m) typedef char AK_SASSERT_CAT(ak_sa_, __LINE__)[(c) ? 1 : -1]
#endif
""".strip("\n")


def _join(ty, name):
    """`int32_t x`, `void *x`: a pointer declarator binds to the name."""
    return "%s%s%s" % (ty, "" if ty.endswith("*") else " ", name)


def _decl(name, params, ret):
    args = ", ".join(_join(cty(t), a) for a, t in params) or "void"
    return "%s(%s);" % (_join(cty(ret) if ret else "void", name), args)


def _lifecycle(p):
    """ABI v1 section 3, from `plan.lifecycle` (R-G7). The struct members and the
    prototype are the plan's; `ak_err`, `ak_log_fn` and the flag values are fixed text
    (see the module docstring) pinned by size assertions."""
    lc = p.lifecycle
    oname, ofields = lc.opts_struct
    o = ["/* ---- section 3: the lifecycle (plan.lifecycle, R-G7) ----------------------------",
         " * Every binding rendered from this plan calls `%s` before its first codec or RPC" % lc.init[0],
         " * call and treats %s and %s as success. A core built with `%s`" % (lc.success + (lc.gate_feature,)),
         " * refuses every entry point with AK_ERR_UNINITIALIZED until it has. */",
         "#define AK_INIT_OWN_LOGGING   (1u << 0)",
         "#define AK_INIT_NO_PANIC_HOOK (1u << 1)",
         "#define AK_INIT_NO_CRYPTO     (1u << 2)",
         "typedef void (*ak_log_fn)(void *ctx, uint32_t level, const uint8_t *msg, size_t msg_len);",
         "struct %s {" % oname]
    for fn, ty in ofields:
        base = ty.split(" (")[0]
        o.append("  %s;%s" % (_join(cty(base), fn), "  /* nullable */" if "nullable" in ty else ""))
    o.append("};")
    o.append("struct ak_err { int32_t code; uint32_t detail; };")
    name, params, ret = lc.init
    o.append(_decl(name, params, ret))
    o.append("int32_t ak_initialized(void);")
    o.append("")
    return o


def _lifecycle_asserts(p):
    oname, ofields = p.lifecycle.opts_struct
    o = ["AK_SASSERT(sizeof(struct ak_err) == 8, \"sizeof ak_err\");",
         "AK_SASSERT(offsetof(struct %s, %s) == 0, \"%s.%s\");"
         % (oname, ofields[0][0], oname, ofields[0][0]),
         "AK_SASSERT(sizeof(struct %s) == 8 + 2 * sizeof(void *), \"sizeof %s\");"
         % (oname, oname), ""]
    return o


def _rpc(p):
    """ABI v1 section 9, from `plan.rpc` (R-G5): handles, structs, the callback type, the
    constants and every prototype, once. `ak_client_opts`'s layout is asserted member by
    member with offsets from the host compiler, so the host cannot read past it (R-D2)."""
    r = p.rpc
    o = ["/* ---- section 9: the RPC half (plan.rpc, R-G5) -----------------------------------",
         " * Declared only here. A host never hand-declares one of these: R-D2 was a 3-field",
         " * copy of a 6-field struct, R-G5 a `u64` timeout declared `i32` on one side. */"]
    for h in r.handles:
        o.append("typedef struct %s %s;" % (h, h))
    for name, doc, fields in r.structs:
        o.append("/* %s */" % doc)
        o.append("struct %s {" % name)
        for fn, ty, fdoc in fields:
            o.append("  %s;%s" % (_join(cty(ty), fn), ("  /* %s */" % fdoc) if fdoc else ""))
        o.append("};")
        o.append("#define %s_FIELDS %d" % (name.upper(), len(fields)))
    for name, params, ret, doc in r.callbacks:
        o.append("/* %s */" % doc)
        o.append("typedef %s (*%s)(%s);" % (cty(ret) if ret else "void", name,
                                            ", ".join(_join(cty(t), a) for a, t in params)))
    for name, ty, val, doc in r.constants:
        o.append("#define %s %d  /* %s */" % (name, val, doc))
    for name, params, ret, doc in r.functions:
        if doc:
            o.append("/* %s */" % doc)
        o.append(_decl(name, params, ret))
    o.append("")
    return o


def _rpc_asserts(p):
    """Every RPC struct's size is at least the sum of its members and every member is where
    the host compiler put it -- which is what the core's `rpc_check.rs` asserts on the Rust
    side against the SAME plan. The member offsets for a struct of 4-byte scalars only
    (ak_client_opts) are also pinned as numbers, because that is the struct R-D2 was."""
    o = []
    for name, _doc, fields in p.rpc.structs:
        if all(C_OF.get(ty) in ("uint32_t", "int32_t") for _f, ty, _d in fields):
            o.append("AK_SASSERT(sizeof(struct %s) == %d, \"sizeof %s\");"
                     % (name, 4 * len(fields), name))
            for i, (fn, _ty, _d) in enumerate(fields):
                o.append("AK_SASSERT(offsetof(struct %s, %s) == %d, \"%s.%s\");"
                         % (name, fn, 4 * i, name, fn))
    o.append("")
    return o


def emit(x):
    """(ak_abi.h, ak_layout.h, ak_layout_names.h) for a plan."""
    p = as_plan(x)
    head = HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json")
    o = [head, FIXED_TOP]

    # ---- per-message groups (plan.group_fields / ugroup_fields / presence_bits) --------
    layout_asserts = cpp_layout.facts(p)
    for name in abi_order_topo(p):
        m = p.msg(name)
        bits = presence_bits(m)
        for pre in ("e", "d", "u"):
            sname = "ak_%sfix_%s" % (pre, name)
            fields = ugroup_fields(m) if pre == "u" else group_fields(m, pre != "d")
            o.append("/* %s group for `%s`.%s */" % (
                "Decode" if pre == "d" else "Encode", name,
                "  With the unknown-field bag (decision 11 candidate)." if pre == "u" else ""))
            o.append("struct %s {" % sname)
            for fname, ty in fields:
                o.append("  %s %s;" % (cty(ty), fname))
            o.append("  uint32_t presence;")
            o.append("};")
            for fname, b in bits.items():
                o.append("#define %s_PRESENT_%s (1u << %d)" % (sname.upper(), fname.upper(), b))
            o.append("")

    # ---- vtables (plan.vtable_messages / loop_slots / slot_elem) ------------------------
    for name in vtable_messages(p):
        slots = loop_slots(p, name)
        o.append("/* Encode vtable for `%s`. %s */" %
                 (name, "Empty: nothing in this message needs a call."
                  if not slots else "One slot per field that could not ride in the group."))
        o.append("struct ak_evt_%s {" % name)
        if not slots:
            o.append("  /* Reserved: an empty struct has no defined size in C. */")
            o.append("  const void *_reserved;")
        for path, f in slots:
            o.append("  ak_loop_f loop_%s;" % slot_name(path))
            et = elem_type(f)
            if et and loop_slots(p, et):
                o.append("  const struct ak_evt_%s *elem_%s;" % (et, slot_name(path)))
        o.append("};")
        o.append("")
        o.append("/* Decode vtable for `%s` (the push family, ABI v1 section 7.1). */" % name)
        o.append("struct ak_dvt_%s {" % name)
        o.append("  void (*apply)(ak_dec_ctx *, void *, const struct ak_dfix_%s *);" % name)
        o.append("  ak_unk_f unknown;")
        for path, f in slots:
            sn = slot_name(path)
            dty, _ = slot_elem(f)
            et = elem_type(f)
            batchable = not (et and not p.msg(et).leaf)
            if et:
                o.append("  ak_unk_f unk_%s;" % sn)
            if batchable:
                o.append("  void (*add_%s)(ak_dec_ctx *, void *, int64_t, const %s *, int32_t);"
                         % (sn, cty(dty)))
            else:
                o.append("  int64_t (*new_%s)(ak_dec_ctx *, void *);" % sn)
                o.append("  void (*apply_%s)(ak_dec_ctx *, void *, int64_t, const struct ak_dfix_%s *);"
                         % (sn, et))
                for ipath, iff in loop_slots(p, et):
                    idty, _ = slot_elem(iff)
                    iet = elem_type(iff)
                    if iet and not p.msg(iet).leaf:
                        raise NotImplementedError(
                            "a non-leaf element inside a non-leaf element (%s.%s)"
                            % (et, slot_name(ipath)))
                    o.append("  void (*add_%s_%s)(ak_dec_ctx *, void *, int64_t, const %s *, int32_t);"
                             % (sn, slot_name(ipath), cty(idty)))
        o.append("};")
        o.append("")

    # ---- entry points --------------------------------------------------------------
    o.append("/* ABI v1 section 6: what the host calls are PLAIN EXPORTS, not a table. */")
    for root in p.roots:
        dargs = ", const uint8_t *direct, size_t direct_len" if direct_fields(p, root) else ""
        o.append("intptr_t ak_encode_%s(const void *obj, ak_enc_ctx *ctx,"
                 " const struct ak_evt_%s *vt, const struct ak_efix_%s *fix%s);"
                 % (root, root, root, dargs))
        o.append("intptr_t ak_uencode_%s(const void *obj, ak_enc_ctx *ctx,"
                 " const struct ak_evt_%s *vt, const struct ak_ufix_%s *fix%s);"
                 % (root, root, root, dargs))
        o.append("int32_t ak_decode_%s(ak_dec_ctx *ctx, void *obj, const uint8_t *buf,"
                 " size_t len, const struct ak_dvt_%s *vt);" % (root, root))
    for et in sorted(element_types(p)):
        if p.msg(et).leaf:
            o.append("int32_t ak_elem_%s(ak_enc_ctx *ctx, const struct ak_efix_%s *elems, int32_t n);"
                     % (et, et))
            o.append("int32_t ak_uelem_%s(ak_enc_ctx *ctx, const struct ak_ufix_%s *elems, int32_t n);"
                     % (et, et))
        else:
            o.append("int32_t ak_elemu_%s(ak_enc_ctx *ctx, const struct ak_efix_%s *elems,"
                     " int32_t n, int64_t tok0);" % (et, et))
            o.append("int32_t ak_uelemu_%s(ak_enc_ctx *ctx, const struct ak_ufix_%s *elems,"
                     " int32_t n, int64_t tok0);" % (et, et))
    o.append("int32_t ak_blob_run(ak_enc_ctx *ctx, const struct ak_str *elems, int32_t n);")
    for ty in RUN_TYPES:
        o.append("int32_t ak_run_%s(ak_enc_ctx *ctx, const %s *p, size_t n);" % (ty, C_OF[ty]))
    o.append("")
    o.append(FIXED_EXPORTS)
    o.append("")
    o.extend(_lifecycle(p))
    o.extend(_rpc(p))

    # ---- section 10: group layouts exported and asserted ---------------------------
    o.append(SASSERT)
    o.append("")
    o.extend(_lifecycle_asserts(p))
    o.extend(_rpc_asserts(p))
    o.append("/* Number of (struct, member) layout facts this header pins. */")
    n = sum(1 + len(ms) for _, ms in layout_asserts)
    o.append("#define AK_LAYOUT_FACTS %d" % n)
    o.append("")
    o.append("/* The core writes its own view of the same facts here; the host compares. */")
    o.append("size_t ak_layout_facts(uint32_t *out, size_t cap);")
    o.append("")
    o.append("#ifdef __cplusplus")
    o.append("} /* extern \"C\" */")
    o.append("#endif")
    o.append("#endif /* AK_ABI_H */")
    o.append("")

    # The host-side compile-time table lives in its own header so ak_abi.h stays C.
    tbl = [head, "/* The layout facts, in the order ak_layout_facts() writes them. */",
           "#ifndef AK_LAYOUT_H", "#define AK_LAYOUT_H", "#include <cstddef>",
           "#include <cstdint>", "#include \"ak_abi.h\"", "",
           "static const uint32_t AK_LAYOUT_HOST[AK_LAYOUT_FACTS] = {"]
    names = [head,
             "/* One name per fact, in the same order, so a disagreement can be NAMED and",
             " * not merely counted. */",
             "#ifndef AK_LAYOUT_NAMES_H", "#define AK_LAYOUT_NAMES_H",
             "static const char *const AK_LAYOUT_NAMES[AK_LAYOUT_FACTS] = {"]
    for sname, members in layout_asserts:
        tbl.append("  (uint32_t)sizeof(struct %s)," % sname)
        names.append("  \"sizeof %s\"," % sname)
        for mem in members:
            tbl.append("  (uint32_t)offsetof(struct %s, %s)," % (sname, mem))
            names.append("  \"%s.%s\"," % (sname, mem))
    tbl.append("};")
    tbl.append("#endif")
    tbl.append("")
    names.append("};")
    names.append("#endif")
    names.append("")
    return "\n".join(o), "\n".join(tbl), "\n".join(names)
