"""Rust backend: the `core-native` control, rendered from the SAME plans as the core.

FIX-PLAN WP5 step 1, R-E1. `rust_core.py` claimed "one traversal, two backends" while its
native backend carried its own copy of every wire decision (review finding R-E1, verified):
it wrote a double with `!= 0.0`, read a packed field's unpacked form at any wire type,
replaced a repeated singular message instead of merging it, and skipped an empty map key.
Here the native codec renders `plan.MessagePlan.encode` and `.decode` -- the very lists the
C ABI core renders in `rust_abi.py` -- so the two differ in exactly one thing: where a
value comes from (a facade object here, a group the host filled there). That difference is
the boundary, which is what the control exists to isolate.

One output per unknown-field mode, because a facade codec has no per-call switch the way
the C ABI has two families: `emit_core_native(plan_with_unknown="drop")` and
`...("retain")` are two modules from one renderer (owner position 6: both behaviours built).

What this module decides (the plan contract's "may"): the facade spelling of each access
(`o.f`, `Option`, `Vec`, `BTreeMap`, the enum's `to_i32`), allocation, `#[inline]`. What
it may not decide, it does not: every write, presence test, accepted wire type, merge, the
unknown-field behaviour, the UTF-8 policy and the depth limit are the plan's.

A recursive message (the corpus's `Nest`) is fine here -- a facade can hold one through a
`Box` -- and is refused by the C ABI (plan.check_expressible). Its `Option<Box<M>>` field
spelling is rendered from `FieldPlan.recursive`.
"""
from plan import LEN, as_plan
from rustnames import camel, oneof_type

HEAD_FMT = "// @generated by ffi/poc/codec/gen/rust_native.py (plan from %s). Do not edit.\n"

W_I32 = 5


def snake(camel_name):
    out = []
    for i, c in enumerate(camel_name):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


class Sites:
    def __init__(self):
        self.ids = {}

    def id(self, key):
        return self.ids.setdefault(key, len(self.ids))

    def __len__(self):
        return len(self.ids)


# -------------------------------------------------------------------- value spellings

def _write(f, v):
    """Write one value of `f` (no key test): the plan's value codec, facade side."""
    return {
        "varint_i32": "e.varint_field(%d, %s as i64 as u64);",
        "varint_i64": "e.varint_field(%d, %s as u64);",
        "varint_bool": "e.varint_field(%d, %s as u64);",
        "fixed64_f64": "e.f64_field(%d, %s);",
        "fixed32_u32": "e.fixed32_field(%d, %s);",
    }[f.value] % (f.tag, v)


def _raw(f, v):
    """A scalar value as the wire sees it: an enum through `to_i32`."""
    return "%s.to_i32()" % v if f.kind == "enum" else v


def _implicit(f, v):
    if f.value == "fixed64_f64":
        return "%s.to_bits() != 0" % v          # plan rule R-E3: -0.0 is written
    if f.value == "varint_bool":
        return v
    return "%s != 0" % v


def _read(f, rd):
    """Read one value of `f` from reader `rd`, as the facade type."""
    r = {"varint_i32": "%s.varint() as i32", "varint_i64": "%s.varint() as i64",
         "varint_bool": "%s.varint() != 0", "fixed64_f64": "%s.f64()",
         "fixed32_u32": "%s.fixed32()"}[f.value] % rd
    if f.kind == "enum":
        return "%s::from_i32(%s)" % (f.of, r)
    return r


def _bytes_of(f, v):
    return "%s.as_bytes()" % v if f.kind == "string" else "&%s[..]" % v


def _str_dec(p):
    return ("ak_rt::strings::decode_str_reject" if p.options.utf8 == "reject"
            else "ak_rt::strings::decode_str_lossy")


# -------------------------------------------------------------------- encode

def _enc_message(p, m, o, sites, acc="o"):
    """Render `m.encode` over the facade object `acc`."""
    retain = p.options.unknown == "retain"
    for st in m.encode:
        f = st.field
        if st.op == "unknown_tail":
            if retain:
                o.append("    e.buf.extend_from_slice(&%s.unknown_fields);" % acc)
            continue
        v = "%s.%s" % (acc, f.name)
        if st.op == "child":
            s = sites.id((m.name, f.name))
            o.append("    if let Some(c) = &%s {" % v)
            o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
            o.append("        enc_%s(c, e);" % snake(f.of))
            o.append("        e.end(mk);")
            o.append("    }")
        elif st.op == "blob":
            if f.presence == "explicit":
                o.append("    if let Some(x) = &%s { e.blob_field(%d, %s); }"
                         % (v, f.tag, _bytes_of(f, "x")))
            else:
                o.append("    if !%s.is_empty() { e.blob_field(%d, %s); }" % (v, f.tag, _bytes_of(f, v)))
        elif st.op == "scalar":
            if f.presence == "explicit":
                o.append("    if let Some(x) = &%s { %s }" % (v, _write(f, _raw(f, "(*x)"))))
            else:
                o.append("    { let x = %s; if %s { %s } }"
                         % (_raw(f, v), _implicit(f, "x"), _write(f, "x")))
        elif st.op == "packed":
            s = sites.id(("packed", m.name, f.name))
            o.append("    if !%s.is_empty() {" % v)
            o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
            if f.value == "fixed64_f64":
                o.append("        for x in &%s { e.buf.extend_from_slice(&x.to_le_bytes()); }" % v)
            elif f.value == "fixed32_u32":
                o.append("        for x in &%s { e.buf.extend_from_slice(&x.to_le_bytes()); }" % v)
            elif f.value == "varint_i32":
                o.append("        for x in &%s { e.varint(%s as i64 as u64); }" % (v, _raw(f, "(*x)")))
            else:
                o.append("        for x in &%s { e.varint(*x as u64); }" % v)
            o.append("        e.end(mk);")
            o.append("    }")
        elif st.op == "repeated_blob":
            o.append("    for x in &%s { e.blob_field(%d, %s); }" % (v, f.tag, _bytes_of(f, "x")))
        elif st.op == "repeated_message":
            s = sites.id((m.name, f.name))
            o.append("    for c in &%s {" % v)
            o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
            o.append("        enc_%s(c, e);" % snake(f.of))
            o.append("        e.end(mk);")
            o.append("    }")
        elif st.op == "map":
            s = sites.id(("map", m.name, f.name))
            entry = p.msg(f.entry)
            o.append("    for (k, val) in &%s {" % v)
            o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
            # The pair message's OWN encode plan, over (k, val).
            for est in entry.encode:
                if est.op == "unknown_tail":
                    continue                 # a facade map entry has no bag
                ef = est.field
                if est.op != "blob" or ef.kind != "string":
                    raise NotImplementedError("map %s.%s: only map<string, string> is in "
                                              "any description" % (m.name, f.name))
                x = "k" if ef.name == "key" else "val"
                o.append("        if !%s.is_empty() { e.blob_field(%d, %s.as_bytes()); }" % (x, ef.tag, x))
            o.append("        e.end(mk);")
            o.append("    }")
        elif st.op == "oneof_member":
            ty = oneof_type(m.name, st.oneof)
            vv = camel(f.name)
            o.append("    if let Some(%s::%s(x)) = &%s.%s {" % (ty, vv, acc, st.oneof))
            if f.is_blob:
                o.append("        e.blob_field(%d, %s);" % (f.tag, _bytes_of(f, "x")))
            elif f.kind == "message":
                s = sites.id(("oneof", m.name, st.oneof, f.name))
                o.append("        let mk = e.begin(%d, %d);" % (f.tag, s))
                o.append("        enc_%s(x, e);" % snake(f.of))
                o.append("        e.end(mk);")
            else:
                o.append("        %s" % _write(f, _raw(f, "(*x)")))
            o.append("    }")
        else:
            raise NotImplementedError("encode step %r (%s)" % (st.op, m.name))
    # oneof_checks need no rendering here: a facade enum cannot hold an unknown case.


# -------------------------------------------------------------------- decode

def _dec_message(p, m, o):
    """Render `m.decode` as the arms of one facade decoder's match."""
    sd = _str_dec(p)
    for (tag, wire), act in sorted(m.decode.items()):
        f = act.field
        op = act.op
        pat = "            (%d, %d) => {" % (tag, wire)
        if op == "set_scalar":
            val = _read(f, "d")
            o.append(pat)
            o.append("                let v = %s;" % val)
            o.append("                if d.err == 0 { out.%s = %s; }" % (f.name, "Some(v)" if f.explicit else "v"))
            o.append("            }")
        elif op == "set_blob":
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            if f.kind == "string":
                o.append("                match %s(&buf[off..off + n]) {" % sd)
                o.append("                    Ok(s) => out.%s = %s," % (f.name, "Some(s)" if f.explicit else "s"))
                o.append("                    Err(er) => { d.err = er; return; }")
                o.append("                }")
            else:
                val = "::bytes::Bytes::copy_from_slice(&buf[off..off + n])"
                o.append("                out.%s = %s;" % (f.name, "Some(%s)" % val if f.explicit else val))
            o.append("            }")
        elif op == "merge_child":
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
            o.append("                // Plan rule: a repeated occurrence MERGES into the one decoded.")
            o.append("                let c = out.%s.get_or_insert_with(Default::default);" % f.name)
            o.append("                dec_%s(&mut sub, c, depth + 1);" % snake(f.of))
            o.append("                if sub.err != 0 { d.err = sub.err; return; }")
            o.append("            }")
        elif op == "append_message" and f.card != "map":
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
            o.append("                let mut c = %s::default();" % f.of)
            o.append("                dec_%s(&mut sub, &mut c, depth + 1);" % snake(f.of))
            o.append("                if sub.err != 0 { d.err = sub.err; return; }")
            o.append("                out.%s.push(c);" % f.name)
            o.append("            }")
        elif op == "append_blob":
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            if f.kind == "string":
                o.append("                match %s(&buf[off..off + n]) {" % sd)
                o.append("                    Ok(s) => out.%s.push(s)," % f.name)
                o.append("                    Err(er) => { d.err = er; return; }")
                o.append("                }")
            else:
                o.append("                out.%s.push(::bytes::Bytes::copy_from_slice(&buf[off..off + n]));" % f.name)
            o.append("            }")
        elif op == "packed_run":
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
            o.append("                while !sub.at_end() {")
            o.append("                    let v = %s;" % _read(f, "sub"))
            o.append("                    if sub.err != 0 { break; }")
            o.append("                    out.%s.push(v);" % f.name)
            o.append("                }")
            o.append("                if sub.err != 0 { d.err = sub.err; return; }")
            o.append("            }")
        elif op == "packed_one":
            o.append(pat)
            o.append("                let v = %s;" % _read(f, "d"))
            o.append("                if d.err == 0 { out.%s.push(v); }" % f.name)
            o.append("            }")
        # WP5 step 7: to the decode plan a map IS a repeated pair message (decision 11).
        elif op == "append_message" and f.card == "map":
            entry = p.msg(f.entry)
            o.append(pat)
            o.append("                let (off, n) = d.len_body();")
            o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
            o.append("                if depth + 1 > LIMIT { d.err = ak_rt::ERR_DEPTH; return; }")
            o.append("                let (mut k, mut val) = (String::new(), String::new());")
            o.append("                let eb = sub.buf;")
            o.append("                while !sub.at_end() {")
            o.append("                    let kk = sub.varint();")
            o.append("                    if sub.err != 0 { break; }")
            o.append("                    let (et, ew) = ((kk >> 3) as u32, (kk & 7) as u32);")
            o.append("                    if et == 0 || (kk >> 3) > ak_rt::MAX_FIELD_NUMBER { sub.err = ak_rt::ERR_MALFORMED; break; }")
            o.append("                    match (et, ew) {")
            # The pair message's OWN decode plan.
            for (etag, ewire), eact in sorted(entry.decode.items()):
                ef = eact.field
                if eact.op != "set_blob" or ef.kind != "string":
                    raise NotImplementedError("map %s.%s: only map<string, string>" % (m.name, f.name))
                x = "k" if ef.name == "key" else "val"
                o.append("                        (%d, %d) => {" % (etag, ewire))
                o.append("                            let (a, b) = sub.len_body();")
                o.append("                            match %s(&eb[a..a + b]) {" % sd)
                o.append("                                Ok(s) => %s = s," % x)
                o.append("                                Err(er) => { d.err = er; return; }")
                o.append("                            }")
                o.append("                        }")
            o.append("                        // A facade map entry has no bag: an unknown field inside")
            o.append("                        // an entry is skipped in both modes (`U-map-entry`, disputed).")
            o.append("                        _ => sub.skip(et, ew),")
            o.append("                    }")
            o.append("                }")
            o.append("                if sub.err != 0 { d.err = sub.err; return; }")
            o.append("                // Plan rule: a duplicate key replaces the earlier value.")
            o.append("                out.%s.insert(k, val);" % f.name)
            o.append("            }")
        elif op == "oneof_set":
            ty = oneof_type(m.name, act.oneof)
            vv = camel(f.name)
            o.append(pat)
            if f.is_blob:
                o.append("                let (off, n) = d.len_body();")
                if f.kind == "string":
                    o.append("                match %s(&buf[off..off + n]) {" % sd)
                    o.append("                    Ok(s) => out.%s = Some(%s::%s(s))," % (act.oneof, ty, vv))
                    o.append("                    Err(er) => { d.err = er; return; }")
                    o.append("                }")
                else:
                    o.append("                out.%s = Some(%s::%s(::bytes::Bytes::copy_from_slice(&buf[off..off + n])));"
                             % (act.oneof, ty, vv))
            elif f.kind == "message":
                o.append("                let (off, n) = d.len_body();")
                o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
                o.append("                // Plan rule: the SAME member merges; another one starts empty.")
                o.append("                if !matches!(out.%s, Some(%s::%s(_))) {" % (act.oneof, ty, vv))
                o.append("                    out.%s = Some(%s::%s(Default::default()));" % (act.oneof, ty, vv))
                o.append("                }")
                o.append("                if let Some(%s::%s(c)) = &mut out.%s {" % (ty, vv, act.oneof))
                o.append("                    dec_%s(&mut sub, c, depth + 1);" % snake(f.of))
                o.append("                }")
                o.append("                if sub.err != 0 { d.err = sub.err; return; }")
            else:
                o.append("                let v = %s;" % _read(f, "d"))
                o.append("                if d.err == 0 { out.%s = Some(%s::%s(v)); }" % (act.oneof, ty, vv))
            o.append("            }")
        else:
            raise NotImplementedError("decode action %r (%s.%s)" % (op, m.name, f.name))


def emit_core_native(x, unknown="drop", types_path="super::types::*"):
    """One `core-native` module for one unknown-field mode ("drop" or "retain")."""
    p = as_plan(x)
    if unknown not in ("drop", "retain"):
        raise ValueError("a facade codec is one mode; render both for both")
    if p.options.unknown != unknown:
        # The same plan, lowered again with the other option. Lowering is pure.
        p = _relower(p, unknown)
    sites = Sites()
    retain = unknown == "retain"
    body = []
    for name in p.order:
        m = p.msg(name)
        if m.synthetic:
            continue
        body.append("#[inline]")
        body.append("#[allow(unused_variables)]")
        body.append("fn enc_%s(o: &%s, e: &mut Enc) {" % (snake(name), name))
        _enc_message(p, m, body, sites)
        body.append("}")
        body.append("")
    for name in p.order:
        m = p.msg(name)
        if m.synthetic:
            continue
        body.append("#[inline]")
        body.append("#[allow(unused_variables, unused_mut)]")
        body.append("fn dec_%s(d: &mut Dec, out: &mut %s, depth: u32) {" % (snake(name), name))
        body.append("    // Plan rule: a message more than LIMIT levels below the root is refused.")
        body.append("    if depth > LIMIT { d.err = ak_rt::ERR_DEPTH; return; }")
        body.append("    let buf = d.buf;")
        body.append("    while !d.at_end() {")
        body.append("        let s0 = d.pos;")
        body.append("        let k = d.varint();")
        body.append("        if d.err != 0 { return; }")
        body.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        body.append("        if tag == 0 || (k >> 3) > ak_rt::MAX_FIELD_NUMBER { d.err = ak_rt::ERR_MALFORMED; return; }")
        body.append("        match (tag, wire) {")
        _dec_message(p, m, body)
        if retain:
            body.append("            // Plan rule (retain): an unknown field is captured verbatim, key")
            body.append("            // included, and re-emitted after the known fields on encode.")
            body.append("            _ => {")
            body.append("                d.skip(tag, wire);")
            body.append("                if d.err == 0 { out.unknown_fields.extend_from_slice(&buf[s0..d.pos]); }")
            body.append("            }")
        else:
            body.append("            // Plan rule (drop): an unknown field -- including a known number at")
            body.append("            // a wire type the table has no arm for (R-E2) -- is skipped.")
            body.append("            _ => d.skip(tag, wire),")
        body.append("        }")
        body.append("    }")
        body.append("}")
        body.append("")

    o = [HEAD_FMT % getattr(p, "source", "ffi/schema/shapes.json"),
         "//! Arm `core-native` (unknown fields: %s): the codec rendered into the host from the"
         % unknown.upper(),
         "//! SAME plans as the core behind the C ABI (`poc/codec/gen/plan.py`), over the facade",
         "//! types, with no boundary at all. README R3's no-boundary control; R-E1: the two",
         "//! arms differ only in where a value comes from.",
         "#![allow(clippy::all)]",
         "use %s;" % types_path,
         "use ak_rt::dec::Dec;",
         "use ak_rt::Enc;",
         "",
         "/// One learned length-prefix slot per site in this file (ABI v1 section 6).",
         "pub const SITES: usize = %d;" % len(sites),
         "/// The plan's recursion limit (Options.recursion_limit).",
         "pub const LIMIT: u32 = %d;" % p.options.recursion_limit,
         "/// The plan's UTF-8 policy on decode, for a log to name.",
         "pub const UTF8_POLICY: &str = \"%s\";" % p.options.utf8,
         "/// The plan's unknown-field mode this module renders.",
         "pub const UNKNOWN_FIELDS: &str = \"%s\";" % unknown,
         ""]
    o += body
    for root in p.roots:
        o.append("pub fn encode_%s(o: &%s) -> Vec<u8> {" % (snake(root), root))
        o.append("    let mut e = Enc::new(SITES);")
        o.append("    enc_%s(o, &mut e);" % snake(root))
        o.append("    e.buf")
        o.append("}")
        o.append("")
        o.append("/// Encode into a context that is reused, so the learned widths survive and the")
        o.append("/// allocation is not part of what is timed. This is the shape a real host uses.")
        o.append("pub fn encode_into_%s(o: &%s, e: &mut Enc) {" % (snake(root), root))
        o.append("    e.reset();")
        o.append("    enc_%s(o, e);" % snake(root))
        o.append("}")
        o.append("")
        o.append("/// After an error the value is discarded, never returned (plan rule, R-G6).")
        o.append("pub fn decode_%s(b: &[u8]) -> Result<%s, i32> {" % (snake(root), root))
        o.append("    let mut d = Dec::new(b);")
        o.append("    let mut out = %s::default();" % root)
        o.append("    dec_%s(&mut d, &mut out, 0);" % snake(root))
        o.append("    if d.err != 0 { Err(d.err) } else { Ok(out) }")
        o.append("}")
        o.append("")
    return "\n".join(o)


def _relower(p, unknown):
    """Lower the plan's own source again with another unknown-field option. The plan keeps
    a reference to its lowering input for exactly this."""
    import plan as P
    return P.relower(p, p.options.with_unknown(unknown))
