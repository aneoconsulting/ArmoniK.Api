def _emit_unk_clear(ir, root):
    """Test support for decision 11's discard control: clear the facade bag of every
    message at one position (plan.unk_positions order), which is what decoding with that
    position's entry zeroed must produce."""
    rs = snake(root)
    o = ["/// Decision 11 control: clear every bag at position `pos` (plan.unk_positions).",
         "pub fn unk_clear_%s(o: &mut %s, pos: usize) {" % (rs, root),
         "    match pos {"]
    for i, (path, _m) in enumerate(unk_positions(ir, root)):
        body = _clear_path(ir, root, "o", path, 0)
        o.append("        %d => { %s }" % (i, body))
    o.append("        _ => {}")
    o.append("    }")
    o.append("}")
    o.append("")
    return o


def _clear_path(ir, name, expr, path, depth):
    if not path:
        return "%s.unknown_fields.clear();" % expr
    m = ir.msg(name)
    key = path[0]
    v = "x%d" % depth
    if key in m.oneofs:
        # Decision 11 rule 4: ONE position per oneof: the active message member's bag.
        ty = "%s%s" % (name, _camel(key))
        arms = ["Some(%s::%s(%s)) => { %s }" % (ty, _camel(g.name), v, _clear_path(ir, g.of, v, path[1:], depth + 1))
                for g in m.oneofs[key] if g.kind == "message"]
        return "match %s.%s.as_mut() { %s _ => {} }" % (expr, key, " ".join(arms))
    for f in m.fields:
        k = f.name
        if k != key or f.oneof:
            continue
        if f.card == "map":
            # A facade map entry has no bag: nothing to clear (and nothing kept).
            return ""
        if f.card == "repeated":
            return "for %s in %s.%s.iter_mut() { %s }" % (
                v, expr, f.name, _clear_path(ir, f.of, v, path[1:], depth + 1))
        return "if let Some(%s) = %s.%s.as_mut() { %s }" % (
            v, expr, f.name, _clear_path(ir, f.of, v, path[1:], depth + 1))
    raise KeyError("%s: no field for position key %s" % (name, key))


def _emit_unk_controls(ir, root):
    """Decision 11's controls on one input: every position zeroed in turn must drop exactly
    that position (`unk_clear_*`); the pull family must deliver what push does; a map
    entry's bytes arrive unless the entry position is zeroed. `plant` skips the clear, so
    the comparison is seen failing where the input has unknowns."""
    rs = snake(root)
    mem = unk_opts_members(ir, root)
    ent = ", ".join("true" if (m != "oneof" and ir.msg(m).synthetic) else "false" for _n, m in mem)
    return [
        "pub fn unk_controls_%s(ctx: DecCtxs, b: &[u8], plant: bool) -> Result<UnkReport, i32> {" % rs,
        "    const IS_ENTRY: [bool; %d] = [%s];" % (len(mem), ent),
        "    unk_entry_bytes();",
        "    let all = decode_with_%s_unk(ctx, b)?;" % rs,
        "    let eb_all = unk_entry_bytes();",
        "    let mut toks = Vec::new();",
        "    let pw = parse_walk_with_%s_unk(ctx, b, &mut toks)?;" % rs,
        "    unk_entry_bytes();",
        "    // Compared through Debug so a NaN equals itself (S-double-nan); bytes are the corpus's job.",
        "    let dbg = |x: &%s| format!(\"{:?}\", x);" % root,
        "    let mut rep = UnkReport { positions: %d, pull_equal: dbg(&pw) == dbg(&all), entry_bytes: eb_all, ..Default::default() };" % len(mem),
        "    for i in 0..%d {" % len(mem),
        "        let got = decode_with_%s_opts(ctx, b, &mut unk_opts_%s(Some(i)))?;" % (rs, rs),
        "        let eb = unk_entry_bytes();",
        "        let mut exp = all.clone();",
        "        if !plant { unk_clear_%s(&mut exp, i); }" % rs,
        "        if dbg(&exp) != dbg(&all) { rep.changed += 1; }",
        "        if dbg(&got) != dbg(&exp) { rep.mismatched.push(i); }",
        "        if eb != (if IS_ENTRY[i] { 0 } else { eb_all }) { rep.entry_mismatch.push(i); }",
        "    }",
        "    Ok(rep)",
        "}",
        "",
    ]


def _dec_ctxs(ir):
    """Decision 11 rule 6 (WP5 step 8): a decode context is BOUND to its root, so a host that
    decodes several roots holds one context per root. `DecCtxs` is that set, created in drop
    mode (NULL options); `decode_with_<root>` picks its own."""
    o = ["/// One decode context per root (decision 11 rule 6: contexts are root-bound).",
         "#[derive(Clone, Copy)]",
         "pub struct DecCtxs {"]
    for root in ir.roots:
        o.append("    pub %s: *mut ak_dec_ctx," % snake(root))
    o.append("}")
    o.append("impl DecCtxs {")
    o.append("    /// Every root's context, bound, in drop mode. Requires `ak_init` first.")
    o.append("    pub fn new() -> Self {")
    o.append("        unsafe {")
    o.append("            let d = DecCtxs {")
    for root in ir.roots:
        o.append("                %s: ak_dec_ctx_new_%s(%s)," % (snake(root), root, "" if NOUNK else "::core::ptr::null_mut()"))
    o.append("            };")
    for root in ir.roots:
        o.append("            assert!(!d.%s.is_null(), \"ak_dec_ctx_new_%s\");" % (snake(root), root))
    o.append("            d")
    o.append("        }")
    o.append("    }")
    o.append("    pub unsafe fn free(self) {")
    for root in ir.roots:
        o.append("        ak_dec_ctx_free(self.%s);" % snake(root))
    o.append("    }")
    o.append("}")
    o.append("")
    return o
