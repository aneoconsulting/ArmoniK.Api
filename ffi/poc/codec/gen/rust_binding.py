def _emit_loop_zeroed(ir, o, root, path, f, sn):
    """The same top-level loop callback with the ZEROED-GROUP fill: one memset per chunk,
    then only the fields that differ from the default. ABI v1 open decision 9 candidate.

    Only the top-level element group is built this way. A nested loop inside an element
    keeps the total fill, so this arm prices the OUTER group and nothing else, and the log
    says so."""
    rs = snake(root)
    et = f.of
    o.append("unsafe extern \"C\" fn loop_%s_%s_zeroed(" % (rs, sn))
    o.append("    ctx: *mut ak_enc_ctx,")
    o.append("    obj: *const c_void,")
    o.append("    token: i64,")
    o.append(") -> i32 {")
    o.append("    guard(ctx, || {")
    o.append("        let o = &*(obj as *const %s);" % root)
    o.append("        let tc = tcs();")
    o.extend(_top_src(path))
    o.append("        const CHUNK: usize = ak_rt::arena_n(::core::mem::size_of::<ak_efix_%s>());" % et)
    o.append("        const SZ: usize = ::core::mem::size_of::<ak_efix_%s>();" % et)
    o.append("        let mut chunk: [::core::mem::MaybeUninit<ak_efix_%s>; CHUNK] =" % et)
    o.append("            [const { ::core::mem::MaybeUninit::uninit() }; CHUNK];")
    o.append("        // All-zero is a valid group: `ak_efix_%s::ZERO` is exactly this bit pattern." % et)
    o.append("        ::core::ptr::write_bytes(chunk.as_mut_ptr() as *mut u8, 0, CHUNK * SZ);")
    o.append("        let mut i = 0usize;")
    o.append("        let mut done = 0usize;")
    o.append("        for v in src.iter() {")
    o.append("            fill_%s_sparse(&mut *chunk[i].as_mut_ptr(), v, tc);" % snake(et))
    o.append("            i += 1;")
    o.append("            if i == CHUNK {")
    o.extend("                " + ln for ln in _run_call(ir, f, et, "i", "done"))
    o.append("                done += i;")
    o.append("                // Only what was dirtied is put back, which is the same volume")
    o.append("                // per element as the total fill and is where this trade is paid.")
    o.append("                ::core::ptr::write_bytes(chunk.as_mut_ptr() as *mut u8, 0, i * SZ);")
    o.append("                i = 0;")
    o.append("            }")
    o.append("        }")
    o.append("        if i > 0 {")
    o.extend("            " + ln for ln in _run_call(ir, f, et, "i", "done"))
    o.append("        }")
    o.append("        AK_OK")
    o.append("    })")
    o.append("}")
    o.append("")


def _emit_loop(ir, o, root, path, f, sn, top, elem_path=None, inner_path=None, elem_type=None):
    """One host-driven loop callback. The host fills an array of element groups from objects
    it is already walking and hands over extracted data; the codec never names a host object,
    never dereferences one, and nothing is pinned (ABI v1 section 6)."""
    rs = snake(root)
    et = globals()["elem_type"](f) if not top or True else None
    et = None
    if f.card == "map":
        et = f.entry
    elif f.kind == "message":
        et = f.of
    o.append("unsafe extern \"C\" fn loop_%s_%s(" % (rs, sn))
    o.append("    ctx: *mut ak_enc_ctx,")
    o.append("    obj: *const c_void,")
    o.append("    token: i64,")
    o.append(") -> i32 {")
    o.append("    guard(ctx, || {")
    o.append("        let o = &*(obj as *const %s);" % root)
    o.append("        let tc = tcs();")
    if top:
        o.extend(_top_src(path))
    else:
        o.append("        let e = &o.%s[token as usize];" % slot_name(elem_path))
        expr = "e"
        owner = elem_type
        for i, p in enumerate(inner_path):
            fl = next(x for x in ir.msg(owner).plain if x.name == p)
            if i == len(inner_path) - 1:
                expr = "%s.%s" % (expr, p)
            else:
                o.append("        let Some(c%d) = &%s.%s else { return AK_OK };" % (i, expr, p))
                expr = "c%d" % i
                owner = fl.of
        o.append("        let src = &%s;" % expr)
    if f.card == "packed":
        # ABI v1 section 6: a packed repeated scalar is the host's OWN ARRAY, handed over
        # whole. One symbol per host layout, the wire encoding comes from the schema and
        # lives in the context, so bool and enum need no cases. No chunk, no element loop:
        # this is the one shape that crosses once per FIELD however long it is.
        rty = {"int32": "i32", "int64": "i64", "double": "f64", "bool": "u8", "enum": "i32"}[f.kind]
        if f.kind in ("bool", "enum"):
            o.append("        // bool and enum have no contiguous host layout of their own, so")
            o.append("        // the binding materialises one. A host that already stores the")
            o.append("        // wire representation hands over a pointer and copies nothing.")
            conv = "*x as u8" if f.kind == "bool" else "x.to_i32()"
            o.append("        let tmp: Vec<%s> = src.iter().map(|x| %s).collect();" % (rty, conv))
            o.append("        let rc = ak_run_%s(ctx, tmp.as_ptr(), tmp.len());" % rty)
        else:
            o.append("        let rc = ak_run_%s(ctx, src.as_ptr(), src.len());" % rty)
        o.append("        if rc < 0 { return rc; }")
        o.append("        AK_OK")
        o.append("    })")
        o.append("}")
        o.append("")
        return
    gty = ("ak_efix_%s" % et) if et else "ak_str"
    o.append("        const CHUNK: usize = ak_rt::arena_n(::core::mem::size_of::<%s>());" % gty)
    o.append("        let mut chunk: [::core::mem::MaybeUninit<%s>; CHUNK] =" % gty)
    o.append("            [const { ::core::mem::MaybeUninit::uninit() }; CHUNK];")
    o.append("        let mut i = 0usize;")
    o.append("        let mut done = 0usize;")
    if f.card == "map":
        o.append("        for (k, v) in src.iter() {")
        o.append("            chunk[i].write(ak_efix_%s {" % et)
        o.append("                key: str_arg(k, tc.0),")
        o.append("                value: str_arg(v, tc.0),")
        o.append("                presence: 0,")
        o.append("            });")
    elif f.kind in ("string", "bytes"):
        acc = "str_arg(v, tc.0)" if f.kind == "string" else \
              "blob_arg(v, tc.1)"
        o.append("        for v in src.iter() {")
        o.append("            chunk[i].write(%s);" % acc)
    elif f.kind == "message":
        o.append("        for v in src.iter() {")
        o.append("            chunk[i].write(make_%s(v, tc));" % snake(et))
    else:
        raise NotImplementedError("loop for %s %s" % (f.card, f.kind))
    o.append("            i += 1;")
    o.append("            if i == CHUNK {")
    o.extend("                " + ln for ln in _run_call(ir, f, et, "i", "done"))
    o.append("                done += i;")
    o.append("                i = 0;")
    o.append("            }")
    o.append("        }")
    o.append("        if i > 0 {")
    o.extend("            " + ln for ln in _run_call(ir, f, et, "i", "done"))
    o.append("        }")
    o.append("        AK_OK")
    o.append("    })")
    o.append("}")
    o.append("")


def _run_call(ir, f, et, n, done, bag=False):
    """Hand the filled chunk over. One element entry point taking a count: `n == 1` is the
    unbatched call, and the host may decline to batch at all and lose only what its own
    crossing costs."""
    g = "u" if bag else "e"
    ptr = "chunk.as_ptr() as *const %s" % (("ak_%sfix_%s" % (g, et)) if et else "ak_str")
    u = "u" if bag else ""
    if et and not ir.msg(et).leaf:
        return ["let rc = ak_%selemu_%s(ctx, %s, %s as i32, %s as i64);" % (u, et, ptr, n, done),
                "if rc < 0 { return rc; }"]
    if et:
        return ["let rc = ak_%selem_%s(ctx, %s, %s as i32);" % (u, et, ptr, n),
                "if rc < 0 { return rc; }"]
    return ["let rc = ak_blob_run(ctx, %s, %s as i32);" % (ptr, n),
            "if rc < 0 { return rc; }"]



