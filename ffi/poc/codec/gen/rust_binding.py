def _facade_path(ir, root, path):
    """A Rust expression reaching the facade field at `path` from `e`, through the Options
    that a singular message child is."""
    expr = "e"
    owner = root
    for i, p in enumerate(path):
        f = next(x for x in ir.msg(owner).plain if x.name == p)
        if i == len(path) - 1:
            return "%s.%s" % (expr, p), owner, f
        expr = "%s.%s" % (expr, p)
        owner = f.of
    raise AssertionError


def _lifecycle(p):
    """R-G7: the binding renders `ak_init` from `plan.lifecycle`, so no host can get a
    codec binding without it. AK_OK and AK_ALREADY_INITIALIZED are both success."""
    lc = p.lifecycle
    return [
        "/// ABI v1 section 3, rendered from `plan.lifecycle` (R-G7): every binding calls",
        "/// `ak_init` before its first codec or RPC call. Idempotent under identical options",
        "/// (`%s` is a success), so a host library may call it defensively." % lc.success[1],
        "/// Returns AK_OK, or the refusal.",
        "pub fn ak_init_once() -> i32 {",
        "    unsafe {",
        "        let o = ak_init_opts {",
        "            abi_version: AK_ABI_VERSION,",
        "            flags: %s," % " | ".join(lc.default_flags),
        "            log: None,",
        "            log_ctx: ::core::ptr::null_mut(),",
        "        };",
        "        let mut e = ak_err::default();",
        "        let rc = %s(&o, &mut e);" % lc.init[0],
        "        if rc == %s || rc == %s { AK_OK } else { rc }" % lc.success,
        "    }",
        "}",
        "",
    ]


def emit_binding(ir):
    ir = as_plan(ir)
    global NOUNK
    # WP5 step 10: the NO-UNKNOWN variant's binding (plan: THE NO-UNKNOWN VARIANT): no
    # u-groups, no bags handed to the core or taken from it, no options, no `_unk` family.
    NOUNK = unknown_compiled_out(ir)
    # The unknown-field prelude sits right after the `use` lines, where it always did, so
    # the full variant's text is unchanged by the split.
    head, tail = BINDING_PRELUDE.split('use facade::*;\n\n', 1)
    o = [HEAD, head + 'use facade::*;\n\n' + ("" if NOUNK else BINDING_UNK_PRELUDE) + tail, ""]
    o += _lifecycle(ir)
    o += _dec_ctxs(ir)

    # ---- encode groups: a total-fill constructor per message, loop fields excluded
    for name in ir.abi_order:
        m = ir.msg(name)
        bits = presence_bits(m)
        src = "TaskOptionsOptionsEntryLike" if m.synthetic else name
        if m.synthetic:
            continue
        o.append("/// Total fill: every group field assigned, presence assigned and not OR-ed.")
        o.append("#[inline(always)]")
        o.append("pub(crate) fn make_%s(o: &%s, tc: (ak_transcode_fn, ak_transcode_fn)) -> ak_efix_%s {"
                 % (snake(name), name, name))
        o.append("    ak_efix_%s {" % name)
        pres = []
        for f in m.plain:
            if f.card != "singular":
                continue
            if f.explicit:
                # Total fill: an absent field still gets all three words of its ak_str and
                # its scalar written, and the presence WORD is what says it is absent. A
                # partial fill does not fail, it inherits the previous element's value.
                if f.kind == "string":
                    o.append("        %s: match &o.%s {" % (f.name, f.name))
                    o.append("            Some(v) => str_arg(v, tc.0),")
                    o.append("            None => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                    o.append("        },")
                elif f.kind == "bytes":
                    o.append("        %s: match &o.%s {" % (f.name, f.name))
                    o.append("            Some(v) => blob_arg(v, tc.1),")
                    o.append("            None => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                    o.append("        },")
                elif f.kind == "bool":
                    o.append("        %s: o.%s.unwrap_or(false) as u8," % (f.name, f.name))
                elif f.kind == "enum":
                    o.append("        %s: o.%s.map(|v| v.to_i32()).unwrap_or(0)," % (f.name, f.name))
                else:
                    o.append("        %s: o.%s.unwrap_or(0)," % (f.name, f.name))
                pres.append("((o.%s.is_some() as u32) << %d)" % (f.name, bits[f.name]))
                continue
            if f.direct:
                o.append("        // ABI v1 section 8: the sentinel says the bytes are an")
                o.append("        // argument of the call, not a pointer into staging.")
                o.append("        %s: ak_str { data: AK_STR_DIRECT, len: o.%s.len(), tc: None },"
                         % (f.name, f.name))
            elif f.kind == "string":
                o.append("        %s: str_arg(&o.%s, tc.0)," % (f.name, f.name))
            elif f.kind == "bytes":
                o.append("        %s: blob_arg(&o.%s, tc.1)," % (f.name, f.name))
            elif f.kind == "message":
                o.append("        %s: match &o.%s {" % (f.name, f.name))
                o.append("            Some(c) => make_%s(c, tc)," % snake(f.of))
                o.append("            None => ak_efix_%s::ZERO," % f.of)
                o.append("        },")
                pres.append("((o.%s.is_some() as u32) << %d)" % (f.name, bits[f.name]))
            elif f.kind == "enum":
                o.append("        %s: o.%s.to_i32()," % (f.name, f.name))
            elif f.kind == "bool":
                o.append("        %s: o.%s as u8," % (f.name, f.name))
            else:
                o.append("        %s: o.%s," % (f.name, f.name))
        for oname, members in m.oneofs.items():
            ty = "%s%s" % (name, "".join(p.capitalize() for p in oname.split("_")))
            o.append("        %s_case: match &o.%s {" % (oname, oname))
            o.append("            None => 0,")
            for g in members:
                o.append("            Some(%s::%s(_)) => %d," % (ty, _camel(g.name), g.tag))
            o.append("        },")
            for g in members:
                o.append("        %s_%s: match &o.%s {" % (oname, g.name, oname))
                if g.kind == "string":
                    o.append("            Some(%s::%s(v)) => str_arg(v, tc.0)," % (ty, _camel(g.name)))
                    o.append("            _ => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                elif g.kind == "bytes":
                    o.append("            Some(%s::%s(v)) => blob_arg(v, tc.1),"
                             % (ty, _camel(g.name)))
                    o.append("            _ => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                elif g.kind == "message":
                    o.append("            Some(%s::%s(v)) => make_%s(v, tc)," % (ty, _camel(g.name), snake(g.of)))
                    o.append("            _ => ak_efix_%s::ZERO," % g.of)
                elif g.kind == "bool":
                    o.append("            Some(%s::%s(v)) => *v as u8," % (ty, _camel(g.name)))
                    o.append("            _ => 0,")
                elif g.kind == "enum":
                    o.append("            Some(%s::%s(v)) => v.to_i32()," % (ty, _camel(g.name)))
                    o.append("            _ => 0,")
                else:
                    o.append("            Some(%s::%s(v)) => *v," % (ty, _camel(g.name)))
                    o.append("            _ => %s," % ("0.0" if g.kind == "double" else "0"))
                o.append("        },")
        o.append("        presence: %s," % (" | ".join(pres) if pres else "0"))
        o.append("    }")
        o.append("}")
        o.append("")

    for name in ir.abi_order:
        m = ir.msg(name)
        bits = presence_bits(m)
        src = "TaskOptionsOptionsEntryLike" if m.synthetic else name
        if m.synthetic:
            continue
        if NOUNK:
            continue
        o.append("/// Total fill, PLUS the unknown-field bag (decision 11 candidate). One more")
        o.append("/// `ak_str` slot per group -- which is what makes this interact with decision 9:")
        o.append("/// the total fill grows on every message, including the ones that encode to nothing.")
        o.append("#[inline(always)]")
        o.append("pub(crate) fn make_%s_unk(o: &%s, tc: (ak_transcode_fn, ak_transcode_fn)) -> ak_ufix_%s {"
                 % (snake(name), name, name))
        o.append("    ak_ufix_%s {" % name)
        pres = []
        for f in m.plain:
            if f.card != "singular":
                continue
            if f.explicit:
                # Total fill: an absent field still gets all three words of its ak_str and
                # its scalar written, and the presence WORD is what says it is absent. A
                # partial fill does not fail, it inherits the previous element's value.
                if f.kind == "string":
                    o.append("        %s: match &o.%s {" % (f.name, f.name))
                    o.append("            Some(v) => str_arg(v, tc.0),")
                    o.append("            None => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                    o.append("        },")
                elif f.kind == "bytes":
                    o.append("        %s: match &o.%s {" % (f.name, f.name))
                    o.append("            Some(v) => blob_arg(v, tc.1),")
                    o.append("            None => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                    o.append("        },")
                elif f.kind == "bool":
                    o.append("        %s: o.%s.unwrap_or(false) as u8," % (f.name, f.name))
                elif f.kind == "enum":
                    o.append("        %s: o.%s.map(|v| v.to_i32()).unwrap_or(0)," % (f.name, f.name))
                else:
                    o.append("        %s: o.%s.unwrap_or(0)," % (f.name, f.name))
                pres.append("((o.%s.is_some() as u32) << %d)" % (f.name, bits[f.name]))
                continue
            if f.direct:
                o.append("        // ABI v1 section 8: the sentinel says the bytes are an")
                o.append("        // argument of the call, not a pointer into staging.")
                o.append("        %s: ak_str { data: AK_STR_DIRECT, len: o.%s.len(), tc: None },"
                         % (f.name, f.name))
            elif f.kind == "string":
                o.append("        %s: str_arg(&o.%s, tc.0)," % (f.name, f.name))
            elif f.kind == "bytes":
                o.append("        %s: blob_arg(&o.%s, tc.1)," % (f.name, f.name))
            elif f.kind == "message":
                o.append("        %s: match &o.%s {" % (f.name, f.name))
                o.append("            Some(c) => make_%s_unk(c, tc)," % snake(f.of))
                o.append("            None => ak_ufix_%s::ZERO," % f.of)
                o.append("        },")
                pres.append("((o.%s.is_some() as u32) << %d)" % (f.name, bits[f.name]))
            elif f.kind == "enum":
                o.append("        %s: o.%s.to_i32()," % (f.name, f.name))
            elif f.kind == "bool":
                o.append("        %s: o.%s as u8," % (f.name, f.name))
            else:
                o.append("        %s: o.%s," % (f.name, f.name))
        for oname, members in m.oneofs.items():
            ty = "%s%s" % (name, "".join(p.capitalize() for p in oname.split("_")))
            o.append("        %s_case: match &o.%s {" % (oname, oname))
            o.append("            None => 0,")
            for g in members:
                o.append("            Some(%s::%s(_)) => %d," % (ty, _camel(g.name), g.tag))
            o.append("        },")
            for g in members:
                o.append("        %s_%s: match &o.%s {" % (oname, g.name, oname))
                if g.kind == "string":
                    o.append("            Some(%s::%s(v)) => str_arg(v, tc.0)," % (ty, _camel(g.name)))
                    o.append("            _ => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                elif g.kind == "bytes":
                    o.append("            Some(%s::%s(v)) => blob_arg(v, tc.1),"
                             % (ty, _camel(g.name)))
                    o.append("            _ => ak_str { data: ::core::ptr::null(), len: 0, tc: None },")
                elif g.kind == "message":
                    o.append("            Some(%s::%s(v)) => make_%s_unk(v, tc)," % (ty, _camel(g.name), snake(g.of)))
                    o.append("            _ => ak_ufix_%s::ZERO," % g.of)
                elif g.kind == "bool":
                    o.append("            Some(%s::%s(v)) => *v as u8," % (ty, _camel(g.name)))
                    o.append("            _ => 0,")
                elif g.kind == "enum":
                    o.append("            Some(%s::%s(v)) => v.to_i32()," % (ty, _camel(g.name)))
                    o.append("            _ => 0,")
                else:
                    o.append("            Some(%s::%s(v)) => *v," % (ty, _camel(g.name)))
                    o.append("            _ => %s," % ("0.0" if g.kind == "double" else "0"))
                o.append("        },")
        o.append("        unknown: ak_blob { data: o.unknown_fields.as_ptr() as *const c_void, len: o.unknown_fields.len() },")
        o.append("        presence: %s," % (" | ".join(pres) if pres else "0"))
        o.append("    }")
        o.append("}")
        o.append("")

    # ---- ABI v1 open decision 9 candidate, built as an ARM and not as the default.
    #
    # The proposal: zero the element-group array once per chunk with a memset and assign
    # only the fields that are not at their default, instead of the total fill section 6
    # requires. It REVERSES a trade the ABI already made and priced -- the total fill was
    # bought so the codec never resets the group between elements, worth 5.4 ns per
    # ResultRaw and 24.4 per TaskDetailed -- so it pays that back on every element of every
    # payload to save the scattered stores on the empty ones.
    #
    # Everything below is emitted ALONGSIDE the default path and reached only through
    # `encode_into_*_zeroed`. Nothing the default path uses changes.
    for name in ir.abi_order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        bits = presence_bits(m)
        o.append("/// Sparse fill: `d` is ALREADY ZERO, so only what differs from the default is")
        o.append("/// written. The cost traded is a compare and a branch per field against an")
        o.append("/// unconditional store per field, plus one memset per chunk.")
        o.append("#[inline(always)]")
