            et = elem_type(f)
            if et and has_slots(ir, et):
                for ipath, iff in loop_slots(ir, et):
                    _emit_loop(ir, o, root, path + ipath, iff, "%s_%s" % (sn, slot_name(ipath)),
                               top=False, elem_path=path, inner_path=ipath, elem_type=et)
                o.append("static ELEM_VT_%s_%s: ak_evt_%s = ak_evt_%s {" % (root, sn, et, et))
