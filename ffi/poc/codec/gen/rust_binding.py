def _camel(snake_name):
    return "".join(p.capitalize() for p in snake_name.split("_"))


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def has_slots(ir, name):
    return bool(loop_slots(ir, name))


def _top_src(path, indent="        "):
    """Lines reaching a ROOT's loop slot at `path` through the Options its inlined parents
    are; an absent parent means an empty field (return AK_OK). A root whose slot lives on
    an inlined child (a message used as a root that also inlines one with a repeated
    field -- the corpus roots `TaskDetailed`, `TaskSummary`, `ChunkElement`) needs it."""
    out = []
    expr = "o"
    for i, p in enumerate(path[:-1]):
        out.append("%slet Some(c%d) = &%s.%s else { return AK_OK };" % (indent, i, expr, p))
        expr = "c%d" % i
    out.append("%slet src = &%s.%s;" % (indent, expr, path[-1]))
    return out


