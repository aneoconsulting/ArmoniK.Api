"""Rust backend: the HOST BINDING of the rust slice's `core-ffi-rust` arm.

Renders a plan (`plan.py`'s contract) into `poc/rust/crates/harness/src/generated/
binding.rs`: the host side of the C ABI for the rust slice's facade types -- a total-fill
constructor per group, the loop and element callbacks, and the decode callbacks that build
facade values from groups and spans. It decides no wire rule and no layout: every group
member, presence bit, loop slot and element type comes from `plan`'s ABI layout functions,
the same ones `rust_abi` renders the ABI from, so the two sides cannot restate a layout
differently (ABI v1 section 10).

Moved here out of `rust_abi.py` by FIX-PLAN WP5 step 1, which made `rust_abi` the core's
renderer only. The emitted text is unchanged by the move.
"""
