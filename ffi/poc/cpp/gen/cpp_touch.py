"""Campaign glue (design/CAMPAIGN.md requirement 9): "decode followed by reading every
field". One traversal per message over the C++ FACADE (`shapes::touch::touch`) and one over
protoc's own types (`pbtouch::touch`), emitted from the plan's descriptor view so the two
read the same fields in the same order and neither is hand-written.

What "read" means, identically in both: a scalar and an enum value are folded in; a string
or bytes value contributes its length and its first and last byte (the bytes are touched,
not copied); an explicit-presence field and a message child are tested and, if present,
read; a repeated field is walked element by element; a map entry by entry (key and value);
a oneof by its case, then the active member. The fold is returned so nothing is dead code.
No wire rule: this reads values a codec already produced.
"""
from cpp_names import camel, oneof_type

HEAD = "// @generated by ffi/poc/cpp/gen/cpp_touch.py (campaign glue). Do not edit.\n"
NS = "armonik::ffi::shapes::v1"


def _fs(expr):
    return "fs(%s)" % expr


def _fac_value(kind, e, of):
    if kind in ("string", "bytes"):
        return "h = mix(h, %s);" % _fs(e)
    if kind == "enum":
        return "h = mix(h, (uint64_t)(int64_t)(%s).v);" % e
    if kind == "message":
        return "h = mix(h, touch(%s));" % e
    if kind == "double":
        return "h = mix(h, ak::f64_bits(%s));" % e
    if kind == "bool":
        return "h = mix(h, (%s) ? 1u : 0u);" % e
    return "h = mix(h, (uint64_t)(int64_t)(%s));" % e


def _pb_value(kind, e, of):
    if kind in ("string", "bytes"):
        return "h = mix(h, %s);" % _fs(e)
    if kind == "enum":
        return "h = mix(h, (uint64_t)(int64_t)(int)(%s));" % e
    if kind == "message":
        return "h = mix(h, touch(%s));" % e
    if kind == "double":
        return "h = mix(h, ak::f64_bits(%s));" % e
    if kind == "bool":
        return "h = mix(h, (%s) ? 1u : 0u);" % e
    return "h = mix(h, (uint64_t)(int64_t)(%s));" % e


PRE = """
static inline uint64_t mix(uint64_t h, uint64_t v) { return (h ^ v) * 0x100000001b3ull; }
template <class S> static inline uint64_t fs(const S &s) {
  uint64_t n = (uint64_t)s.size();
  if (n) n ^= ((uint64_t)(unsigned char)s.data()[0] << 32) ^
              ((uint64_t)(unsigned char)s.data()[n - 1] << 40);
  return n;
}
"""


def emit_header(p):
    o = [HEAD, "#ifndef AK_TOUCH_H", "#define AK_TOUCH_H", "#include <cstdint>",
         '#include "generated/types.h"', '#include "shapes.pb.h"', "",
         "namespace shapes {", "namespace touch {"]
    for r in p.roots:
        o.append("uint64_t touch(const %s &o);" % r)
    o += ["}  // namespace touch", "}  // namespace shapes", "", "namespace pbtouch {"]
    for r in p.roots:
        o.append("uint64_t touch(const %s::%s &o);" % (NS, r))
    o += ["}  // namespace pbtouch", "#endif", ""]
    return "\n".join(o)


def emit(p):
    msgs = [n for n in p.order if not p.msg(n).synthetic]
    o = [HEAD, '#include "generated/touch.h"', '#include "ak/rt.h"', "",
         "namespace shapes {", "namespace touch {", PRE]
    for n in msgs:
        o.append("uint64_t touch(const %s &o);" % n)
    for n in msgs:
        m = p.msg(n)
        o.append("uint64_t touch(const %s &o) {" % n)
        o.append("  uint64_t h = 0xcbf29ce484222325ull;")
        for f in m.plain:
            e = "o.%s" % f.name
            if f.card == "map":
                # Order-independent: protobuf's Map iterates in no fixed order, and the two
                # traversals must fold to the same value (the campaign binary checks it).
                o.append("  { uint64_t acc = 0;")
                o.append("    for (std::map<std::string, std::string>::const_iterator it = %s.begin(); it != %s.end(); ++it)" % (e, e))
                o.append("      acc += mix(fs(it->first) * 31u, fs(it->second));")
                o.append("    h = mix(h, acc); }")
            elif f.card in ("repeated", "packed"):
                o.append("  for (size_t i = 0; i < %s.size(); ++i) { %s }"
                         % (e, _fac_value(f.kind, "%s[i]" % e, f.of)))
            elif f.kind == "message" or f.explicit:
                o.append("  if (%s.has_value()) { %s }" % (e, _fac_value(f.kind, "*%s" % e, f.of)))
            else:
                o.append("  %s" % _fac_value(f.kind, e, f.of))
        for oname, members in m.oneofs.items():
            ty = oneof_type(n, oname)
            o.append("  h = mix(h, (uint64_t)o.%s.which());" % oname)
            o.append("  switch (o.%s.which()) {" % oname)
            for g in members:
                o.append("    case %s::k%s: %s break;"
                         % (ty, camel(g.name), _fac_value(g.kind, "o.%s.%s()" % (oname, g.name), g.of)))
            o.append("    default: break;")
            o.append("  }")
        o.append("  return h;")
        o.append("}")
        o.append("")
    o += ["}  // namespace touch", "}  // namespace shapes", "", "namespace pbtouch {", PRE,
          "namespace pb = %s;" % NS]
    for n in msgs:
        o.append("uint64_t touch(const pb::%s &o);" % n)
    for n in msgs:
        m = p.msg(n)
        o.append("uint64_t touch(const pb::%s &o) {" % n)
        o.append("  uint64_t h = 0xcbf29ce484222325ull;")
        for f in m.plain:
            if f.card == "map":
                o.append("  { uint64_t acc = 0;")
                o.append("    for (auto it = o.%s().begin(); it != o.%s().end(); ++it)" % (f.name, f.name))
                o.append("      acc += mix(fs(it->first) * 31u, fs(it->second));")
                o.append("    h = mix(h, acc); }")
            elif f.card in ("repeated", "packed"):
                o.append("  for (int i = 0; i < o.%s_size(); ++i) { %s }"
                         % (f.name, _pb_value(f.kind, "o.%s(i)" % f.name, f.of)))
            elif f.kind == "message" or f.explicit:
                o.append("  if (o.has_%s()) { %s }" % (f.name, _pb_value(f.kind, "o.%s()" % f.name, f.of)))
            else:
                o.append("  %s" % _pb_value(f.kind, "o.%s()" % f.name, f.of))
        for oname, members in m.oneofs.items():
            o.append("  h = mix(h, (uint64_t)o.%s_case());" % oname)
            o.append("  switch (o.%s_case()) {" % oname)
            for g in members:
                o.append("    case pb::%s::k%s: %s break;"
                         % (n, camel(g.name), _pb_value(g.kind, "o.%s()" % g.name, g.of)))
            o.append("    default: break;")
            o.append("  }")
        o.append("  return h;")
        o.append("}")
        o.append("")
    o += ["}  // namespace pbtouch", ""]
    return "\n".join(o)
