"""The payload builder over the C++ facade types.

Mirrors `ffi/schema/emit/payloads.py` -- which value goes in which field, which fields the
absent-path modes remove, how explicit presence cycles, how the adapter's three states are
cycled -- and calls the value rules of `src/values.cpp`. Generated rather than written, so
the arms' objects and the manifest's bytes cannot drift, and so that the protobuf arm
(whose builder is `pb_build`, constructed independently over protoc's own types) and the
facade arms reach their values by two routes.
"""
from cppnames import camel, oneof_type, snake, variant

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

VALUE_FN = {"guid": "v::guid", "word": "v::word", "sentence": "v::sentence"}


def _enum_table(ename):
    return "shapes::tbl_%s()" % ename


def absent_expr(f):
    """`absent()` in emit/payloads.py. The precedence matters: `all_absent` drops EVERY
    field and the `half_absent` rules are checked only after that."""
    if f.adapter_site == "nested" or (f.kind == "message" and f.of == "Timestamp"
                                      and f.tag % 2 == 0):
        return "(mode == kAllAbsent || mode == kHalfAbsent)"
    return "(mode == kAllAbsent)"


def _string_expr(f, path, idx="idx"):
    return "%s(%s, (int)(%s))" % (VALUE_FN[f.value_rule], path, idx)


def _scalar_expr(f, path, idx="idx"):
    fn = {"int32": "v::scalar_i32", "int64": "v::scalar_i64",
          "bool": "v::scalar_bool", "double": "v::scalar_double"}[f.kind]
    return "%s(%s, (int)(%s))" % (fn, path, idx)


def _msg_call(ir, f, path, idx="idx"):
    if f.of == "Timestamp":
        return "mk_timestamp((int)(%s))" % idx
    if f.of == "Duration":
        return "mk_duration((int)(%s))" % idx
    return "build_%s(%s, %s, mode, repeats, bulk)" % (snake(f.of), path, idx)


def _emit_field(ir, m, f, o):
    fp = '(path + ".%s")' % f.name
    dst = "r.%s" % f.name

    if f.adapter_site == "nested":
        o.append("  if (!%s) {" % absent_expr(f))
        o.append("    switch (adapter_state(idx)) {")
        o.append("      case kAdapterInvalid: break;")
        o.append("      case kAdapterOk: {")
        o.append("        %s.emplace().success = true;" % dst)
        o.append("        break;")
        o.append("      }")
        o.append("      case kAdapterError: {")
        o.append("        %s::%s &c = %s.emplace();" % ("shapes", f.of, dst))
        o.append("        c.error = v::sentence(path + \".%s.error\", (int)idx);" % f.name)
        o.append("        break;")
        o.append("      }")
        o.append("    }")
        o.append("  }")
        return
    if f.adapter_site == "plain":
        o.append("  if (!%s && adapter_state(idx) == kAdapterError) %s = %s;"
                 % (absent_expr(f), dst, _string_expr(f, fp)))
        return

    o.append("  if (!%s) {" % absent_expr(f))
    if f.card == "map":
        n = f.raw.get("entries", 4)
        o.append("    for (int64_t k = 0; k < %d; ++k) {" % n)
        o.append("      char kb[8];")
        o.append("      std::snprintf(kb, sizeof(kb), \"k%02d-\", (int)k);")
        o.append("      std::string key = std::string(kb) + v::word(path + \".%s.key\", (int)(idx * 31 + k));"
                 % f.name)
        o.append("      std::string val;")
        o.append("      if (!(mode == kHalfAbsent && k % 2 == 0))")
        o.append("        val = v::word(path + \".%s.value\", (int)(idx * 31 + k));" % f.name)
        o.append("      %s[key] = val;" % dst)
        o.append("    }")
    elif f.card == "packed":
        n = f.raw.get("count", 30)
        o.append("    %s.reserve(%d);" % (dst, n))
        o.append("    for (int64_t j = 0; j < %d; ++j)" % n)
        if f.kind == "enum":
            o.append("      %s.push_back(shapes::%s(v::enum_value(%s, (int)(idx * 97 + j))));"
                     % (dst, f.of, _enum_table(f.of)))
        else:
            o.append("      %s.push_back(%s);" % (dst, _scalar_expr(f, fp, "idx * 97 + j")))
    elif f.card == "repeated" and f.kind == "string":
        o.append("    %s.reserve((size_t)repeats);" % dst)
        o.append("    for (int64_t j = 0; j < repeats; ++j)")
        o.append("      %s.push_back(%s);" % (dst, _string_expr(f, fp, "idx * 211 + j")))
    elif f.card == "repeated" and f.kind == "message":
        o.append("    %s.reserve((size_t)repeats);" % dst)
        o.append("    for (int64_t j = 0; j < repeats; ++j)")
        o.append("      %s.push_back(%s);" % (dst, _msg_call(ir, f, fp, "j")))
    elif f.card == "singular" and f.kind == "message":
        o.append("    %s.set(%s);" % (dst, _msg_call(ir, f, fp)))
    elif f.card == "singular" and f.kind == "string":
        if f.explicit:
            o.append("    if (explicit_present(%d, idx))" % f.tag)
            o.append("      %s.set(idx %% 7 == 0 ? std::string() : %s);" % (dst, _string_expr(f, fp)))
        else:
            o.append("    %s = %s;" % (dst, _string_expr(f, fp)))
    elif f.card == "singular" and f.kind == "bytes":
        if f.value_rule == "bulk":
            o.append("    %s = v::bulk(bulk);" % dst)
        else:
            o.append("    %s = v::blob(%s, (int)idx, 16);" % (dst, fp))
    elif f.card == "singular" and f.kind == "enum":
        o.append("    %s = shapes::%s(v::enum_value(%s, (int)idx));"
                 % (dst, f.of, _enum_table(f.of)))
    elif f.card == "singular" and f.is_scalar_leaf:
        if f.explicit:
            zero = {"int32": "0", "int64": "0", "bool": "false", "double": "0.0"}[f.kind]
            o.append("    if (explicit_present(%d, idx))" % f.tag)
            o.append("      %s.set(idx %% 7 == 0 ? %s : %s);" % (dst, zero, _scalar_expr(f, fp)))
        else:
            o.append("    %s = %s;" % (dst, _scalar_expr(f, fp)))
    else:
        # R1: a backend that has no case for a shape RAISES; it does not skip. Before this
        # the branches below the repeated ones did not re-test cardinality, so a repeated
        # `bytes` fell into the singular-`bytes` arm and an unpacked repeated enum into the
        # singular-`enum` arm, each emitting a scalar store against a std::vector.
        raise NotImplementedError(
            "REFUSED: the facade payload builder has no case for %s.%s (card=%s kind=%s)"
            % (m.name, f.name, f.card, f.kind))
    o.append("  }")


def _oneof_value(ir, msg, g, dst_expr):
    path = '"%s.%s"' % (msg, g.name)
    if g.kind == "string":
        return "%s = v::word(%s, (int)idx);" % (dst_expr, path)
    if g.kind == "bytes":
        return "%s = v::blob(%s, (int)idx, 16);" % (dst_expr, path)
    if g.kind == "int64":
        return "%s = v::scalar_i64(%s, (int)idx);" % (dst_expr, path)
    if g.kind == "int32":
        return "%s = v::scalar_i32(%s, (int)idx);" % (dst_expr, path)
    if g.kind == "message" and g.of == "Empty":
        return "(void)%s;" % dst_expr
    if g.kind == "message":
        return "%s = mk_timestamp((int)idx);" % dst_expr
    raise NotImplementedError("oneof member %s" % g.kind)


PRE = '''// Build any payload of shapes.json as facade values.
#include "generated/build.h"

#include <cstdio>

namespace shapes {
namespace build {

namespace v = ak::values;

// `explicit_present()`: presence cycles per field, and one element in seven is present AND
// zero, which a by-value group cannot tell from absent unless it is designed to.
static inline bool explicit_present(int64_t tag, int64_t idx) {
  return idx % (tag + 1) != 0;
}

static inline AdapterState adapter_state(int64_t idx) {
  switch (idx % 3) {
    case 0: return kAdapterError;
    case 1: return kAdapterOk;
    default: return kAdapterInvalid;
  }
}

static Timestamp mk_timestamp(int idx) {
  ak::values::Stamp s = v::timestamp(idx);
  Timestamp t;
  t.seconds = s.seconds;
  t.nanos = s.nanos;
  return t;
}

static Duration mk_duration(int idx) {
  ak::values::Stamp s = v::duration(idx);
  Duration t;
  t.seconds = s.seconds;
  t.nanos = s.nanos;
  return t;
}
'''


def emit_header(ir):
    o = [HEAD, "#ifndef AK_BUILD_H", "#define AK_BUILD_H",
         '#include "ak/values.h"', '#include "generated/types.h"', "",
         "namespace shapes {", "namespace build {", "",
         "enum Mode { kFull = 0, kAllAbsent = 1, kHalfAbsent = 2 };",
         "enum AdapterState { kAdapterError = 0, kAdapterOk = 1, kAdapterInvalid = 2 };", ""]
    for name in ir.order:
        if ir.msg(name).synthetic:
            continue
        o.append("%s build_%s(const std::string &path, int64_t idx, Mode mode,"
                 " int64_t repeats, size_t bulk);" % (name, snake(name)))
    o.append("")
    for pid, spec in ir.schema["payloads"].items():
        if spec["root"] not in ir.messages or spec.get("interleaved"):
            continue
        o.append("%s payload_%s();" % (spec["root"], pid.replace(".", "_").lower()))
    o.append("")
    o.append("// Every payload this build covers, by the id design/SHAPES.md uses.")
    o.append("extern const char *const kCovered[];")
    o.append("extern const int kNumCovered;")
    o.append("")
    o.append("}  // namespace build")
    o.append("}  // namespace shapes")
    o.append("#endif")
    o.append("")
    return "\n".join(o)


def emit(ir):
    o = [HEAD, PRE]
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        o.append("%s build_%s(const std::string &path, int64_t idx, Mode mode,"
                 " int64_t repeats, size_t bulk) {" % (name, snake(name)))
        o.append("  (void)path; (void)idx; (void)mode; (void)repeats; (void)bulk;")
        o.append("  %s r;" % name)
        for f in m.plain:
            if f.oneof:
                continue
            _emit_field(ir, m, f, o)
        for oname, members in m.oneofs.items():
            o.append("  switch (idx %% %d) {" % len(members))
            for i, g in enumerate(members):
                arm = "case %d:" % i if i < len(members) - 1 else "default:"
                o.append("    %s {" % arm)
                o.append("      %s"
                         % _oneof_value(ir, name, g, "r.%s.set_%s()" % (oname, g.name)))
                o.append("      break;")
                o.append("    }")
            o.append("  }")
        o.append("  return r;")
        o.append("}")
        o.append("")

    o.append("// ---- payloads -------------------------------------------------------")
    o.append("")
    ids = []
    for pid, spec in ir.schema["payloads"].items():
        root = spec["root"]
        if root not in ir.messages:
            continue
        m = ir.msg(root)
        fn = "payload_" + pid.replace(".", "_").lower()
        if spec.get("interleaved"):
            o.append("// %s has no builder: no canonical writer can produce it, so M7 is" % pid)
            o.append("// validated by DECODE (design/SHAPES.md, P7.1's row).")
            o.append("")
            continue
        ids.append(pid)
        o.append("// %s: %s, %s" % (pid, root, spec.get("mode", "full")))
        o.append("%s %s() {" % (root, fn))
        o.append("  %s r;" % root)
        if "bulk" in spec:
            f = m.plain[0]
            o.append("  r.%s.set(build_%s(\"%s\", 0, kFull, 3, %d));"
                     % (f.name, snake(f.of), f.of, spec["bulk"]))
        else:
            field = next(f for f in m.plain if f.name == spec["field"])
            reps = spec.get("repeats", 3)
            reps = reps if isinstance(reps, list) else [reps]
            o.append("  static const int64_t kReps[%d] = {%s};"
                     % (len(reps), ", ".join(str(r) for r in reps)))
            o.append("  r.%s.reserve(%d);" % (field.name, spec["count"]))
            mode = {"all_absent": "kAllAbsent", "half_absent": "kHalfAbsent"}.get(
                spec.get("mode"), "kFull")
            o.append("  for (int64_t j = 0; j < %d; ++j)" % spec["count"])
            o.append("    r.%s.push_back(build_%s(\"%s\", j, %s, kReps[j %% %d], 0));"
                     % (field.name, snake(field.of), field.of, mode, len(reps)))
            for f in m.plain:
                if f.name == "page":
                    o.append("  r.page = 1;")
                elif f.name == "total":
                    o.append("  r.total = %d;" % spec["count"])
        o.append("  return r;")
        o.append("}")
        o.append("")
    o.append("const char *const kCovered[] = {%s};" % ", ".join('"%s"' % p for p in ids))
    o.append("const int kNumCovered = %d;" % len(ids))
    o.append("")
    o.append("}  // namespace build")
    o.append("}  // namespace shapes")
    o.append("")
    return "\n".join(o)
