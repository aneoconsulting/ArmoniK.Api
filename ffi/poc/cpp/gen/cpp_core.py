"""Arm `core-native-cpp`: the generated codec emitted into C++, over the same facade
objects, with no boundary at all. README R3's no-boundary control, which is not optional.

One traversal emitter, two backends, exactly as the rust slice's `rust_core.py` says: the
field order, the wire types and the skip rules are decided by `walk_encode`/`walk_decode`
(imported read-only from the rust generator) and a Backend decides only where a value comes
from or goes to. A backend that has no case for a shape RAISES; it does not skip -- that
rule is what a silently-missing oneof cost the rust slice.

The C++11/C++17 divergence lives HERE and in the binding, never in an installed header
type (README 5.1's hard stop). `AK_CXX17` selects `if constexpr`-free tag dispatch at the
floor and the direct form at the target; the wire bytes are identical by construction,
because the traversal is one function.
"""
from rust_core import walk_encode, walk_decode, Sites
from cppnames import camel, oneof_type, snake, variant

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")


class CppEnc:
    def __init__(self, sites):
        self.sites = sites

    def child(self, m, f, o):
        s = self.sites.id((m.name, f.name))
        o.append("  if (o.%s.has_value()) {" % f.name)
        o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
        o.append("    enc_%s(*o.%s, e);" % (snake(f.of), f.name))
        o.append("    e->end(mk);")
        o.append("  }")

    def repeated_message(self, m, f, o):
        s = self.sites.id((m.name, f.name))
        o.append("  for (size_t i = 0; i < o.%s.size(); ++i) {" % f.name)
        o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
        o.append("    enc_%s(o.%s[i], e);" % (snake(f.of), f.name))
        o.append("    e->end(mk);")
        o.append("  }")

    def blob(self, m, f, o):
        if f.explicit:
            o.append("  if (o.%s.has_value()) e->blob_field(%d, *o.%s);"
                     % (f.name, f.tag, f.name))
            return
        o.append("  if (!o.%s.empty()) e->blob_field(%d, o.%s);" % (f.name, f.tag, f.name))

    def scalar(self, m, f, o):
        n = "o.%s" % f.name
        if f.explicit:
            v = "(uint64_t)(int64_t)*o.%s" % f.name
            if f.kind == "bool":
                v = "(uint64_t)(*o.%s ? 1 : 0)" % f.name
            o.append("  if (o.%s.has_value()) e->varint_field(%d, %s);" % (f.name, f.tag, v))
            return
        if f.kind == "enum":
            o.append("  if (%s.v != 0) e->varint_field(%d, (uint64_t)(int64_t)%s.v);"
                     % (n, f.tag, n))
        elif f.kind == "bool":
            o.append("  if (%s) e->varint_field(%d, 1);" % (n, f.tag))
        elif f.kind == "int32":
            o.append("  if (%s != 0) e->varint_field(%d, (uint64_t)(int64_t)%s);"
                     % (n, f.tag, n))
        else:
            o.append("  if (%s != 0) e->varint_field(%d, (uint64_t)%s);" % (n, f.tag, n))

    def double(self, m, f, o):
        o.append("  if (o.%s != 0.0) e->f64_field(%d, o.%s);" % (f.name, f.tag, f.name))

    def repeated_blob(self, m, f, o):
        o.append("  for (size_t i = 0; i < o.%s.size(); ++i) e->blob_field(%d, o.%s[i]);"
                 % (f.name, f.tag, f.name))

    def packed(self, m, f, o):
        s = self.sites.id(("packed", m.name, f.name))
        o.append("  if (!o.%s.empty()) {" % f.name)
        o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
        o.append("    for (size_t i = 0; i < o.%s.size(); ++i)" % f.name)
        if f.kind == "double":
            o.append("      { double dv = o.%s[i]; e->raw((const uint8_t *)&dv, 8); }" % f.name)
        elif f.kind == "bool":
            o.append("      e->varint(o.%s[i] ? 1 : 0);" % f.name)
        elif f.kind == "enum":
            o.append("      e->varint((uint64_t)(int64_t)o.%s[i].v);" % f.name)
        elif f.kind == "int32":
            o.append("      e->varint((uint64_t)(int64_t)o.%s[i]);" % f.name)
        else:
            o.append("      e->varint((uint64_t)o.%s[i]);" % f.name)
        o.append("    e->end(mk);")
        o.append("  }")

    def oneof(self, m, oname, members, o):
        ty = oneof_type(m.name, oname)
        o.append("  switch (o.%s.which()) {" % oname)
        for g in members:
            o.append("    case %s::k%s: {" % (ty, camel(g.name)))
            if g.kind in ("string", "bytes"):
                o.append("      e->blob_field(%d, o.%s.%s());" % (g.tag, oname, g.name))
            elif g.kind == "message":
                s = self.sites.id(("oneof", m.name, oname, g.name))
                o.append("      { ak::Mark mk = e->begin(%d, %d);" % (g.tag, s))
                o.append("        enc_%s(o.%s.%s(), e);" % (snake(g.of), oname, g.name))
                o.append("        e->end(mk); }")
            elif g.kind == "double":
                o.append("      e->f64_field(%d, o.%s.%s());" % (g.tag, oname, g.name))
            elif g.kind == "bool":
                o.append("      e->varint_field(%d, o.%s.%s() ? 1 : 0);" % (g.tag, oname, g.name))
            elif g.kind == "int32":
                o.append("      e->varint_field(%d, (uint64_t)(int64_t)o.%s.%s());"
                         % (g.tag, oname, g.name))
            else:
                o.append("      e->varint_field(%d, (uint64_t)o.%s.%s());" % (g.tag, oname, g.name))
            o.append("      break;")
            o.append("    }")
        o.append("    default: break;")
        o.append("  }")

    def map(self, m, f, o):
        s = self.sites.id(("map", m.name, f.name))
        o.append("  for (std::map<std::string, std::string>::const_iterator it = o.%s.begin();"
                 % f.name)
        o.append("       it != o.%s.end(); ++it) {" % f.name)
        o.append("    ak::Mark mk = e->begin(%d, %d);" % (f.tag, s))
        o.append("    if (!it->first.empty()) e->blob_field(1, it->first);")
        o.append("    if (!it->second.empty()) e->blob_field(2, it->second);")
        o.append("    e->end(mk);")
        o.append("  }")


class CppDec:
    def __init__(self, sites=None):
        self.sites = sites

    def _sub(self, o, fn, target):
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("        ak::Dec sub(d->buf + off, n);")
        o.append("        %s" % target)
        o.append("        %s(&sub, &dst_);" % fn)
        o.append("        if (sub.err != 0) { d->err = sub.err; return; }")

    def child(self, m, f, o):
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("        ak::Dec sub(d->buf + off, n);")
        o.append("        %s &dst_ = out->%s.emplace();" % (f.of, f.name))
        o.append("        dec_%s(&sub, &dst_);" % snake(f.of))
        o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        o.append("        break; } else { d->skip(wire); break; }")

    def repeated_message(self, m, f, o):
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("        ak::Dec sub(d->buf + off, n);")
        o.append("        out->%s.push_back(%s());" % (f.name, f.of))
        o.append("        dec_%s(&sub, &out->%s.back());" % (snake(f.of), f.name))
        o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        o.append("        break; } else { d->skip(wire); break; }")

    def blob(self, m, f, o):
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        tgt = "out->%s" % f.name
        if f.explicit:
            o.append("        std::string &s_ = out->%s.emplace();" % f.name)
            tgt = "s_"
        if f.kind == "string":
            o.append("        int32_t rc = ak::decode_str(d->buf + off, n, &%s);" % tgt)
            o.append("        if (rc != 0) { d->err = rc; return; }")
        else:
            o.append("        %s.assign((const char *)(d->buf + off), n);" % tgt)
        o.append("        break; } else { d->skip(wire); break; }")

    def scalar(self, m, f, o):
        o.append("      case %d: if (wire == 0) {" % f.tag)
        if f.kind == "enum":
            v = "%s((int32_t)d->varint())" % f.of
        elif f.kind == "bool":
            v = "(d->varint() != 0)"
        elif f.kind == "int32":
            v = "(int32_t)d->varint()"
        else:
            v = "(int64_t)d->varint()"
        if f.explicit:
            o.append("        out->%s.set(%s);" % (f.name, v))
        else:
            o.append("        out->%s = %s;" % (f.name, v))
        o.append("        break; } else { d->skip(wire); break; }")

    def double(self, m, f, o):
        o.append("      case %d: if (wire == 1) { out->%s = d->f64(); break; }"
                 " else { d->skip(wire); break; }" % (f.tag, f.name))

    def repeated_blob(self, m, f, o):
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("#if AK_CXX17")
        o.append("        // C++17: emplace_back returns the reference the writer needs.")
        o.append("        std::string &b_ = out->%s.emplace_back();" % f.name)
        o.append("#else")
        o.append("        out->%s.push_back(std::string());" % f.name)
        o.append("        std::string &b_ = out->%s.back();" % f.name)
        o.append("#endif")
        if f.kind == "string":
            o.append("        int32_t rc = ak::decode_str(d->buf + off, n, &b_);")
            o.append("        if (rc != 0) { d->err = rc; return; }")
        else:
            o.append("        b_.assign((const char *)(d->buf + off), n);")
        o.append("        break; } else { d->skip(wire); break; }")

    def packed(self, m, f, o):
        rd = {"double": "sub.f64()", "bool": "(sub.varint() != 0)",
              "int32": "(int32_t)sub.varint()", "int64": "(int64_t)sub.varint()",
              "enum": "%s((int32_t)sub.varint())" % f.of}[f.kind]
        rd1 = {"double": "d->f64()", "bool": "(d->varint() != 0)",
               "int32": "(int32_t)d->varint()", "int64": "(int64_t)d->varint()",
               "enum": "%s((int32_t)d->varint())" % f.of}[f.kind]
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("        ak::Dec sub(d->buf + off, n);")
        o.append("        while (!sub.at_end()) out->%s.push_back(%s);" % (f.name, rd))
        o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        o.append("        break;")
        o.append("      } else {")
        o.append("        // A decoder must accept the unpacked form too: proto3 makes packed")
        o.append("        // the default, it does not make the other form illegal.")
        o.append("        out->%s.push_back(%s); break;" % (f.name, rd1))
        o.append("      }")

    def oneof(self, m, oname, members, o):
        for g in members:
            if g.kind in ("string", "bytes"):
                o.append("      case %d: if (wire == 2) {" % g.tag)
                o.append("        size_t off, n; d->len_body(&off, &n);")
                o.append("        std::string &s_ = out->%s.set_%s();" % (oname, g.name))
                if g.kind == "string":
                    o.append("        int32_t rc = ak::decode_str(d->buf + off, n, &s_);")
                    o.append("        if (rc != 0) { d->err = rc; return; }")
                else:
                    o.append("        s_.assign((const char *)(d->buf + off), n);")
                o.append("        break; } else { d->skip(wire); break; }")
            elif g.kind == "message":
                o.append("      case %d: if (wire == 2) {" % g.tag)
                o.append("        size_t off, n; d->len_body(&off, &n);")
                o.append("        ak::Dec sub(d->buf + off, n);")
                o.append("        %s &c_ = out->%s.set_%s();" % (g.of, oname, g.name))
                o.append("        dec_%s(&sub, &c_);" % snake(g.of))
                o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
                o.append("        break; } else { d->skip(wire); break; }")
            elif g.kind == "double":
                o.append("      case %d: if (wire == 1) { out->%s.set_%s() = d->f64(); break; }"
                         " else { d->skip(wire); break; }" % (g.tag, oname, g.name))
            else:
                cast = {"int32": "(int32_t)", "int64": "(int64_t)", "bool": "0 != "}[g.kind]
                o.append("      case %d: if (wire == 0) { out->%s.set_%s() = %sd->varint();"
                         " break; } else { d->skip(wire); break; }"
                         % (g.tag, oname, g.name, cast))

    def map(self, m, f, o):
        o.append("      case %d: if (wire == 2) {" % f.tag)
        o.append("        size_t off, n; d->len_body(&off, &n);")
        o.append("        ak::Dec sub(d->buf + off, n);")
        o.append("        std::string k_, v_;")
        o.append("        while (!sub.at_end()) {")
        o.append("          uint64_t kk = sub.varint();")
        o.append("          uint32_t et = (uint32_t)(kk >> 3), ew = (uint32_t)(kk & 7);")
        o.append("          if (et == 1 && ew == 2) {")
        o.append("            size_t a, b; sub.len_body(&a, &b);")
        o.append("            int32_t rc = ak::decode_str(sub.buf + a, b, &k_);")
        o.append("            if (rc != 0) { d->err = rc; return; }")
        o.append("          } else if (et == 2 && ew == 2) {")
        o.append("            size_t a, b; sub.len_body(&a, &b);")
        o.append("            int32_t rc = ak::decode_str(sub.buf + a, b, &v_);")
        o.append("            if (rc != 0) { d->err = rc; return; }")
        o.append("          } else {")
        o.append("            sub.skip(ew);")
        o.append("          }")
        o.append("        }")
        o.append("        if (sub.err != 0) { d->err = sub.err; return; }")
        o.append("#if AK_CXX17")
        o.append("        // C++17: one insertion, no default-construct-then-assign.")
        o.append("        out->%s.insert_or_assign(std::move(k_), std::move(v_));" % f.name)
        o.append("#else")
        o.append("        out->%s[k_] = v_;" % f.name)
        o.append("#endif")
        o.append("        break; } else { d->skip(wire); break; }")


def emit_header(ir):
    o = [HEAD, "#ifndef AK_CORE_NATIVE_H", "#define AK_CORE_NATIVE_H",
         '#include "ak/rt.h"', '#include "generated/types.h"', "",
         "namespace shapes {", "namespace native {", "",
         "// One learned length-prefix slot per site in this file (ABI v1 section 6).",
         "extern const size_t kSites;", ""]
    for root in ir.roots:
        o.append("void encode_into_%s(const %s &o, ak::Enc *e);" % (snake(root), root))
        o.append("int32_t decode_%s(const uint8_t *b, size_t n, %s *out);" % (snake(root), root))
    o.append("")
    o.append("}  // namespace native")
    o.append("}  // namespace shapes")
    o.append("#endif")
    o.append("")
    return "\n".join(o)


def emit(ir):
    sites = Sites()
    body = []
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("static void enc_%s(const %s &o, ak::Enc *e) {" % (snake(name), name))
        body.append("  (void)o; (void)e;")
        walk_encode(ir, m, CppEnc(sites), body)
        body.append("}")
        body.append("")
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("static void dec_%s(ak::Dec *d, %s *out) {" % (snake(name), name))
        body.append("  (void)out;")
        body.append("  while (!d->at_end()) {")
        body.append("    uint64_t k = d->varint();")
        body.append("    uint32_t tag = (uint32_t)(k >> 3), wire = (uint32_t)(k & 7);")
        body.append("    if (tag == 0) { d->err = ak::ERR_MALFORMED; return; }")
        body.append("    switch (tag) {")
        walk_decode(ir, m, CppDec(), body)
        body.append("      default: d->skip(wire); break;")
        body.append("    }")
        body.append("  }")
        body.append("}")
        body.append("")

    fwd = []
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        fwd.append("static void enc_%s(const %s &o, ak::Enc *e);" % (snake(name), name))
        fwd.append("static void dec_%s(ak::Dec *d, %s *out);" % (snake(name), name))
    fwd.append("")

    o = [HEAD, """
// Arm `core-native-cpp`: the same generated traversal as the core behind the C ABI, over
// the same facade objects, with no boundary at all. README R3's no-boundary control.
//
// R5's second half applies to this arm in the opposite direction from the FFI one: an arm
// named "no boundary" is only a control if it is not FUSED INTO THE BENCHMARK LOOP. In C++
// that question is `-flto` over this file, and `gen/boundary.sh` answers it from the built
// artifact rather than from a claim.
#include "generated/core_native.h"

#include <cstring>

namespace shapes {
namespace native {
""".lstrip("\n")]
    o += fwd
    o += body
    for root in ir.roots:
        o.append("void encode_into_%s(const %s &o, ak::Enc *e) {" % (snake(root), root))
        o.append("  e->reset();")
        o.append("  enc_%s(o, e);" % snake(root))
        o.append("}")
        o.append("")
        o.append("int32_t decode_%s(const uint8_t *b, size_t n, %s *out) {" % (snake(root), root))
        o.append("  ak::Dec d(b, n);")
        o.append("  dec_%s(&d, out);" % snake(root))
        o.append("  return d.err;")
        o.append("}")
        o.append("")
    o.append("const size_t kSites = %d;" % len(sites))
    o.append("")
    o.append("}  // namespace native")
    o.append("}  // namespace shapes")
    o.append("")
    return "\n".join(o)
