#!/usr/bin/env python3
"""W8: the cpp slice consumes the conformance corpus, as far as its scope reaches.

`ffi/corpus/CONTRACT.md` is the obligation; this file runs it. The C++ half is
`src/corpus.cpp`, which decodes, projects and re-encodes; everything that reads JSON is
here, because a JSON reader in C++ would be a second thing to be wrong about.

**Why this exists at all, stated before any number.** This slice's correctness gate is
byte identity against `ffi/schema/generated/manifest.json`, generated from the SAME proto3
description the codec is generated from. proto3 cannot express a group, so no payload in
that manifest carries wire type 3, and `ak::Dec::skip` refused wire type 3 outright --
rejecting a message protobuf C++ and upb both accept -- while 443 conformance checks
passed. The corpus is written against a superset schema by a different tool. That is the
second opinion, and it is the only kind of oracle that could have found it.

**Scope.** This slice's codec is generated for seven roots (`gen/generate.py`'s ROOTS),
which is what `AK_ROOTS` in `src/generated/cases.h` exports so the scope claimed here
cannot exceed the scope the codec has. Every row outside it is reported by root and by
class, never silently dropped (R11).

**Obligations run**: C1 (parse), C2 (project), C3 (re-encode to an accepted form, and say
which), C4 (refuse, and record what the refusal looked like), on BOTH arms. C5 (produce)
is discussed at the end and is a partial claim, stated as one.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SLICE = os.path.dirname(HERE)
FFI = os.path.dirname(os.path.dirname(SLICE))
CORPUS = os.path.join(FFI, "corpus", "generated")
SCHEMA = os.path.join(FFI, "schema", "generated")
MAN = json.load(open(os.path.join(CORPUS, "manifest.json")))


def roots_from_cases():
    """The roots the CODEC has, read out of the generated header rather than restated."""
    t = open(os.path.join(SLICE, "src", "generated", "cases.h")).read()
    m = re.search(r"#define AK_ROOTS\(X\)(.*?)\n\n", t, re.S)
    return [x for x in re.findall(r"X\((\w+),", m.group(1))]


def check_rule_zero(roots):
    """CONTRACT.md rule 0: the reader is built against `corpus.proto`, never against
    `corpus_superset.proto`. A reader generated from the superset knows every field,
    executes no unknown-field skip, and passes class `unknown` while testing nothing.

    Checked rather than asserted: this slice's own `shapes.proto` is diffed against both,
    for every message the corpus roots at within scope.
    """
    def msgs(path):
        t = open(path).read()
        out = {}
        for m in re.finditer(r"^message (\w+) \{(.*?)^\}", t, re.S | re.M):
            out[m.group(1)] = [l.strip() for l in m.group(2).splitlines()
                               if l.strip() and not l.strip().startswith("//")]
        return out
    mine = msgs(os.path.join(SCHEMA, "shapes.proto"))
    reader = msgs(os.path.join(CORPUS, "corpus.proto"))
    sup = msgs(os.path.join(CORPUS, "corpus_superset.proto"))
    ok, notes = True, []
    for n in roots:
        if n not in reader:
            notes.append("%s: not declared in corpus.proto at all" % n)
            ok = False
            continue
        if mine.get(n) != reader.get(n):
            ok = False
            notes.append("%s: this slice's schema differs from corpus.proto" % n)
            continue
        extra = [x for x in sup.get(n, []) if x not in mine.get(n, [])]
        if not extra:
            notes.append("%s: identical to corpus.proto; the superset adds nothing HERE, "
                         "so this root's unknown-field claim rests on its element types"
                         % n)
        else:
            notes.append("%s: identical to corpus.proto; the superset adds %d field(s) "
                         "this reader does not know (%s)"
                         % (n, len(extra), ", ".join(x.split()[-3] for x in extra[:4])))
    return ok, notes


# ---- an INDEPENDENT projection oracle, and why a consumer needs one ------------------
#
# CONTRACT.md's own warning is that a corpus generated by one tool and read by one reader
# is a single opinion. The corpus is a second opinion about this slice; protobuf-python on
# upb is a third about both, and it costs nothing here because it needs no generated code:
# a descriptor set plus `message_factory` builds the reader at run time.
#
# So when this slice's projection differs from the corpus's, the question "which of the two
# is right" is answered by a decode rather than by argument. That is what turned the first
# C2 mismatch here from "a defect in this slice" into a defect in the corpus's projection.
def oracle_pool():
    from google.protobuf import descriptor_pb2, descriptor_pool
    desc = os.path.join(SLICE, "build", "corpus.desc")
    if not os.path.exists(desc):
        subprocess.run(["protoc", "--descriptor_set_out=" + desc, "-I", CORPUS,
                        os.path.join(CORPUS, "corpus.proto")], check=True)
    fds = descriptor_pb2.FileDescriptorSet()
    fds.ParseFromString(open(desc, "rb").read())
    pool = descriptor_pool.DescriptorPool()
    for f in fds.file:
        pool.Add(f)
    return pool


def oracle_project(pool, root, buf):
    """CONTRACT.md section 3's encoding, over protobuf-python's own `ListFields`.

    `ListFields` IS the section 3 rule: it returns exactly the set fields, so an
    implicit-presence scalar at its default is absent and an explicit-presence zero is
    present. Nothing here re-implements presence; it only spells the values.
    """
    from google.protobuf import message_factory
    from google.protobuf.descriptor import FieldDescriptor as FD
    cls = message_factory.GetMessageClass(
        pool.FindMessageTypeByName("armonik.ffi.corpus.v1." + root))
    m = cls()
    m.ParseFromString(buf)

    def val(fd, v):
        if fd.type == FD.TYPE_MESSAGE:
            return proj(v)
        if fd.type in (FD.TYPE_STRING,):
            return v
        if fd.type in (FD.TYPE_BYTES,):
            return v.hex()
        if fd.type == FD.TYPE_BOOL:
            return bool(v)
        if fd.type == FD.TYPE_DOUBLE:
            return "%.17g" % v
        return str(int(v))

    def proj(msg):
        out = {}
        for fd, v in msg.ListFields():
            if fd.label == FD.LABEL_REPEATED and fd.message_type is not None \
                    and fd.message_type.GetOptions().map_entry:
                vfd = fd.message_type.fields_by_name["value"]
                out[fd.name] = {str(k): val(vfd, v[k]) for k in v}
            elif fd.label == FD.LABEL_REPEATED:
                out[fd.name] = [val(fd, x) for x in v]
            else:
                out[fd.name] = val(fd, v)
        return out

    return proj(m)


def oracle_both(pool, root, path):
    """The same projection from protobuf's TWO backends.

    `protobuf-python` ships upb and a pure-Python implementation of the same descriptor,
    selected by an environment variable, and they are separate parsers. Asking both costs
    one subprocess and it is what turned `U-map-entry` from "one implementation disagrees
    with this slice" into "two Google implementations disagree with each other".
    """
    upb = oracle_project(pool, root, open(path, "rb").read())
    env = dict(os.environ)
    env["PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION"] = "python"
    p = subprocess.run([sys.executable, os.path.abspath(__file__), "--project", root,
                        path], stdout=subprocess.PIPE, env=env)
    try:
        pure = json.loads(p.stdout.decode())
    except ValueError:
        pure = None
    return upb, pure


def triples(buf):
    """Top-level (tag, wire type, body) triples, as a sorted multiset.

    Only used to say what a re-encode of an INTERLEAVED vector is: P7.1 puts two repeated
    fields' elements in alternation, no canonical writer can reproduce that order, and a
    contiguous re-encode is a permutation of the same triples rather than the same bytes.
    """
    out, i = [], 0
    while i < len(buf):
        k, s = 0, 0
        while True:
            if i >= len(buf):
                return None
            c = buf[i]
            i += 1
            k |= (c & 0x7f) << s
            if not c & 0x80:
                break
            s += 7
        t, w = k >> 3, k & 7
        if w == 0:
            st = i
            while i < len(buf) and buf[i] & 0x80:
                i += 1
            i += 1
            out.append((t, w, bytes(buf[st:i])))
        elif w == 1:
            out.append((t, w, bytes(buf[i:i + 8]))); i += 8
        elif w == 2:
            n, s2 = 0, 0
            while True:
                c = buf[i]; i += 1
                n |= (c & 0x7f) << s2
                if not c & 0x80:
                    break
                s2 += 7
            out.append((t, w, bytes(buf[i:i + n]))); i += n
        elif w == 5:
            out.append((t, w, bytes(buf[i:i + 4]))); i += 4
        else:
            return None
    return sorted(out)


def strip_unknown(d):
    """`_unknown` is optional per CONTRACT.md section 3, because whether the core retains
    unknown fields is ABI v1 open decision 11. This core DROPS them, which is this slice's
    answer to that decision and is reported as such below."""
    if isinstance(d, dict):
        return {k: strip_unknown(v) for k, v in d.items() if k != "_unknown"}
    if isinstance(d, list):
        return [strip_unknown(x) for x in d]
    return d


def vpath(r):
    return os.path.normpath(os.path.join(CORPUS, r["file"]))


def _side(x, mine, corpus):
    if x is None:
        return "?"
    if x == mine:
        return "this slice"
    if x == corpus:
        return "the corpus"
    return "a third answer"


def pdiff(got, want):
    gk, wk = set(got), set(want)
    if gk != wk:
        return "keys +%s -%s" % (sorted(gk - wk)[:3], sorted(wk - gk)[:3])
    for k in sorted(gk):
        if got[k] != want[k]:
            return "%s: %.60r vs %.60r" % (k, str(got[k]), str(want[k]))
    return "equal?"


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--project":
        # A worker for `oracle_both`: project one vector with whichever protobuf backend
        # the environment selects, and print it. Its own process, because the backend is
        # chosen once per interpreter.
        print(json.dumps(oracle_project(oracle_pool(), sys.argv[2],
                                        open(sys.argv[3], "rb").read())))
        return 0
    binary = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SLICE, "build",
                                                                "corpus_a17_shared")
    roots = roots_from_cases()
    rows = MAN["vectors"]

    print("# cpp slice: the conformance corpus (W8), as far as this scope reaches")
    print("# corpus:   %s" % MAN.get("corpus_version", "?"))
    print("# vectors:  %d in the corpus" % len(rows))
    print("# reader:   generated from ffi/schema/shapes.json; roots = %s"
          % ", ".join(roots))
    print("# binary:   %s" % os.path.basename(binary))
    print()

    print("## CONTRACT.md rule 0: the reader is not generated from the superset")
    ok, notes = check_rule_zero(roots)
    for n in notes:
        print("   %s %s" % ("[ok] " if ok else "FAIL ", n))
    if not ok:
        return 1

    inscope = {k: r for k, r in rows.items() if r.get("root") in roots}
    print("\n## scope")
    print("   %d of %d rows root at a message this slice's codec covers."
          % (len(inscope), len(rows)))
    byroot = {}
    for r in rows.values():
        byroot[r.get("root")] = byroot.get(r.get("root"), 0) + 1
    print("   Out of scope, by root. Every one is a message this slice does not have,")
    print("   never a row it chose to skip:")
    for k, v in sorted(((k, v) for k, v in byroot.items() if k not in roots),
                       key=lambda x: -x[1]):
        print("      %-28s %d" % (k, v))
    cls = {}
    for r in inscope.values():
        cls[r["class"]] = cls.get(r["class"], 0) + 1
    print("   In scope, by class: %s"
          % ", ".join("%s=%d" % kv for kv in sorted(cls.items())))

    # The walker rows: every vector rooted at a message this slice does NOT have, run
    # through `ak::Dec::skip` with no schema. It is not a root decode and is never counted
    # as one; it is the only way this slice can reach the corpus's wire-form vectors, and
    # they are the ones that exercise what this work unit fixed.
    walkable = {k: r for k, r in rows.items()
                if r.get("root") == "WireZoo"}

    tasks = []
    for vid, r in sorted(inscope.items()):
        tasks.append("msg\t%s\t%s\t%s" % (vid, r["root"], vpath(r)))
    for vid, r in sorted(walkable.items()):
        tasks.append("walk\t%s\t-\t%s" % (vid, vpath(r)))
    tfile = os.path.join(SLICE, "build", "corpus_tasks.tsv")
    open(tfile, "w").write("\n".join(tasks) + "\n")

    p = subprocess.run([binary, tfile], stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    res, proj, agree, walked, unhandled, hexes = {}, {}, {}, {}, [], {}
    head = []
    for line in p.stdout.decode("utf-8", "replace").splitlines():
        if line.startswith("#"):
            head.append(line)
            continue
        f = line.split("\t")
        if f[0] == "R" and len(f) >= 7:
            res[(f[1], f[2])] = (f[3], int(f[4]), f[5], int(f[6]))
        elif f[0] == "P" and len(f) >= 4:
            proj[(f[1], f[2])] = f[3]
        elif f[0] == "B" and len(f) >= 4:
            hexes[(f[1], f[2])] = f[3]
        elif f[0] == "A" and len(f) >= 3:
            agree[f[1]] = f[2]
        elif f[0] == "W" and len(f) >= 6:
            walked[f[1]] = (f[2], int(f[3]), int(f[4]), int(f[5]))
        elif f[0] == "U":
            unhandled.append(f[1])
    print()
    for h in head:
        print(h)
    if unhandled:
        print("   FAIL the binary had no root case for: %s" % ", ".join(unhandled))

    pool = oracle_pool()
    fails = []
    forms = {}
    unknown_forms = {}
    rejects_seen = []
    incumbent = []     # rows the INCUMBENT itself does not reproduce
    disputed = {}      # C2 rows where this slice and the corpus disagree
    permuted = {}      # C3 rows re-encoded to a permutation of the same triples
    print("\n## C1 parse, C2 project, C3 re-encode, C4 refuse")
    n_acc = sum(1 for r in inscope.values() if r["expect"] == "accept")
    n_rej = len(inscope) - n_acc
    n_proj = sum(1 for r in inscope.values()
                 if r["expect"] == "accept" and r.get("projection"))
    for arm in ("native", "ffi", "pb"):
        c1 = c2 = c3 = c4 = 0
        bad = []
        for vid, r in sorted(inscope.items()):
            got = res.get((vid, arm))
            if got is None:
                bad.append("%s: the binary produced no result" % vid)
                continue
            status, err, sha, nbytes = got
            if r["expect"] == "reject":
                if status == "reject":
                    c4 += 1
                    rejects_seen.append((arm, vid, err))
                else:
                    bad.append("%s: C4 ACCEPTED a reject vector" % vid)
                continue
            if status != "accept":
                bad.append("%s: C1 refused with err %d" % (vid, err))
                continue
            c1 += 1
            if r.get("projection"):
                want = strip_unknown(json.load(open(
                    os.path.normpath(os.path.join(CORPUS, r["projection"])))))
                try:
                    g = json.loads(proj.get((vid, arm), ""))
                except ValueError as e:
                    bad.append("%s: C2 projection is not JSON: %s" % (vid, e))
                    continue
                if g == want:
                    c2 += 1
                else:
                    # The corpus is a second opinion about this slice. protobuf-python on
                    # upb is a third about both, and it decides which of the two is right
                    # instead of leaving it as an assertion.
                    upb, pure = oracle_both(pool, r["root"], vpath(r))
                    try:
                        pbp = json.loads(proj.get((vid, "pb"), ""))
                    except ValueError:
                        pbp = None
                    who = []
                    if g == upb:
                        who.append("protobuf-python/upb")
                    if pure is not None and g == pure:
                        who.append("protobuf-python/pure")
                    if pbp is not None and g == pbp:
                        who.append("protobuf C++ (the incumbent)")
                    if who:
                        disputed.setdefault(vid, []).append(
                            (arm, pdiff(g, want),
                             "this slice agrees with " + " and ".join(who)
                             + "; the corpus's projection does not",
                             "upb=%s  pure-python=%s  protobuf C++=%s"
                             % (_side(upb, g, want), _side(pure, g, want),
                                _side(pbp, g, want))))
                    else:
                        bad.append("%s: C2 projection differs from the corpus AND from "
                                   "both protobuf backends: %s" % (vid, pdiff(g, want)))
            # C3. Rows whose only accepted form is the vector itself (the `baseline` rows
            # that REFERENCE ffi/schema's payloads) carry no `accepted_encodings`.
            enc = r.get("accepted_encodings") or [
                {"sha256": r["sha256"], "bytes": r["bytes"], "forms": ["as committed"]}]
            acc = {a["sha256"]: a.get("forms", ["?"]) for a in enc}
            if sha in acc:
                c3 += 1
                for form in acc[sha]:
                    forms.setdefault(arm, {}).setdefault(form, 0)
                    forms[arm][form] += 1
                    if r["class"] == "unknown":
                        unknown_forms.setdefault(arm, {}).setdefault(form, 0)
                        unknown_forms[arm][form] += 1
            else:
                # An INTERLEAVED vector has no canonical writer: P7.1 alternates two
                # repeated fields' elements and any conformant encoder writes each field
                # contiguously. Before calling that a defect, check what it actually is --
                # a permutation of the same (tag, wire type, body) triples, which is the
                # same message. Reported in its own section, NEVER counted as a C3 pass.
                mine = hexes.get((vid, arm))
                perm = False
                if mine is not None:
                    a = triples(bytes.fromhex(mine))
                    b = triples(open(vpath(r), "rb").read())
                    if a is not None and a == b:
                        perm = True
                        permuted.setdefault(vid, []).append((arm, sha[:12], nbytes))
                if perm:
                    continue
                bad.append("%s: C3 wrote a form the manifest does not accept "
                           "(%s, %d B; accepted: %s)"
                           % (vid, sha[:12], nbytes,
                              ", ".join("%s=%s" % (a["sha256"][:8],
                                                   "/".join(a.get("forms", ["?"])))
                                        for a in enc)))
        print("   %-8s C1 %3d/%-3d  C2 %3d/%-3d  C3 %3d/%-3d  C4 %d/%d%s"
              % (arm, c1, n_acc, c2, n_proj, c3, n_acc, c4, n_rej,
                 "   (the INCUMBENT: an oracle here, not a claimant)"
                 if arm == "pb" else ""))
        for b in bad:
            print("        %s %s" % ("note" if arm == "pb" else "FAIL", b))
        if arm == "pb":
            incumbent.extend(bad)
        else:
            fails.extend(bad)

    if disputed:
        print("\n## C2 rows where this slice and the CORPUS disagree, and who is right")
        print("#  Decided by a third implementation rather than by argument: the vector is")
        print("#  re-read with protobuf-python on upb, built at run time from a descriptor")
        print("#  set of corpus.proto. A row here is a finding about the corpus and is")
        print("#  reported to the corpus's owner; this slice does not write corpus/**.")
        for vid, rows_ in sorted(disputed.items()):
            for arm, d, verdict, tally in rows_:
                print("   %-22s %-8s %s" % (vid, arm, verdict))
                print("        the difference: %s" % d)
                print("        who says what: %s" % tally)

    if permuted:
        print("\n## C3 rows re-encoded to a PERMUTATION of the same triples")
        print("#  Not counted as a C3 pass anywhere above. An interleaved vector has no")
        print("#  canonical writer, so every conformant encoder writes each repeated field")
        print("#  contiguously and no encoder on earth reproduces the committed bytes. The")
        print("#  manifest lists one accepted form for it. Recorded so the difference is")
        print("#  visible as what it is: the same (tag, wire type, body) multiset.")
        for vid, rows_ in sorted(permuted.items()):
            for arm, sha, n in rows_:
                print("   %-22s %-8s %s %d B: same triples, different order"
                      % (vid, arm, sha, n))

    dis = [k for k, v in agree.items() if v != "agree"]
    print("\n## R2 / CONTRACT.md 5.5: the two arms agree on the decoded value")
    print("   %d of %d rows: the native arm and the ffi arm decode to the same facade"
          % (len(agree) - len(dis), len(agree)))
    for k in dis:
        print("        FAIL %s: the arms DISAGREE" % k)
    fails.extend(dis)

    print("\n## C3: which accepted form this slice writes")
    print("#  CONTRACT.md C3: a vector may have more than one accepted form, and which one")
    print("#  a slice writes is a fact about it rather than a verdict.")
    for arm in sorted(forms):
        print("   %-8s %s" % (arm, ", ".join("%s=%d" % kv
                                             for kv in sorted(forms[arm].items()))))

    print("\n## ABI v1 open decision 11, answered for this slice")
    n_unknown = sum(1 for r in inscope.values()
                    if r["class"] == "unknown" and r["expect"] == "accept")
    for arm in sorted(unknown_forms):
        print("   %-8s %s  (of %d unknown-class rows)"
              % (arm, ", ".join("%s=%d" % kv
                                for kv in sorted(unknown_forms[arm].items())), n_unknown))
    print("   **This slice DROPS unknown fields**, in both arms. protobuf C++, the")
    print("   incumbent every ratio here is against, RETAINS them, so adopting the core")
    print("   removes a proto3 guarantee a C++ caller has today. That is decision 11 and")
    print("   it is a behaviour change, not a performance one.")

    print("\n## C4: what the refusals looked like")
    print("#  CONTRACT.md C4: 'a rejection test that nothing rejects is a test nobody has")
    print("#  watched work'. Error codes are ABI v1 section 5's.")
    names = {-2: "AK_ERR_MALFORMED", -3: "AK_ERR_TRUNCATED", -4: "AK_ERR_DEPTH",
             -6: "AK_ERR_TRANSCODE"}
    for arm, vid, err in rejects_seen:
        print("   %-8s %-26s %d %s" % (arm, vid, err, names.get(err, "?")))

    # ---- the walker ------------------------------------------------------------------
    print("\n## the unknown-field walker over the corpus's WireZoo vectors")
    print("#  NOT a root decode and not counted as one: `ak::Dec::skip` over a buffer with")
    print("#  no schema, which is the path a root decoder takes for a field it does not")
    print("#  know. WireZoo is not in this slice's schema, so these rows are out of scope")
    print("#  for C1-C3; the wire FORM they carry is exactly what this work unit fixed.")
    wok = wbad = 0
    wfail = []
    for vid, r in sorted(walkable.items()):
        got = walked.get(vid)
        if got is None:
            wfail.append("%s: no result" % vid)
            continue
        status, err, pos, n = got
        want = r["expect"]
        if status == want:
            wok += 1
        else:
            wbad += 1
            wfail.append("%s (%s): the walker said %s, the corpus says %s"
                         % (vid, r["class"], status, want))
        print("   %-26s %-6s %-6s err %-3d at %d of %d   %s"
              % (vid, want, status, err, pos, n,
                 "ok" if status == want else "MISMATCH"))
    print("   walker: %d of %d agree with the corpus's verdict" % (wok, wok + wbad))
    for f in wfail:
        print("        NOTE %s" % f)

    print("\n## C5 produce, and what is NOT claimed")
    produce = sorted(k for k, r in inscope.items() if "cpp" in (r.get("produce") or []))
    baseline = [k for k in produce if rows[k]["class"] == "baseline"]
    print("   %d in-scope rows name `cpp` in `produce`." % len(produce))
    print("   %d of them are `baseline` rows, which REFERENCE ffi/schema's payloads; this"
          % len(baseline))
    print("   slice builds every one of those from its own facade and from protoc's types")
    print("   and checks the bytes against manifest.json in `conformance` already.")
    print("   The remaining %d (classes empty and shape) are NOT produced here and that is"
          % (len(produce) - len(baseline)))
    print("   a partial claim, named as one (R11): producing them needs the CORPUS's own")
    print("   value rules re-implemented in C++, a second value-rule implementation this")
    print("   slice does not have. Listed by id in STATE.md.")

    # Three buckets, and they are kept apart on purpose. A `fail` is this slice being
    # wrong. A `disputed` row is the corpus's expectation disagreeing with two protobuf
    # implementations AND with this slice, which is a finding for the corpus's owner and
    # is not a pass here either. `permuted` is a vector with no canonical writer. Only the
    # first decides the exit status; all three are printed, because R11 says a slice that
    # does not name its gaps is not finished.
    print("\n## the verdict, in three buckets")
    print("   failures (this slice is wrong):            %d" % (len(fails) + wbad))
    print("   disputed  (the corpus vs two protobufs):   %d  %s"
          % (len(disputed), ", ".join(sorted(disputed)) or "-"))
    print("   permuted  (no canonical writer exists):    %d  %s"
          % (len(permuted), ", ".join(sorted(permuted)) or "-"))
    print("   the INCUMBENT's own C3 misses:             %d" % len(incumbent))
    print("      protobuf C++ does not reproduce those accepted forms either. It is in")
    print("      this table as an oracle for C1 and C2, where it agrees with this slice")
    print("      on every row but the disputed one; its C3 misses are a fact about where")
    print("      protobuf C++ places a RETAINED unknown field and about P2.5's two valid")
    print("      encodings, and they are not this slice's failures.")
    print("\n%s" % ("CORPUS SUBSET PASSES, with %d disputed and %d permuted row(s) named"
                    % (len(disputed), len(permuted))
                    if not fails and not wbad
                    else "%d FAILURE(S)" % (len(fails) + wbad)))
    return 1 if (fails or wbad) else 0


