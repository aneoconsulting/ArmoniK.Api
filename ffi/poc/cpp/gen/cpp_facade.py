"""The C++ facade: hand-written-style idiomatic types, emitted from the one description.

README 5.1.1 is the rule this file follows. `std::string`, `std::vector`, `std::map` are
used directly: they exist at C++11 and mean the same thing at every level. Nothing here
names `std::optional`, `std::variant` or `std::string_view`, because those arrive after
C++11 and aliasing one would make a public header's meaning depend on a switch the consumer
owns -- README 5.1's hard stop. The two that are needed are OURS:

  ak::Optional<T>   explicit presence and a singular message child
  <M><Oneof>        a tagged sum over a C++11 unrestricted union

Both are one concrete type at every standard level, which is what `gen/odr_check.sh` asserts
mechanically rather than by reading.
"""
from ir import loop_slots
from cppnames import FSCALAR, camel, facade_type, oneof_type, snake, variant

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")


def _oneof_member_type(g):
    if g.kind in ("string", "bytes"):
        return "std::string"
    if g.kind == "message":
        return g.of
    return FSCALAR[g.kind]


def emit_types(ir):
    o = [HEAD, """
// The facade every arm reads and writes. One data model, so no arm is handed a different
// one: `std::string` for string AND bytes is what protobuf C++ itself holds.
#ifndef AK_TYPES_H
#define AK_TYPES_H
#include <cstdint>
#include <map>
#include <new>
#include <string>
#include <vector>
#include "ak/vocab.h"

namespace shapes {
""".lstrip("\n")]

    for ename in ir.enum_order:
        e = ir.enums[ename]
        o.append("// Open enum: the VALUE may be one the reader was not built against, and it")
        o.append("// round-trips losslessly because the wire says exactly where to put it.")
        o.append("struct %s {" % ename)
        o.append("  int32_t v;")
        o.append("  enum Value {")
        for vname, val in e["values"].items():
            o.append("    %s = %d," % (variant(ename, vname), val))
        o.append("  };")
        o.append("  %s() : v(0) {}" % ename)
        o.append("  explicit %s(int32_t x) : v(x) {}" % ename)
        o.append("  bool operator==(const %s &o) const { return v == o.v; }" % ename)
        o.append("  bool operator!=(const %s &o) const { return v != o.v; }" % ename)
        o.append("};")
        o.append("")
        o.append("// The declared value list, in declaration order: what `enum_value()`")
        o.append("// cycles through, so every payload with enough elements reaches the")
        o.append("// large one (ResultStatus 127 is a two-byte varint).")
        o.append("inline const std::vector<int32_t> &tbl_%s() {" % ename)
        o.append("  static const std::vector<int32_t> t = {%s};"
                 % ", ".join(str(x) for x in e["values"].values()))
        o.append("  return t;")
        o.append("}")
        o.append("")

    for name in ir.order:
        if ir.msg(name).synthetic:
            continue
        o.append("struct %s;" % name)
    o.append("")

    emitted = set()

    def emit_msg(name):
        if name in emitted:
            return
        m = ir.msg(name)
        if m.synthetic:
            emitted.add(name)
            return
        emitted.add(name)
        # Children by value, so they must be complete first.
        for f in m.fields:
            if f.kind == "message":
                emit_msg(f.of)

        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            o.append("// The oneof as a C++11 sum type: a discriminant carrying the ACTIVE")
            o.append("// MEMBER'S TAG (the same discriminant the ABI group uses) over an")
            o.append("// unrestricted union. This is the shape README 5.1.1 calls ours: one")
            o.append("// concrete type at every standard level, never std::variant.")
            o.append("class %s {" % ty)
            o.append(" public:")
            o.append("  enum Case {")
            o.append("    kNotSet = 0,")
            for g in members:
                o.append("    k%s = %d," % (camel(g.name), g.tag))
            o.append("  };")
            o.append("  %s() : case_(kNotSet) {}" % ty)
            o.append("  %s(const %s &o) : case_(kNotSet) { copy_from(o); }" % (ty, ty))
            o.append("  %s &operator=(const %s &o) {" % (ty, ty))
            o.append("    if (this != &o) { clear(); copy_from(o); }")
            o.append("    return *this;")
            o.append("  }")
            o.append("  ~%s() { clear(); }" % ty)
            o.append("  Case which() const { return case_; }")
            o.append("  void clear();")
            for g in members:
                mt = _oneof_member_type(g)
                o.append("  const %s &%s() const { return u_.%s; }" % (mt, g.name, g.name))
                o.append("  %s &set_%s();" % (mt, g.name))
            o.append("  bool operator==(const %s &o) const;" % ty)
            o.append("  bool operator!=(const %s &o) const { return !(*this == o); }" % ty)
            o.append(" private:")
            o.append("  void copy_from(const %s &o);" % ty)
            o.append("  Case case_;")
            o.append("  union U {")
            for g in members:
                o.append("    %s %s;" % (_oneof_member_type(g), g.name))
            o.append("    U() {}")
            o.append("    ~U() {}")
            o.append("  } u_;")
            o.append("};")
            o.append("")

        o.append("struct %s {" % name)
        for f in m.plain:
            if f.oneof:
                continue
            ty = facade_type(f)
            init = ""
            if f.card == "singular" and not f.explicit and f.kind in ("int32", "int64", "double"):
                init = " = 0"
            elif f.card == "singular" and not f.explicit and f.kind == "bool":
                init = " = false"
            o.append("  %s %s%s;" % (ty, f.name, init))
        for oname in m.oneofs:
            o.append("  %s %s;" % (oneof_type(name, oname), oname))
        o.append("  bool operator==(const %s &o) const;" % name)
        o.append("  bool operator!=(const %s &o) const { return !(*this == o); }" % name)
        o.append("};")
        o.append("")

    for name in ir.order:
        emit_msg(name)

    o.append("}  // namespace shapes")
    o.append("#endif  // AK_TYPES_H")
    o.append("")
    return "\n".join(o)


def emit_types_impl(ir):
    """The out-of-line halves: the sum type's lifetime dispatch and structural equality.

    The lifetime dispatch is the concrete cost README 5.1.1 prices: five variants is
    `clear`, `copy_from` and one `set_` each, all hand-rolled, where a Rust enum is a
    declaration. It is generated rather than hand-written, which is the whole point.
    """
    o = [HEAD, '#include "generated/types.h"', "", "namespace shapes {", ""]
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            o.append("void %s::clear() {" % ty)
            o.append("  switch (case_) {")
            for g in members:
                mt = _oneof_member_type(g)
                if g.kind in ("string", "bytes") or g.kind == "message":
                    o.append("    case k%s: u_.%s.~%s(); break;"
                             % (camel(g.name), g.name,
                                "basic_string" if g.kind in ("string", "bytes") else mt))
                else:
                    o.append("    case k%s: break;" % camel(g.name))
            o.append("    default: break;")
            o.append("  }")
            o.append("  case_ = kNotSet;")
            o.append("}")
            o.append("")
            o.append("void %s::copy_from(const %s &o) {" % (ty, ty))
            o.append("  switch (o.case_) {")
            for g in members:
                mt = _oneof_member_type(g)
                o.append("    case k%s: new (&u_.%s) %s(o.u_.%s); break;"
                         % (camel(g.name), g.name, mt, g.name))
            o.append("    default: break;")
            o.append("  }")
            o.append("  case_ = o.case_;")
            o.append("}")
            o.append("")
            for g in members:
                mt = _oneof_member_type(g)
                o.append("%s &%s::set_%s() {" % (mt, ty, g.name))
                o.append("  clear();")
                o.append("  new (&u_.%s) %s();" % (g.name, mt))
                o.append("  case_ = k%s;" % camel(g.name))
                o.append("  return u_.%s;" % g.name)
                o.append("}")
                o.append("")
            o.append("bool %s::operator==(const %s &o) const {" % (ty, ty))
            o.append("  if (case_ != o.case_) return false;")
            o.append("  switch (case_) {")
            for g in members:
                o.append("    case k%s: return u_.%s == o.u_.%s;"
                         % (camel(g.name), g.name, g.name))
            o.append("    default: return true;")
            o.append("  }")
            o.append("}")
            o.append("")

        o.append("bool %s::operator==(const %s &o) const {" % (name, name))
        parts = []
        for f in m.plain:
            if f.oneof:
                continue
            parts.append("%s == o.%s" % (f.name, f.name))
        for oname in m.oneofs:
            parts.append("%s == o.%s" % (oname, oname))
        o.append("  return %s;" % (" &&\n         ".join(parts) if parts else "true"))
        o.append("}")
        o.append("")
    o.append("}  // namespace shapes")
    o.append("")
    return "\n".join(o)


def emit_odr_asserts(ir):
    """README 5.1's hard stop, checked MECHANICALLY rather than by reading.

    The check is not a pinned constant in a header (which only says what one build saw).
    It is a table of layout facts -- `sizeof`, `alignof` and every member `offsetof` of
    every installed facade type -- emitted here and INSTANTIATED IN TWO TRANSLATION UNITS,
    one compiled at `-std=c++11` and one at `-std=c++17`. The two are linked together, the
    tables are compared elementwise, and facade objects are passed across the seam in both
    directions. A type whose layout moved with the standard level shows up as a differing
    row rather than as a wrong field at run time.

    `gen/odr_check.sh` also runs the positive control: with `-DAK_ODR_BREAK` the header
    grows one `#if __cplusplus >= 201703L` member and the check must FAIL. A guard with no
    failing test is a guard nobody has seen work.
    """
    o = [HEAD, """
// Included by BOTH the c++11 and the c++17 translation unit of the ODR check.
#ifndef AK_ODR_H
#define AK_ODR_H
#include <cstddef>
#include <cstdint>
#include "generated/types.h"
#include "ak/vocab.h"

struct AkOdrFact { const char *what; uint32_t value; };

// The host's view of every installed type's layout, as data. One row per fact.
#define AK_ODR_FACTS(F) \\
""".strip("\n")]
    rows = []

    def add(ty, expr, what):
        rows.append((what, expr))

    for ename in ir.enum_order:
        t = "shapes::" + ename
        add(t, "sizeof(%s)" % t, "sizeof %s" % t)
        add(t, "alignof(%s)" % t, "alignof %s" % t)
        add(t, "offsetof(%s, v)" % t, "%s.v" % t)
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        t = "shapes::" + name
        add(t, "sizeof(%s)" % t, "sizeof %s" % t)
        add(t, "alignof(%s)" % t, "alignof %s" % t)
        for f in m.plain:
            if f.oneof:
                continue
            add(t, "offsetof(%s, %s)" % (t, f.name), "%s.%s" % (t, f.name))
        for oname in m.oneofs:
            add(t, "offsetof(%s, %s)" % (t, oname), "%s.%s" % (t, oname))
            ot = "shapes::" + oneof_type(name, oname)
            add(ot, "sizeof(%s)" % ot, "sizeof %s" % ot)
            add(ot, "alignof(%s)" % ot, "alignof %s" % ot)
    # The vocabulary types README 5.1.1 makes ours.
    for t in ("ak::Optional<int32_t>", "ak::Optional<int64_t>", "ak::Optional<double>",
              "ak::StringView"):
        add(t, "sizeof(%s)" % t, "sizeof %s" % t)
        add(t, "alignof(%s)" % t, "alignof %s" % t)
    for i, (what, expr) in enumerate(rows):
        o.append("  F(\"%s\", (uint32_t)%s)%s" % (what, expr, " \\" if i + 1 < len(rows) else ""))
    o.append("")
    o.append("#define AK_ODR_NFACTS %d" % len(rows))
    o.append("#endif  // AK_ODR_H")
    o.append("")
    return "\n".join(o)
