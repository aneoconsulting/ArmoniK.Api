"""Arm `core-ffi`: the generated C++ host binding over the C ABI of ABI-v1.md.

Two invariants from the specification are load-bearing here and both are GENERATED rather
than left to a binding author's discipline.

Section 6, "the fill must be total": every scalar and all three words of every `ak_str`
are assigned unconditionally, and the presence word is assigned rather than OR-ed. In
exchange the codec resets nothing between elements. A partial fill does not fail, it
silently inherits the previous element's value.

Section 5, the guard: every reverse-call accessor is wrapped so a host exception becomes
`ak_fail` plus a return. In C++ the hazard is not a managed exception but the same thing
one level down -- an exception crossing `extern "C"` into Rust is undefined behaviour --
so the guard is a `try/catch(...)`. Every published managed figure was taken WITHOUT the
guard, so this slice measures with it on and prices it separately.

One rule the decode side cannot do without: a message whose type carries a repeated or map
field is filled IN PLACE, never constructed, because `apply` arrives after the runs that
populated those fields (ABI v1 section 7.1).

Three arms are emitted per root, which is what ABI v1 open decision 1 needs:
  <root>            total fill, batched runs           the specified path
  <root>_zeroed     bulk clear + sparse fill, batched  decision 9's candidate
  <root>_nobatch    total fill, one element per call   "a host may decline to batch"
The transcoder is a parameter, so string-as-DATA (a core transcoder, zero crossings) and
string-as-a-CALL (a host transcoder, one reverse crossing per string) are the same code
with a different `Tcs`. That is the third mechanism decision 1 asks the price of.
"""
from ir import direct_fields, loop_slots, slot_name
import rust_abi as RA
from cppnames import abi_order_topo, camel, oneof_type, snake

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

NULLSTR = "ak_str_absent()"


def DIRECT(ir, root):
    """The one direct-argument field of this tree, as a C++ expression on the root object.

    ABI v1 section 8 builds the path for ONE field of one root message and the generator
    refuses anything else (`ir.check_direct`), so there is at most one.
    """
    ds = direct_fields(ir, root)
    if not ds:
        return None
    path, _f = ds[0]
    cur = root
    expr = "o"
    for comp in path[:-1]:
        fld = next(x for x in ir.msg(cur).plain if x.name == comp)
        expr = "(*%s.%s)" % (expr, comp)
        cur = fld.of
    return "%s.%s" % (expr, path[-1])


def has_slots(ir, name):
    return bool(loop_slots(ir, name))


def _str_arg(expr, tc):
    return "ak_str_of(%s, %s)" % (expr, tc)


# ---------------------------------------------------------------- encode groups

def _make_field(ir, m, f, o):
    """One group member of the TOTAL fill. Assigned unconditionally, always."""
    n = f.name
    if f.kind in ("string", "bytes"):
        tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
        if f.direct:
            # ABI v1 section 8: the sentinel says the bytes are an ARGUMENT of the call,
            # not a pointer into staging. C++ never needs it -- there is nothing to pin --
            # and pays nothing for it; it is built so the path is exercised.
            o.append("  g.%s = ak_str_direct(o.%s.size());" % (n, n))
        elif f.explicit:
            o.append("  g.%s = o.%s.has_value() ? %s : %s;"
                     % (n, n, _str_arg("*o." + n, tc), NULLSTR))
        else:
            o.append("  g.%s = %s;" % (n, _str_arg("o." + n, tc)))
    elif f.kind == "message":
        o.append("  g.%s = o.%s.has_value() ? make_%s(*o.%s, t) : ak_efix_%s();"
                 % (n, n, snake(f.of), n, f.of))
    elif f.kind == "enum":
        o.append("  g.%s = o.%s.v;" % (n, n))
    elif f.kind == "bool":
        if f.explicit:
            o.append("  g.%s = (uint8_t)(o.%s.has_value() && *o.%s);" % (n, n, n))
        else:
            o.append("  g.%s = (uint8_t)(o.%s ? 1 : 0);" % (n, n))
    else:
        if f.explicit:
            o.append("  g.%s = o.%s.has_value() ? *o.%s : 0;" % (n, n, n))
        else:
            o.append("  g.%s = o.%s;" % (n, n))


def _oneof_make(ir, m, oname, members, o):
    ty = oneof_type(m.name, oname)
    o.append("  g.%s_case = (uint32_t)o.%s.which();" % (oname, oname))
    for gm in members:
        slot = "%s_%s" % (oname, gm.name)
        acc = "o.%s.%s()" % (oname, gm.name)
        cond = "o.%s.which() == shapes::%s::k%s" % (oname, ty, camel(gm.name))
        if gm.kind in ("string", "bytes"):
            tc = "t.bytes" if gm.kind == "bytes" else "t.utf8"
            o.append("  g.%s = %s ? %s : %s;" % (slot, cond, _str_arg(acc, tc), NULLSTR))
        elif gm.kind == "message":
            o.append("  g.%s = %s ? make_%s(%s, t) : ak_efix_%s();"
                     % (slot, cond, snake(gm.of), acc, gm.of))
        elif gm.kind == "bool":
            o.append("  g.%s = (uint8_t)(%s ? (%s ? 1 : 0) : 0);" % (slot, cond, acc))
        else:
            o.append("  g.%s = %s ? %s : 0;" % (slot, cond, acc))


def _sparse_field(ir, m, f, o, bits):
    """Decision 9's candidate: the host bulk-clears the chunk and assigns only what differs
    from the default. The codec still resets nothing between elements; only the host's fill
    changes."""
    n = f.name
    if f.kind in ("string", "bytes"):
        tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
        if f.direct:
            o.append("  if (!o.%s.empty()) d->%s = ak_str_direct(o.%s.size());" % (n, n, n))
        elif f.explicit:
            o.append("  if (o.%s.has_value()) { d->%s = %s; d->presence |= 1u << %d; }"
                     % (n, n, _str_arg("*o." + n, tc), bits[n]))
        else:
            o.append("  if (!o.%s.empty()) d->%s = %s;" % (n, n, _str_arg("o." + n, tc)))
    elif f.kind == "message":
        o.append("  if (o.%s.has_value()) { fill_%s_sparse(&d->%s, *o.%s, t);"
                 " d->presence |= 1u << %d; }" % (n, snake(f.of), n, n, bits[n]))
    elif f.kind == "enum":
        o.append("  if (o.%s.v != 0) d->%s = o.%s.v;" % (n, n, n))
    elif f.explicit:
        if f.kind == "bool":
            o.append("  if (o.%s.has_value()) { d->%s = (uint8_t)(*o.%s ? 1 : 0);"
                     " d->presence |= 1u << %d; }" % (n, n, n, bits[n]))
        else:
            o.append("  if (o.%s.has_value()) { d->%s = *o.%s;"
                     " d->presence |= 1u << %d; }" % (n, n, n, bits[n]))
    elif f.kind == "bool":
        o.append("  if (o.%s) d->%s = 1;" % (n, n))
    else:
        o.append("  if (o.%s != 0) d->%s = o.%s;" % (n, n, n))


def _oneof_sparse(ir, m, oname, members, o):
    ty = oneof_type(m.name, oname)
    o.append("  if (o.%s.which() != shapes::%s::kNotSet) {" % (oname, ty))
    o.append("    d->%s_case = (uint32_t)o.%s.which();" % (oname, oname))
    o.append("    switch (o.%s.which()) {" % oname)
    for gm in members:
        acc = "o.%s.%s()" % (oname, gm.name)
        slot = "%s_%s" % (oname, gm.name)
        o.append("      case shapes::%s::k%s:" % (ty, camel(gm.name)))
        if gm.kind in ("string", "bytes"):
            tc = "t.bytes" if gm.kind == "bytes" else "t.utf8"
            o.append("        d->%s = %s; break;" % (slot, _str_arg(acc, tc)))
        elif gm.kind == "message":
            o.append("        fill_%s_sparse(&d->%s, %s, t); break;"
                     % (snake(gm.of), slot, acc))
        elif gm.kind == "bool":
            o.append("        d->%s = (uint8_t)(%s ? 1 : 0); break;" % (slot, acc))
        else:
            o.append("        d->%s = %s; break;" % (slot, acc))
    o.append("      default: break;")
    o.append("    }")
    o.append("  }")


# ---------------------------------------------------------------- decode


def _decode_field(ir, m, f, o, bits, dst):
    n = f.name
    if f.kind == "string":
        if f.explicit:
            o.append("  if (f.presence & (1u << %d)) s_of(base, f.%s, ctx, &%s.emplace());"
                     % (bits[n], n, dst + n))
        else:
            o.append("  s_of(base, f.%s, ctx, &%s);" % (n, dst + n))
    elif f.kind == "bytes":
        if f.explicit:
            o.append("  if (f.presence & (1u << %d)) b_of(base, f.%s, &%s.emplace());"
                     % (bits[n], n, dst + n))
        else:
            o.append("  b_of(base, f.%s, &%s);" % (n, dst + n))
    elif f.kind == "message":
        if has_slots(ir, f.of):
            o.append("  if (f.presence & (1u << %d)) fill_%s(&%s.get_or_insert(), f.%s, base, ctx);"
                     % (bits[n], snake(f.of), dst + n, n))
            o.append("  else %s.reset();" % (dst + n))
        else:
            o.append("  if (f.presence & (1u << %d)) %s.set(from_%s(f.%s, base, ctx));"
                     % (bits[n], dst + n, snake(f.of), n))
            o.append("  else %s.reset();" % (dst + n))
    elif f.kind == "enum":
        o.append("  %s = shapes::%s(f.%s);" % (dst + n, f.of, n))
    elif f.explicit:
        conv = "(f.%s != 0)" % n if f.kind == "bool" else "f.%s" % n
        o.append("  if (f.presence & (1u << %d)) %s.set(%s);" % (bits[n], dst + n, conv))
        o.append("  else %s.reset();" % (dst + n))
    elif f.kind == "bool":
        o.append("  %s = (f.%s != 0);" % (dst + n, n))
    else:
        o.append("  %s = f.%s;" % (dst + n, n))


def _decode_oneof(ir, m, oname, members, o, dst):
    ty = oneof_type(m.name, oname)
    o.append("  switch (f.%s_case) {" % oname)
    for gm in members:
        slot = "%s_%s" % (oname, gm.name)
        o.append("    case %d: {" % gm.tag)
        if gm.kind == "string":
            o.append("      s_of(base, f.%s, ctx, &%s.set_%s()); break; }"
                     % (slot, dst + oname, gm.name))
        elif gm.kind == "bytes":
            o.append("      b_of(base, f.%s, &%s.set_%s()); break; }"
                     % (slot, dst + oname, gm.name))
        elif gm.kind == "message":
            if has_slots(ir, gm.of):
                raise NotImplementedError("a oneof member with loop slots (%s.%s)"
                                          % (m.name, gm.name))
            o.append("      %s.set_%s() = from_%s(f.%s, base, ctx); break; }"
                     % (dst + oname, gm.name, snake(gm.of), slot))
        elif gm.kind == "bool":
            o.append("      %s.set_%s() = (f.%s != 0); break; }" % (dst + oname, gm.name, slot))
        else:
            o.append("      %s.set_%s() = f.%s; break; }" % (dst + oname, gm.name, slot))
    o.append("    default: %s.clear(); break;" % (dst + oname))
    o.append("  }")


# ---------------------------------------------------------------- loops


def _nav(ir, start, prefix, var, o, src_name):
    """Walk a loop slot's prefix of singular message children from `var`."""
    cur = start
    expr = var
    for i, comp in enumerate(prefix):
        fld = next(f for f in ir.msg(cur).plain if f.name == comp)
        o.append("    if (!%s.%s.has_value()) return AK_OK;" % (expr, comp))
        expr = "(*%s.%s)" % (expr, comp)
        cur = fld.of
    o.append("    const %s &%s_owner = %s;" % (cur, src_name, expr))
    return cur


def _emit_loop(ir, o, root, path, f, fname, elem_of=None, batch=True, zeroed=False):
    """One reverse-call loop over a host container. Chunked at ABI v1 7.3's 32 KB arena, or
    one element per call when `batch` is false -- "a host may decline to batch at all and
    loses only what its own crossing costs", which is the arm that prices the predicate."""
    et = RA.elem_type(f)
    if f.card == "packed":
        cty = {"int32": "int32_t", "int64": "int64_t", "double": "double",
               "bool": "uint8_t", "enum": "int32_t"}[f.kind]
        run = {"int32": "ak_run_i32", "int64": "ak_run_i64", "double": "ak_run_f64",
               "bool": "ak_run_u8", "enum": "ak_run_i32"}[f.kind]
    elif f.card == "map":
        cty = "struct ak_efix_%s" % f.entry
    elif f.kind in ("string", "bytes"):
        cty = "struct ak_str"
    else:
        cty = "struct ak_efix_%s" % et

    o.append("static int32_t %s(ak_enc_ctx *ctx, const void *obj, int64_t token) {" % fname)
    o.append("  AK_GUARD_BEGIN")
    o.append("    const EncObj_%s *h = (const EncObj_%s *)obj;" % (root, root))
    o.append("    const Tcs &t = h->t;")
    o.append("    (void)t; (void)token;")
    if elem_of is None:
        owner = _nav(ir, root, path[:-1], "(*h->o)", o, "src")
    else:
        # A slot that lives on the ELEMENT of a top-level repeated field: the codec names
        # the element by token, and a token is an INDEX, never an address (section 10).
        o.append("    const %s &el = (*h->o).%s[(size_t)token];" % (elem_of[1], elem_of[0]))
        owner = _nav(ir, elem_of[1], path[:-1], "el", o, "src")
    last = path[-1]
    srcty = ("std::map<std::string, std::string>" if f.card == "map"
             else "std::vector<%s>" % _velem(ir, f))
    o.append("    const %s &src = src_owner.%s;" % (srcty, last))
    if f.card == "packed" and f.kind in ("bool", "enum"):
        # "Its own array" is doing work in that sentence: a vector<bool> or a vector<Enum>
        # is not the wire layout, so the binding materialises a contiguous array first and
        # part of the crossing saved is paid back as a copy. The cost is the host's to
        # avoid by choosing its storage, and this arm shows what it is.
        o.append("    std::vector<%s> flat;" % cty)
        o.append("    flat.reserve(src.size());")
        if f.kind == "bool":
            o.append("    for (size_t i = 0; i < src.size(); ++i) flat.push_back(src[i] ? 1 : 0);")
        else:
            o.append("    for (size_t i = 0; i < src.size(); ++i) flat.push_back(src[i].v);")
        o.append("    if (!flat.empty()) { int32_t rc = %s(ctx, &flat[0], flat.size());"
                 " if (rc < 0) return rc; }" % run)
        o.append("  AK_GUARD_END")
        o.append("}")
        o.append("")
        return
    if f.card == "packed":
        o.append("    if (!src.empty()) { int32_t rc = %s(ctx, &src[0], src.size());"
                 " if (rc < 0) return rc; }" % run)
        o.append("  AK_GUARD_END")
        o.append("}")
        o.append("")
        return

    if batch:
        o.append("    constexpr size_t kChunk = ak::arena_n(sizeof(%s));" % cty)
    else:
        o.append("    constexpr size_t kChunk = 1;  // the host declines to batch")
    o.append("    %s chunk[kChunk];" % cty)
    if zeroed:
        o.append("    // All-zero is a valid group, and the bulk clear is what lets the")
        o.append("    // fill below be sparse (ABI v1 open decision 9's candidate).")
        o.append("    std::memset(chunk, 0, sizeof(chunk));")
    o.append("    size_t i = 0, done = 0;")
    o.append("    (void)done;")
    if f.card == "map":
        o.append("    for (std::map<std::string, std::string>::const_iterator it = src.begin();"
                 " it != src.end(); ++it) {")
        o.append("      chunk[i].key = ak_str_of(it->first, t.utf8);")
        o.append("      chunk[i].value = ak_str_of(it->second, t.utf8);")
        o.append("      chunk[i].presence = 0;")
    else:
        o.append("    for (size_t k = 0; k < src.size(); ++k) {")
        if f.kind in ("string", "bytes"):
            tc = "t.bytes" if f.kind == "bytes" else "t.utf8"
            o.append("      chunk[i] = ak_str_of(src[k], %s);" % tc)
        elif zeroed:
            o.append("      fill_%s_sparse(&chunk[i], src[k], t);" % snake(et))
        else:
            o.append("      chunk[i] = make_%s(src[k], t);" % snake(et))
    o.append("      ++i;")
    o.append("      if (i == kChunk) {")
    o.append("        int32_t rc = %s;" % _run_call(ir, f, et, "(int32_t)i"))
    o.append("        if (rc < 0) return rc;")
    o.append("        done += i;")
    if zeroed and f.card != "map" and f.kind not in ("string", "bytes"):
        o.append("        // Only what was dirtied is put back.")
        o.append("        std::memset(chunk, 0, i * sizeof(%s));" % cty)
    o.append("        i = 0;")
    o.append("      }")
    o.append("    }")
    o.append("    if (i > 0) {")
    o.append("      int32_t rc = %s;" % _run_call(ir, f, et, "(int32_t)i"))
    o.append("      if (rc < 0) return rc;")
    o.append("    }")
    o.append("  AK_GUARD_END")
    o.append("}")
    o.append("")


def _velem(ir, f):
    from cppnames import FSCALAR
    if f.kind in ("string", "bytes"):
        return "std::string"
    if f.kind == "message":
        return f.of
    if f.kind == "enum":
        return f.of
    return FSCALAR[f.kind]


def _run_call(ir, f, et, n):
    if f.card == "map":
        return "ak_elem_%s(ctx, chunk, %s)" % (f.entry, n)
    if f.kind in ("string", "bytes"):
        return "ak_blob_run(ctx, chunk, %s)" % n
    if ir.msg(et).leaf:
        return "ak_elem_%s(ctx, chunk, %s)" % (et, n)
    return "ak_elemu_%s(ctx, chunk, %s, (int64_t)done)" % (et, n)


PRE = '''// Arm `core-ffi`: the generated C++ host binding over the C ABI.
#include "generated/binding.h"

#include <cstring>

namespace shapes {
namespace ffi {

// ABI v1 section 5. An exception crossing `extern "C"` into Rust is undefined behaviour,
// so every reverse-call accessor is wrapped and a throw becomes `ak_fail` plus a return.
// On by default; -DAK_NO_GUARD exists only to price it, because every published managed
// figure was measured without it.
#ifdef AK_NO_GUARD
#define AK_GUARD_BEGIN {
#define AK_GUARD_END } return AK_OK;
#define AK_DGUARD_BEGIN {
#define AK_DGUARD_END }
#else
#define AK_GUARD_BEGIN try {
#define AK_GUARD_END                                                              \\
  } catch (...) {                                                                 \\
    static const char kMsg[] = "host exception in a reverse call";                \\
    ak_fail(ctx, AK_ERR_HOST, (const uint8_t *)kMsg, (uint32_t)(sizeof(kMsg) - 1)); \\
    return AK_ERR_HOST;                                                           \\
  }                                                                               \\
  return AK_OK;
#define AK_DGUARD_BEGIN try {
#define AK_DGUARD_END                                                             \\
  } catch (...) {                                                                 \\
    static const char kMsg[] = "host exception in a reverse call";                \\
    ak_fail(ctx, AK_ERR_HOST, (const uint8_t *)kMsg, (uint32_t)(sizeof(kMsg) - 1)); \\
  }
#endif

static inline struct ak_str ak_str_absent() {
  struct ak_str s;
  s.data = NULL;
  s.len = 0;
  s.tc = NULL;
  return s;
}

static inline struct ak_str ak_str_direct(size_t n) {
  struct ak_str s;
  s.data = AK_STR_DIRECT;
  s.len = n;
  s.tc = NULL;
  return s;
}

static inline struct ak_str ak_str_of(const std::string &v, ak_transcode_fn tc) {
  struct ak_str s;
  s.data = v.data();
  s.len = v.size();
  s.tc = tc;
  return s;
}

// ABI v1 7.4: resolve a span against the base pointer you already hold. One add, then the
// same copy. A zero-length span is the common case on the absent path (P1.3, P2.5) and
// must not reach the validator at all.
static inline void s_of(const uint8_t *base, const struct ak_span &s, ak_dec_ctx *ctx,
                        std::string *out) {
  if (s.len == 0) { out->clear(); return; }
  int32_t rc = ak::decode_str(base + s.off, s.len, out);
  if (rc != 0) {
    static const char kMsg[] = "malformed UTF-8 in a decoded string";
    ak_fail(ctx, rc, (const uint8_t *)kMsg, (uint32_t)(sizeof(kMsg) - 1));
    out->clear();
  }
}

static inline void b_of(const uint8_t *base, const struct ak_span &s, std::string *out) {
  out->assign((const char *)(base + s.off), s.len);
}
'''


def emit_header(ir):
    o = [HEAD, "#ifndef AK_BINDING_H", "#define AK_BINDING_H",
         '#include "ak_abi.h"', '#include "ak/rt.h"', '#include "generated/types.h"',
         "#include <map>", "#include <string>", "#include <vector>", "",
         "namespace shapes {", "namespace ffi {", "",
         "// The transcoders, resolved once. `ak_tc_bytes` and `ak_tc_utf8_trusted` are the",
         "// same memcpy with ABI v1 open decision 3 settled, and both live IN THE CORE:",
         "// that is the string-as-DATA form, and it costs zero crossings. `host_*` are the",
         "// same copy implemented in the HOST, which is what a string-as-a-CALL form costs",
         "// -- one reverse crossing per string. Decision 1 asks the price of the difference.",
         "struct Tcs {",
         "  ak_transcode_fn utf8;",
         "  ak_transcode_fn bytes;",
         "};",
         "Tcs tcs_core();      // string as DATA: the core's own transcoder",
         "Tcs tcs_core_validating();",
         "Tcs tcs_host();      // string as a CALL: a transcoder in the host binary",
         ""]
    for root in ir.roots:
        o.append("struct EncObj_%s {" % root)
        o.append("  const %s *o;" % root)
        o.append("  Tcs t;")
        o.append("};")
    o.append("")
    for root in ir.roots:
        for suffix in ("", "_zeroed", "_nobatch"):
            o.append("intptr_t encode_into_%s%s(ak_enc_ctx *ctx, const %s &o, const Tcs &t);"
                     % (snake(root), suffix, root))
        o.append("int32_t decode_with_%s(ak_dec_ctx *ctx, const uint8_t *b, size_t n, %s *out);"
                 % (snake(root), root))
    o.append("")
    o.append("// Exposed so the `groupfill` arm can price the by-value group's host-side fill")
    o.append("// on its own, in ns per element, rather than only as a subtraction between")
    o.append("// two whole encodes (ABI v1 open decision 1).")
    for name in abi_order_topo(ir):
        if ir.msg(name).synthetic:
            continue
        o.append("struct ak_efix_%s make_%s(const %s &o, const Tcs &t);" % (name, snake(name), name))
    o.append("")
    o.append("}  // namespace ffi")
    o.append("}  // namespace shapes")
    o.append("#endif")
    o.append("")
    return "\n".join(o)


def emit(ir):
    o = [HEAD, PRE]

    # ---- the transcoders ----------------------------------------------------------
    o.append("""
// The host's own memcpy transcoder: the same bytes, written from the HOST side, so every
// string costs one reverse crossing instead of none. It is the drafted ABI's string form
// priced without building a second core.
static int32_t host_tc_copy(const void *src, size_t len, uint8_t *dst, int32_t cap,
                            ak_grow_fn grow, void *sink) {
  if ((int64_t)len > (int64_t)cap) {
    int32_t rc = grow(sink, (int32_t)len, &dst, &cap);
    if (rc < 0) return rc;
    if ((int64_t)len > (int64_t)cap) return AK_ERR_CAPACITY;
  }
  std::memcpy(dst, src, len);
  return (int32_t)len;
}

Tcs tcs_core() {
  Tcs t;
  t.utf8 = ak_tc_utf8_trusted();
  t.bytes = ak_tc_bytes();
  return t;
}

Tcs tcs_core_validating() {
  Tcs t;
  t.utf8 = ak_tc_utf8();
  t.bytes = ak_tc_bytes();
  return t;
}

Tcs tcs_host() {
  Tcs t;
  t.utf8 = host_tc_copy;
  t.bytes = host_tc_copy;
  return t;
}
""".strip("\n"))
    o.append("")

    # Forward declarations: a group inlines its children by value and C++ needs the
    # declaration first, where Rust does not.
    for name in abi_order_topo(ir):
        if ir.msg(name).synthetic:
            continue
        o.append("static inline void fill_%s_sparse(struct ak_efix_%s *d, const %s &o,"
                 " const Tcs &t);" % (snake(name), name, name))
    for name in abi_order_topo(ir):
        if ir.msg(name).synthetic:
            continue
        if has_slots(ir, name):
            o.append("static inline void fill_%s(%s *dst, const struct ak_dfix_%s &f,"
                     " const uint8_t *base, ak_dec_ctx *ctx);" % (snake(name), name, name))
        else:
            o.append("static inline %s from_%s(const struct ak_dfix_%s &f,"
                     " const uint8_t *base, ak_dec_ctx *ctx);" % (name, snake(name), name))
    o.append("")

    # ---- group constructors --------------------------------------------------------
    for name in abi_order_topo(ir):
        m = ir.msg(name)
        if m.synthetic:
            continue
        bits = RA.presence_bits(m)
        o.append("// Total fill (ABI v1 section 6): every member assigned, presence ASSIGNED")
        o.append("// and not OR-ed. A partial fill does not fail, it silently inherits the")
        o.append("// previous element's value.")
        o.append("struct ak_efix_%s make_%s(const %s &o, const Tcs &t) {" % (name, snake(name), name))
        o.append("  (void)o; (void)t;")
        o.append("  struct ak_efix_%s g;" % name)
        for f in m.plain:
            if f.oneof or f.card != "singular":
                continue
            _make_field(ir, m, f, o)
        for oname, members in m.oneofs.items():
            _oneof_make(ir, m, oname, members, o)
        if bits:
            parts = []
            for fn, b in bits.items():
                fld = next(x for x in m.plain if x.name == fn)
                parts.append("((o.%s.has_value() ? 1u : 0u) << %d)" % (fn, b))
            o.append("  g.presence = %s;" % " | ".join(parts))
        else:
            o.append("  g.presence = 0;")
        o.append("  return g;")
        o.append("}")
        o.append("")
        o.append("// Decision 9's candidate: the host bulk-clears the chunk once and assigns")
        o.append("// only what differs from the default.")
        o.append("static inline void fill_%s_sparse(struct ak_efix_%s *d, const %s &o,"
                 " const Tcs &t) {" % (snake(name), name, name))
        o.append("  (void)d; (void)o; (void)t;")
        for f in m.plain:
            if f.oneof or f.card != "singular":
                continue
            _sparse_field(ir, m, f, o, bits)
        for oname, members in m.oneofs.items():
            _oneof_sparse(ir, m, oname, members, o)
        o.append("}")
        o.append("")

    # map-entry groups are built inline in their loop, so they need no maker.

    # ---- decode constructors --------------------------------------------------------
    done = set()

    def emit_dec(name):
        if name in done:
            return
        done.add(name)
        m = ir.msg(name)
        if m.synthetic:
            return
        for f in m.fields:
            if f.kind == "message":
                emit_dec(f.of)
        bits = RA.presence_bits(m)
        if has_slots(ir, name):
            o.append("// In place, never constructed: `%s` carries a repeated or map field," % name)
            o.append("// and `apply` arrives AFTER the runs that populated it.")
            o.append("static inline void fill_%s(%s *dst, const struct ak_dfix_%s &f,"
                     " const uint8_t *base, ak_dec_ctx *ctx) {" % (snake(name), name, name))
            o.append("  (void)dst; (void)f; (void)base; (void)ctx;")
            for fld in m.plain:
                if fld.oneof or fld.card != "singular":
                    continue
                _decode_field(ir, m, fld, o, bits, "dst->")
            for oname, members in m.oneofs.items():
                _decode_oneof(ir, m, oname, members, o, "dst->")
            o.append("}")
        else:
            o.append("static inline %s from_%s(const struct ak_dfix_%s &f, const uint8_t *base,"
                     " ak_dec_ctx *ctx) {" % (name, snake(name), name))
            o.append("  (void)f; (void)base; (void)ctx;")
            o.append("  %s r;" % name)
            for fld in m.plain:
                if fld.oneof or fld.card != "singular":
                    continue
                _decode_field(ir, m, fld, o, bits, "r.")
            for oname, members in m.oneofs.items():
                _decode_oneof(ir, m, oname, members, o, "r.")
            o.append("  return r;")
            o.append("}")
        o.append("")

    for name in abi_order_topo(ir):
        emit_dec(name)

    # ---- per-root encode -------------------------------------------------------------
    for root in ir.roots:
        slots = loop_slots(ir, root)
        for suffix, batch, zeroed in (("", True, False), ("_zeroed", True, True),
                                      ("_nobatch", False, False)):
            fns = {}
            for path, f in slots:
                sn = slot_name(path)
                fname = "loop_%s_%s%s" % (snake(root), sn, suffix)
                fns[sn] = fname
                _emit_loop(ir, o, root, path, f, fname, None, batch, zeroed)
                et = RA.elem_type(f)
                if et and loop_slots(ir, et):
                    inner = {}
                    for ipath, iff in loop_slots(ir, et):
                        isn = slot_name(ipath)
                        ifname = "loop_%s_%s_%s%s" % (snake(root), sn, isn, suffix)
                        inner[isn] = ifname
                        _emit_loop(ir, o, root, ipath, iff, ifname, (path[-1], et), batch, zeroed)
                    o.append("static const struct ak_evt_%s kElemVt_%s_%s%s = {"
                             % (et, root, sn, suffix))
                    for ipath, iff in loop_slots(ir, et):
                        o.append("  %s," % inner[slot_name(ipath)])
                        iet = RA.elem_type(iff)
                        if iet and loop_slots(ir, iet):
                            raise NotImplementedError("three levels of loop slots")
                    o.append("};")
                    o.append("")

            o.append("intptr_t encode_into_%s%s(ak_enc_ctx *ctx, const %s &o, const Tcs &t) {"
                     % (snake(root), suffix, root))
            o.append("  ak_enc_reset(ctx);")
            o.append("  EncObj_%s h;" % root)
            o.append("  h.o = &o;")
            o.append("  h.t = t;")
            o.append("  struct ak_evt_%s vt;" % root)
            if not slots:
                o.append("  vt._reserved = NULL;")
            for path, f in slots:
                sn = slot_name(path)
                o.append("  vt.loop_%s = %s;" % (sn, fns[sn]))
                et = RA.elem_type(f)
                if et and loop_slots(ir, et):
                    o.append("  vt.elem_%s = &kElemVt_%s_%s%s;" % (sn, root, sn, suffix))
            mk = "make_%s(o, t)" % snake(root)
            if zeroed:
                o.append("  struct ak_efix_%s fix;" % root)
                o.append("  std::memset(&fix, 0, sizeof(fix));")
                o.append("  fill_%s_sparse(&fix, o, t);" % snake(root))
            else:
                o.append("  struct ak_efix_%s fix = %s;" % (root, mk))
            ds = DIRECT(ir, root)
            if ds:
                o.append("  const std::string &dbuf = %s;" % ds)
                o.append("  return ak_encode_%s(&h, ctx, &vt, &fix,"
                         " (const uint8_t *)dbuf.data(), dbuf.size());" % root)
            else:
                o.append("  return ak_encode_%s(&h, ctx, &vt, &fix);" % root)
            o.append("}")
            o.append("")

    # ---- per-root decode --------------------------------------------------------------
    for root in ir.roots:
        slots = loop_slots(ir, root)
        m = ir.msg(root)
        bits = RA.presence_bits(m)
        o.append("struct Sink_%s {" % root)
        o.append("  %s *out;" % root)
        o.append("  const uint8_t *base;")
        o.append("};")
        o.append("")
        o.append("static void apply_%s(ak_dec_ctx *ctx, void *obj,"
                 " const struct ak_dfix_%s *fx) {" % (snake(root), root))
        o.append("  AK_DGUARD_BEGIN")
        o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
        o.append("    const struct ak_dfix_%s &f = *fx;" % root)
        o.append("    const uint8_t *base = s->base;")
        o.append("    (void)f; (void)base;")
        for fld in m.plain:
            if fld.oneof or fld.card != "singular":
                continue
            _decode_field(ir, m, fld, o, bits, "s->out->")
        for oname, members in m.oneofs.items():
            _decode_oneof(ir, m, oname, members, o, "s->out->")
        o.append("  AK_DGUARD_END")
        o.append("}")
        o.append("")
        for path, f in slots:
            sn = slot_name(path)
            et = RA.elem_type(f)
            dst = "s->out->" + ".".join(path)
            if f.card == "packed":
                cdt = {"int32": "int32_t", "int64": "int64_t", "double": "double",
                       "bool": "uint8_t", "enum": "int32_t"}[f.kind]
                o.append("static void add_%s_%s(ak_dec_ctx *ctx, void *obj, int64_t tok,"
                         " const %s *elems, int32_t n) {" % (snake(root), sn, cdt))
                o.append("  AK_DGUARD_BEGIN")
                o.append("    Sink_%s *s = (Sink_%s *)obj; (void)tok;" % (root, root))
                o.append("    %s.reserve(%s.size() + (size_t)n);" % (dst, dst))
                if f.kind == "bool":
                    o.append("    for (int32_t i = 0; i < n; ++i) %s.push_back(elems[i] != 0);" % dst)
                elif f.kind == "enum":
                    o.append("    for (int32_t i = 0; i < n; ++i)"
                             " %s.push_back(shapes::%s(elems[i]));" % (dst, f.of))
                else:
                    o.append("    for (int32_t i = 0; i < n; ++i) %s.push_back(elems[i]);" % dst)
                o.append("  AK_DGUARD_END")
                o.append("}")
                o.append("")
                continue
            if f.kind in ("string", "bytes"):
                o.append("static void add_%s_%s(ak_dec_ctx *ctx, void *obj, int64_t tok,"
                         " const struct ak_span *elems, int32_t n) {" % (snake(root), sn))
                o.append("  AK_DGUARD_BEGIN")
                o.append("    Sink_%s *s = (Sink_%s *)obj; (void)tok;" % (root, root))
                o.append("    // ABI v1 7.4: a batched add may be called more than once per")
                o.append("    // field. Append; never size to the count you were handed.")
                o.append("    %s.reserve(%s.size() + (size_t)n);" % (dst, dst))
                o.append("    for (int32_t i = 0; i < n; ++i) {")
                o.append("      %s.push_back(std::string());" % dst)
                if f.kind == "string":
                    o.append("      s_of(s->base, elems[i], ctx, &%s.back());" % dst)
                else:
                    o.append("      b_of(s->base, elems[i], &%s.back());" % dst)
                o.append("    }")
                o.append("  AK_DGUARD_END")
                o.append("}")
                o.append("")
                continue
            # a repeated message or a map
            elem_ty = f.entry if f.card == "map" else et
            if ir.msg(elem_ty).leaf:
                o.append("static void add_%s_%s(ak_dec_ctx *ctx, void *obj, int64_t tok,"
                         " const struct ak_dfix_%s *elems, int32_t n) {"
                         % (snake(root), sn, elem_ty))
                o.append("  AK_DGUARD_BEGIN")
                o.append("    Sink_%s *s = (Sink_%s *)obj; (void)tok;" % (root, root))
                if f.card == "map":
                    o.append("    std::string k_, v_;")
                    o.append("    for (int32_t i = 0; i < n; ++i) {")
                    o.append("      s_of(s->base, elems[i].key, ctx, &k_);")
                    o.append("      s_of(s->base, elems[i].value, ctx, &v_);")
                    o.append("      %s[k_] = v_;" % dst)
                    o.append("    }")
                else:
                    o.append("    %s.reserve(%s.size() + (size_t)n);" % (dst, dst))
                    o.append("    for (int32_t i = 0; i < n; ++i)")
                    o.append("      %s.push_back(from_%s(elems[i], s->base, ctx));"
                             % (dst, snake(elem_ty)))
                o.append("  AK_DGUARD_END")
                o.append("}")
                o.append("")
            else:
                o.append("static int64_t new_%s_%s(ak_dec_ctx *ctx, void *obj) {"
                         % (snake(root), sn))
                o.append("#ifndef AK_NO_GUARD")
                o.append("  try {")
                o.append("#endif")
                o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                o.append("    %s.push_back(%s());" % (dst, elem_ty))
                o.append("    return (int64_t)(%s.size() - 1);" % dst)
                o.append("#ifndef AK_NO_GUARD")
                o.append("  } catch (...) {")
                o.append("    static const char kMsg[] = \"host exception in a reverse call\";")
                o.append("    ak_fail(ctx, AK_ERR_HOST, (const uint8_t *)kMsg,"
                         " (uint32_t)(sizeof(kMsg) - 1));")
                o.append("    return 0;")
                o.append("  }")
                o.append("#endif")
                o.append("}")
                o.append("")
                o.append("static void apply_%s_%s(ak_dec_ctx *ctx, void *obj, int64_t tok,"
                         " const struct ak_dfix_%s *fx) {" % (snake(root), sn, elem_ty))
                o.append("  AK_DGUARD_BEGIN")
                o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                o.append("    fill_%s(&%s[(size_t)tok], *fx, s->base, ctx);"
                         % (snake(elem_ty), dst))
                o.append("  AK_DGUARD_END")
                o.append("}")
                o.append("")
                for ipath, iff in loop_slots(ir, elem_ty):
                    isn = slot_name(ipath)
                    idst = "%s[(size_t)tok]" % dst
                    cur = elem_ty
                    for comp in ipath[:-1]:
                        idst += ".%s.get_or_insert()" % comp
                        cur = next(x for x in ir.msg(cur).plain if x.name == comp).of
                    idst += "." + ipath[-1]
                    iet = RA.elem_type(iff)
                    if iff.kind in ("string", "bytes") and iff.card == "repeated":
                        o.append("static void add_%s_%s_%s(ak_dec_ctx *ctx, void *obj,"
                                 " int64_t tok, const struct ak_span *elems, int32_t n) {"
                                 % (snake(root), sn, isn))
                        o.append("  AK_DGUARD_BEGIN")
                        o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                        o.append("    std::vector<std::string> &dst = %s;" % idst)
                        o.append("    dst.reserve(dst.size() + (size_t)n);")
                        o.append("    for (int32_t i = 0; i < n; ++i) {")
                        o.append("      dst.push_back(std::string());")
                        o.append("      s_of(s->base, elems[i], ctx, &dst.back());")
                        o.append("    }")
                        o.append("  AK_DGUARD_END")
                        o.append("}")
                        o.append("")
                    elif iff.card == "map":
                        o.append("static void add_%s_%s_%s(ak_dec_ctx *ctx, void *obj,"
                                 " int64_t tok, const struct ak_dfix_%s *elems, int32_t n) {"
                                 % (snake(root), sn, isn, iff.entry))
                        o.append("  AK_DGUARD_BEGIN")
                        o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                        o.append("    std::map<std::string, std::string> &dst = %s;" % idst)
                        o.append("    std::string k_, v_;")
                        o.append("    for (int32_t i = 0; i < n; ++i) {")
                        o.append("      s_of(s->base, elems[i].key, ctx, &k_);")
                        o.append("      s_of(s->base, elems[i].value, ctx, &v_);")
                        o.append("      dst[k_] = v_;")
                        o.append("    }")
                        o.append("  AK_DGUARD_END")
                        o.append("}")
                        o.append("")
                    elif iff.card == "packed":
                        cdt = {"int32": "int32_t", "int64": "int64_t", "double": "double",
                               "bool": "uint8_t", "enum": "int32_t"}[iff.kind]
                        o.append("static void add_%s_%s_%s(ak_dec_ctx *ctx, void *obj,"
                                 " int64_t tok, const %s *elems, int32_t n) {"
                                 % (snake(root), sn, isn, cdt))
                        o.append("  AK_DGUARD_BEGIN")
                        o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                        vel = _velem(ir, iff)
                        o.append("    std::vector<%s> &dst = %s;" % (vel, idst))
                        o.append("    dst.reserve(dst.size() + (size_t)n);")
                        if iff.kind == "bool":
                            o.append("    for (int32_t i = 0; i < n; ++i) dst.push_back(elems[i] != 0);")
                        elif iff.kind == "enum":
                            o.append("    for (int32_t i = 0; i < n; ++i)"
                                     " dst.push_back(shapes::%s(elems[i]));" % iff.of)
                        else:
                            o.append("    for (int32_t i = 0; i < n; ++i) dst.push_back(elems[i]);")
                        o.append("  AK_DGUARD_END")
                        o.append("}")
                        o.append("")
                    elif iff.kind == "message" and iff.card == "repeated":
                        o.append("static void add_%s_%s_%s(ak_dec_ctx *ctx, void *obj,"
                                 " int64_t tok, const struct ak_dfix_%s *elems, int32_t n) {"
                                 % (snake(root), sn, isn, iet))
                        o.append("  AK_DGUARD_BEGIN")
                        o.append("    Sink_%s *s = (Sink_%s *)obj;" % (root, root))
                        o.append("    std::vector<%s> &dst = %s;" % (iet, idst))
                        o.append("    dst.reserve(dst.size() + (size_t)n);")
                        o.append("    for (int32_t i = 0; i < n; ++i)")
                        o.append("      dst.push_back(from_%s(elems[i], s->base, ctx));"
                                 % snake(iet))
                        o.append("  AK_DGUARD_END")
                        o.append("}")
                        o.append("")
                    else:
                        raise NotImplementedError(
                            "decode inner slot %s.%s (%s %s)"
                            % (elem_ty, isn, iff.card, iff.kind))

        o.append("int32_t decode_with_%s(ak_dec_ctx *ctx, const uint8_t *b, size_t n, %s *out) {"
                 % (snake(root), root))
        o.append("  Sink_%s sink;" % root)
        o.append("  sink.out = out;")
        o.append("  sink.base = b;")
        o.append("  struct ak_dvt_%s vt;" % root)
        o.append("  vt.apply = apply_%s;" % snake(root))
        o.append("  vt.unknown = NULL;")
        for path, f in slots:
            sn = slot_name(path)
            et = RA.elem_type(f)
            if et:
                o.append("  vt.unk_%s = NULL;" % sn)
            elem_ty = f.entry if f.card == "map" else et
            if elem_ty is None or ir.msg(elem_ty).leaf:
                o.append("  vt.add_%s = add_%s_%s;" % (sn, snake(root), sn))
            else:
                o.append("  vt.new_%s = new_%s_%s;" % (sn, snake(root), sn))
                o.append("  vt.apply_%s = apply_%s_%s;" % (sn, snake(root), sn))
                for ipath, _iff in loop_slots(ir, elem_ty):
                    isn = slot_name(ipath)
                    o.append("  vt.add_%s_%s = add_%s_%s_%s;" % (sn, isn, snake(root), sn, isn))
        o.append("  return ak_decode_%s(ctx, &sink, b, n, &vt);" % root)
        o.append("}")
        o.append("")

    o.append("}  // namespace ffi")
    o.append("}  // namespace shapes")
    o.append("")
    return "\n".join(o)
