"""The corpus's PROJECTION, emitted over the facade.

`ffi/corpus/CONTRACT.md` obligation C2: "the decoded message must equal that JSON. This is
the obligation that byte identity does not imply, and the reason the corpus carries
projections at all: a codec can round-trip bytes it has misunderstood."

Which is the whole reason this file exists rather than a re-encode-and-compare. Section 3
of that document fixes the encoding and it is NOT proto3 JSON: a projection is the
message's SET FIELDS, in the `ListFields`/`HasField` sense, so an implicit-presence scalar
equal to its default does not appear and an explicit-presence one set to zero does.

Generated, like every other backend here, from the one description (R1). A shape this file
has no case for RAISES -- it never falls through to a default -- because a field walker
that silently skipped a shape is what produced a complete-looking codec for a message
whose oneof it ignored entirely.

The JSON spellings themselves are in `src/projjson.h`, which knows no shapes.
"""
from cppnames import camel, oneof_type, snake

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")


class Unsupported(NotImplementedError):
    pass


def _leaf(kind, expr, of, o, indent):
    """One scalar/blob VALUE, already known to be present."""
    p = " " * indent
    if kind == "string":
        o.append('%sak::proj::str(%s, out);' % (p, expr))
    elif kind == "bytes":
        o.append('%sak::proj::hex(%s, out);' % (p, expr))
    elif kind == "bool":
        o.append('%sak::proj::boolean(%s, out);' % (p, expr))
    elif kind in ("int32", "int64"):
        o.append('%sak::proj::i64((long long)%s, out);' % (p, expr))
    elif kind == "enum":
        o.append('%sak::proj::i64((long long)(%s).v, out);' % (p, expr))
    elif kind == "double":
        o.append('%sak::proj::f64(%s, out);' % (p, expr))
    elif kind == "message":
        o.append('%sproj_%s(%s, out);' % (p, snake(of), expr))
    else:
        raise Unsupported("REFUSED: no projection case for kind %r" % kind)


def _present(f, expr):
    """CONTRACT.md section 3's presence rule, per shape. This is the whole difference
    between a projection and proto3 JSON, so it is one expression per shape and nothing
    reaches a default arm."""
    if f.explicit:
        return "%s.has_value()" % expr
    if f.kind == "message":
        return "%s.has_value()" % expr
    if f.kind in ("string", "bytes"):
        return "!%s.empty()" % expr
    if f.kind == "bool":
        return expr
    if f.kind in ("int32", "int64"):
        return "%s != 0" % expr
    if f.kind == "enum":
        return "%s.v != 0" % expr
    if f.kind == "double":
        return "%s != 0" % expr
    raise Unsupported("REFUSED: no presence rule for kind %r" % f.kind)


def _field(ir, m, f, o):
    e = "o.%s" % f.name
    if f.card == "map":
        # ABI v1 section 11 turns a map into a repeated pair message everywhere else; the
        # PROJECTION is an object, keys stringified, so it is the one place the map shape
        # survives. Derived from the description's declared key/value kinds, never assumed.
        if f.raw.get("key") != "string":
            raise Unsupported("REFUSED: a map key of kind %r has no projection spelling"
                              % f.raw.get("key"))
        vk = f.raw.get("value_kind")
        o.append('  if (!%s.empty()) {' % e)
        o.append('    ak::proj::key("%s", &first, out);' % f.name)
        o.append('    out->push_back(\'{\');')
        o.append('    bool mf = true;')
        o.append('    for (std::map<AkStrT, AkStrT>::const_iterator it = %s.begin();' % e)
        o.append('         it != %s.end(); ++it) {' % e)
        o.append('      ak::proj::sep(&mf, out);')
        o.append('      ak::proj::str(it->first, out);')
        o.append("      out->push_back(':');")
        _leaf(vk, "it->second", None, o, 6)
        o.append('    }')
        o.append("    out->push_back('}');")
        o.append('  }')
        return
    if f.card in ("repeated", "packed"):
        o.append('  if (!%s.empty()) {' % e)
        o.append('    ak::proj::key("%s", &first, out);' % f.name)
        o.append("    out->push_back('[');")
        o.append('    for (size_t i = 0; i < %s.size(); ++i) {' % e)
        o.append('      if (i) out->push_back(\',\');')
        _leaf(f.kind, "%s[i]" % e, f.of, o, 6)
        o.append('    }')
        o.append("    out->push_back(']');")
        o.append('  }')
        return
    if f.card != "singular":
        raise Unsupported("REFUSED: no projection case for cardinality %r" % f.card)
    o.append('  if (%s) {' % _present(f, e))
    o.append('    ak::proj::key("%s", &first, out);' % f.name)
    deref = "*%s" % e if (f.explicit or f.kind == "message") else e
    _leaf(f.kind, deref, f.of, o, 4)
    o.append('  }')


def _oneof(ir, m, oname, members, o):
    t = oneof_type(m.name, oname)
    o.append('  switch (o.%s.which()) {' % oname)
    for g in members:
        if g.card != "singular":
            raise Unsupported("REFUSED: a %r oneof member has no projection spelling"
                              % g.card)
        o.append('    case %s::k%s: {' % (t, camel(g.name)))
        o.append('      ak::proj::key("%s", &first, out);' % g.name)
        _leaf(g.kind, "o.%s.%s()" % (oname, g.name), g.of, o, 6)
        o.append('      break;')
        o.append('    }')
    # A oneof with nothing set contributes nothing, which is `kNotSet` and is not a
    # default arm swallowing an unhandled member: every declared member has a case above.
    o.append('    case %s::kNotSet: break;' % t)
    o.append('  }')


def emit_header(ir):
    o = [HEAD, "#ifndef AK_PROJECT_H", "#define AK_PROJECT_H",
         '#include <string>', '#include "generated/types.h"', "",
         "// ffi/corpus/CONTRACT.md obligation C2, section 3's encoding.",
         "namespace shapes {", "namespace project {", ""]
    for root in ir.roots:
        o.append("std::string project_%s(const %s &o);" % (snake(root), root))
    o += ["", "}  // namespace project", "}  // namespace shapes", "#endif", ""]
    return "\n".join(o)


def emit(ir):
    body = []
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("static void proj_%s(const %s &o, std::string *out) {"
                    % (snake(name), name))
        body.append("  (void)o;")
        body.append("  out->push_back('{');")
        body.append("  bool first = true;")
        body.append("  (void)first;")
        done = set()
        for f in m.fields:
            if f.oneof:
                if f.oneof in done:
                    continue
                done.add(f.oneof)
                _oneof(ir, m, f.oneof, m.oneofs[f.oneof], body)
            else:
                _field(ir, m, f, body)
        body.append("  out->push_back('}');")
        body.append("}")
        body.append("")

    fwd = []
    for name in ir.order:
        if ir.msg(name).synthetic:
            continue
        fwd.append("static void proj_%s(const %s &o, std::string *out);"
                   % (snake(name), name))

    o = [HEAD, """
// ffi/corpus/CONTRACT.md obligation C2: what a reader must SEE, which byte identity does
// not imply. The presence rules of section 3 are the whole content of this file; the JSON
// spellings are in src/projjson.h.
""".strip(), '#include "generated/project.h"', "",
         "#include <map>", "#include <string>", "#include <vector>", "",
         '#include "ak/projjson.h"', "",
         "namespace shapes {", "namespace project {", ""]
    o.extend(fwd)
    o.append("")
    o.extend(body)
    for root in ir.roots:
        o.append("std::string project_%s(const %s &o) {" % (snake(root), root))
        o.append("  std::string out;")
        o.append("  proj_%s(o, &out);" % snake(root))
        o.append("  return out;")
        o.append("}")
        o.append("")
    o += ["}  // namespace project", "}  // namespace shapes", ""]
    return "\n".join(o)
