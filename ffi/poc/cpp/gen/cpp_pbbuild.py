"""The incumbent arm's payload builder, over protoc's own generated C++ types.

A SECOND, INDEPENDENT construction route. The facade builder (`cpp_build.py`) and this one
walk the same description and call the same value rules, but they construct different
object graphs through different APIs, so a defect in one is not a defect in the other and
the manifest is the oracle for both. The rust slice's D15 was caught exactly this way: the
three generated-builder arms matched a new hash and the independently built prost arm did
not.
"""
from cppnames import snake

HEAD = ("// @generated by ffi/poc/cpp/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

VALUE_FN = {"guid": "v::guid", "word": "v::word", "sentence": "v::sentence"}
NS = "armonik::ffi::shapes::v1"


def absent_expr(f):
    if f.adapter_site == "nested" or (f.kind == "message" and f.of == "Timestamp"
                                      and f.tag % 2 == 0):
        return "(mode == kAllAbsent || mode == kHalfAbsent)"
    return "(mode == kAllAbsent)"


def _sv(f, path, idx="idx"):
    return "%s(%s, (int)(%s))" % (VALUE_FN[f.value_rule], path, idx)


def _scal(f, path, idx="idx"):
    fn = {"int32": "v::scalar_i32", "int64": "v::scalar_i64",
          "bool": "v::scalar_bool", "double": "v::scalar_double"}[f.kind]
    return "%s(%s, (int)(%s))" % (fn, path, idx)


def _child(ir, f, path, idx, target):
    if f.of == "Timestamp":
        return ("{ ak::values::Stamp st = v::timestamp((int)(%s));"
                " %s->set_seconds(st.seconds); %s->set_nanos(st.nanos); }" % (idx, target, target))
    if f.of == "Duration":
        return ("{ ak::values::Stamp st = v::duration((int)(%s));"
                " %s->set_seconds(st.seconds); %s->set_nanos(st.nanos); }" % (idx, target, target))
    return "build_%s(%s, %s, mode, repeats, bulk, %s);" % (snake(f.of), path, idx, target)


def _emit_field(ir, m, f, o):
    fp = '(path + ".%s")' % f.name
    o.append("  if (!%s) {" % absent_expr(f))
    if f.adapter_site == "nested":
        o.append("    switch (adapter_state(idx)) {")
        o.append("      case kAdapterInvalid: break;")
        o.append("      case kAdapterOk: r->mutable_%s()->set_success(true); break;" % f.name)
        o.append("      case kAdapterError:")
        o.append("        r->mutable_%s()->set_error(v::sentence(path + \".%s.error\", (int)idx));"
                 % (f.name, f.name))
        o.append("        break;")
        o.append("    }")
        o.append("  }")
        return
    if f.adapter_site == "plain":
        o.append("    if (adapter_state(idx) == kAdapterError) r->set_%s(%s);"
                 % (f.name, _sv(f, fp)))
        o.append("  }")
        return
    if f.card == "map":
        n = f.raw.get("entries", 4)
        o.append("    for (int64_t k = 0; k < %d; ++k) {" % n)
        o.append("      char kb[8];")
        o.append("      std::snprintf(kb, sizeof(kb), \"k%02d-\", (int)k);")
        o.append("      std::string key = std::string(kb) + v::word(path + \".%s.key\", (int)(idx * 31 + k));"
                 % f.name)
        o.append("      std::string val;")
        o.append("      if (!(mode == kHalfAbsent && k % 2 == 0))")
        o.append("        val = v::word(path + \".%s.value\", (int)(idx * 31 + k));" % f.name)
        o.append("      (*r->mutable_%s())[key] = val;" % f.name)
        o.append("    }")
    elif f.card == "packed":
        n = f.raw.get("count", 30)
        o.append("    for (int64_t j = 0; j < %d; ++j)" % n)
        if f.kind == "enum":
            o.append("      r->add_%s((%s::%s)v::enum_value(shapes::tbl_%s(), (int)(idx * 97 + j)));"
                     % (f.name, NS, f.of, f.of))
        else:
            o.append("      r->add_%s(%s);" % (f.name, _scal(f, fp, "idx * 97 + j")))
    elif f.card == "repeated" and f.kind == "string":
        o.append("    for (int64_t j = 0; j < repeats; ++j)")
        o.append("      r->add_%s(%s);" % (f.name, _sv(f, fp, "idx * 211 + j")))
    elif f.card == "repeated" and f.kind == "message":
        o.append("    for (int64_t j = 0; j < repeats; ++j) {")
        o.append("      %s::%s *c = r->add_%s();" % (NS, f.of, f.name))
        o.append("      %s" % _child(ir, f, fp, "j", "c"))
        o.append("    }")
    elif f.card == "singular" and f.kind == "message":
        o.append("    { %s::%s *c = r->mutable_%s();" % (NS, f.of, f.name))
        o.append("      %s }" % _child(ir, f, fp, "idx", "c"))
    elif f.card == "singular" and f.kind == "string":
        if f.explicit:
            o.append("    if (explicit_present(%d, idx))" % f.tag)
            o.append("      r->set_%s(idx %% 7 == 0 ? std::string() : %s);" % (f.name, _sv(f, fp)))
        else:
            o.append("    r->set_%s(%s);" % (f.name, _sv(f, fp)))
    elif f.card == "singular" and f.kind == "bytes":
        if f.value_rule == "bulk":
            o.append("    r->set_%s(v::bulk(bulk));" % f.name)
        else:
            o.append("    r->set_%s(v::blob(%s, (int)idx, 16));" % (f.name, fp))
    elif f.card == "singular" and f.kind == "enum":
        o.append("    r->set_%s((%s::%s)v::enum_value(shapes::tbl_%s(), (int)idx));"
                 % (f.name, NS, f.of, f.of))
    elif f.card == "singular" and f.is_scalar_leaf:
        if f.explicit:
            zero = {"int32": "0", "int64": "0", "bool": "false", "double": "0.0"}[f.kind]
            o.append("    if (explicit_present(%d, idx))" % f.tag)
            o.append("      r->set_%s(idx %% 7 == 0 ? %s : %s);" % (f.name, zero, _scal(f, fp)))
        else:
            o.append("    r->set_%s(%s);" % (f.name, _scal(f, fp)))
    else:
        raise NotImplementedError(
            "REFUSED: the protobuf payload builder has no case for %s.%s (card=%s kind=%s)"
            % (m.name, f.name, f.card, f.kind))
    o.append("  }")


def _oneof_value(ir, msg, g):
    path = '"%s.%s"' % (msg, g.name)
    if g.kind == "string":
        return "r->set_%s(v::word(%s, (int)idx));" % (g.name, path)
    if g.kind == "bytes":
        return "r->set_%s(v::blob(%s, (int)idx, 16));" % (g.name, path)
    if g.kind in ("int32", "int64"):
        fn = "v::scalar_i32" if g.kind == "int32" else "v::scalar_i64"
        return "r->set_%s(%s(%s, (int)idx));" % (g.name, fn, path)
    if g.kind == "message" and g.of == "Empty":
        return "r->mutable_%s();" % g.name
    if g.kind == "message":
        return ("{ ak::values::Stamp st = v::timestamp((int)idx);"
                " r->mutable_%s()->set_seconds(st.seconds);"
                " r->mutable_%s()->set_nanos(st.nanos); }" % (g.name, g.name))
    raise NotImplementedError("pb oneof member %s" % g.kind)


def emit_header(ir):
    o = [HEAD, "#ifndef AK_PB_BUILD_H", "#define AK_PB_BUILD_H",
         '#include "shapes.pb.h"', '#include "ak/values.h"', '#include "generated/types.h"',
         "", "namespace pbbuild {", "",
         "enum Mode { kFull = 0, kAllAbsent = 1, kHalfAbsent = 2 };",
         "enum AdapterState { kAdapterError = 0, kAdapterOk = 1, kAdapterInvalid = 2 };", ""]
    for name in ir.order:
        if ir.msg(name).synthetic:
            continue
        o.append("void build_%s(const std::string &path, int64_t idx, Mode mode,"
                 " int64_t repeats, size_t bulk, %s::%s *r);" % (snake(name), NS, name))
    o.append("")
    for pid, spec in ir.schema["payloads"].items():
        if spec["root"] not in ir.messages or spec.get("interleaved"):
            continue
        o.append("void payload_%s(%s::%s *r);"
                 % (pid.replace(".", "_").lower(), NS, spec["root"]))
    o.append("")
    o.append("// P7.1 has no builder anywhere: no canonical writer can produce interleaved")
    o.append("// repeated fields. It is validated by DECODE and by re-encoding to a")
    o.append("// permutation of the same (tag, wire type, body) triples.")
    o.append("}  // namespace pbbuild")
    o.append("#endif")
    o.append("")
    return "\n".join(o)


def emit(ir):
    o = [HEAD, '#include "generated/pb_build.h"', "", "#include <cstdio>", "",
         "namespace pbbuild {", "", "namespace v = ak::values;", "",
         "static inline bool explicit_present(int64_t tag, int64_t idx) {",
         "  return idx % (tag + 1) != 0;", "}", "",
         "static inline AdapterState adapter_state(int64_t idx) {",
         "  switch (idx % 3) {",
         "    case 0: return kAdapterError;",
         "    case 1: return kAdapterOk;",
         "    default: return kAdapterInvalid;",
         "  }", "}", ""]
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        o.append("void build_%s(const std::string &path, int64_t idx, Mode mode,"
                 " int64_t repeats, size_t bulk, %s::%s *r) {" % (snake(name), NS, name))
        o.append("  (void)path; (void)idx; (void)mode; (void)repeats; (void)bulk; (void)r;")
        for f in m.plain:
            if f.oneof:
                continue
            _emit_field(ir, m, f, o)
        for oname, members in m.oneofs.items():
            o.append("  switch (idx %% %d) {" % len(members))
            for i, g in enumerate(members):
                arm = "case %d:" % i if i < len(members) - 1 else "default:"
                o.append("    %s %s break;" % (arm, _oneof_value(ir, name, g)))
            o.append("  }")
        o.append("}")
        o.append("")

    for pid, spec in ir.schema["payloads"].items():
        root = spec["root"]
        if root not in ir.messages or spec.get("interleaved"):
            continue
        m = ir.msg(root)
        o.append("void payload_%s(%s::%s *r) {" % (pid.replace(".", "_").lower(), NS, root))
        if "bulk" in spec:
            f = m.plain[0]
            o.append("  build_%s(\"%s\", 0, kFull, 3, %d, r->mutable_%s());"
                     % (snake(f.of), f.of, spec["bulk"], f.name))
        else:
            field = next(f for f in m.plain if f.name == spec["field"])
            reps = spec.get("repeats", 3)
            reps = reps if isinstance(reps, list) else [reps]
            mode = {"all_absent": "kAllAbsent", "half_absent": "kHalfAbsent"}.get(
                spec.get("mode"), "kFull")
            o.append("  static const int64_t kReps[%d] = {%s};"
                     % (len(reps), ", ".join(str(x) for x in reps)))
            o.append("  for (int64_t j = 0; j < %d; ++j)" % spec["count"])
            o.append("    build_%s(\"%s\", j, %s, kReps[j %% %d], 0, r->add_%s());"
                     % (snake(field.of), field.of, mode, len(reps), field.name))
            for f in m.plain:
                if f.name == "page":
                    o.append("  r->set_page(1);")
                elif f.name == "total":
                    o.append("  r->set_total(%d);" % spec["count"])
        o.append("}")
        o.append("")
    o.append("}  // namespace pbbuild")
    o.append("")
    return "\n".join(o)
