"""Corpus glue: the per-root dispatch and the projection of a facade value, for the
corpus harness (`ak.RunCorpus`, `gen/corpus.py`). Harness glue, not a backend: it holds no
wire rule. It reads the plan's descriptor view (field names, kinds, presence) to walk a
facade value, which is what CONTRACT.md section 3's projection is -- the set fields.

Generated rather than reflected, so a fixed32 prints unsigned, an enum prints its number
and a borrowed view prints its string, by the field's declared kind rather than by the
Java type that happens to hold it.

    Dispatch   root name -> arm R (drop, retain), the ffi binding (push, pull), and the
               borrowed facade's binding; ffi entries only for roots that cross the C ABI
    Project    root name -> the projection JSON of a value of that facade
"""
import java_names as N
import java_ffiarms

HEAD = "// @generated by ffi/poc/java/gen/java_corpus.py (corpus glue). Do not edit.\n"


def _val(p, f, v, kind_of=None):
    """A statement appending the projection of value `v` of field `f` (one element)."""
    k = f.kind
    if k == "string":
        return "str(%s, sb);" % (v if not N.is_borrow() else "%s.str()" % v)
    if k == "bytes":
        return "hex(%s, sb);" % v
    if k in ("int32", "int64", "enum"):
        return "str(String.valueOf(%s), sb);" % v
    if k == "fixed32":
        return "str(Long.toString(%s & 0xFFFFFFFFL), sb);" % v
    if k == "bool":
        return "sb.append(%s ? \"true\" : \"false\");" % v
    if k == "double":
        return "dbl(%s, sb);" % v
    if k == "message":
        return "p%s(%s, sb);" % (f.of, v)
    raise NotImplementedError("projection of %s.%s kind %s" % (f.owner, f.name, k))


def _implicit_set(f, v):
    k = f.kind
    if k == "string":
        return ("!%s.isEmpty()" % v) if not N.is_borrow() else "%s.byteLength() > 0" % v
    if k == "bytes":
        return "%s.length > 0" % v
    if k == "bool":
        return v
    if k == "double":
        return "Double.doubleToRawLongBits(%s) != 0L" % v
    return "%s != 0" % v


def emit_project(p, ns):
    o = [HEAD, "package %s;" % ns, "",
         "/** CONTRACT.md section 3: a value's SET fields as JSON. A double is printed as its",
         " *  raw bits (\"D:<hex>\"); gen/corpus.py renders it with %.17g. */",
         "public final class Project {",
         "  private Project() {}",
         "",
         "  public static String project(String root, Object o) {",
         "    StringBuilder sb = new StringBuilder();",
         "    switch (root) {"]
    for name in p.order:
        if p.msg(name).synthetic:
            continue
        o.append("      case \"%s\": p%s((%s) o, sb); break;" % (name, name, name))
    o.append("      default: throw new IllegalArgumentException(root);")
    o.append("    }")
    o.append("    return sb.toString();")
    o.append("  }")
    for name in p.order:
        m = p.msg(name)
        if m.synthetic:
            continue
        o.append("")
        o.append("  static void p%s(%s o, StringBuilder sb) {" % (name, name))
        o.append("    boolean first = true;")
        o.append("    sb.append('{');")
        for f in m.plain:
            v = "o.%s" % f.name
            if f.card == "map":
                o.append("    if (!%s.isEmpty()) {" % v)
                o.append("      first = key(sb, first, \"%s\");" % f.name)
                o.append("      sb.append('{');")
                o.append("      boolean f2 = true;")
                st = N.string_type()
                o.append("      for (java.util.Map.Entry<%s, %s> en : %s.entrySet()) {" % (st, st, v))
                kx = "en.getKey()" if not N.is_borrow() else "en.getKey().str()"
                vx = "en.getValue()" if not N.is_borrow() else "en.getValue().str()"
                o.append("        f2 = key(sb, f2, %s);" % kx)
                o.append("        str(%s, sb);" % vx)
                o.append("      }")
                o.append("      sb.append('}');")
                o.append("    }")
            elif f.card == "packed":
                o.append("    if (%s.length > 0) {" % v)
                o.append("      first = key(sb, first, \"%s\");" % f.name)
                o.append("      sb.append('[');")
                o.append("      for (int i = 0; i < %s.length; i++) { if (i > 0) sb.append(','); %s }"
                         % (v, _val(p, f, "%s[i]" % v)))
                o.append("      sb.append(']');")
                o.append("    }")
            elif f.card == "repeated":
                o.append("    if (!%s.isEmpty()) {" % v)
                o.append("      first = key(sb, first, \"%s\");" % f.name)
                o.append("      sb.append('[');")
                o.append("      boolean f2 = true;")
                o.append("      for (%s x : %s) { if (!f2) sb.append(','); f2 = false; %s }"
                         % (N.elem_type_java(f), v, _val(p, f, "x")))
                o.append("      sb.append(']');")
                o.append("    }")
            else:
                if f.kind == "message" or (f.explicit and f.kind in ("string", "bytes")):
                    cond = "%s != null" % v
                elif f.explicit:
                    cond = "o.has_%s" % f.name
                else:
                    cond = _implicit_set(f, v)
                o.append("    if (%s) { first = key(sb, first, \"%s\"); %s }" % (cond, f.name, _val(p, f, v)))
        for oname, members in m.oneofs.items():
            for g in members:
                mv = "o.%s_%s" % (oname, g.name)
                o.append("    if (o.%s_case == %d) {" % (oname, g.tag))
                o.append("      first = key(sb, first, \"%s\");" % g.name)
                if g.kind == "message":
                    o.append("      if (%s == null) sb.append(\"{}\"); else %s" % (mv, _val(p, g, mv)))
                elif g.kind in ("string", "bytes"):
                    o.append("      if (%s == null) sb.append(\"\\\"\\\"\"); else %s" % (mv, _val(p, g, mv)))
                else:
                    o.append("      %s" % _val(p, g, mv))
                o.append("    }")
        o.append("    sb.append('}');")
        o.append("  }")
    o.append(HELPERS)
    o.append("}")
    o.append("")
    return "\n".join(o)


HELPERS = '''
  static boolean key(StringBuilder sb, boolean first, String k) {
    if (!first) sb.append(',');
    str(k, sb);
    sb.append(':');
    return false;
  }

  static void dbl(double d, StringBuilder sb) {
    str("D:" + Long.toHexString(Double.doubleToRawLongBits(d)), sb);
  }

  static void hex(byte[] b, StringBuilder sb) {
    StringBuilder h = new StringBuilder();
    for (byte x : b) h.append(String.format("%02x", x & 0xff));
    str(h.toString(), sb);
  }

  static void str(String s, StringBuilder sb) {
    sb.append('"');
    for (int i = 0; i < s.length(); i++) {
      char ch = s.charAt(i);
      if (ch == '"' || ch == '\\\\') sb.append('\\\\').append(ch);
      else if (ch < 0x20 || ch > 0x7e) sb.append(String.format("\\\\u%04x", (int) ch));
      else sb.append(ch);
    }
    sb.append('"');
  }
'''


def emit_dispatch(p, pa, ns, owning=True, nounk=False):
    """Root -> each arm's decode and encode. `pa` is the plan of the C ABI's roots."""
    o = [HEAD, "package %s;" % ns, "", "import ak.Dec;", "import ak.Enc;", "",
         "/** Root name -> each arm's decode and encode, so the corpus harness carries no",
         " *  reflection. Arm R for every message; the binding for the C ABI's roots. */",
         "public final class Dispatch {",
         "  private Dispatch() {}", ""]
    names = [n for n in p.order if not p.msg(n).synthetic]
    abi = list(pa.roots)
    o.append("  public static final String[] ALL = {%s};" % ", ".join('"%s"' % n for n in names))
    o.append("  public static final String[] ABI = {%s};" % ", ".join('"%s"' % n for n in abi))
    codecs = [("R", "Codec")] + ([("RRetain", "CodecRetain")] if owning and not nounk else [])
    if owning and nounk:
        o.append("")
        o.append("  /** The no-unknown build (WP5 step 10) has no retain codec. */")
        o.append("  public static Object decRRetain(String root, byte[] b) {")
        o.append("    throw new UnsupportedOperationException(\"no-unknown build: no retain mode\");")
        o.append("  }")
        o.append("")
        o.append("  public static byte[] encRRetain(String root, Object o) {")
        o.append("    throw new UnsupportedOperationException(\"no-unknown build: no retain mode\");")
        o.append("  }")
    for tag, cls in codecs:
        o.append("")
        o.append("  public static Object dec%s(String root, byte[] b) {" % tag)
        o.append("    Dec d = new Dec().reset(b, 0, b.length);")
        o.append("    switch (root) {")
        for n in names:
            o.append("      case \"%s\": return %s.dec%s(d);" % (n, cls, n))
        o.append("      default: throw new IllegalArgumentException(root);")
        o.append("    }")
        o.append("  }")
        o.append("")
        o.append("  public static byte[] enc%s(String root, Object o) {" % tag)
        o.append("    Enc e = new Enc(%s.SITES);" % cls)
        o.append("    e.reset();")
        o.append("    switch (root) {")
        for n in names:
            o.append("      case \"%s\": %s.enc%s(e, (%s) o); break;" % (n, cls, n, n))
        o.append("      default: throw new IllegalArgumentException(root);")
        o.append("    }")
        o.append("    return e.toBytes();")
        o.append("  }")
    o.append("")
    o.append("  public static Object decFfi(Binding b, String root, byte[] w) {")
    o.append("    switch (root) {")
    for n in abi:
        o.append("      case \"%s\": return b.decode%s(w, 0, w.length);" % (n, n))
    o.append("      default: throw new IllegalArgumentException(root);")
    o.append("    }")
    o.append("  }")
    o.append("")
    o.append("  public static Object parseFfi(Binding b, String root, byte[] w) {")
    o.append("    switch (root) {")
    for n in abi:
        o.append("      case \"%s\": return b.parse%s(w, 0, w.length);" % (n, n))
    o.append("      default: throw new IllegalArgumentException(root);")
    o.append("    }")
    o.append("  }")
    o.append("")
    o.append("  public static byte[] encFfi(Binding b, String root, Object o) {")
    o.append("    switch (root) {")
    for n in abi:
        o.append("      case \"%s\": b.encode%s((%s) o); break;" % (n, n, n))
    o.append("      default: throw new IllegalArgumentException(root);")
    o.append("    }")
    o.append("    return b.take();")
    o.append("  }")
    o += java_ffiarms.unk_helpers("Binding", nounk)
    o.append("}")
    o.append("")
    return "\n".join(o)
