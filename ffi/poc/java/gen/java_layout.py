"""ABI v1 section 10 and obligation 12.3: group layouts reproduced by hand, and asserted
at load.

**This slice is the case section 10 exists for.** The rust slice recorded the assertion as
"specified and not built", because both of its sides compiled against one generated header
and there was nothing to disagree. The cpp slice built it, and its two sides were a C
header and `#[repr(C)]` -- two compilers, but still two compilers. A Java binding has no
compiler on its side at all: it writes fields into off-heap memory at offsets a *generator
computed by hand from the SysV x86-64 rules*, which is precisely the "host that reproduces
offsets by hand" section 10 names, and whose failure mode it calls "a wrong value in a
field, the worst way to find it".

So the offsets below are derived here, from the same field lists the core's `#[repr(C)]`
structs are built from, and compared at load against the numbers the core exports. If this
file's layout engine is wrong, the assert fires with the name of the fact that disagreed;
that is the whole point, and `gen/layout_break.sh` shows it firing.
"""
import javanames as N
import rust_abi as RA
import cpp_layout as CL

HEAD = ("// @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

# (size, align) of every leaf type an ABI group can hold, on the SysV x86-64 C ABI.
# `ak_str` is {const void*, size_t, fn ptr}; `ak_span` is three u32; `ak_blob` is two
# words (decision 11's bag is two, not three: it carries wire bytes, so there is no
# transcoder it could legally hold but the identity).
LEAF = {
    "i32": (4, 4), "i64": (8, 8), "u8": (1, 1), "f64": (8, 8), "u32": (4, 4),
    "ak_str": (24, 8), "ak_span": (12, 4), "ak_blob": (16, 8),
}


class Layout(object):
    def __init__(self):
        self.groups = {}        # struct name -> (size, align, [(member, offset)])

    def of(self, name):
        return self.groups[name]

    def add(self, name, members):
        """`members` is [(name, type-spelling)] in declaration order; the type is either a
        LEAF key or another group's struct name."""
        off, align = 0, 1
        out = []
        for mname, ty in members:
            if ty in LEAF:
                sz, al = LEAF[ty]
            else:
                g = self.groups[ty]
                sz, al = g[0], g[1]
            off = (off + al - 1) // al * al
            out.append((mname, off))
            off += sz
            align = max(align, al)
        size = (off + align - 1) // align * align
        self.groups[name] = (size, align, out)
        return self.groups[name]


def build(ir):
    """Every group, in the order `cpp_layout.facts` enumerates them, which is the order
    the core exports and therefore the order the assert walks."""
    lay = Layout()
    for name in N.abi_order_topo(ir):
        m = ir.msg(name)
        for pre in ("e", "d", "u"):
            enc = pre != "d"
            sname = "ak_%sfix_%s" % (pre, name)
            fields = RA.group_fields(m, enc)
            if pre == "u":
                fields = [(fn, ty.replace("ak_efix_", "ak_ufix_")) for fn, ty in fields]
                fields = fields + [("unknown", "ak_blob")]
            lay.add(sname, fields + [("presence", "u32")])
    return lay


def emit_java(ir, ns=N.PKG):
    lay = build(ir)
    facts = CL.facts(ir)

    o = [HEAD, "package %s;" % ns, "",
         "/** Group sizes and member offsets, reproduced by hand from the SysV x86-64 C",
         " *  ABI rules and asserted at load against what the core exports (ABI v1",
         " *  section 10). A Java binding writes into off-heap memory at these numbers,",
         " *  so getting one wrong is a wrong value in a field and nothing louder. */",
         "public final class Layout {",
         "  private Layout() {}",
         ""]

    for sname, (size, align, members) in lay.groups.items():
        up = N.screaming(sname.replace("ak_", "").replace("fix_", "FIX_")).upper()
        up = sname.upper()
        o.append("  public static final int %s_SIZE = %d;   // align %d"
                 % (up, size, align))
        for mname, off in members:
            o.append("  public static final int %s__%s = %d;" % (up, mname.upper(), off))
        o.append("")

    # The assert table, in the core's own order. One flat int[] so the comparison is a
    # loop and not 380 lines of generated `if`.
    o.append("  /** The same facts the core exports, in the core's order, so the two can")
    o.append("   *  be compared by index. */")
    o.append("  public static final int[] HOST = {")
    names = []
    for sname, members in facts:
        size, _al, moff = lay.groups[sname]
        o.append("    %d," % size)
        names.append("sizeof " + sname)
        by = dict(moff)
        for mem in members:
            o.append("    %d," % by[mem])
            names.append("%s.%s" % (sname, mem))
    o.append("  };")
    o.append("")
    o.append("  /** One name per fact, so a disagreement is NAMED rather than indexed. */")
    o.append("  public static final String[] NAMES = {")
    for nm in names:
        o.append('    "%s",' % nm)
    o.append("  };")
    o.append("")
    o.append(ASSERT)
    o.append("}")
    o.append("")
    return "\n".join(o)


def group_const(sname, member=None):
    """The Java constant name for a group's size or a member's offset."""
    up = sname.upper()
    return "%s_SIZE" % up if member is None else "%s__%s" % (up, member.upper())


ASSERT = """  /**
   * ABI v1 section 10 and obligation 12.3, exercised rather than specified.
   *
   * <p>The core exports its own `size_of` and `offset_of` for every group; the table above
   * was computed BY HAND from the SysV x86-64 rules by this slice's generator. A
   * disagreement between them is otherwise "a wrong value in a field, the worst way to
   * find it" -- section 10's own words, and the reason the check exists.
   *
   * <p>`gen/layout_break.sh` perturbs one fact and shows this firing, because a guard with
   * no failing test is a guard nobody has seen work.
   */
  public static void assertAgreement() {
    int[] core = new int[HOST.length];
    int have = ak.Native.layoutFacts(core);
    if (have != HOST.length)
      throw new IllegalStateException(
          "ABI v1 section 10: the core exports " + have + " layout facts and this host"
          + " reproduced " + HOST.length + ". The two sides are not describing the same"
          + " set of groups.");
    int bad = 0;
    StringBuilder sb = null;
    for (int i = 0; i < have; i++) {
      if (core[i] == HOST[i]) continue;
      if (sb == null) sb = new StringBuilder("ABI v1 section 10: group layout disagreement\\n");
      if (++bad <= 12)
        sb.append("  ").append(NAMES[i]).append(": core ").append(core[i])
          .append(", host ").append(HOST[i]).append('\\n');
    }
    if (sb != null) {
      sb.append("  (").append(bad).append(" of ").append(have).append(" facts disagree)");
      throw new IllegalStateException(sb.toString());
    }
  }
"""
