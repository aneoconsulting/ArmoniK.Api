"""Arm `R`: the generated pure-Java codec over the facade.

Two jobs at once, and they do not conflict:

* README R3's **no-boundary control** -- the same generated codec emitted into the host
  language, over the same facade objects, so the delta against `core-ffi` is the boundary
  and nothing else. R3 says the control is not optional and names Java as the slice where
  it changed the recommendation.
* README section 13 outcome 2's **fallback architecture** -- generate the codec into each
  host language and keep only the RPC layer on the C ABI. That is Java's own published
  recommendation, so this arm is a candidate and not a control only.

It is emitted from the same IR as the binding and the core, so a shape cannot be answered
one way here and another there. Where it presizes, it presizes exactly where the binding
does; the brief for this slice names that as the way to turn a container policy into a
false architecture result, and the cpp slice found it twice.
"""
import javanames as N

HEAD = ("// @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

WIRE_VARINT, WIRE_I64, WIRE_LEN = 0, 1, 2


def _wire(f):
    if f.kind == "double":
        return WIRE_I64
    if f.kind in ("string", "bytes", "message", "map"):
        return WIRE_LEN
    return WIRE_VARINT


class Sites(object):
    """One length-prefix site per (message, field) that opens a length-delimited body
    whose size is not known in advance, numbered in one walk so arm R and the core agree
    on what a site IS even though each numbers its own."""

    def __init__(self):
        self.ids = {}

    def of(self, key):
        if key not in self.ids:
            self.ids[key] = len(self.ids)
        return self.ids[key]

    def __len__(self):
        return len(self.ids)


# ----------------------------------------------------------------- encode

def _enc_value(o, ind, f, src, sites, owner, suffix=""):
    """Write ONE occurrence of `f` holding `src`. Presence is the caller's business."""
    p = " " * ind
    if f.kind == "string":
        o.append("%se.stringField(%d, %s);" % (p, f.tag, src))
    elif f.kind == "bytes":
        o.append("%se.blobField(%d, %s);" % (p, f.tag, src))
    elif f.kind == "double":
        o.append("%se.f64Field(%d, %s);" % (p, f.tag, src))
    elif f.kind == "bool":
        o.append("%se.varintField(%d, %s ? 1 : 0);" % (p, f.tag, src))
    elif f.kind in ("int32", "enum"):
        # A negative int32 is ten bytes on the wire, which is protobuf's rule and not a
        # choice: sign-extend to 64 bits before the varint.
        o.append("%se.varintField(%d, (long) (%s));" % (p, f.tag, src))
    elif f.kind == "int64":
        o.append("%se.varintField(%d, %s);" % (p, f.tag, src))
    elif f.kind == "message":
        site = sites.of((owner, f.name, suffix))
        o.append("%s{" % p)
        o.append("%s  long m = e.begin(%d, %d);" % (p, f.tag, site))
        o.append("%s  enc%s(e, %s);" % (p, f.of, src))
        o.append("%s  e.end(m);" % p)
        o.append("%s}" % p)
    else:
        raise NotImplementedError("REFUSED: no encode case for %s.%s kind=%s"
                                  % (owner, f.name, f.kind))


def _enc_field(ir, o, m, f, sites):
    """Presence, then the value. The canonical form of schema/README:
    an implicit-presence leaf holding the proto zero is omitted; an explicit-presence
    field is written when set, zero or not; a message field is written when present,
    empty or not; repeated scalars are always packed; map entries are sorted by key."""
    src = "o.%s" % f.name
    if f.card == "map":
        site = sites.of((m.name, f.name, "entry"))
        ks = sites.of((m.name, f.name, "entrykey"))
        o.append("    for (java.util.Map.Entry<%s, %s> en : %s.entrySet()) {"
                 % (N.string_type(), N.string_type(), src))
        o.append("      long mk = e.begin(%d, %d);" % (f.tag, site))
        o.append("      e.stringField(1, %s);" % _sref("en.getKey()"))
        o.append("      if (%s) e.stringField(2, %s);"
                 % (_nonempty("en.getValue()"), _sref("en.getValue()")))
        o.append("      e.end(mk);")
        o.append("    }")
        del ks
        return
    if f.card == "packed":
        site = sites.of((m.name, f.name, "packed"))
        o.append("    if (%s.length > 0) {" % src)
        o.append("      long mp = e.begin(%d, %d);" % (f.tag, site))
        o.append("      for (int i = 0; i < %s.length; i++)" % src)
        if f.kind == "double":
            o.append("        { e.ensure(8); long bits = Double.doubleToRawLongBits(%s[i]);"
                     " for (int q = 0; q < 8; q++) e.buf[e.len++] = (byte) (bits >>> (8 * q)); }" % src)
        elif f.kind == "bool":
            o.append("        e.varint(%s[i] ? 1 : 0);" % src)
        elif f.kind in ("int32", "enum"):
            o.append("        e.varint((long) %s[i]);" % src)
        else:
            o.append("        e.varint(%s[i]);" % src)
        o.append("      e.end(mp);")
        o.append("    }")
        return
    if f.card == "repeated":
        base = "x"
        jt = ("byte[]" if f.kind == "bytes" else N.string_type() if f.kind == "string"
              else f.of)
        o.append("    for (%s %s : %s) {" % (jt, base, src))
        _enc_value(o, 6, f, _sref(base) if f.kind == "string" else base, sites, m.name, "rep")
        o.append("    }")
        return
    # singular
    if f.kind == "message":
        o.append("    if (%s != null) {" % src)
        _enc_value(o, 6, f, src, sites, m.name)
        o.append("    }")
    elif f.kind == "string":
        cond = ("%s != null" % src) if f.explicit else _nonempty(src)
        o.append("    if (%s) {" % cond)
        _enc_value(o, 6, f, _sref(src), sites, m.name)
        o.append("    }")
    elif f.kind == "bytes":
        o.append("    if (%s.length > 0) {" % src)
        _enc_value(o, 6, f, src, sites, m.name)
        o.append("    }")
    elif f.kind == "bool":
        cond = ("o.has_%s" % f.name) if f.explicit else src
        o.append("    if (%s) {" % cond)
        _enc_value(o, 6, f, src, sites, m.name)
        o.append("    }")
    else:
        cond = ("o.has_%s" % f.name) if f.explicit else ("%s != %s" % (src, N.ZERO[f.kind]))
        o.append("    if (%s) {" % cond)
        _enc_value(o, 6, f, src, sites, m.name)
        o.append("    }")


def _sref(expr):
    """A borrowed facade holds a view; the codec needs the String the wire form is made
    from. `Utf8View` carries its own bytes, so this is a no-op for the owning facade and a
    materialisation for the borrowed one -- which is exactly why the borrowed arm is a
    DECODE arm and its encode column is not quoted."""
    return expr if not N.is_borrow() else "%s.str()" % expr


def _nonempty(expr):
    return "!%s.isEmpty()" % expr if not N.is_borrow() else "%s.length() > 0" % expr


# ----------------------------------------------------------------- decode

def _dec_field(ir, o, m, f):
    """One case of the tag switch. `case` values are the full key, so the wire type is
    checked by construction rather than by a second test."""
    dst = "r.%s" % f.name
    key = (f.tag << 3) | _wire(f)
    if f.card == "map":
        o.append("        case %d: {" % key)
        o.append("          int outer = d.push();")
        o.append("          %s k = %s; %s v = %s;"
                 % (N.string_type(), _empty_str(), N.string_type(), _empty_str()))
        o.append("          while (!d.done()) {")
        o.append("            int t2 = d.readTag();")
        o.append("            if (t2 == 10) k = %s;" % _mk_str("d.readString()"))
        o.append("            else if (t2 == 18) v = %s;" % _mk_str("d.readString()"))
        o.append("            else d.skip(t2);")
        o.append("          }")
        o.append("          d.pop(outer);")
        o.append("          %s.put(k, v);" % dst)
        o.append("          break;")
        o.append("        }")
        return
    if f.card == "packed":
        jt = {"int32": "int", "int64": "long", "bool": "boolean",
              "double": "double", "enum": "int"}[f.kind]
        rd = {"int32": "(int) d.readVarint()", "int64": "d.readVarint()",
              "bool": "d.readVarint() != 0", "double": "d.readDouble()",
              "enum": "(int) d.readVarint()"}[f.kind]
        o.append("        case %d: {   // the packed form" % ((f.tag << 3) | WIRE_LEN))
        o.append("          int outer = d.push();")
        o.append("          %s[] acc = new %s[8];" % (jt, jt))
        o.append("          int n = 0;")
        o.append("          while (!d.done()) {")
        o.append("            if (n == acc.length) acc = java.util.Arrays.copyOf(acc, n * 2);")
        o.append("            acc[n++] = %s;" % rd)
        o.append("          }")
        o.append("          d.pop(outer);")
        o.append("          %s = append(%s, acc, n);" % (dst, dst))
        o.append("          break;")
        o.append("        }")
        # A conformant parser accepts the unpacked form of a packed field too. Nothing in
        # the payload set produces it and that is exactly why it is here: the shape is
        # legal wire that a corpus generated from a canonical writer never contains.
        uw = WIRE_I64 if f.kind == "double" else WIRE_VARINT
        o.append("        case %d: {   // the same field, written unpacked: legal wire"
                 % ((f.tag << 3) | uw))
        o.append("          %s[] one = {%s};" % (jt, rd))
        o.append("          %s = append(%s, one, 1);" % (dst, dst))
        o.append("          break;")
        o.append("        }")
        return
    if f.card == "repeated":
        o.append("        case %d:" % key)
        if f.kind == "string":
            o.append("          %s.add(%s);" % (dst, _mk_str("d.readString()")))
        elif f.kind == "message":
            o.append("          { int outer = d.push(); %s.add(dec%s(d)); d.pop(outer); }"
                     % (dst, f.of))
        else:
            raise NotImplementedError("REFUSED: no decode case for repeated %s" % f.kind)
        o.append("          break;")
        return
    o.append("        case %d:" % key)
    if f.kind == "string":
        o.append("          %s = %s;" % (dst, _mk_str("d.readString()")))
    elif f.kind == "bytes":
        o.append("          %s = d.readBytes();" % dst)
    elif f.kind == "message":
        o.append("          { int outer = d.push(); %s = dec%s(d); d.pop(outer); }"
                 % (dst, f.of))
    elif f.kind == "bool":
        o.append("          %s = d.readVarint() != 0;" % dst)
    elif f.kind in ("int32", "enum"):
        o.append("          %s = (int) d.readVarint();" % dst)
    elif f.kind == "int64":
        o.append("          %s = d.readVarint();" % dst)
    elif f.kind == "double":
        o.append("          %s = d.readDouble();" % dst)
    else:
        raise NotImplementedError("REFUSED: no decode case for %s.%s kind=%s"
                                  % (m.name, f.name, f.kind))
    if N.has_flag(f):
        o.append("          r.has_%s = true;" % f.name)
    o.append("          break;")


def _dec_oneof(ir, o, m, oname, members):
    for g in members:
        key = (g.tag << 3) | _wire(g)
        o.append("        case %d:" % key)
        o.append("          r.%s_case = %s.%s_CASE_%s;"
                 % (oname, m.name, N.screaming(oname), N.screaming(g.name)))
        dst = "r.%s_%s" % (oname, g.name)
        if g.kind == "string":
            o.append("          %s = %s;" % (dst, _mk_str("d.readString()")))
        elif g.kind == "bytes":
            o.append("          %s = d.readBytes();" % dst)
        elif g.kind == "message":
            o.append("          { int outer = d.push(); %s = dec%s(d); d.pop(outer); }"
                     % (dst, g.of))
        elif g.kind == "int64":
            o.append("          %s = d.readVarint();" % dst)
        elif g.kind == "int32":
            o.append("          %s = (int) d.readVarint();" % dst)
        elif g.kind == "bool":
            o.append("          %s = d.readVarint() != 0;" % dst)
        else:
            raise NotImplementedError("REFUSED: no decode case for oneof member %s" % g.kind)
        o.append("          break;")


def _mk_str(expr):
    return expr if not N.is_borrow() else "%s.of(%s)" % (N.string_type(), expr)


def _empty_str():
    return '""' if not N.is_borrow() else "%s.EMPTY" % N.string_type()


APPEND = '''
  // Presizing, and why it is spelled like this. A batched `add` may be called more than
  // once per field (ABI v1 7.4), so the binding APPENDS and never sizes to the count it
  // was handed; this arm does the same, from the same generator, so the two differ in
  // where the bytes are parsed and in nothing else. Sizing to the first run here would
  // have made arm R look better than the binding for a reason that is a container policy.
  static int[] append(int[] a, int[] b, int n) {
    int[] out = java.util.Arrays.copyOf(a, a.length + n);
    System.arraycopy(b, 0, out, a.length, n);
    return out;
  }

  static long[] append(long[] a, long[] b, int n) {
    long[] out = java.util.Arrays.copyOf(a, a.length + n);
    System.arraycopy(b, 0, out, a.length, n);
    return out;
  }

  static double[] append(double[] a, double[] b, int n) {
    double[] out = java.util.Arrays.copyOf(a, a.length + n);
    System.arraycopy(b, 0, out, a.length, n);
    return out;
  }

  static boolean[] append(boolean[] a, boolean[] b, int n) {
    boolean[] out = java.util.Arrays.copyOf(a, a.length + n);
    System.arraycopy(b, 0, out, a.length, n);
    return out;
  }
'''


def emit(ir, ns=N.PKG, cls="Codec"):
    sites = Sites()
    body = []
    for name in N.abi_order_topo(ir):
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("")
        body.append("  static void enc%s(Enc e, %s o) {" % (name, name))
        for f in m.plain:
            if f.oneof:
                continue
            _enc_field(ir, body, m, f, sites)
        for oname, members in m.oneofs.items():
            body.append("    switch (o.%s_case) {" % oname)
            for g in members:
                body.append("      case %s.%s_CASE_%s:"
                            % (name, N.screaming(oname), N.screaming(g.name)))
                src = "o.%s_%s" % (oname, g.name)
                if g.kind == "message":
                    site = sites.of((name, "%s_%s" % (oname, g.name), "oneof"))
                    body.append("        { long m = e.begin(%d, %d); enc%s(e, %s); e.end(m); }"
                                % (g.tag, site, g.of, src))
                elif g.kind == "string":
                    body.append("        e.stringField(%d, %s);" % (g.tag, _sref(src)))
                elif g.kind == "bytes":
                    body.append("        e.blobField(%d, %s);" % (g.tag, src))
                elif g.kind == "bool":
                    body.append("        e.varintField(%d, %s ? 1 : 0);" % (g.tag, src))
                elif g.kind == "int32":
                    body.append("        e.varintField(%d, (long) %s);" % (g.tag, src))
                else:
                    body.append("        e.varintField(%d, %s);" % (g.tag, src))
                body.append("        break;")
            body.append("      default: break;")
            body.append("    }")
        body.append("  }")

    for name in N.abi_order_topo(ir):
        m = ir.msg(name)
        if m.synthetic:
            continue
        body.append("")
        body.append("  static %s dec%s(Dec d) {" % (name, name))
        body.append("    %s r = new %s();" % (name, name))
        body.append("    while (!d.done()) {")
        body.append("      int t = d.readTag();")
        body.append("      switch (t) {")
        for f in m.plain:
            if f.oneof:
                continue
            _dec_field(ir, body, m, f)
        for oname, members in m.oneofs.items():
            _dec_oneof(ir, body, m, oname, members)
        body.append("        default:")
        body.append("          d.skip(t);")
        body.append("          break;")
        body.append("      }")
        body.append("    }")
        body.append("    return r;")
        body.append("  }")

    o = [HEAD, "package %s;" % ns, "", "import ak.Dec;", "import ak.Enc;", "",
         "/** Arm `R`: the generated pure-Java codec. README R3's no-boundary control,",
         " *  and README section 13 outcome 2's fallback architecture, which is the same",
         " *  code seen twice. */",
         "public final class %s {" % cls,
         "  private %s() {}" % cls,
         "",
         "  /** One learned length-prefix width per site, the same mechanism ABI v1",
         "   *  section 6 fixes for the core. */",
         "  public static final int SITES = %d;" % len(sites),
         APPEND]
    o.extend(body)
    o.append("")
    o.append("  // ---- the roots ------------------------------------------------------")
    for root in ir.roots:
        o.append("")
        o.append("  public static byte[] encode%s(Enc e, %s o) {" % (root, root))
        o.append("    e.reset();")
        o.append("    enc%s(e, o);" % root)
        o.append("    return e.toBytes();")
        o.append("  }")
        o.append("")
        o.append("  public static void encodeInto%s(Enc e, %s o) {" % (root, root))
        o.append("    e.reset();")
        o.append("    enc%s(e, o);" % root)
        o.append("  }")
        o.append("")
        o.append("  public static %s decode%s(Dec d, byte[] buf, int off, int len) {"
                 % (root, root))
        o.append("    d.reset(buf, off, len);")
        o.append("    return dec%s(d);" % root)
        o.append("  }")
    o.append("}")
    o.append("")
    return "\n".join(o)
