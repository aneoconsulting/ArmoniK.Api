#!/usr/bin/env python3
"""The java slice's generator: glue over the ONE generator (FIX-PLAN WP5 step 3).

Every generated codec, binding, layout, header and shim of this slice is rendered by the
Java backend in `poc/codec/gen/` (`java_backend.py` and the `java_*.py` modules it lists)
from `plan.py`'s plans. This file decides WHICH descriptions and roots are rendered and
WHERE the files go, and renders the slice's own harness glue (payload builders, arm
dispatchers, the corpus projection), which reads the plan's descriptor view and holds no
wire rule, no IR and no layout derivation (CLAUDE.md, one generator).

It writes under `poc/java/` only. Before WP5 it also wrote the core's `codec.rs` and
`layout.rs` into `poc/codec/`; it no longer writes any core-owned file -- the core is
generated by `poc/codec/gen/generate.py` alone, and `--check` here verifies that the core
this slice builds against is the one that generator commits.

Two descriptions:
  shapes  ffi/schema/shapes.json, the seven roots every slice covers (the payload set)
          -> native/generated/, src/generated/{shared,java17,java8}/
  corpus  ffi/corpus's reader schema: arm R over EVERY corpus message; the binding over
          the roots the C ABI can carry (plan.expressible_roots: `Nest` is refused), built
          against the core's `corpus` feature
          -> native/generated_corpus/, src/generated_corpus/{shared,java17,java8}/

  gen/generate.py            write the generated files
  gen/generate.py --check    fail if a committed file is stale, if the core's committed
                             generated files are stale against poc/codec/gen, or if a Java
                             backend module imports the IR or a schema (WP5 item 7)
"""
import importlib.util
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# AK_CODECGEN: render from another copy of poc/codec/gen (e.g. a `git archive` snapshot of
# the committed one, while another agent has the working tree mid-change); the default is
# the working tree.
CODECGEN = os.environ.get("AK_CODECGEN") or os.path.abspath(os.path.join(HERE, "..", "..", "codec", "gen"))
# THIS directory first: poc/codec/gen also has a `generate.py`.
sys.path.insert(0, CODECGEN)
sys.path.insert(0, HERE)

import plan as P             # noqa: E402  the ONE rule layer
import java_backend          # noqa: E402  the Java backend (poc/codec/gen)
import java_names as N       # noqa: E402
import java_build            # noqa: E402  glue: payload builder over the facade
import java_pbbuild          # noqa: E402  glue: payload builder over protoc's classes
import java_arms             # noqa: E402  glue: payload -> arm R dispatch
import pbarms                # noqa: E402  glue: payload -> protobuf-java dispatch
import java_ffiarms          # noqa: E402  glue: payload -> binding dispatch
import java_corpus           # noqa: E402  glue: corpus dispatch and projection
import java_walk             # noqa: E402  glue: campaign decode-and-read walkers

ROOT = os.path.dirname(HERE)

# The same roots as every other slice (poc/codec/gen/generate.py ROOTS).
ROOTS = [
    "ListResultsResponse",          # M1
    "ListTasksDetailedResponse",    # M2
    "ListProbeResponse",            # M3
    "ListTaskSummaryResponse",      # M4, the adapter site
    "UploadResultDataMessage",      # M5, bulk bytes
    "ListMetricsResponse",          # M6, packed scalars (control) and a packed enum (not)
    "DualResponse",                 # M7, control, decode only
]

LEVELS = java_backend.LEVELS

# The slice's generator glue (the corpus DRIVER, gen/corpus.py, reads the manifest and is
# not a generator module).
GLUE = ["generate.py", "java_build.py", "java_pbbuild.py", "java_arms.py", "pbarms.py",
        "java_ffiarms.py", "java_corpus.py", "java_walk.py"]


def shapes_targets():
    p = P.load(ROOTS)
    out = java_backend.emit(p, pkg="ak.shapes", entry="ak.NativeEntry",
                            java_root="src/generated", native_dir="native/generated",
                            shared_dir="src/generated/shared", floor_pkg="ak.floor",
                            borrow_pkg="ak.borrow")
    for level_dir, _level in LEVELS:
        d = "src/generated/%s/ak/shapes" % level_dir
        out["%s/Build.java" % d] = java_build.emit(p)
        out["%s/PbBuild.java" % d] = java_pbbuild.emit(p)
        out["%s/Arms.java" % d] = java_arms.emit(p)
        out["%s/PbArms.java" % d] = pbarms.emit(p)
        out["%s/FfiArms.java" % d] = java_ffiarms.emit(p)
        out["%s/Walk.java" % d] = java_walk.emit_walk(p, "ak.shapes")
        out["%s/PbWalk.java" % d] = java_walk.emit_pbwalk(p, "ak.shapes")
        out["src/generated/%s/ak/floor/FfiArms.java" % level_dir] = java_ffiarms.emit(
            p, ns="ak.floor", facade=N.PKG)
        with N.string_type_as("ak.Utf8View"):
            out["src/generated/%s/ak/borrow/FfiArms.java" % level_dir] = java_ffiarms.emit(
                p, ns="ak.borrow")
    return out


def corpus_plans():
    names = P.corpus_messages()
    full = P.load_corpus(names)
    ok, refused = P.expressible_roots(names, full)
    return full, P.load_corpus(ok), refused


def corpus_targets():
    full, pa, _refused = corpus_plans()
    out = java_backend.emit(full, pkg="ak.corpus", entry="ak.corpus.NativeEntry",
                            java_root="src/generated_corpus", native_dir="native/generated_corpus",
                            shared_dir="src/generated_corpus/shared", borrow_pkg="ak.corpus.borrow",
                            pa=pa)
    for level_dir, _level in LEVELS:
        d = "src/generated_corpus/%s/ak/corpus" % level_dir
        out["%s/Project.java" % d] = java_corpus.emit_project(full, "ak.corpus")
        out["%s/Dispatch.java" % d] = java_corpus.emit_dispatch(full, pa, "ak.corpus")
        out["%s/Walk.java" % d] = java_walk.emit_walk(full, "ak.corpus")
        with N.string_type_as("ak.Utf8View"):
            out["%s/borrow/Project.java" % d] = java_corpus.emit_project(full, "ak.corpus.borrow")
            out["%s/borrow/Dispatch.java" % d] = java_corpus.emit_dispatch(
                full, pa, "ak.corpus.borrow", owning=False)
    return out


def targets():
    out = shapes_targets()
    out.update(corpus_targets())
    for rel in out:
        assert not rel.startswith(".."), "this generator writes under poc/java only: %s" % rel
    return out


def guard():
    """WP5 item 7 for the Java backend: poc/codec/gen/generate.py's own rule (a backend
    imports plans, never the IR or a schema), applied to the Java modules, with its own
    planted violation seen failing. Loaded by path: both directories have a generate.py."""
    spec = importlib.util.spec_from_file_location("codec_generate",
                                                  os.path.join(CODECGEN, "generate.py"))
    cg = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cg)
    sources = {b: open(os.path.join(CODECGEN, b)).read() for b in java_backend.BACKEND_MODULES}
    bad = cg.guard_violations(sources)
    caught = cg.guard_violations({"planted.py": "import ir as IR\nfrom shapes import load\n"})
    # The slice's own glue must not reach for the IR either.
    glue = {f: open(os.path.join(HERE, f)).read() for f in GLUE}
    gbad = {k: v for k, v in cg.guard_violations(glue).items()}
    return bad, gbad, caught.get("planted.py") == ["ir", "shapes"]


def main(argv):
    check = "--check" in argv
    bad = 0
    if check:
        vb, gb, caught = guard()
        for mod, hit in sorted(vb.items()):
            print("GUARD poc/codec/gen/%s imports %s" % (mod, ", ".join(hit)))
            bad += 1
        for mod, hit in sorted(gb.items()):
            print("GUARD poc/java/gen/%s imports %s" % (mod, ", ".join(hit)))
            bad += 1
        if not caught:
            print("GUARD the planted violation was NOT caught")
            bad += 1
        if not vb and not gb and caught:
            print("guard %d Java backend modules and the slice glue import plans only; a planted"
                  " IR import is caught" % len(java_backend.BACKEND_MODULES))
        # The core this slice links is the one poc/codec/gen commits: its --check, run as is.
        r = subprocess.run([sys.executable, os.path.join(CODECGEN, "generate.py"), "--check", "--core-only"],
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        stale = [ln for ln in r.stdout.decode().splitlines() if ln.startswith(("STALE", "GUARD"))]
        print("core  poc/codec/gen/generate.py --check --core-only: exit %d%s" % (
            r.returncode, "" if not stale else " (" + "; ".join(stale) + ")"))
        if r.returncode != 0:
            bad += 1
    for rel, text in sorted(targets().items()):
        path = os.path.join(ROOT, rel)
        old = open(path).read() if os.path.exists(path) else None
        if check:
            if old != text:
                print("STALE %s" % rel)
                bad += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if old != text:
                open(path, "w").write(text)
                print("wrote %s  (%d lines)" % (rel, text.count("\n") + 1))
    if check:
        print("checked %d generated files, %d problem(s)" % (len(targets()), bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
