"""The Java facade: hand-written-shaped, idiomatic types, emitted from one description.

R1: the facade is generated so that the arms cannot drift, but its SHAPE is the shape a
Java author would write by hand -- plain classes, public fields, `null` for an absent
child, `java.util.List` for a repeated field. The point of the exploration is that the
facade stays hand-written and idiomatic while the binding is generated; emitting it here
is a measurement convenience and the report says so.
"""
import javanames as N

HEAD = ("// @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")


def _pkg(ns):
    return "package %s;\n" % ns


def emit_enums(ir, ns=N.PKG):
    """One `public final class` of `int` constants per enum, plus the declared-value table
    the payload builder cycles through.

    Not a Java `enum`: design/SHAPES.md requires `status = 999` to survive a round trip as
    an unrecognised value, and a Java enum cannot carry one. protobuf-java hits the same
    wall and answers it the same way, with an `int` accessor beside the enum one.
    """
    out = {}
    for ename in ir.enum_order:
        o = [HEAD, _pkg(ns), "",
             "/** %s. An `int`, not a Java enum: an open enum must be able to hold a" % ename,
             " *  value the reader was not built against, and 999 has to round-trip. */",
             "public final class %s {" % ename,
             "  private %s() {}" % ename]
        vals = []
        for vname, v in ir.enums[ename]["values"].items():
            o.append("  public static final int %s = %d;" % (N.const(ename, vname), v))
            vals.append(v)
        o.append("")
        o.append("  /** The declared values in declaration order, which is what")
        o.append("   *  `values.enumValue()` cycles through. */")
        o.append("  public static final int[] DECLARED = {%s};" % ", ".join(str(v) for v in vals))
        o.append("}")
        o.append("")
        out["%s.java" % ename] = "\n".join(o)
    return out


def emit_types(ir, ns=N.PKG):
    """One file per message."""
    out = {}
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        o = [HEAD, _pkg(ns), ""]
        src = m.raw.get("source", "")
        if src:
            o.append("/** %s */" % src)
        o.append("public final class %s {" % name)
        o.append("  static final byte[] EMPTY_BYTES = new byte[0];")
        o.append("  static final int[] EMPTY_I32 = new int[0];")
        o.append("  static final long[] EMPTY_I64 = new long[0];")
        o.append("  static final double[] EMPTY_F64 = new double[0];")
        o.append("  static final boolean[] EMPTY_BOOL = new boolean[0];")
        o.append("")
        for f in m.plain:
            if f.oneof:
                continue
            o.append("  public %s %s%s;" % (N.facade_type(f), f.name, N.facade_init(f)))
            if N.has_flag(f):
                o.append("  public boolean has_%s;" % f.name)
        for oname, members in m.oneofs.items():
            o.append("")
            o.append("  /** oneof `%s`: a case tag plus one slot per member." % oname)
            o.append("   *  ABI v1 section 6 inlines every member flat rather than as a")
            o.append("   *  union, and the facade mirrors that so the fill is a straight")
            o.append("   *  copy. `%s_CASE_NONE` is no member set. */" % N.screaming(oname))
            o.append("  public static final int %s_CASE_NONE = 0;" % N.screaming(oname))
            for g in members:
                o.append("  public static final int %s_CASE_%s = %d;"
                         % (N.screaming(oname), N.screaming(g.name), g.tag))
            o.append("  public int %s_case;" % oname)
            for g in members:
                gt = ("byte[]" if g.kind == "bytes" else N.string_type() if g.kind == "string"
                      else g.of if g.kind == "message" else N.FSCALAR[g.kind])
                init = (" = EMPTY_BYTES" if g.kind == "bytes"
                        else " = null" if g.kind in ("string", "message")
                        else " = %s" % N.ZERO[g.kind])
                o.append("  public %s %s_%s%s;" % (gt, oname, g.name, init))
        o.append("}")
        o.append("")
        out["%s.java" % name] = "\n".join(o)
    return out
