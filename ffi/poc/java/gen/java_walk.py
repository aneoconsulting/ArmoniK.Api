"""Campaign glue: "decode followed by reading every field" (design/CAMPAIGN.md req 9).

Two readers of the same description, generated so neither arm reads less than the other:
  Walk    over the facade (arm R, core-ffi, core-ffi-pull);
  PbWalk  over protoc's classes (incumbent-prod, incumbent-best).
Every present field is read: a scalar's value, a string's length (for protobuf-java that is
the lazy UTF-8 decode the facade arms paid at decode time), a bytes field's length, every
element of every repeated field and every map entry, the active oneof member. Harness
glue, no wire rule; reads the plan's descriptor view.
"""
import java_names as N

HEAD = "// @generated by ffi/poc/java/gen/java_walk.py (campaign glue). Do not edit.\n"


def _fac_val(f, v):
    k = f.kind
    if k in ("string",):
        return "h += %s.length();" % v
    if k == "bytes":
        return "h += %s.length;" % v
    if k == "bool":
        return "h += %s ? 1 : 0;" % v
    if k == "double":
        return "h += Double.doubleToRawLongBits(%s);" % v
    if k == "message":
        return "h += w%s(%s);" % (f.of, v)
    return "h += %s;" % v


def emit_walk(p, ns):
    o = [HEAD, "package %s;" % ns, "",
         "/** Read every field of a decoded facade value (CAMPAIGN.md req 9). */",
         "public final class Walk {", "  private Walk() {}", "",
         "  public static long walk(String root, Object o) {", "    switch (root) {"]
    names = [n for n in p.order if not p.msg(n).synthetic]
    for n in names:
        o.append("      case \"%s\": return w%s((%s) o);" % (n, n, n))
    o += ["      default: throw new IllegalArgumentException(root);", "    }", "  }"]
    for n in names:
        m = p.msg(n)
        o.append("")
        o.append("  static long w%s(%s o) {" % (n, n))
        o.append("    long h = 0;")
        for f in m.plain:
            v = "o.%s" % f.name
            if f.card == "map":
                o.append("    for (java.util.Map.Entry<String, String> e : %s.entrySet())"
                         " h += e.getKey().length() + e.getValue().length();" % v)
            elif f.card == "packed":
                el = "%s[i]" % v
                o.append("    for (int i = 0; i < %s.length; i++) { %s }" % (v, _fac_val(f, el)))
            elif f.card == "repeated":
                o.append("    for (%s x : %s) { %s }" % (N.elem_type_java(f), v, _fac_val(f, "x")))
            elif f.kind == "message" or (f.explicit and f.kind in ("string", "bytes")):
                o.append("    if (%s != null) { %s }" % (v, _fac_val(f, v)))
            else:
                o.append("    %s" % _fac_val(f, v))
        for oname, members in m.oneofs.items():
            o.append("    switch (o.%s_case) {" % oname)
            for g in members:
                mv = "o.%s_%s" % (oname, g.name)
                guard = "if (%s != null) " % mv if g.kind in ("string", "bytes", "message") else ""
                o.append("      case %d: %s{ %s } break;" % (g.tag, guard, _fac_val(g, mv)))
            o.append("      default: break;")
            o.append("    }")
        o.append("    return h;")
        o.append("  }")
    o += ["}", ""]
    return "\n".join(o)


def _pb_get(f, idx=None):
    c = N.camel(f.name)
    if f.kind == "enum":
        return "m.get%sValue(%s)" % (c, idx or "")
    return "m.get%s(%s)" % (c, idx or "")


def _pb_val(f, v):
    k = f.kind
    if k == "string":
        return "h += %s.length();" % v
    if k == "bytes":
        return "h += %s.size();" % v
    if k == "bool":
        return "h += %s ? 1 : 0;" % v
    if k == "double":
        return "h += Double.doubleToRawLongBits(%s);" % v
    if k == "message":
        return "h += w%s(%s);" % (f.of, v)
    return "h += %s;" % v


def emit_pbwalk(p, ns):
    o = [HEAD, "package %s;" % ns, "",
         "/** Read every field of a decoded protobuf-java message (CAMPAIGN.md req 9). */",
         "public final class PbWalk {", "  private PbWalk() {}", "",
         "  public static long walk(String root, Object o) {", "    switch (root) {"]
    names = [n for n in p.order if not p.msg(n).synthetic]
    for n in names:
        o.append("      case \"%s\": return w%s((ak.pb.%s) o);" % (n, n, n))
    o += ["      default: throw new IllegalArgumentException(root);", "    }", "  }"]
    for n in names:
        m = p.msg(n)
        o.append("")
        o.append("  static long w%s(ak.pb.%s m) {" % (n, n))
        o.append("    long h = 0;")
        for f in m.plain:
            c = N.camel(f.name)
            if f.card == "map":
                o.append("    for (java.util.Map.Entry<String, String> e : m.get%sMap().entrySet())"
                         " h += e.getKey().length() + e.getValue().length();" % c)
            elif f.card in ("packed", "repeated"):
                o.append("    for (int i = 0, n = m.get%sCount(); i < n; i++) { %s }"
                         % (c, _pb_val(f, _pb_get(f, "i"))))
            elif f.kind == "message":
                o.append("    if (m.has%s()) { %s }" % (c, _pb_val(f, "m.get%s()" % c)))
            elif f.explicit:
                o.append("    if (m.has%s()) { %s }" % (c, _pb_val(f, _pb_get(f))))
            else:
                o.append("    %s" % _pb_val(f, _pb_get(f)))
        for oname, members in m.oneofs.items():
            o.append("    switch (m.get%sCase().getNumber()) {" % N.camel(oname))
            for g in members:
                o.append("      case %d: { %s } break;" % (g.tag, _pb_val(g, _pb_get(g))))
            o.append("      default: break;")
            o.append("    }")
        o.append("    return h;")
        o.append("  }")
    o += ["}", ""]
    return "\n".join(o)
