"""The payload builder over the Java facade types.

Mirrors `ffi/schema/emit/payloads.py` -- which value goes in which field, which fields the
absent-path modes remove, how explicit presence cycles, how the adapter's three states are
cycled -- and calls `ak.Values`. Generated rather than written, so the arms' objects and
the manifest's bytes cannot drift, and so that the protobuf-java arm (whose builder is
`PbBuild`, constructed independently over protoc's own types) and the facade arms reach
their values by two routes.
"""
import java_names as N

HEAD = ("// @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

VALUE_FN = {"guid": "Values.guid", "word": "Values.word", "sentence": "Values.sentence"}


def absent_expr(f):
    """`absent()` in emit/payloads.py. The precedence matters: `all_absent` drops EVERY
    field and the `half_absent` rules are checked only after that."""
    if f.adapter_site == "nested" or (f.kind == "message" and f.of == "Timestamp"
                                      and f.tag % 2 == 0):
        return "(mode == ALL_ABSENT || mode == HALF_ABSENT)"
    return "(mode == ALL_ABSENT)"


def _cs(expr):
    """Every string the builder produces goes through the content set, so an arm that
    touches the string path can be re-measured on Latin-1 or above U+00FF without a second
    builder. `Values.recode` is the identity on the ASCII set, which is what the manifest
    pins and what every correctness check runs on."""
    return "Values.recode(%s, cs)" % expr


def _string_expr(f, path, idx="idx"):
    return _cs("%s(%s, (int) (%s))" % (VALUE_FN[f.value_rule], path, idx))


def _scalar_expr(f, path, idx="idx"):
    fn = {"int32": "Values.scalarI32", "int64": "Values.scalarI64",
          "bool": "Values.scalarBool", "double": "Values.scalarDouble"}[f.kind]
    return "%s(%s, (int) (%s))" % (fn, path, idx)


def _msg_call(f, path, idx="idx"):
    if f.of == "Timestamp":
        return "mkTimestamp((int) (%s))" % idx
    if f.of == "Duration":
        return "mkDuration((int) (%s))" % idx
    return "build%s(%s, %s, mode, repeats, bulk, cs)" % (f.of, path, idx)


def _emit_field(m, f, o):
    fp = '(path + ".%s")' % f.name
    dst = "r.%s" % f.name

    if f.adapter_site == "nested":
        o.append("    if (!%s) {" % absent_expr(f))
        o.append("      switch (adapterState(idx)) {")
        o.append("        case ADAPTER_INVALID: break;")
        o.append("        case ADAPTER_OK: {")
        o.append("          %s = new %s();" % (dst, f.of))
        o.append("          %s.success = true;" % dst)
        o.append("          break;")
        o.append("        }")
        o.append("        default: {")
        o.append("          %s = new %s();" % (dst, f.of))
        o.append("          %s.error = %s;" % (dst, _cs('Values.sentence(path + ".%s.error", (int) idx)' % f.name)))
        o.append("          break;")
        o.append("        }")
        o.append("      }")
        o.append("    }")
        return
    if f.adapter_site == "plain":
        o.append("    if (!%s && adapterState(idx) == ADAPTER_ERROR) %s = %s;"
                 % (absent_expr(f), dst, _string_expr(f, fp)))
        return

    o.append("    if (!%s) {" % absent_expr(f))
    if f.card == "map":
        n = f.raw.get("entries", 4)
        o.append("      for (int k = 0; k < %d; k++) {" % n)
        o.append("        String key = pad2(k) + %s;"
                 % _cs('Values.word(path + ".%s.key", idx * 31 + k)' % f.name))
        o.append("        String val = \"\";")
        o.append("        if (!(mode == HALF_ABSENT && k % 2 == 0))")
        o.append("          val = %s;" % _cs('Values.word(path + ".%s.value", idx * 31 + k)' % f.name))
        o.append("        %s.put(%s, %s);" % (dst, _wrap("key"), _wrap("val")))
        o.append("      }")
    elif f.card == "packed":
        n = f.raw.get("count", 30)
        jty = {"int32": "int", "int64": "long", "bool": "boolean",
               "double": "double", "enum": "int"}[f.kind]
        o.append("      %s = new %s[%d];" % (dst, jty, n))
        o.append("      for (int j = 0; j < %d; j++)" % n)
        if f.kind == "enum":
            o.append("        %s[j] = Values.enumValue(%s.DECLARED, idx * 97 + j);"
                     % (dst, f.of))
        else:
            o.append("        %s[j] = %s;" % (dst, _scalar_expr(f, fp, "idx * 97 + j")))
    elif f.card == "repeated" and f.kind == "string":
        o.append("      for (int j = 0; j < repeats; j++)")
        o.append("        %s.add(%s);" % (dst, _wrap(_string_expr(f, fp, "idx * 211 + j"))))
    elif f.card == "repeated" and f.kind == "message":
        o.append("      for (int j = 0; j < repeats; j++)")
        o.append("        %s.add(%s);" % (dst, _msg_call(f, fp, "j")))
    elif f.card == "singular" and f.kind == "message":
        o.append("      %s = %s;" % (dst, _msg_call(f, fp)))
    elif f.card == "singular" and f.kind == "string":
        if f.explicit:
            o.append("      if (explicitPresent(%d, idx))" % f.tag)
            o.append("        %s = %s;" % (dst, _wrap('idx %% 7 == 0 ? "" : %s' % _string_expr(f, fp))))
        else:
            o.append("      %s = %s;" % (dst, _wrap(_string_expr(f, fp))))
    elif f.card == "singular" and f.kind == "bytes":
        if f.value_rule == "bulk":
            o.append("      %s = Values.bulk(bulk);" % dst)
        else:
            o.append("      %s = Values.blob(%s, (int) idx, 16);" % (dst, fp))
    elif f.card == "singular" and f.kind == "enum":
        o.append("      %s = Values.enumValue(%s.DECLARED, (int) idx);" % (dst, f.of))
    elif f.card == "singular" and f.is_scalar_leaf:
        if f.explicit:
            o.append("      if (explicitPresent(%d, idx)) {" % f.tag)
            o.append("        %s = idx %% 7 == 0 ? %s : %s;"
                     % (dst, N.ZERO[f.kind], _scalar_expr(f, fp)))
            o.append("        r.has_%s = true;" % f.name)
            o.append("      }")
        else:
            o.append("      %s = %s;" % (dst, _scalar_expr(f, fp)))
    else:
        # R1: a backend with no case for a shape RAISES; it does not skip. The cpp slice
        # learned this here exactly: without re-testing cardinality a repeated `bytes`
        # falls into the singular-`bytes` arm and emits a scalar store against a list.
        raise NotImplementedError(
            "REFUSED: the facade payload builder has no case for %s.%s (card=%s kind=%s)"
            % (m.name, f.name, f.card, f.kind))
    o.append("    }")


def _wrap(expr):
    """The borrowed facade holds a view rather than a `String`, so the builder wraps. The
    ASCII content set is what the manifest pins and what the builder produces, so the
    conversion is `Utf8View.of`, never a re-encode."""
    return expr if not N.is_borrow() else "%s.of(%s)" % (N.string_type(), expr)


def _oneof_value(msg, g, dst):
    path = '"%s.%s"' % (msg, g.name)
    if g.kind == "string":
        return "%s = %s;" % (dst, _wrap(_cs("Values.word(%s, (int) idx)" % path)))
    if g.kind == "bytes":
        return "%s = Values.blob(%s, (int) idx, 16);" % (dst, path)
    if g.kind == "int64":
        return "%s = Values.scalarI64(%s, (int) idx);" % (dst, path)
    if g.kind == "int32":
        return "%s = Values.scalarI32(%s, (int) idx);" % (dst, path)
    if g.kind == "message" and g.of == "Empty":
        return "%s = new Empty();" % dst
    if g.kind == "message":
        return "%s = mkTimestamp((int) idx);" % dst
    raise NotImplementedError("oneof member %s" % g.kind)


PRE = '''/** Build any payload of shapes.json as facade values. */
public final class Build {
  private Build() {}

  public static final int FULL = 0, ALL_ABSENT = 1, HALF_ABSENT = 2;
  public static final int ADAPTER_ERROR = 0, ADAPTER_OK = 1, ADAPTER_INVALID = 2;

  /** Presence cycles per field, and one element in seven is present AND zero, which a
   *  by-value group cannot tell from absent unless it is designed to. */
  static boolean explicitPresent(int tag, int idx) {
    return idx % (tag + 1) != 0;
  }

  /** Cycled Error, Ok, Invalid rather than 0,1,2 so element 0 is Error: `half_absent`
   *  removes the nested site and P2.5 keeps a written one first. */
  static int adapterState(int idx) {
    switch (idx % 3) {
      case 0: return ADAPTER_ERROR;
      case 1: return ADAPTER_OK;
      default: return ADAPTER_INVALID;
    }
  }

  /** `"k%02d-"`, without String.format: on JDK 21 and later one String.format with a
   *  numeric conversion permanently deoptimises every char narrowing loop in the process
   *  (README R9), and protobuf-java's own encoder is such a loop. The builder runs in the
   *  same process as the benchmark. */
  static String pad2(int k) {
    return "k" + (k < 10 ? "0" : "") + k + "-";
  }

  static Timestamp mkTimestamp(int idx) {
    Timestamp t = new Timestamp();
    t.seconds = Values.stampSeconds(idx);
    t.nanos = Values.stampNanos(idx);
    return t;
  }

  static Duration mkDuration(int idx) {
    Duration t = new Duration();
    t.seconds = Values.durSeconds(idx);
    t.nanos = Values.durNanos(idx);
    return t;
  }
'''


def emit(ir, ns=N.PKG):
    o = [HEAD, "package %s;" % ns, "", "import ak.Values;", "", PRE]
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic:
            continue
        o.append("")
        o.append("  public static %s build%s(String path, int idx, int mode, int repeats,"
                 " int bulk, int cs) {" % (name, name))
        o.append("    %s r = new %s();" % (name, name))
        for f in m.plain:
            if f.oneof:
                continue
            _emit_field(m, f, o)
        for oname, members in m.oneofs.items():
            o.append("    switch (idx %% %d) {" % len(members))
            for i, g in enumerate(members):
                arm = "case %d:" % i if i < len(members) - 1 else "default:"
                o.append("      %s {" % arm)
                o.append("        r.%s_case = %s.%s_CASE_%s;"
                         % (oname, name, N.screaming(oname), N.screaming(g.name)))
                o.append("        %s" % _oneof_value(name, g, "r.%s_%s" % (oname, g.name)))
                o.append("        break;")
                o.append("      }")
            o.append("    }")
        o.append("    return r;")
        o.append("  }")

    o.append("")
    o.append("  // ---- the payload set ------------------------------------------------")
    ids = []
    for pid, spec in ir.payloads.items():
        root = spec["root"]
        if root not in ir.messages:
            continue
        m = ir.msg(root)
        fn = "payload" + pid.replace(".", "_")
        if spec.get("interleaved"):
            o.append("")
            o.append("  // %s has no builder: no canonical writer can produce it, so M7 is" % pid)
            o.append("  // validated by DECODE (design/SHAPES.md, P7.1's row).")
            continue
        ids.append(pid)
        o.append("")
        o.append("  /** %s: %s, %s. */" % (pid, root, spec.get("mode", "full")))
        o.append("  public static %s %s(int cs) {" % (root, fn))
        o.append("    %s r = new %s();" % (root, root))
        if "bulk" in spec:
            f = m.plain[0]
            o.append("    r.%s = build%s(\"%s\", 0, FULL, 3, %d, cs);"
                     % (f.name, f.of, f.of, spec["bulk"]))
        else:
            field = next(f for f in m.plain if f.name == spec["field"])
            reps = spec.get("repeats", 3)
            reps = reps if isinstance(reps, list) else [reps]
            o.append("    final int[] kReps = {%s};" % ", ".join(str(r) for r in reps))
            mode = {"all_absent": "ALL_ABSENT", "half_absent": "HALF_ABSENT"}.get(
                spec.get("mode"), "FULL")
            o.append("    for (int j = 0; j < %d; j++)" % spec["count"])
            o.append("      r.%s.add(build%s(\"%s\", j, %s, kReps[j %% %d], 0, cs));"
                     % (field.name, field.of, field.of, mode, len(reps)))
            for f in m.plain:
                if f.name == "page":
                    o.append("    r.page = 1;")
                elif f.name == "total":
                    o.append("    r.total = %d;" % spec["count"])
        o.append("    return r;")
        o.append("  }")
    o.append("")
    o.append("  /** Every payload this build covers, by the id design/SHAPES.md uses. */")
    o.append("  public static final String[] COVERED = {%s};"
             % ", ".join('"%s"' % p for p in ids))
    o.append("}")
    o.append("")
    return "\n".join(o)
