HEAD = ("/* @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit. */\n")

PRE = r'''
#include <jni.h>
#include <stdint.h>
#include <string.h>

#include "ak_abi.h"

/* ABI v1 section 4 specifies five transcoders. The core implemented the two a UTF-8 host
 * needs, and `cpp_header.py` -- which this slice imports read-only so the three hosts
 * share one header -- declares those two. A JVM host holds UTF-16, so it reaches the two
 * the specification wrote for it and no slice had needed before. Declared here rather than
 * by editing a header another slice owns. */
ak_transcode_fn ak_tc_utf16(void);
ak_transcode_fn ak_tc_latin1(void);

/* ---- the reverse-call context ----------------------------------------------------
 *
 * A trampoline has to find the JNIEnv and the Binding instance, and the ABI hands it
 * neither: `ak_loop_f` takes the host's own `obj`, which on the JVM cannot be a Java
 * reference because a reference is not an address the codec may hold across a call.
 *
 * So the entry points push a frame and pop it, and the frame is THREAD LOCAL, never a
 * static. The slice's brief calls re-entrancy the thing to settle before anything is
 * trusted, and a static here would make two encoding threads share one Binding -- a wrong
 * byte under contention, which is the bad failure mode the rust slice names.
 *
 * A stack rather than a single slot because an entry point may be reached from inside a
 * reverse call in principle. Nothing in this slice does that; the depth is 8 and an
 * overflow is reported rather than wrapped, so if something ever does, it says so. */
typedef struct {
  JNIEnv *env;
  jobject self;
} ak_frame;

#define AK_DEPTH 8
static __thread ak_frame g_stack[AK_DEPTH];
static __thread int g_depth;

static jclass g_binding_cls;
static jmethodID g_encLoop, g_decApply, g_decNew, g_decApplyElem, g_decAdd;

static inline int ak_push(JNIEnv *env, jobject self) {
  if (g_depth >= AK_DEPTH) return 0;
  g_stack[g_depth].env = env;
  g_stack[g_depth].self = self;
  g_depth++;
  return 1;
}

static inline void ak_pop(void) { if (g_depth > 0) g_depth--; }

static inline ak_frame *ak_top(void) { return &g_stack[g_depth - 1]; }

/* ABI v1 section 5: an exception crossing `extern "C"` into Rust is undefined behaviour,
 * so a throw becomes `ak_fail` plus a return. The Java side also wraps its own body in a
 * try/catch, which is free until it throws; this is the half that catches what JNI itself
 * can raise, and it is one load and one predictable branch. */
#ifdef AK_NO_GUARD
#define AK_GUARD(env, ctx) ((void) 0)
#else
#define AK_GUARD(env, ctx)                                                       \
  do {                                                                           \
    if ((*(env))->ExceptionCheck(env)) {                                         \
      static const char kMsg[] = "host exception in a reverse call";             \
      (*(env))->ExceptionClear(env);                                             \
      ak_fail((ctx), AK_ERR_HOST, (const uint8_t *) kMsg, (uint32_t)(sizeof(kMsg) - 1)); \
    }                                                                            \
  } while (0)
#endif

/* AK_CROSSING_TAX: the cpp slice's most portable measurement, lifted rather than
 * re-derived. A calibrated delay in front of every FORWARD entry-point call prices the
 * crossing up, so the batching predicate's crossover can be reported as a number. Compiled
 * in only by the tax build. */
#ifdef AK_CROSSING_TAX
void ak_crossing_tax(void);
#define AK_TAX() ak_crossing_tax()
#else
#define AK_TAX() ((void) 0)
#endif

JNIEXPORT void JNICALL Java_ak_Native_bind(JNIEnv *env, jclass cls, jclass binding) {
  (void) cls;
  g_binding_cls = (*env)->NewGlobalRef(env, binding);
  g_encLoop = (*env)->GetMethodID(env, binding, "encLoop", "(JIJ)I");
  g_decApply = (*env)->GetMethodID(env, binding, "decApply", "(JIJ)V");
  g_decNew = (*env)->GetMethodID(env, binding, "decNew", "(JI)J");
  g_decApplyElem = (*env)->GetMethodID(env, binding, "decApplyElem", "(JIJJ)V");
  g_decAdd = (*env)->GetMethodID(env, binding, "decAdd", "(JIJJI)V");
}
'''

TRAMP = r'''
/* ---- the trampolines --------------------------------------------------------------
 *
 * One per slot, because a vtable slot is a distinct address and that address is how the
 * codec says which field it is calling about. The slot index is a compile-time constant in
 * each, so the upcall carries it without a lookup. */

static inline int32_t ak_enc_loop(ak_enc_ctx *ctx, int32_t slot, int64_t token) {
  ak_frame *f = ak_top();
  JNIEnv *env = f->env;
  jint rc = (*env)->CallIntMethod(env, f->self, g_encLoop, (jlong)(intptr_t) ctx,
                                  (jint) slot, (jlong) token);
  AK_GUARD(env, ctx);
  return (int32_t) rc;
}

static inline void ak_dec_apply(ak_dec_ctx *ctx, int32_t slot, const void *fix) {
  ak_frame *f = ak_top();
  JNIEnv *env = f->env;
  (*env)->CallVoidMethod(env, f->self, g_decApply, (jlong)(intptr_t) ctx, (jint) slot,
                         (jlong)(intptr_t) fix);
  AK_GUARD(env, ctx);
}

static inline int64_t ak_dec_new(ak_dec_ctx *ctx, int32_t slot) {
  ak_frame *f = ak_top();
  JNIEnv *env = f->env;
  jlong t = (*env)->CallLongMethod(env, f->self, g_decNew, (jlong)(intptr_t) ctx,
                                   (jint) slot);
  AK_GUARD(env, ctx);
  return (int64_t) t;
}

static inline void ak_dec_apply_elem(ak_dec_ctx *ctx, int32_t slot, int64_t token,
                                     const void *fix) {
  ak_frame *f = ak_top();
  JNIEnv *env = f->env;
  (*env)->CallVoidMethod(env, f->self, g_decApplyElem, (jlong)(intptr_t) ctx, (jint) slot,
                         (jlong) token, (jlong)(intptr_t) fix);
  AK_GUARD(env, ctx);
}

static inline void ak_dec_add(ak_dec_ctx *ctx, int32_t slot, int64_t token,
                              const void *elems, int32_t n) {
  ak_frame *f = ak_top();
  JNIEnv *env = f->env;
  (*env)->CallVoidMethod(env, f->self, g_decAdd, (jlong)(intptr_t) ctx, (jint) slot,
                         (jlong) token, (jlong)(intptr_t) elems, (jint) n);
  AK_GUARD(env, ctx);
}
'''


def _jname(sym):
    """JNI mangles an underscore in a Java method name, so the Java side spells every
    entry point in camel case and this maps to it."""
    return sym


def emit(ir):
    o = [HEAD, PRE, TRAMP]

    enc = S.enc_slots(ir)
    dec = S.dec_slots(ir)

    o.append("/* encode loop slots: %d */" % len(enc))
    for i, (msg, path, f) in enumerate(enc):
        o.append("static int32_t etr_%d(ak_enc_ctx *c, const void *o, int64_t t) {"
                 "  (void) o;  return ak_enc_loop(c, %d, t); }   /* %s.%s */"
                 % (i, i, msg, IR.slot_name(path)))
    o.append("static const ak_loop_f AK_ETR[] = {%s};"
             % ", ".join("etr_%d" % i for i in range(len(enc))))
    o.append("")

    kinds = {}
    for i, (msg, kind, sn, et) in enumerate(dec):
        kinds.setdefault(kind, []).append((i, msg, sn))
    o.append("/* decode callbacks: %d */" % len(dec))
    for i, (msg, kind, sn, et) in enumerate(dec):
        label = "%s.%s%s" % (msg, kind, (" " + sn) if sn else "")
        if kind == "apply":
            o.append("static void dtr_%d(ak_dec_ctx *c, void *o, const void *fx) {"
                     "  (void) o;  ak_dec_apply(c, %d, fx); }   /* %s */" % (i, i, label))
        elif kind == "new":
            o.append("static int64_t dtr_%d(ak_dec_ctx *c, void *o) {"
                     "  (void) o;  return ak_dec_new(c, %d); }   /* %s */" % (i, i, label))
        elif kind == "applyelem":
            o.append("static void dtr_%d(ak_dec_ctx *c, void *o, int64_t t, const void *fx) {"
                     "  (void) o;  ak_dec_apply_elem(c, %d, t, fx); }   /* %s */"
                     % (i, i, label))
        else:   # add, addinner
            o.append("static void dtr_%d(ak_dec_ctx *c, void *o, int64_t t, const void *e,"
                     " int32_t n) {  (void) o;  ak_dec_add(c, %d, t, e, n); }   /* %s */"
                     % (i, i, label))
    o.append("static const void *const AK_DTR[] = {%s};"
             % ", ".join("(const void *) dtr_%d" % i for i in range(len(dec))))
    o.append("")
    o.append("JNIEXPORT jlong JNICALL Java_ak_NativeEntry_encTrampoline(JNIEnv *e, jclass c, jint i) {")
    o.append("  (void) e; (void) c;  return (jlong)(intptr_t) AK_ETR[i];")
    o.append("}")
    o.append("")
    o.append("JNIEXPORT jlong JNICALL Java_ak_NativeEntry_decTrampoline(JNIEnv *e, jclass c, jint i) {")
    o.append("  (void) e; (void) c;  return (jlong)(intptr_t) AK_DTR[i];")
    o.append("}")
    o.append("")

    # ---- the forward entry points, one JNI native each
    o.append("/* ---- forward entry points: one JNI native each, never a dispatch table."
             "\n * The batching delta this slice measures is a difference in forward"
             "\n * crossing COUNTS, so a shared switch would inflate the thing measured. */")
    for root in ir.roots:
        direct = IR.direct_fields(ir, root)
        extra = ", jlong direct, jlong dlen" if direct else ""
        dargs = ", (const uint8_t *)(intptr_t) direct, (size_t) dlen" if direct else ""
        o.append("")
        o.append("JNIEXPORT jlong JNICALL Java_ak_NativeEntry_encode%s(JNIEnv *env,"
                 " jclass cls, jobject self, jlong ctx, jlong vt, jlong fix%s) {"
                 % (root, extra))
        o.append("  (void) cls;")
        o.append("  if (!ak_push(env, self)) return (jlong) AK_ERR_INVALID_STATE;")
        o.append("  AK_TAX();")
        o.append("  intptr_t rc = ak_encode_%s((const void *) (intptr_t) 1,"
                 " (ak_enc_ctx *)(intptr_t) ctx," % root)
        o.append("      (const struct ak_evt_%s *)(intptr_t) vt," % root)
        o.append("      (const struct ak_efix_%s *)(intptr_t) fix%s);" % (root, dargs))
        o.append("  ak_pop();")
        o.append("  return (jlong) rc;")
        o.append("}")
        o.append("")
        o.append("JNIEXPORT jint JNICALL Java_ak_NativeEntry_decode%s(JNIEnv *env,"
                 " jclass cls, jobject self, jlong ctx, jlong buf, jlong len, jlong vt) {"
                 % root)
        o.append("  (void) cls;")
        o.append("  if (!ak_push(env, self)) return (jint) AK_ERR_INVALID_STATE;")
        o.append("  AK_TAX();")
        o.append("  int32_t rc = ak_decode_%s((ak_dec_ctx *)(intptr_t) ctx,"
                 " (void *)(intptr_t) 1," % root)
        o.append("      (const uint8_t *)(intptr_t) buf, (size_t) len,")
        o.append("      (const struct ak_dvt_%s *)(intptr_t) vt);" % root)
        o.append("  ak_pop();")
        o.append("  return (jint) rc;")
        o.append("}")

    # element entry points
    seen = set()
    for name in ir.abi_order:
        for _p, f in IR.loop_slots(ir, name):
            et = RA.elem_type(f)
            if not et or et in seen:
                continue
            seen.add(et)
            leaf = ir.msg(et).leaf
            o.append("")
            if leaf:
                o.append("JNIEXPORT jint JNICALL Java_ak_NativeEntry_elem%s(JNIEnv *env,"
                         " jclass cls, jlong ctx, jlong elems, jint n) {" % et)
                o.append("  (void) env; (void) cls;")
                o.append("  AK_TAX();")
                o.append("  return (jint) ak_elem_%s((ak_enc_ctx *)(intptr_t) ctx," % et)
                o.append("      (const struct ak_efix_%s *)(intptr_t) elems, (int32_t) n);" % et)
                o.append("}")
            else:
                o.append("JNIEXPORT jint JNICALL Java_ak_NativeEntry_elemu%s(JNIEnv *env,"
                         " jclass cls, jlong ctx, jlong elems, jint n, jlong tok0) {" % et)
                o.append("  (void) env; (void) cls;")
                o.append("  AK_TAX();")
                o.append("  return (jint) ak_elemu_%s((ak_enc_ctx *)(intptr_t) ctx," % et)
                o.append("      (const struct ak_efix_%s *)(intptr_t) elems, (int32_t) n,"
                         " (int64_t) tok0);" % et)
                o.append("}")

    o.append(FIXED)
    return "\n".join(o)


