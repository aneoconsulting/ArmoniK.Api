"""The JNI shim: the C half of arm `core-ffi`.

ABI v1 section 2: "Everywhere this document says 'the host answers', read 'the binding
answers': the accessor contract is a contract with a binding, never with a host language."
On the JVM the binding has two halves, and this is the small one. It does three things and
deliberately no more:

1. **One JNI native per ABI entry point.** Not a switch on an index. A jump table would add
   a branch to an 11 ns forward crossing -- 10 to 18 percent of the thing being measured --
   and the batching delta this slice exists to measure is a difference between forward
   crossing counts.
2. **Trampolines for the reverse calls**, because a Java method has no address. ABI v1
   section 6 says the asymmetry is forced: "a function pointer is the only callable address
   .NET, the JVM and CPython can produce."
3. **The generated guard of ABI v1 section 5.** A Java exception escaping into Rust through
   `extern "C"` is undefined behaviour, so every trampoline checks and converts it to
   `ak_fail` plus a return. On by default; `-DAK_NO_GUARD` exists only to price it, because
   every published managed figure in the branch was measured without it.

What it does NOT do is read facade fields. A generated C shim speaking the JNI API the way
README 9.1 has Python's shim speak the CPython API is a different binding shape with a
different cost, and it is recorded in STATE.md as not measured rather than half-built.
"""
