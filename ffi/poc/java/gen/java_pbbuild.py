"""The payload builder over protoc's own Java types: the incumbent arm's objects.

A second, independent route to the same values. The facade builder (`java_build`) and this
one share the value rules of `ak.Values` and nothing else -- different types, different
setters, different presence model -- so a defect in one is visible as a byte disagreement
rather than as two arms being wrong together. The rust slice records the one time that
separation fired and it is the reason it exists.

The presence model is where the two genuinely differ and where this file earns its
keep:

* protobuf-java has `hasX()` for an explicit-presence field and a `clearX()`; the facade
  has a `has_` flag or a `null`. Neither is translated into the other, both are set from
  the same rule.
* protobuf-java's enum accessors come in two forms and this uses `setXValue(int)`, because
  design/SHAPES.md requires an unrecognised value to round-trip and `setX(enum)` cannot
  express one.
* a `bytes` field is a `ByteString`, so this arm allocates one per field where the facade
  holds a `byte[]`. That is protobuf-java's data model, not a handicap: the incumbent
  column is what the library costs a Java application, and a Java application holds
  `ByteString`.
"""
import java_names as N

HEAD = ("// @generated by ffi/poc/java/gen/generate.py from ffi/schema/shapes.json."
        " Do not edit.\n")

VALUE_FN = {"guid": "Values.guid", "word": "Values.word", "sentence": "Values.sentence"}


def absent_expr(f):
    if f.adapter_site == "nested" or (f.kind == "message" and f.of == "Timestamp"
                                      and f.tag % 2 == 0):
        return "(mode == Build.ALL_ABSENT || mode == Build.HALF_ABSENT)"
    return "(mode == Build.ALL_ABSENT)"


def _cs(expr):
    return "Values.recode(%s, cs)" % expr


def _string_expr(f, path, idx="idx"):
    return _cs("%s(%s, (int) (%s))" % (VALUE_FN[f.value_rule], path, idx))


def _scalar_expr(f, path, idx="idx"):
    fn = {"int32": "Values.scalarI32", "int64": "Values.scalarI64",
          "bool": "Values.scalarBool", "double": "Values.scalarDouble"}[f.kind]
    return "%s(%s, (int) (%s))" % (fn, path, idx)


def _setter(f):
    return "set" + N.camel(f.name)


def _adder(f):
    return "add" + N.camel(f.name)


def _msg_call(f, path, idx="idx"):
    if f.of == "Timestamp":
        return "mkTimestamp((int) (%s))" % idx
    if f.of == "Duration":
        return "mkDuration((int) (%s))" % idx
    return "build%s(%s, %s, mode, repeats, bulk, cs)" % (f.of, path, idx)


def _emit_field(m, f, o):
    fp = '(path + ".%s")' % f.name
    b = "b"

    if f.adapter_site == "nested":
        o.append("    if (!%s) {" % absent_expr(f))
        o.append("      switch (Build.adapterState(idx)) {")
        o.append("        case Build.ADAPTER_INVALID: break;")
        o.append("        case Build.ADAPTER_OK:")
        o.append("          %s.%s(ak.pb.%s.newBuilder().setSuccess(true));"
                 % (b, _setter(f), f.of))
        o.append("          break;")
        o.append("        default:")
        o.append("          %s.%s(ak.pb.%s.newBuilder().setError(%s));"
                 % (b, _setter(f), f.of,
                    _cs('Values.sentence(path + ".%s.error", (int) idx)' % f.name)))
        o.append("          break;")
        o.append("      }")
        o.append("    }")
        return
    if f.adapter_site == "plain":
        o.append("    if (!%s && Build.adapterState(idx) == Build.ADAPTER_ERROR)"
                 % absent_expr(f))
        o.append("      %s.%s(%s);" % (b, _setter(f), _string_expr(f, fp)))
        return

    o.append("    if (!%s) {" % absent_expr(f))
    if f.card == "map":
        n = f.raw.get("entries", 4)
        o.append("      for (int k = 0; k < %d; k++) {" % n)
        o.append("        String key = Build.pad2(k) + %s;"
                 % _cs('Values.word(path + ".%s.key", idx * 31 + k)' % f.name))
        o.append("        String val = \"\";")
        o.append("        if (!(mode == Build.HALF_ABSENT && k % 2 == 0))")
        o.append("          val = %s;" % _cs('Values.word(path + ".%s.value", idx * 31 + k)' % f.name))
        o.append("        %s.put%s(key, val);" % (b, N.camel(f.name)))
        o.append("      }")
    elif f.card == "packed":
        n = f.raw.get("count", 30)
        add = ("add%sValue" % N.camel(f.name)) if f.kind == "enum" else _adder(f)
        o.append("      for (int j = 0; j < %d; j++)" % n)
        if f.kind == "enum":
            o.append("        %s.%s(Values.enumValue(ak.shapes.%s.DECLARED, idx * 97 + j));"
                     % (b, add, f.of))
        else:
            o.append("        %s.%s(%s);" % (b, add, _scalar_expr(f, fp, "idx * 97 + j")))
    elif f.card == "repeated" and f.kind == "string":
        o.append("      for (int j = 0; j < repeats; j++)")
        o.append("        %s.%s(%s);" % (b, _adder(f), _string_expr(f, fp, "idx * 211 + j")))
    elif f.card == "repeated" and f.kind == "message":
        o.append("      for (int j = 0; j < repeats; j++)")
        o.append("        %s.%s(%s);" % (b, _adder(f), _msg_call(f, fp, "j")))
    elif f.card == "singular" and f.kind == "message":
        o.append("      %s.%s(%s);" % (b, _setter(f), _msg_call(f, fp)))
    elif f.card == "singular" and f.kind == "string":
        if f.explicit:
            o.append("      if (Build.explicitPresent(%d, idx))" % f.tag)
            o.append("        %s.%s(idx %% 7 == 0 ? \"\" : %s);"
                     % (b, _setter(f), _string_expr(f, fp)))
        else:
            o.append("      %s.%s(%s);" % (b, _setter(f), _string_expr(f, fp)))
    elif f.card == "singular" and f.kind == "bytes":
        src = ("Values.bulk(bulk)" if f.value_rule == "bulk"
               else "Values.blob(%s, (int) idx, 16)" % fp)
        o.append("      %s.%s(com.google.protobuf.ByteString.copyFrom(%s));"
                 % (b, _setter(f), src))
    elif f.card == "singular" and f.kind == "enum":
        o.append("      %s.set%sValue(Values.enumValue(ak.shapes.%s.DECLARED, (int) idx));"
                 % (b, N.camel(f.name), f.of))
    elif f.card == "singular" and f.is_scalar_leaf:
        if f.explicit:
            o.append("      if (Build.explicitPresent(%d, idx))" % f.tag)
            o.append("        %s.%s(idx %% 7 == 0 ? %s : %s);"
                     % (b, _setter(f), N.ZERO[f.kind], _scalar_expr(f, fp)))
        else:
            o.append("      %s.%s(%s);" % (b, _setter(f), _scalar_expr(f, fp)))
    else:
        raise NotImplementedError(
            "REFUSED: the protobuf-java payload builder has no case for %s.%s"
            " (card=%s kind=%s)" % (m.name, f.name, f.card, f.kind))
    o.append("    }")


def _oneof_value(msg, g):
    path = '"%s.%s"' % (msg, g.name)
    st = "set" + N.camel(g.name)
    if g.kind == "string":
        return "b.%s(%s);" % (st, _cs("Values.word(%s, (int) idx)" % path))
    if g.kind == "bytes":
        return ("b.%s(com.google.protobuf.ByteString.copyFrom("
                "Values.blob(%s, (int) idx, 16)));" % (st, path))
    if g.kind == "int64":
        return "b.%s(Values.scalarI64(%s, (int) idx));" % (st, path)
    if g.kind == "int32":
        return "b.%s(Values.scalarI32(%s, (int) idx));" % (st, path)
    if g.kind == "message" and g.of == "Empty":
        return "b.%s(ak.pb.Empty.newBuilder());" % st
    if g.kind == "message":
        return "b.%s(mkTimestamp((int) idx));" % st
    raise NotImplementedError("oneof member %s" % g.kind)


PRE = '''/** Build any payload of shapes.json as protobuf-java values: the incumbent's objects. */
public final class PbBuild {
  private PbBuild() {}

  static ak.pb.Timestamp mkTimestamp(int idx) {
    return ak.pb.Timestamp.newBuilder()
        .setSeconds(Values.stampSeconds(idx)).setNanos(Values.stampNanos(idx)).build();
  }

  static ak.pb.Duration mkDuration(int idx) {
    return ak.pb.Duration.newBuilder()
        .setSeconds(Values.durSeconds(idx)).setNanos(Values.durNanos(idx)).build();
  }
'''


def emit(ir, ns=N.PKG):
    o = [HEAD, "package %s;" % ns, "", "import ak.Values;", "", PRE]
    for name in ir.order:
        m = ir.msg(name)
        if m.synthetic or name in ("Timestamp", "Duration"):
            continue
        o.append("")
        o.append("  public static ak.pb.%s build%s(String path, int idx, int mode,"
                 " int repeats, int bulk, int cs) {" % (name, name))
        o.append("    ak.pb.%s.Builder b = ak.pb.%s.newBuilder();" % (name, name))
        for f in m.plain:
            if f.oneof:
                continue
            _emit_field(m, f, o)
        for oname, members in m.oneofs.items():
            o.append("    switch (idx %% %d) {" % len(members))
            for i, g in enumerate(members):
                arm = "case %d:" % i if i < len(members) - 1 else "default:"
                o.append("      %s" % arm)
                o.append("        %s" % _oneof_value(name, g))
                o.append("        break;")
            o.append("    }")
        o.append("    return b.build();")
        o.append("  }")

    o.append("")
    o.append("  // ---- the payload set ------------------------------------------------")
    for pid, spec in ir.payloads.items():
        root = spec["root"]
        if root not in ir.messages:
            continue
        m = ir.msg(root)
        fn = "payload" + pid.replace(".", "_")
        if spec.get("interleaved"):
            o.append("")
            o.append("  // %s has no builder: no canonical writer can produce it." % pid)
            continue
        o.append("")
        o.append("  /** %s: %s, %s. */" % (pid, root, spec.get("mode", "full")))
        o.append("  public static ak.pb.%s %s(int cs) {" % (root, fn))
        o.append("    ak.pb.%s.Builder b = ak.pb.%s.newBuilder();" % (root, root))
        if "bulk" in spec:
            f = m.plain[0]
            o.append("    b.set%s(build%s(\"%s\", 0, Build.FULL, 3, %d, cs));"
                     % (N.camel(f.name), f.of, f.of, spec["bulk"]))
        else:
            field = next(f for f in m.plain if f.name == spec["field"])
            reps = spec.get("repeats", 3)
            reps = reps if isinstance(reps, list) else [reps]
            o.append("    final int[] kReps = {%s};" % ", ".join(str(r) for r in reps))
            mode = {"all_absent": "Build.ALL_ABSENT",
                    "half_absent": "Build.HALF_ABSENT"}.get(spec.get("mode"), "Build.FULL")
            o.append("    for (int j = 0; j < %d; j++)" % spec["count"])
            o.append("      b.add%s(build%s(\"%s\", j, %s, kReps[j %% %d], 0, cs));"
                     % (N.camel(field.name), field.of, field.of, mode, len(reps)))
            for f in m.plain:
                if f.name == "page":
                    o.append("    b.setPage(1);")
                elif f.name == "total":
                    o.append("    b.setTotal(%d);" % spec["count"])
        o.append("    return b.build();")
        o.append("  }")
    o.append("}")
    o.append("")
    return "\n".join(o)
