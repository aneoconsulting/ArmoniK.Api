"""Work unit 1's C shim: a generated C encoder with NO core behind it.

Kept because work unit 1's encode column was measured with it and README R4's last
paragraph says a figure whose harness is not in the tree cannot be defended.  It is
NOT the design: the design is `py_binding.py`, which calls the shared core at
`poc/codec/`.  What this one prices is the shim-to-facade edge on its own.

Moved here from `mech/gen/generate.py` unchanged, so the emitted text -- and
therefore `logs/python/40-codec-py3.11.log` -- is the same file it always was.
"""
from walk import walk, Unsupported


C_PRELUDE = r'''/* GENERATED by gen/generate.py from ffi/schema/shapes.json. Do not edit. */
#include <Python.h>
#include <structmember.h>
#include <string.h>
#include <stdint.h>

/* README R5, counting build. Compiled with -DAK_COUNT it counts every crossing
 * the shim makes into CPython, per direction and per kind, so the counts in the
 * log are counted and not inferred. */
#ifdef AK_COUNT
static uint64_t CNT[8];
#define C_ATTR   0
#define C_READ   1
#define C_ITEM   2
#define C_PYCALL 3
#define BUMP(i) (CNT[i]++)
#else
#define BUMP(i) ((void)0)
#endif

/* A growable output buffer. Not part of the comparison: every C arm shares it,
 * so it cancels between them, and the pure-Python and upb arms have their own. */
typedef struct { uint8_t *p; size_t len, cap; } Buf;

static int buf_need(Buf *b, size_t extra) {
  if (b->len + extra <= b->cap) return 0;
  size_t cap = b->cap ? b->cap : 4096;
  while (cap < b->len + extra) cap *= 2;
  uint8_t *q = (uint8_t *)PyMem_Realloc(b->p, cap);
  if (!q) { PyErr_NoMemory(); return -1; }
  b->p = q; b->cap = cap;
  return 0;
}

static int put_varint(Buf *b, uint64_t v) {
  if (buf_need(b, 10)) return -1;
  while (v >= 0x80) { b->p[b->len++] = (uint8_t)(v | 0x80); v >>= 7; }
  b->p[b->len++] = (uint8_t)v;
  return 0;
}

static int put_key(Buf *b, uint32_t tag, uint32_t wire) {
  return put_varint(b, ((uint64_t)tag << 3) | wire);
}

static int put_bytes(Buf *b, const void *src, size_t n) {
  if (buf_need(b, n)) return -1;
  memcpy(b->p + b->len, src, n);
  b->len += n;
  return 0;
}

/* A length-delimited body whose length is not known until it is written.
 * Reserved at one byte and moved on a miss, which is the SIMPLEST form -- ABI
 * v1 decision 5's learned width is a core-side mechanism and is not what this
 * microbenchmark is about. Every C arm pays the same thing here. */
static size_t open_ld(Buf *b, uint32_t tag) {
  if (put_key(b, tag, 2)) return (size_t)-1;
  if (buf_need(b, 1)) return (size_t)-1;
  b->len += 1;
  return b->len;   /* body starts here; the placeholder is at body-1 */
}

static int close_ld(Buf *b, size_t body) {
  size_t n = b->len - body;
  if (n < 128) { b->p[body - 1] = (uint8_t)n; return 0; }
  uint8_t tmp[10];
  size_t w = 0, v = n;
  while (v >= 0x80) { tmp[w++] = (uint8_t)(v | 0x80); v >>= 7; }
  tmp[w++] = (uint8_t)v;
  if (buf_need(b, w - 1)) return -1;
  memmove(b->p + body + w - 1, b->p + body, n);
  memcpy(b->p + body - 1, tmp, w);
  b->len += w - 1;
  return 0;
}
'''


def c_type_struct(schema, name, scope):
    """The generated C facade type: storage candidate 3."""
    L = ["typedef struct {", "  PyObject_HEAD"]
    for f, k, c in walk(schema, name, scope):
        if c == "repeated" or k in ("string", "bytes", "message"):
            L.append("  PyObject *%s;" % f["name"])
        elif k == "int64":
            L.append("  long long %s;" % f["name"])
        elif k in ("int32", "enum"):
            L.append("  long %s;" % f["name"])
        elif k == "bool":
            L.append("  int %s;" % f["name"])
        else:
            raise Unsupported("%s.%s" % (name, f["name"]))
    L.append("} C%s;" % name)
    return "\n".join(L)


def emit(schema, scope, root):
    L = [C_PRELUDE, ""]

    # --- the generated C facade type -------------------------------------
    for name in scope:
        L.append(c_type_struct(schema, name, scope))
        L.append("")

    for name in scope:
        flds = list(walk(schema, name, scope))
        L.append("static PyMemberDef mem_%s[] = {" % name)
        for f, k, c in flds:
            if c == "repeated" or k in ("string", "bytes", "message"):
                t = "T_OBJECT_EX"
            elif k == "int64":
                t = "T_LONGLONG"
            elif k in ("int32", "enum"):
                t = "T_LONG"
            else:
                t = "T_BOOL"
            L.append('  {"%s", %s, offsetof(C%s, %s), 0, NULL},'
                     % (f["name"], t, name, f["name"]))
        L.append("  {NULL}};")
        L.append("")

    # Keyword init, so the C facade is constructed exactly like the Python ones.
    for name in scope:
        flds = list(walk(schema, name, scope))
        objs = [f for f, k, c in flds if c == "repeated" or k in ("string", "bytes", "message")]
        fmt = ""
        for f, k, c in flds:
            if c == "repeated" or k in ("string", "bytes", "message"):
                fmt += "O"
            elif k == "int64":
                fmt += "L"
            elif k in ("int32", "enum"):
                fmt += "l"
            else:
                fmt += "p"
        L.append("static int init_%s(PyObject *self, PyObject *args, PyObject *kw) {" % name)
        L.append("  static char *kwl[] = {%s NULL};"
                 % "".join('"%s", ' % f["name"] for f, _, _ in flds))
        L.append("  C%s *o = (C%s *)self;" % (name, name))
        for f, k, c in flds:
            if c == "repeated" or k in ("string", "bytes", "message"):
                L.append("  PyObject *a_%s = NULL;" % f["name"])
            elif k == "int64":
                L.append("  long long v_%s = 0;" % f["name"])
            elif k in ("int32", "enum"):
                L.append("  long v_%s = 0;" % f["name"])
            else:
                L.append("  int v_%s = 0;" % f["name"])
        L.append('  if (!PyArg_ParseTupleAndKeywords(args, kw, "|%s", kwl, %s))'
                 % (fmt, ", ".join(
                     "&a_" + f["name"] if (c == "repeated" or k in ("string", "bytes", "message"))
                     else "&v_" + f["name"] for f, k, c in flds)))
        L.append("    return -1;")
        for f, k, c in flds:
            nm = f["name"]
            if c == "repeated" or k in ("string", "bytes", "message"):
                L.append("  { PyObject *v = a_%s ? a_%s : Py_None; Py_INCREF(v);"
                         " Py_XSETREF(o->%s, v); }" % (nm, nm, nm))
            else:
                L.append("  o->%s = v_%s;" % (nm, nm))
        L.append("  return 0;")
        L.append("}")
        L.append("")
        L.append("static int trav_%s(PyObject *self, visitproc visit, void *arg) {" % name)
        if objs:
            L.append("  C%s *o = (C%s *)self;" % (name, name))
            for f in objs:
                L.append("  Py_VISIT(o->%s);" % f["name"])
        else:
            L.append("  (void)self; (void)visit; (void)arg;")
        L.append("  return 0;\n}")
        L.append("static int clear_%s(PyObject *self) {" % name)
        if objs:
            L.append("  C%s *o = (C%s *)self;" % (name, name))
            for f in objs:
                L.append("  Py_CLEAR(o->%s);" % f["name"])
        else:
            L.append("  (void)self;")
        L.append("  return 0;\n}")
        L.append("static void dealloc_%s(PyObject *self) {" % name)
        L.append("  PyTypeObject *t = Py_TYPE(self);")
        L.append("  PyObject_GC_UnTrack(self);")
        L.append("  clear_%s(self);" % name)
        L.append("  ((freefunc)PyType_GetSlot(t, Py_tp_free))(self);")
        L.append("  Py_DECREF(t);\n}")
        L.append("static PyType_Slot slots_%s[] = {" % name)
        L.append("  {Py_tp_init, (void *)init_%s}," % name)
        L.append("  {Py_tp_members, (void *)mem_%s}," % name)
        L.append("  {Py_tp_new, (void *)PyType_GenericNew},")
        L.append("  {Py_tp_dealloc, (void *)dealloc_%s}," % name)
        L.append("  {Py_tp_traverse, (void *)trav_%s}," % name)
        L.append("  {Py_tp_clear, (void *)clear_%s}," % name)
        L.append("  {0, NULL}};")
        L.append('static PyType_Spec spec_%s = {"_akcodec.C%s", sizeof(C%s), 0,'
                 % (name, name, name))
        L.append("  Py_TPFLAGS_DEFAULT | Py_TPFLAGS_BASETYPE | Py_TPFLAGS_HAVE_GC,"
                 " slots_%s};" % name)
        L.append("")

    # --- interned attribute-name keys, one per field ---------------------
    names = sorted({f["name"] for n in scope for f, _, _ in walk(schema, n, scope)})
    L.append("/* Interned once at module init. PyObject_GetAttrString rebuilds the")
    L.append(" * name on every call and measured 5x worse; a generated shim would")
    L.append(" * never do that, so neither does this one. */")
    for nm in names:
        L.append("static PyObject *K_%s;" % nm)
    L.append("")
    L.append("static int intern_keys(void) {")
    for nm in names:
        L.append('  K_%s = PyUnicode_InternFromString("%s"); if (!K_%s) return -1;'
                 % (nm, nm, nm))
    L.append("  return 0;\n}")
    L.append("")

    # --- the three encode backends ---------------------------------------
    # Forward declarations first: a message's encoder calls its children's, and
    # the scope order is not a topological order. Emitted mechanically rather
    # than by sorting, so a cycle in the schema would be a compile error here
    # instead of a silently reordered tree.
    L.append("/* forward declarations: an encoder calls its children's */")
    for backend in ("attr", "cext", "pyacc"):
        for name in scope:
            L.append("static int enc_%s_%s(PyObject *, Buf *, PyObject *);"
                     % (backend, name))
    L.append("")
    for backend in ("attr", "cext", "pyacc"):
        for name in scope:
            L.append(emit_c_encode(schema, name, backend, scope))
            L.append("")
    return "\n".join(L)


def emit_c_encode(schema, name, backend, scope):
    """One message, one backend.

    `getters` is a dict passed in from Python for the `pyacc` control, so the
    control's accessor is a real Python call and not a C read wearing a Python
    name.
    """
    L = []
    if backend == "cext":
        L.append("static int enc_%s_%s(PyObject *obj, Buf *b, PyObject *getters) {"
                 % (backend, name))
        L.append("  (void)getters;")
        L.append("  C%s *o = (C%s *)obj;" % (name, name))
    else:
        L.append("static int enc_%s_%s(PyObject *obj, Buf *b, PyObject *getters) {"
                 % (backend, name))
    for f, k, c in walk(schema, name, scope):
        nm, tag = f["name"], f["tag"]
        L.append("  { /* %s (tag %d, %s %s) */" % (nm, tag, c, k))
        if backend == "cext" and not (c == "repeated" or k in ("string", "bytes", "message")):
            # An unboxed scalar: no PyObject at all on this path.
            if k == "bool":
                L.append("    if (o->%s) { if (put_key(b, %d, 0)) return -1;"
                         " if (put_varint(b, 1)) return -1; }" % (nm, tag))
            else:
                L.append("    if (o->%s) { if (put_key(b, %d, 0)) return -1;"
                         " if (put_varint(b, (uint64_t)o->%s)) return -1; }"
                         % (nm, tag, nm))
            L.append("  }")
            continue
        # Fetch the value.
        if backend == "cext":
            L.append("    PyObject *v = o->%s; Py_XINCREF(v);" % nm)
        elif backend == "attr":
            L.append("    BUMP(C_ATTR);")
            L.append("    PyObject *v = PyObject_GetAttr(obj, K_%s);" % nm)
            L.append("    if (!v) return -1;")
        else:  # pyacc
            L.append("    BUMP(C_PYCALL);")
            L.append("    PyObject *g = PyDict_GetItemString(getters, \"%s\");" % nm)
            L.append("    if (!g) { PyErr_SetString(PyExc_KeyError, \"%s\"); return -1; }" % nm)
            L.append("    PyObject *v = PyObject_CallOneArg(g, obj);")
            L.append("    if (!v) return -1;")
        L.append(emit_c_write(f, k, c, backend))
        L.append("    Py_XDECREF(v);")
        L.append("  }")
    L.append("  return 0;\n}")
    return "\n".join(L)


def emit_c_write(f, k, c, backend):
    nm, tag = f["name"], f["tag"]
    P = "    "
    if c == "repeated":
        return "\n".join([
            P + "Py_ssize_t n = PyList_Size(v);",
            P + "if (n < 0) { Py_XDECREF(v); return -1; }",
            P + "for (Py_ssize_t i = 0; i < n; i++) {",
            P + "  BUMP(C_ITEM);",
            P + "  PyObject *e = PyList_GetItem(v, i);",
            P + "  if (!e) { Py_XDECREF(v); return -1; }",
            P + "  size_t body = open_ld(b, %d);" % tag,
            P + "  if (body == (size_t)-1) { Py_XDECREF(v); return -1; }",
            P + "  if (enc_%s_%s(e, b, getters)) { Py_XDECREF(v); return -1; }"
              % (backend, f["of"]),
            P + "  if (close_ld(b, body)) { Py_XDECREF(v); return -1; }",
            P + "}",
        ])
    if k == "string":
        return "\n".join([
            P + "BUMP(C_READ);",
            P + "Py_ssize_t sl = 0;",
            P + "const char *sp = PyUnicode_AsUTF8AndSize(v, &sl);",
            P + "if (!sp) { Py_XDECREF(v); return -1; }",
            P + "if (sl) {",
            P + "  if (put_key(b, %d, 2) || put_varint(b, (uint64_t)sl)" % tag,
            P + "      || put_bytes(b, sp, (size_t)sl)) { Py_XDECREF(v); return -1; }",
            P + "}",
        ])
    if k == "bytes":
        return "\n".join([
            P + "BUMP(C_READ);",
            P + "char *bp = NULL; Py_ssize_t bl = 0;",
            P + "if (PyBytes_AsStringAndSize(v, &bp, &bl)) { Py_XDECREF(v); return -1; }",
            P + "if (bl) {",
            P + "  if (put_key(b, %d, 2) || put_varint(b, (uint64_t)bl)" % tag,
            P + "      || put_bytes(b, bp, (size_t)bl)) { Py_XDECREF(v); return -1; }",
            P + "}",
        ])
    if k in ("int32", "int64", "enum"):
        return "\n".join([
            P + "BUMP(C_READ);",
            P + "long long iv = PyLong_AsLongLong(v);",
            P + "if (iv == -1 && PyErr_Occurred()) { Py_XDECREF(v); return -1; }",
            P + "if (iv) {",
            P + "  if (put_key(b, %d, 0) || put_varint(b, (uint64_t)iv))" % tag,
            P + "    { Py_XDECREF(v); return -1; }",
            P + "}",
        ])
    if k == "bool":
        return "\n".join([
            P + "BUMP(C_READ);",
            P + "int tv = PyObject_IsTrue(v);",
            P + "if (tv < 0) { Py_XDECREF(v); return -1; }",
            P + "if (tv) {",
            P + "  if (put_key(b, %d, 0) || put_varint(b, 1)) { Py_XDECREF(v); return -1; }" % tag,
            P + "}",
        ])
    if k == "message":
        return "\n".join([
            P + "if (v != Py_None) {",
            P + "  size_t body = open_ld(b, %d);" % tag,
            P + "  if (body == (size_t)-1) { Py_XDECREF(v); return -1; }",
            P + "  if (enc_%s_%s(v, b, getters)) { Py_XDECREF(v); return -1; }"
              % (backend, f["of"]),
            P + "  if (close_ld(b, body)) { Py_XDECREF(v); return -1; }",
            P + "}",
        ])
    raise Unsupported(nm)


