def _find_ffi_root():
    """Walk up until `schema/shapes.json` is found.

    NOT an absolute path baked in at generate time, which is what the first version did:
    a clone of this branch at any other path then regenerated a different file and
    `generate.py --check` refused the tree as stale, so the committed sources could not
    rebuild themselves. Defect D4.
    """
    d = os.path.dirname(os.path.abspath(__file__))
    for _ in range(12):
        if os.path.exists(os.path.join(d, "schema", "shapes.json")):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    raise RuntimeError("cannot find the ffi/ root above %s" % __file__)


