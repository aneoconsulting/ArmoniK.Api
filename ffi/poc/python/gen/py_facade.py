"""The Python facade, in its two storages, emitted from one description.

Moved here from `mech/gen/` when work unit 2 needed the same facade: two emitters
for one facade is the defect README R0 is about, one level down from the core.
`mech/` now reads `gen/out/` like everything else, and the classes it measured in
work unit 1 come out byte-identical (`gen/generate.py --check` is what says so).

*   `Plain*` -- a plain class. Attributes live in an instance `__dict__`.
*   `Slots*` -- `__slots__`. A descriptor with a fixed offset, no dict.

The third candidate, a C extension type, is emitted by `py_binding.py` into the C
shim, because its whole point is that a field read from C is a struct member
rather than a crossing.
"""
from walk import walk, pydefault


def emit(schema, scope):
    L = ['"""GENERATED by gen/generate.py from ffi/schema/shapes.json. Do not edit.',
         '',
         'Two storages for the same facade, so README 9.1\'s choice is a measured one:',
         '',
         '*   `Plain*`  -- a plain class. Attributes live in an instance __dict__.',
         '*   `Slots*`  -- `__slots__`. A descriptor with a fixed offset, no dict.',
         '',
         'The third candidate, a C extension type, is emitted into out/_akcodec.c,',
         'because its point is that a field read from C is a struct member rather',
         'than a crossing.',
         '',
         'Both are IDIOMATIC on purpose: keyword arguments, defaults, an __eq__ that',
         'a test can use. A facade that is fast because it is unusable is not a',
         'facade.',
         '"""',
         '']
    for variant, slots in (("Plain", False), ("Slots", True)):
        for name in scope:
            flds = list(walk(schema, name))
            L.append("class %s%s:" % (variant, name))
            if slots:
                L.append("    __slots__ = (%s)"
                         % "".join('"%s", ' % f["name"] for f, _, _ in flds))
            args = ", ".join("%s=%s" % (f["name"], pydefault(k, c))
                             for f, k, c in flds)
            L.append("    def __init__(self, %s):" % args)
            for f, k, c in flds:
                if c in ("repeated", "map"):
                    # A map is a `dict` on the facade, which is what a Python user
                    # expects, and a repeated field of a pair message on the wire (ABI v1
                    # section 11). The canonical form sorts map entries by key, so the
                    # shim sorts on encode; the facade does not pretend to be ordered.
                    empty = "{}" if c == "map" else "[]"
                    L.append("        self.%s = %s if %s is None else %s"
                             % (f["name"], empty, f["name"], f["name"]))
                else:
                    L.append("        self.%s = %s" % (f["name"], f["name"]))
            L.append("")
            L.append("    def __eq__(self, o):")
            L.append("        return type(o) is type(self) and (%s) == (%s)"
                     % (", ".join("self." + f["name"] for f, _, _ in flds),
                        ", ".join("o." + f["name"] for f, _, _ in flds)))
            L.append("")
            L.append("")
    return "\n".join(L)


