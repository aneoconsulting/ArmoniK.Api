"""The generated pure-Python codec: README R3's no-boundary control, both directions.

The same traversal the C shim makes, emitted into Python instead, over the same
facade objects.  It makes no crossing at all, so it is what the shim has to beat
to be worth existing -- and README R9 says in advance that it may lose to upb by
an order of magnitude, which is a result rather than a defect: it says the codec
question in Python is native against native.

The ENCODE half is the one work unit 1 measured and its emitted text is unchanged,
so `logs/python/40-codec-py3.11.log` still traces to this file.  The DECODE half is
new in work unit 2.
"""
from walk import walk, Unsupported


PY_PRELUDE = '''"""GENERATED by gen/generate.py from ffi/schema/shapes.json. Do not edit.

README R3's **no-boundary control** for the codec arms: the same traversal the C
shim makes, emitted into Python instead, over the same facade objects.  It makes
no crossing at all, so it is what the shim has to beat to be worth existing.

README R9 applies to it: a pure-Python control may lose to upb by an order of
magnitude, and that is a result rather than a defect -- it says the codec
question in Python is native against native.

Canonical form is `ffi/schema/generated/manifest.json`'s: fields ascending by
tag, an implicit-presence leaf holding the proto zero omitted, a message field
written when present.
"""

import struct as _struct

_VARINT_CACHE = [bytes([i]) for i in range(128)]


def _varint(n, out):
    if n < 0:
        n += 1 << 64
    if n < 128:
        out += _VARINT_CACHE[n]
        return
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return


def _key(tag, wire, out):
    _varint((tag << 3) | wire, out)


def _packed_varint(tag, vals, out):
    """A packed run: ONE length-delimited field holding the concatenated varints.

    Written even when every value is the proto zero. The omit-when-zero rule is about a
    leaf, and a run is not one -- an empty run is absent, a run of zeros is not.
    """
    body = bytearray()
    for v in vals:
        _varint(int(v), body)
    _key(tag, 2, out)
    _varint(len(body), out)
    out += body


def _packed_f64(tag, vals, out):
    body = _struct.pack("<%dd" % len(vals), *vals)
    _key(tag, 2, out)
    _varint(len(body), out)
    out += body
'''



def _write(k, f, tag, val, ind):
    """The lines that write ONE value of kind `k`, with no presence test of their own.

    Split out from the guards because M3 made the same three writers serve three different
    presence rules, and a copy per rule is how an `optional` field ends up silently sharing
    the implicit-presence test.
    """
    if k == "string":
        return [ind + "_b = %s.encode('utf-8')" % val,
                ind + "_key(%d, 2, out)" % tag,
                ind + "_varint(len(_b), out)",
                ind + "out += _b"]
    if k == "bytes":
        return [ind + "_key(%d, 2, out)" % tag,
                ind + "_varint(len(%s), out)" % val,
                ind + "out += %s" % val]
    if k in ("int32", "int64", "enum"):
        return [ind + "_key(%d, 0, out)" % tag,
                ind + "_varint(%s, out)" % val]
    if k == "bool":
        return [ind + "_key(%d, 0, out)" % tag,
                ind + "out.append(1 if %s else 0)" % val]
    if k == "message":
        return [ind + "_key(%d, 2, out)" % tag,
                ind + "_sub = bytearray()",
                ind + "encode_%s(%s, _sub)" % (f["of"], val),
                ind + "_varint(len(_sub), out)",
                ind + "out += _sub"]
    raise Unsupported("kind %r" % k)


def emit_encode(schema, scope, root, roots):
    L = [PY_PRELUDE]
    for name in scope:
        L.append("")
        L.append("def encode_%s(o, out):" % name)
        body = []
        for f, k, c in walk(schema, name):
            tag, nm = f["tag"], f["name"]
            if c == "map":
                # ABI v1 section 11: a map has no case of its own on the wire, it is a
                # repeated field of a pair message. The canonical form sorts entries by
                # key and omits BOTH members when they hold the proto zero, because both
                # are implicit-presence leaves of that pair message. Writing the key
                # unconditionally was defect D10: it is invisible on every payload in the
                # manifest, where no key is empty, and the corpus's `E-map-entry-empty`
                # is the vector that exists for it -- an entry whose whole body is zero
                # bytes. The shared core had it right; this control did not.
                body += [
                    "    for _mk in sorted(o.%s):" % nm,
                    "        _mv = o.%s[_mk]" % nm,
                    "        _sub = bytearray()",
                    "        if _mk:",
                    "            _kb = _mk.encode('utf-8')",
                    "            _key(1, 2, _sub); _varint(len(_kb), _sub); _sub += _kb",
                    "        if _mv:",
                    "            _vb = _mv.encode('utf-8')",
                    "            _key(2, 2, _sub); _varint(len(_vb), _sub); _sub += _vb",
                    "        _key(%d, 2, out)" % tag,
                    "        _varint(len(_sub), out)",
                    "        out += _sub",
                ]
            elif c == "packed":
                # A packed field is one call, not a loop: that is the whole point of the
                # control. `flags` packs as varints too -- proto3 packs a `bool` run as
                # one byte per value, not as a bitmap.
                if k == "double":
                    body += ["    _v = o.%s" % nm, "    if _v:",
                             "        _packed_f64(%d, _v, out)" % tag]
                else:
                    body += ["    _v = o.%s" % nm, "    if _v:",
                             "        _packed_varint(%d, _v, out)" % tag]
            elif c == "repeated" and k == "string":
                body += [
                    "    for e in o.%s:" % nm,
                    "        _b = e.encode('utf-8')",
                    "        _key(%d, 2, out)" % tag,
                    "        _varint(len(_b), out)",
                    "        out += _b",
                ]
            elif c == "repeated":
                body += [
                    "    for e in o.%s:" % nm,
                    "        _key(%d, 2, out)" % tag,
                    "        _sub = bytearray()",
                    "        encode_%s(e, _sub)" % f["of"],
                    "        _varint(len(_sub), out)",
                    "        out += _sub",
                ]
            elif c in ("singular", "optional", "oneof"):
                # One writer, three guards. Which guard applies is the whole of proto3's
                # presence story and it is the part a hand-written codec gets wrong:
                #
                #   implicit (`singular`)  -- write when the value differs from the zero
                #   explicit (`optional`)  -- write when it is not None, zero INCLUDED
                #   oneof                  -- write when this member is the selected one,
                #                             zero included, and never more than one
                #
                # An `optional int32` holding 0 and a oneof member holding "" are both
                # messages a reader must be able to tell from the absent one, so neither
                # may go through the implicit guard.
                if c == "singular":
                    guard = ("    _v = o.%s" % nm,
                             "    if _v is not None:" if k == "message" else "    if _v:")
                elif c == "optional":
                    guard = ("    _v = o.%s" % nm, "    if _v is not None:")
                else:
                    guard = ("    _v = o.%s" % nm,
                             "    if o.%s_case == %d:" % (f["oneof"], tag))
                body += list(guard) + _write(k, f, tag, "_v", "        ")
            else:
                raise Unsupported("%s.%s: cardinality %r" % (name, nm, c))
        L += body or ["    pass"]
        L.append("")
    L.append("")
    for r in roots:
        L += [
            "",
            "def encode_root_%s(o):" % r,
            "    out = bytearray()",
            "    encode_%s(o, out)" % r,
            "    return bytes(out)",
        ]
    L += ["", "", "encode_root = encode_root_%s   # M1, the work unit 1 and 2 entry point"
          % root, ""]
    return "\n".join(L)




# --------------------------------------------------------------------------------
# Decode.  New in work unit 2.
#
# Constructors are passed IN rather than imported, so one emitted decoder serves
# every Python storage: the plain facade, the `__slots__` facade, and the C
# extension type.  That is the same property the C shim gets from having one
# traversal and three accessor backends, and it is what makes the storage arms a
# comparison of storages rather than of decoders.
# --------------------------------------------------------------------------------

DEC_PRELUDE = '''

def _unpack_f64(b, i, end):
    return _struct.unpack("<%dd" % ((end - i) // 8), bytes(b[i:end]))


def _rd_f64(b, i):
    return _struct.unpack_from("<d", b, i)[0]


def _rd_varint(b, i):
    n = b[i]
    if n < 128:
        return n, i + 1
    n &= 0x7F
    shift = 7
    i += 1
    while True:
        c = b[i]
        i += 1
        n |= (c & 0x7F) << shift
        if c < 128:
            return n, i
        shift += 7


def _skip(b, i, end, wt, tag):
    """An unknown field. protobuf's forward compatibility lives here and a corpus
    generated from the schema that reads it never executes this path.

    Wire types 3 and 4 are the deprecated GROUP form. proto3 cannot express one, so no
    schema-generated corpus contains one -- and every conformant parser still has to skip
    it, because a group carries no length and a skipper has to recurse to find its end.
    The first version of this function raised on wire type 3, and `ffi/corpus`'s
    `U-root-group` and `U-nested-group` are what found it. Defect D6.
    """
    if wt == 0:
        _, i = _rd_varint(b, i)
        return i
    if wt == 2:
        n, i = _rd_varint(b, i)
        if i + n > end:
            raise ValueError("length overruns the enclosing message")
        return i + n
    if wt == 5:
        if i + 4 > end:
            raise ValueError("truncated i32")
        return i + 4
    if wt == 1:
        if i + 8 > end:
            raise ValueError("truncated i64")
        return i + 8
    if wt == 3:
        while i < end:
            k, i = _rd_varint(b, i)
            t, w = k >> 3, k & 7
            if w == 4:
                if t != tag:
                    raise ValueError("END_GROUP tag %d closes group %d" % (t, tag))
                return i
            i = _skip(b, i, end, w, t)
        raise ValueError("unterminated group %d" % tag)
    if wt == 4:
        raise ValueError("END_GROUP with no group open")
    raise ValueError("wire type %d" % wt)


def _len(b, i, end):
    """A length-delimited body, bounds-checked against the ENCLOSING message rather than
    against the whole buffer.

    `ffi/corpus`'s `X-nested-len-overrun` is exactly this: the outer frame is well formed,
    so a decoder that checks against the buffer accepts it and reads a neighbouring
    field's bytes. The first version of this codec did. Defect D5.
    """
    n, i = _rd_varint(b, i)
    if n < 0 or i + n > end:
        raise ValueError("length %d at %d overruns the enclosing message (ends %d)"
                         % (n, i, end))
    return n, i
'''


PAIR = '''

def _pair(b, i, end):
    """One map entry, as the pair message ABI v1 section 11 says it is.

    Both fields are implicit presence, so an absent one is the empty string: a map entry
    with no value field is `key -> ""`, which is a different thing from no entry at all
    and is what design/SHAPES.md's P2.5 is built to reach.
    """
    k = v = ""
    while i < end:
        t, i = _rd_varint(b, i)
        if (t >> 3) == 1 and (t & 7) == 2:
            n, i = _len(b, i, end)
            k = b[i:i + n].decode("utf-8")
            i += n
        elif (t >> 3) == 2 and (t & 7) == 2:
            n, i = _len(b, i, end)
            v = b[i:i + n].decode("utf-8")
            i += n
        else:
            i = _skip(b, i, end, t & 7, t >> 3)
    return k, v, i
'''


def emit_decode(schema, scope, root, roots):
    L = [DEC_PRELUDE, PAIR]
    for name in scope:
        flds = list(walk(schema, name))
        L.append("")
        L.append("def decode_%s(b, i, end, C):" % name)
        L.append("    o = C[%r]()" % name)
        for f, k, c in flds:
            if c == "map":
                L.append("    _m_%s = {}" % f["name"])
            elif c in ("repeated", "packed"):
                L.append("    _r_%s = []" % f["name"])
        L.append("    while i < end:")
        L.append("        _k, i = _rd_varint(b, i)")
        L.append("        _t = _k >> 3")
        first = True
        for f, k, c in flds:
            tag, nm = f["tag"], f["name"]
            kw = "if" if first else "elif"
            first = False
            L.append("        %s _t == %d:" % (kw, tag))
            if c == "packed":
                # BOTH forms, and this is a conformance requirement rather than a
                # kindness: proto3 says a parser must accept a packable field written
                # unpacked, whatever the writer does. Only the packed branch is exercised
                # by the manifest, so the unpacked one is what the corpus is for.
                L.append("            if (_k & 7) == 2:")
                L.append("                _n, i = _len(b, i, end)")
                if k == "double":
                    L.append("                _r_%s.extend(_unpack_f64(b, i, i + _n))" % nm)
                    L.append("                i += _n")
                else:
                    L.append("                _e = i + _n")
                    L.append("                while i < _e:")
                    L.append("                    _v, i = _rd_varint(b, i)")
                    L.append("                    _r_%s.append(%s)"
                             % (nm, "bool(_v)" if k == "bool" else "_v"))
                elif_ = "            else:"
                L.append(elif_)
                if k == "double":
                    L.append("                _r_%s.append(_rd_f64(b, i)); i += 8" % nm)
                else:
                    L.append("                _v, i = _rd_varint(b, i)")
                    L.append("                _r_%s.append(%s)"
                             % (nm, "bool(_v)" if k == "bool" else "_v"))
            elif c == "map":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            _mk, _mv, i = _pair(b, i, i + _n)")
                L.append("            _m_%s[_mk] = _mv" % nm)
            elif c == "repeated" and k == "string":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            _r_%s.append(b[i:i + _n].decode('utf-8'))" % nm)
                L.append("            i += _n")
            elif c == "repeated":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            _r_%s.append(decode_%s(b, i, i + _n, C))"
                         % (nm, f["of"]))
                L.append("            i += _n")
            elif k == "string":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            o.%s = b[i:i + _n].decode('utf-8')" % nm)
                L.append("            i += _n")
            elif k == "bytes":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            o.%s = bytes(b[i:i + _n])" % nm)
                L.append("            i += _n")
            elif k in ("int32", "int64", "enum"):
                L.append("            _v, i = _rd_varint(b, i)")
                L.append("            o.%s = _v" % nm)
            elif k == "bool":
                L.append("            _v, i = _rd_varint(b, i)")
                L.append("            o.%s = bool(_v)" % nm)
            elif k == "message":
                L.append("            _n, i = _len(b, i, end)")
                L.append("            o.%s = decode_%s(b, i, i + _n, C)" % (nm, f["of"]))
                L.append("            i += _n")
            else:
                raise Unsupported("%s.%s" % (name, nm))
            if c == "oneof":
                # Last member on the wire wins, which is proto3's rule and not a choice:
                # a message carrying two members of one oneof is legal input and the
                # reader must end up with the later one selected. Assigning the
                # discriminant here, inside the branch, is what makes that true.
                L.append("            o.%s_case = %d" % (f["oneof"], tag))
        if first:
            L.append("        if False:")
            L.append("            pass")
        L.append("        else:")
        L.append("            i = _skip(b, i, end, _k & 7, _t)")
        for f, k, c in flds:
            if c == "map":
                L.append("    o.%s = _m_%s" % (f["name"], f["name"]))
            elif c in ("repeated", "packed"):
                L.append("    o.%s = _r_%s" % (f["name"], f["name"]))
        L.append("    return o")
    L.append("")
    for r in roots:
        L += ["", "def decode_root_%s(b, C):" % r,
              "    return decode_%s(b, 0, len(b), C)" % r]
    L += ["", "", "decode_root = decode_root_%s" % root, ""]
    return "\n".join(L)


def emit(schema, scope, root, roots):
    return (emit_encode(schema, scope, root, roots)
            + emit_decode(schema, scope, root, roots))
