"""Emit `abi/src/main.rs`, the layout probe, from the IR.

ABI v1 obligation 12.3. C# re-declares every `ak_efix_*`/`ak_dfix_*` by hand, so
the managed `[StructLayout]` is a SECOND declaration and only agreement makes
the by-value group work. The probe prints the Rust build's real sizes and field
offsets and `gen/abi-layout.json` carries them.

It used to be hand-written, which meant a struct could be missing from it and
nothing would say so -- and M2's surface was added to it by hand, twice, with a
presence bit guessed the second time. Emitted from the same derivation the C#
declaration uses, a struct cannot be in one and not the other.
"""
import abi_ir as A

HEAD = '''//! @generated by ffi/poc/csharp/gen/rs_probe.py. Do not edit.
//!
//! Print the size and field offsets of every ABI struct the C# binding declares,
//! and the value of every presence constant it reads.
//!
//! ABI v1 obligation 12.3. See Cargo.toml for why this slice needs it and the
//! earlier ones did not: C# re-declares these types by hand, so the managed
//! `[StructLayout]` is a second declaration and only agreement makes the
//! by-value group work.
//!
//! Output is JSON on stdout, consumed by `gen/cs_abi.py`. Nothing here is
//! measured; it is a build step.

use ak_abi::generated::abi::*;
use ak_abi::{ak_span, ak_str};
use std::mem::{align_of, size_of};

macro_rules! lay {
    ($out:expr, $t:ty, [$($f:ident),* $(,)?]) => {{
        let v = <$t>::ZERO;
        let base = &v as *const $t as usize;
        let mut fields: Vec<String> = Vec::new();
        $(
            let off = (&v.$f as *const _ as usize) - base;
            fields.push(format!("\\"{}\\": {}", stringify!($f), off));
        )*
        $out.push(format!(
            "    \\"{}\\": {{ \\"size\\": {}, \\"align\\": {}, \\"fields\\": {{ {} }} }}",
            stringify!($t), size_of::<$t>(), align_of::<$t>(), fields.join(", ")
        ));
    }};
}

/// A struct with no ZERO const, laid out by a default instance instead.
macro_rules! lay_raw {
    ($out:expr, $t:ty, $v:expr, [$($f:ident),* $(,)?]) => {{
        let v: $t = $v;
        let base = &v as *const $t as usize;
        let mut fields: Vec<String> = Vec::new();
        $(
            let off = (&v.$f as *const _ as usize) - base;
            fields.push(format!("\\"{}\\": {}", stringify!($f), off));
        )*
        $out.push(format!(
            "    \\"{}\\": {{ \\"size\\": {}, \\"align\\": {}, \\"fields\\": {{ {} }} }}",
            stringify!($t), size_of::<$t>(), align_of::<$t>(), fields.join(", ")
        ));
    }};
}

/// Every vtable's SLOT COUNT. Every slot is pointer sized, so a wrong count is a
/// wrong size and nothing subtler is needed to catch it -- which is the check
/// that would have caught a slot invented by analogy on `ak_dvt_TaskDetailed`.
macro_rules! vt {
    ($out:expr, $t:ty) => {{
        $out.push(format!(
            "    \\"{}\\": {{ \\"size\\": {}, \\"slots\\": {} }}",
            stringify!($t), size_of::<$t>(), size_of::<$t>() / size_of::<usize>()
        ));
    }};
}

fn main() {
    let mut out: Vec<String> = Vec::new();
    let mut pres: Vec<String> = Vec::new();
    let mut vts: Vec<String> = Vec::new();
    macro_rules! pc {
        ($c:ident) => { pres.push(format!("    \\"{}\\": {}", stringify!($c), $c)); };
    }

    lay_raw!(out, ak_str, ak_str::default(), [data, len, tc]);
    lay_raw!(out, ak_span, ak_span::default(), [off, len, coder]);
'''


def emit(ir, roots):
    o = [HEAD]
    for enc in (True, False):
        pre = "ak_efix_" if enc else "ak_dfix_"
        o.append("\n    // %s: the by-value group%s.\n"
                 % ("ENCODE" if enc else "DECODE",
                    "" if enc else ", whose blobs are ak_span OFFSETS"))
        for name in A.structs_for(ir, roots):
            fields = [f for f, _ in A.group_fields(ir.msg(name), enc)]
            o.append("    lay!(out, %s%s, [%s]);\n" % (pre, name, ", ".join(fields)))
        for ename, f in A.map_entries(ir, roots):
            o.append("    lay!(out, %s%s, [key, value, presence]);\n" % (pre, ename))

    o.append("\n    // The presence bits, read from the Rust constants rather than\n"
             "    // inferred from a field's position among the singular message children.\n"
             "    // The obvious rule is right today and is still a guess.\n")
    n = 0
    for enc in (True, False):
        for name in A.structs_for(ir, roots):
            m = ir.msg(name)
            for fname in A.presence_bits(m):
                o.append("    pc!(%s);\n" % A.presence_const(m, fname, enc))
                n += 1
    if n == 0:
        o.append("    let _ = &mut pres;\n")

    o.append("\n    // The vtables. A message that only ever appears as an INLINED\n"
             "    // child has none: TaskOptions is reached through TaskDetailed's.\n")
    for name in A.vtable_messages(ir, roots):
        o.append("    vt!(vts, ak_evt_%s);\n" % name)
        o.append("    vt!(vts, ak_dvt_%s);\n" % name)

    o.append('''
    println!("{{");
    println!("  \\"pointer_width\\": {},", size_of::<usize>() * 8);
    println!("  \\"structs\\": {{");
    println!("{}", out.join(",\\n"));
    println!("  }},");
    println!("  \\"presence\\": {{");
    println!("{}", pres.join(",\\n"));
    println!("  }},");
    println!("  \\"vtables\\": {{");
    println!("{}", vts.join(",\\n"));
    println!("  }}");
    println!("}}");
}
''')
    return "".join(o)
