"""Campaign glue (FIX-PLAN WP3, design/CAMPAIGN.md): the per-root table the codec suite's
criterion benchmark and the correctness pre-check drive, and the read-every-field visitors.

No wire rule here. For every root of this slice's plan it renders one `Ops` implementation
that names the calls each arm already has (prost via the tonic codec path, the facade's
generated prost impl, core-native drop/retain, core-ffi push drop/retain, core-ffi pull),
plus a `touch_*` visitor over BOTH object models that reads every field of a decoded value
(CAMPAIGN.md requirement 9: decode followed by reading every field). What "read" means is
stated once, here: every scalar and enum value; every string and bytes field's length and
first and last byte; every element of every repeated field and every map entry (key and
value); every present singular child and the active oneof member, recursively; the
facade's unknown-field bag length.
"""

import json


def q(x):
    return json.dumps(x)


HEAD = "// @generated by ffi/poc/rust/gen/rust_campaign.py from the plan. Do not edit.\n"


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def camel(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_") if p)


def _blob(expr):
    # length, first and last byte of a &[u8]-like expression
    return ("{ let b: &[u8] = %s.as_ref(); h = mix(h, b.len() as u64); "
            "if let (Some(f), Some(l)) = (b.first(), b.last()) { h = mix(h, *f as u64); h = mix(h, *l as u64); } }"
            % expr)


def _val(p, f, expr, model):
    """Statements reading one value of field `f` (not repeated), for model 'f' or 'p'."""
    k = f.kind
    if k == "string":
        return _blob("%s.as_bytes()" % expr)
    if k == "bytes":
        return _blob("%s" % expr)
    if k == "message":
        return "h = touch_%s_%s(&%s, h);" % (model, snake(f.of), expr)
    if k == "enum":
        return "h = mix(h, %s as u64);" % ("(%s).to_i32()" % expr if model == "f" else expr)
    if k == "bool":
        return "h = mix(h, (%s) as u64);" % expr
    if k == "double":
        return "h = mix(h, (%s).to_bits());" % expr
    return "h = mix(h, (%s) as u64);" % expr


def emit_touch(p, model):
    ns = "facade" if model == "f" else "p"
    o = []
    for name in p.order:
        m = p.msg(name)
        if m.synthetic:
            continue
        o.append("#[inline(never)]")
        o.append("pub fn touch_%s_%s(o: &%s::%s, mut h: u64) -> u64 {" % (model, snake(name), ns, name))
        for f in m.plain:
            fx = "o.%s" % f.name
            if f.card == "map":
                entry = p.msg(f.entry)
                kf = [g for g in entry.fields if g.tag == 1][0]
                vf = [g for g in entry.fields if g.tag == 2][0]
                o.append("    for (k, v) in %s.iter() { %s %s }" % (fx, _val(p, kf, "(*k)", model),
                                                               _val(p, vf, "(*v)", model)))
            elif f.card in ("repeated", "packed"):
                o.append("    h = mix(h, %s.len() as u64);" % fx)
                o.append("    for x in %s.iter() { %s }" % (fx, _val(p, f, "(*x)", model)))
            elif f.kind == "message":
                o.append("    if let Some(c) = %s.as_ref() { %s }" % (fx, _val(p, f, "(*c)", model)))
            elif f.explicit:
                o.append("    if let Some(x) = %s.as_ref() { %s }" % (fx, _val(p, f, "(*x)", model)))
            else:
                o.append("    %s" % _val(p, f, fx, model))
        for oname, members in m.oneofs.items():
            if model == "f":
                ty = "facade::%s%s" % (name, camel(oname))
            else:
                ty = "p::%s::%s" % (snake(name), camel(oname))
            o.append("    match o.%s.as_ref() {" % oname)
            for g in members:
                o.append("        Some(%s::%s(x)) => { h = mix(h, %d); %s }"
                         % (ty, camel(g.name), g.tag, _val(p, g, "(*x)", model)))
            o.append("        None => {}")
            o.append("    }")
        if model == "f":
            o.append("    #[cfg(feature = \"unknown-fields\")]")
            o.append("    { h = mix(h, o.unknown_fields.len() as u64); }")
        o.append("    h")
        o.append("}")
        o.append("")
    return o


def emit(p):
    o = [HEAD,
         "#![allow(clippy::all, non_camel_case_types, unused_variables, unused_mut)]",
         "use crate::{mix, Ops};",
         "use harness::arms::core_ffi_arm::Ctx;",
         "use harness::generated::binding;",
         "use facade::generated::{build, core_native};",
         "#[cfg(feature = \"unknown-fields\")]",
         "use facade::generated::core_native_retain;",
         "// The no-unknown build has no retain rendering; MODES there has no retain mode, so",
         "// `retain` is never true and the name resolves to the drop rendering.",
         "#[cfg(not(feature = \"unknown-fields\"))]",
         "use facade::generated::core_native as core_native_retain;",
         "use shapes_prost::shapes as p;",
         ""]
    o += emit_touch(p, "f")
    o += emit_touch(p, "p")
    pays = {}
    for pid, spec in sorted(p.payloads.items()):
        pays.setdefault(spec["root"], []).append(pid)
    for root in p.roots:
        s = snake(root)
        o.append("pub struct R_%s;" % root)
        o.append("impl Ops for R_%s {" % root)
        o.append("    const ROOT: &'static str = %s;" % q(root))
        o.append("    type F = facade::%s;" % root)
        o.append("    type P = p::%s;" % root)
        o.append("    fn build(pid: &str) -> Option<Self::F> {")
        o.append("        match pid {")
        for pid in pays.get(root, []):
            if pid == "P7.1":
                continue   # decode only (SHAPES.md: no canonical writer produces it); no builder
            o.append("            %s => Some(build::payload_%s()),"
                     % (q(pid), pid.lower().replace(".", "_")))
        o.append("            _ => None,")
        o.append("        }")
        o.append("    }")
        o.append("    fn n_decode(b: &[u8], retain: bool) -> Result<Self::F, i32> {")
        o.append("        if retain { core_native_retain::decode_%s(b) } else { core_native::decode_%s(b) }" % (s, s))
        o.append("    }")
        o.append("    fn n_encode(v: &Self::F, e: &mut ak_rt::Enc, retain: bool) {")
        o.append("        if retain { core_native_retain::encode_into_%s(v, e) } else { core_native::encode_into_%s(v, e) }" % (s, s))
        o.append("    }")
        # WP5 step 10: the retain calls exist only in the build with `unknown-fields`; the
        # no-unknown build never asks for them (campaign::MODES).
        o.append("    fn f_decode(c: &Ctx, b: &[u8], retain: bool) -> Result<Self::F, i32> {")
        o.append("        #[cfg(feature = \"unknown-fields\")]")
        o.append("        if retain { return binding::decode_with_%s_unk(c.dec, b); }" % s)
        o.append("        let _ = retain;")
        o.append("        binding::decode_with_%s(c.dec, b)" % s)
        o.append("    }")
        o.append("    fn f_encode(c: &Ctx, v: &Self::F, retain: bool) -> Result<usize, i32> {")
        o.append("        #[cfg(feature = \"unknown-fields\")]")
        o.append("        if retain { return binding::encode_into_%s_unk(c.enc, v, &c.tcs); }" % s)
        o.append("        let _ = retain;")
        o.append("        binding::encode_into_%s(c.enc, v, &c.tcs)" % s)
        o.append("    }")
        o.append("    fn f_pull(c: &Ctx, b: &[u8], retain: bool, toks: &mut Vec<i64>) -> Result<Self::F, i32> {")
        o.append("        #[cfg(feature = \"unknown-fields\")]")
        o.append("        if retain { return binding::parse_walk_with_%s_unk(c.dec, b, toks); }" % s)
        o.append("        let _ = retain;")
        o.append("        binding::parse_walk_with_%s(c.dec, b, toks)" % s)
        o.append("    }")
        o.append("    fn dec_ctx(c: &Ctx) -> *mut ak_abi::ak_dec_ctx { c.dec.%s }" % s)
        o.append("    fn touch_f(v: &Self::F) -> u64 { touch_f_%s(v, 0) }" % s)
        o.append("    fn touch_p(v: &Self::P) -> u64 { touch_p_%s(v, 0) }" % s)
        o.append("}")
        o.append("")
    o.append("/// Call `v.visit::<R>()` for the root named `root`; false if this slice has no such root.")
    o.append("pub fn with_root<V: crate::Visit>(root: &str, v: &mut V) -> bool {")
    o.append("    match root {")
    for root in p.roots:
        o.append("        %s => { v.visit::<R_%s>(); true }" % (q(root), root))
    o.append("        _ => false,")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("pub const ROOTS: &[&str] = &[%s];" % ", ".join(q(r) for r in p.roots))
    o.append("")
    return "\n".join(o)
