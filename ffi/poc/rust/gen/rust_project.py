"""Corpus harness glue: the PROJECTION of a decoded facade value (ffi/corpus/CONTRACT.md s.3).

Not a wire rule and not a layout: it reads a value the codec already decoded and prints the
contract's view of it -- the message's SET fields, in the sense every protobuf runtime
shares (`ListFields`):

  * an implicit-presence scalar equal to its default does not appear;
  * an explicit-presence field that is set appears, zero or not;
  * a message field that is present appears, empty body or not;
  * a repeated or map field appears when it has at least one element;
  * string -> JSON string; bytes -> lowercase hex; every integer and every enum -> a
    decimal string; bool -> true/false; double -> "%.17g" as a string; message -> object;
    repeated -> array; map -> object with stringified keys; a oneof member -> its field
    name, when set.

Renders from the plan's descriptor view (field name, kind, cardinality, presence), which is
the whole of what it needs; `_unknown` is not projected (the contract makes it optional).
"""

HEAD = ("// @generated by ffi/poc/rust/gen/rust_project.py from the corpus plan. Do not edit.\n")


def snake(camel_name):
    out = []
    for i, c in enumerate(camel_name):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def camel(s):
    return "".join(p.capitalize() for p in s.split("_"))


def _scalar_json(kind, v):
    """A Rust expression producing the serde_json::Value of one scalar `v` (a place)."""
    if kind == "string":
        return "Value::String(%s.clone())" % v
    if kind == "bytes":
        return "Value::String(hex(&%s[..]))" % v
    if kind == "bool":
        return "Value::Bool(%s)" % v
    if kind == "double":
        return "Value::String(g17(%s))" % v
    if kind == "enum":
        return "Value::String(%s.to_i32().to_string())" % v
    if kind == "message":
        raise AssertionError
    return "Value::String(%s.to_string())" % v


def _default_test(kind, v):
    if kind in ("string", "bytes"):
        return "!%s.is_empty()" % v
    if kind == "bool":
        return v
    if kind == "double":
        return "%s.to_bits() != 0" % v
    if kind == "enum":
        return "%s.to_i32() != 0" % v
    return "%s != 0" % v


def emit(p):
    o = [HEAD,
         "//! ffi/corpus/CONTRACT.md section 3: what a reader must SEE. One function per",
         "//! message, over the facade types.",
         "#![allow(clippy::all, unused_mut)]",
         "use super::types::*;",
         "use serde_json::{Map, Value};",
         "",
         "pub fn hex(b: &[u8]) -> String {",
         "    let mut s = String::with_capacity(b.len() * 2);",
         "    for x in b { s.push_str(&format!(\"{:02x}\", x)); }",
         "    s",
         "}",
         "",
         "/// C's `%.17g`, which is what the corpus's projections were printed with.",
         "pub fn g17(v: f64) -> String {",
         "    if v.is_nan() { return \"nan\".into(); }",
         "    if v.is_infinite() { return if v > 0.0 { \"inf\".into() } else { \"-inf\".into() }; }",
         "    if v == 0.0 { return if v.is_sign_negative() { \"-0\".into() } else { \"0\".into() }; }",
         "    let e = format!(\"{:.16e}\", v);",
         "    let (mant, exp) = e.split_once('e').unwrap();",
         "    let x: i32 = exp.parse().unwrap();",
         "    fn strip(s: &str) -> String {",
         "        if s.contains('.') { s.trim_end_matches('0').trim_end_matches('.').to_string() } else { s.to_string() }",
         "    }",
         "    if x < -4 || x >= 17 {",
         "        format!(\"{}e{}{:02}\", strip(mant), if x < 0 { '-' } else { '+' }, x.abs())",
         "    } else {",
         "        let prec = (16 - x) as usize;",
         "        strip(&format!(\"{:.*}\", prec, v))",
         "    }",
         "}",
         ""]
    for name in p.order:
        m = p.msg(name)
        if m.synthetic:
            continue
        o.append("pub fn project_%s(x: &%s) -> Value {" % (snake(name), name))
        o.append("    let mut m = Map::new();")
        for f in m.plain:
            v = "x.%s" % f.name
            if f.card == "map":
                o.append("    if !%s.is_empty() {" % v)
                o.append("        let mut mm = Map::new();")
                o.append("        for (k, val) in &%s { mm.insert(k.clone(), Value::String(val.clone())); }" % v)
                o.append("        m.insert(\"%s\".into(), Value::Object(mm));" % f.name)
                o.append("    }")
            elif f.card in ("repeated", "packed"):
                if f.kind == "message":
                    el = "project_%s(e)" % snake(f.of)
                else:
                    el = _scalar_json(f.kind, "(*e)" if f.kind in ("bool", "double") else "e")
                o.append("    if !%s.is_empty() {" % v)
                o.append("        m.insert(\"%s\".into(), Value::Array(%s.iter().map(|e| %s).collect()));"
                         % (f.name, v, el))
                o.append("    }")
            elif f.kind == "message":
                o.append("    if let Some(c) = &%s { m.insert(\"%s\".into(), project_%s(c)); }"
                         % (v, f.name, snake(f.of)))
            elif f.explicit:
                o.append("    if let Some(c) = &%s { m.insert(\"%s\".into(), %s); }"
                         % (v, f.name, _scalar_json(f.kind, "(*c)" if f.kind in ("bool", "double", "enum") else "c")))
            else:
                o.append("    if %s { m.insert(\"%s\".into(), %s); }"
                         % (_default_test(f.kind, v), f.name, _scalar_json(f.kind, v)))
        for oname, members in m.oneofs.items():
            ty = "%s%s" % (name, camel(oname))
            o.append("    match &x.%s {" % oname)
            o.append("        None => {}")
            for g in members:
                if g.kind == "message":
                    val = "project_%s(c)" % snake(g.of)
                else:
                    val = _scalar_json(g.kind, "(*c)" if g.kind in ("bool", "double", "enum") else "c")
                o.append("        Some(%s::%s(c)) => { m.insert(\"%s\".into(), %s); }"
                         % (ty, camel(g.name), g.name, val))
            o.append("    }")
        o.append("    Value::Object(m)")
        o.append("}")
        o.append("")
    return "\n".join(o)
