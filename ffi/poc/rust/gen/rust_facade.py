"""The facade types, and the `armonik` arm's codec over them.

Two emitted files:
  types.rs       the hand-written-shaped idiomatic types: String, bytes::Bytes, a real enum
                 with an Unknown that round-trips, Option for a singular message. This is the
                 shape packages/rust already uses (see armonik/src/objects/results/raw.rs).
  prost_impl.rs  a prost::Message impl per type. This is the `armonik` ARM: hand-written
                 types implementing prost::Message directly, with no conversion layer, which
                 is the bet packages/rust made. Generated rather than written, per R1.
"""
from rustnames import SCALAR, camel, facade_type, oneof_type, variant

HEAD = "// @generated by ffi/poc/rust/gen/%s from ffi/schema/shapes.json. Do not edit.\n"


def emit_types(ir):
    o = [HEAD % "generate.py", ""]
    for name in ir.enum_order:
        e = ir.enums[name]
        o.append("/// %s" % e.get("why", "Open enum: an unknown wire value round-trips losslessly."))
        o.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
        o.append("pub enum %s {" % name)
        for vname, v in e["values"].items():
            o.append("    %s," % variant(name, vname))
        o.append("    /// A value this build was not generated against. Kept so that it")
        o.append("    /// round-trips: the open-enum case of design/SHAPES.md.")
        o.append("    Unknown(i32),")
        o.append("}")
        zero = next(variant(name, k) for k, v in e["values"].items() if v == 0)
        o.append("impl Default for %s {" % name)
        o.append("    fn default() -> Self { Self::%s }" % zero)
        o.append("}")
        o.append("impl %s {" % name)
        o.append("    #[inline]")
        o.append("    pub fn to_i32(self) -> i32 {")
        o.append("        match self {")
        for vname, v in e["values"].items():
            o.append("            Self::%s => %d," % (variant(name, vname), v))
        o.append("            Self::Unknown(v) => v,")
        o.append("        }")
        o.append("    }")
        o.append("    #[inline]")
        o.append("    pub fn from_i32(v: i32) -> Self {")
        o.append("        match v {")
        for vname, v in e["values"].items():
            o.append("            %d => Self::%s," % (v, variant(name, vname)))
        o.append("            other => Self::Unknown(other),")
        o.append("        }")
        o.append("    }")
        o.append("}")
        o.append("")

    for name in ir.order:
        m = ir.msg(name)
        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            o.append("/// The `%s` oneof of `%s`. Exactly one member, and `None` for none:" % (oname, name))
            o.append("/// a member being there is what selects the variant, so presence is")
            o.append("/// information and the payload-free member is a variant like any other.")
            o.append("#[derive(Debug, Clone, PartialEq)]")
            o.append("pub enum %s {" % ty)
            for g in members:
                inner = ("String" if g.kind == "string"
                         else "::bytes::Bytes" if g.kind == "bytes"
                         else g.of if g.kind in ("message", "enum")
                         else SCALAR[g.kind])
                o.append("    %s(%s)," % (camel(g.name), inner))
            o.append("}")
            o.append("")
        if m.raw.get("source"):
            o.append("/// %s" % m.raw["source"])
        o.append("#[derive(Debug, Clone, Default, PartialEq)]")
        o.append("pub struct %s {" % name)
        for f in m.plain:
            o.append("    pub %s: %s," % (f.name, facade_type(f)))
        for oname in m.oneofs:
            o.append("    pub %s: Option<%s>," % (oname, oneof_type(name, oname)))
        o.append("}")
        o.append("")
    return "\n".join(o)


# --------------------------------------------------------------------------- prost arm

def _stmt(f):
    """One field's encode, guard included.

    Guard and value are emitted TOGETHER rather than as a predicate plus an expression.
    The first spelling emitted `if self.status.to_i32() != 0 { ...encode(&self.status.to_i32())... }`,
    which runs the enum's match twice, and `is_some()` followed by `as_ref().unwrap()`,
    which is a second branch and a panic path. Swept across every kind rather than fixed
    on the one that showed it.
    """
    n, t = "self.%s" % f.name, f.tag
    if f.card == "packed" and f.kind == "enum":
        # A packed enum is a packed int32 on the wire; the facade holds real enum values.
        return ("if !%s.is_empty() { let v: Vec<i32> = %s.iter().map(|x| x.to_i32()).collect();"
                " ::prost::encoding::int32::encode_packed(%d, &v, buf); }" % (n, n, t))
    if f.kind == "enum" and f.card == "singular":
        return ("{ let v = %s.to_i32(); if v != 0 { ::prost::encoding::int32::encode(%d, &v, buf); } }"
                % (n, t))
    if f.kind == "message" and f.card == "singular":
        return ("if let Some(v) = &%s { ::prost::encoding::message::encode(%d, v, buf); }" % (n, t))
    if f.explicit:
        return ("if let Some(v) = &%s { ::prost::encoding::%s::encode(%d, v, buf); }"
                % (n, f.kind, t))
    if f.kind == "message" and f.card == "repeated":
        return ("if !%s.is_empty() { ::prost::encoding::message::encode_repeated(%d, &%s, buf); }"
                % (n, t, n))
    if f.kind == "string":
        if f.card == "repeated":
            return ("if !%s.is_empty() { ::prost::encoding::string::encode_repeated(%d, &%s, buf); }"
                    % (n, t, n))
        return "if !%s.is_empty() { ::prost::encoding::string::encode(%d, &%s, buf); }" % (n, t, n)
    if f.kind == "bytes":
        return "if !%s.is_empty() { ::prost::encoding::bytes::encode(%d, &%s, buf); }" % (n, t, n)
    if f.card in ("packed",):
        return ("if !%s.is_empty() { ::prost::encoding::%s::encode_packed(%d, &%s, buf); }"
                % (n, f.kind, t, n))
    if f.card == "map":
        return ("if !%s.is_empty() { ::prost::encoding::btree_map::encode(%s, %s, %s, %s, %d, &%s, buf); }"
                % (n, "::prost::encoding::string::encode", "::prost::encoding::string::encoded_len",
                   "::prost::encoding::string::encode", "::prost::encoding::string::encoded_len", t, n))
    if f.kind == "bool":
        return "if %s { ::prost::encoding::bool::encode(%d, &%s, buf); }" % (n, t, n)
    return "if %s != 0 { ::prost::encoding::%s::encode(%d, &%s, buf); }" % (n, f.kind, t, n)


def _len_stmt(f):
    """The same, for encoded_len: one evaluation of the field, not two."""
    n, t = "self.%s" % f.name, f.tag
    if f.card == "packed" and f.kind == "enum":
        return ("if !%s.is_empty() { let v: Vec<i32> = %s.iter().map(|x| x.to_i32()).collect();"
                " n += ::prost::encoding::int32::encoded_len_packed(%d, &v); }" % (n, n, t))
    if f.kind == "enum" and f.card == "singular":
        return ("{ let v = %s.to_i32(); if v != 0 { n += ::prost::encoding::int32::encoded_len(%d, &v); } }"
                % (n, t))
    if f.kind == "message" and f.card == "singular":
        return ("if let Some(v) = &%s { n += ::prost::encoding::message::encoded_len(%d, v); }" % (n, t))
    if f.explicit:
        return ("if let Some(v) = &%s { n += ::prost::encoding::%s::encoded_len(%d, v); }"
                % (n, f.kind, t))
    if f.kind == "message" and f.card == "repeated":
        return ("if !%s.is_empty() { n += ::prost::encoding::message::encoded_len_repeated(%d, &%s); }"
                % (n, t, n))
    if f.kind == "string":
        if f.card == "repeated":
            return ("if !%s.is_empty() { n += ::prost::encoding::string::encoded_len_repeated(%d, &%s); }"
                    % (n, t, n))
        return "if !%s.is_empty() { n += ::prost::encoding::string::encoded_len(%d, &%s); }" % (n, t, n)
    if f.kind == "bytes":
        return "if !%s.is_empty() { n += ::prost::encoding::bytes::encoded_len(%d, &%s); }" % (n, t, n)
    if f.card == "packed":
        return ("if !%s.is_empty() { n += ::prost::encoding::%s::encoded_len_packed(%d, &%s); }"
                % (n, f.kind, t, n))
    if f.card == "map":
        return ("if !%s.is_empty() { n += ::prost::encoding::btree_map::encoded_len(%s, %s, %d, &%s); }"
                % (n, "::prost::encoding::string::encoded_len",
                   "::prost::encoding::string::encoded_len", t, n))
    if f.kind == "bool":
        return "if %s { n += ::prost::encoding::bool::encoded_len(%d, &%s); }" % (n, t, n)
    return "if %s != 0 { n += ::prost::encoding::%s::encoded_len(%d, &%s); }" % (n, f.kind, t, n)


def _oneof_enc(g):
    t = g.tag
    if g.kind == "string":
        return "::prost::encoding::string::encode(%d, x, buf)" % t
    if g.kind == "bytes":
        return "::prost::encoding::bytes::encode(%d, x, buf)" % t
    if g.kind == "message":
        return "::prost::encoding::message::encode(%d, x, buf)" % t
    return "::prost::encoding::%s::encode(%d, x, buf)" % (g.kind, t)


def _oneof_len(g):
    t = g.tag
    if g.kind == "string":
        return "::prost::encoding::string::encoded_len(%d, x)" % t
    if g.kind == "bytes":
        return "::prost::encoding::bytes::encoded_len(%d, x)" % t
    if g.kind == "message":
        return "::prost::encoding::message::encoded_len(%d, x)" % t
    return "::prost::encoding::%s::encoded_len(%d, x)" % (g.kind, t)


def _oneof_merge(ty, g, oname):
    """A oneof member on the wire REPLACES whatever member was there, which is what makes
    last-one-wins work and what an unknown member cannot do: the parser cannot tell an
    unknown oneof tag from any other unknown field, so it goes to the unknown set and the
    case stays at the last KNOWN member. Every arm here behaves that way, prost included."""
    v = "v"
    if g.kind == "string":
        init, mrg = "String::new()", "::prost::encoding::string::merge(wire_type, &mut %s, buf, ctx)" % v
    elif g.kind == "bytes":
        init, mrg = "Default::default()", "::prost::encoding::bytes::merge(wire_type, &mut %s, buf, ctx)" % v
    elif g.kind == "message":
        init, mrg = "%s::default()" % g.of, "::prost::encoding::message::merge(wire_type, &mut %s, buf, ctx)" % v
    else:
        init, mrg = "Default::default()", "::prost::encoding::%s::merge(wire_type, &mut %s, buf, ctx)" % (g.kind, v)
    return ("{ let mut v = %s; let r = %s; self.%s = Some(%s::%s(v)); r }"
            % (init, mrg, oname, ty, camel(g.name)))


def _merge(f):
    n, t = "self.%s" % f.name, f.tag
    if f.explicit and f.kind in ("string", "bytes"):
        # An explicit-presence blob is Option<T>: seeing the tag is what makes it present,
        # whatever its length. `get_or_insert_with` is what distinguishes present-and-empty
        # from absent here.
        return ("::prost::encoding::%s::merge(wire_type, %s.get_or_insert_with(Default::default), buf, ctx)"
                % (f.kind, n))
    if f.kind == "string":
        if f.card == "repeated":
            return "::prost::encoding::string::merge_repeated(wire_type, &mut %s, buf, ctx)" % n
        return "::prost::encoding::string::merge(wire_type, &mut %s, buf, ctx)" % n
    if f.kind == "bytes":
        return "::prost::encoding::bytes::merge(wire_type, &mut %s, buf, ctx)" % n
    if f.kind == "message":
        if f.card == "repeated":
            return "::prost::encoding::message::merge_repeated(wire_type, &mut %s, buf, ctx)" % n
        return ("::prost::encoding::message::merge(wire_type, "
                "%s.get_or_insert_with(Default::default), buf, ctx)" % n)
    if f.card == "packed" and f.kind == "enum":
        return ("{ let mut v: Vec<i32> = Vec::new();"
                " let r = ::prost::encoding::int32::merge_repeated(wire_type, &mut v, buf, ctx);"
                " %s.extend(v.into_iter().map(%s::from_i32)); r }" % (n, f.of))
    if f.kind == "enum" and f.card == "singular":
        return ("{ let mut v = %s.to_i32(); let r = ::prost::encoding::int32::merge("
                "wire_type, &mut v, buf, ctx); %s = %s::from_i32(v); r }"
                % (n, n, f.of))
    k = f.kind
    if f.explicit:
        return ("::prost::encoding::%s::merge(wire_type, %s.get_or_insert_with(Default::default), buf, ctx)"
                % (k, n))
    if f.card == "packed":
        return "::prost::encoding::%s::merge_repeated(wire_type, &mut %s, buf, ctx)" % (k, n)
    if f.card == "map":
        return ("::prost::encoding::btree_map::merge(::prost::encoding::string::merge, "
                "::prost::encoding::string::merge, &mut %s, buf, ctx)" % n)
    return "::prost::encoding::%s::merge(wire_type, &mut %s, buf, ctx)" % (k, n)


def emit_prost_impl(ir):
    o = [HEAD % "generate.py",
         "//! The `armonik` arm: a prost::Message impl per facade type, with no conversion",
         "//! layer, which is what packages/rust does through armonik-macros. Generated here",
         "//! because that crate's expansions reference armonik-internal paths and read a",
         "//! descriptor built from Protos/V1, so they cannot be reused outside it.",
         "#![allow(clippy::all)]",
         "use super::types::*;", ""]
    for name in ir.order:
        m = ir.msg(name)
        o.append("impl ::prost::Message for %s {" % name)
        o.append("    fn encode_raw(&self, buf: &mut impl ::prost::bytes::BufMut) {")
        for f in m.plain:
            o.append("        %s" % _stmt(f))
        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            o.append("        if let Some(v) = &self.%s {" % oname)
            o.append("            match v {")
            for g in members:
                o.append("                %s::%s(x) => %s," % (ty, camel(g.name), _oneof_enc(g)))
            o.append("            }")
            o.append("        }")
        o.append("    }")
        o.append("    fn encoded_len(&self) -> usize {")
        o.append("        let mut n = 0usize;")
        for f in m.plain:
            o.append("        %s" % _len_stmt(f))
        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            o.append("        if let Some(v) = &self.%s {" % oname)
            o.append("            match v {")
            for g in members:
                o.append("                %s::%s(x) => n += %s," % (ty, camel(g.name), _oneof_len(g)))
            o.append("            }")
            o.append("        }")
        o.append("        n")
        o.append("    }")
        o.append("    fn merge_field(")
        o.append("        &mut self,")
        o.append("        tag: u32,")
        o.append("        wire_type: ::prost::encoding::WireType,")
        o.append("        buf: &mut impl ::prost::bytes::Buf,")
        o.append("        ctx: ::prost::encoding::DecodeContext,")
        o.append("    ) -> Result<(), ::prost::DecodeError> {")
        o.append("        match tag {")
        for f in m.plain:
            o.append("            %d => %s," % (f.tag, _merge(f)))
        for oname, members in m.oneofs.items():
            ty = oneof_type(name, oname)
            for g in members:
                o.append("            %d => %s," % (g.tag, _oneof_merge(ty, g, oname)))
        o.append("            _ => ::prost::encoding::skip_field(wire_type, tag, buf, ctx),")
        o.append("        }")
        o.append("    }")
        o.append("    fn clear(&mut self) { *self = Default::default(); }")
        o.append("}")
        o.append("")
    return "\n".join(o)
