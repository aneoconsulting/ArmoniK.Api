SITE_NAMES = []


def emit_abi(ir):
    o = [HEAD,
         "//! The per-message part of the C ABI: section 6's groups and vtables, section 7's",
         "//! decode fixes. Both the core and the host binding compile against this file.",
         "#![allow(non_camel_case_types, non_upper_case_globals)]",
         "use super::super::{ak_dec_ctx, ak_enc_ctx, ak_span, ak_str};",
         "use core::ffi::c_void;",
         "",
         "/// A host-driven loop over one repeated, packed or map field. The context is the",
         "/// first argument of every host-facing callback (ABI v1 section 5), so a failure",
         "/// always has somewhere to go. `token` names which element of the enclosing run the",
         "/// field belongs to; `AK_TOKEN_ROOT` means the root object itself. A token is an",
         "/// INDEX, never an address, and the codec never dereferences one (section 10).",
         "pub type ak_loop_f = unsafe extern \"C\" fn(",
         "    ctx: *mut ak_enc_ctx,",
         "    obj: *const c_void,",
         "    token: i64,",
         ") -> i32;",
         "",
         "pub const AK_TOKEN_ROOT: i64 = -1;",
         ""]

    for name in ir.abi_order:
        m = ir.msg(name)
        bits = presence_bits(m)
        for enc in (True, False):
            pre = "e" if enc else "d"
            sname = "ak_%sfix_%s" % (pre, name)
            o.append("/// %s group for `%s`." % ("Encode" if enc else "Decode", name))
            o.append("#[repr(C)]")
            o.append("#[derive(Clone, Copy)]")
            o.append("pub struct %s {" % sname)
            fields = group_fields(m, enc)
            for fname, ty in fields:
                o.append("    pub %s: %s," % (fname, ty))
            o.append("    pub presence: u32,")
            o.append("}")
            o.append("impl %s {" % sname)
            o.append("    pub const ZERO: Self = %s {" % sname)
            for fname, ty in fields:
                o.append("        %s: %s," % (fname, _zero_of(ty)))
            o.append("        presence: 0,")
            o.append("    };")
            o.append("}")
            for fname, b in bits.items():
                o.append("pub const %s_PRESENT_%s: u32 = 1 << %d;" % (sname.upper(), fname.upper(), b))
            o.append("")

    for name in vtable_messages(ir):
        slots = loop_slots(ir, name)
        o.append("/// Encode vtable for `%s`. %s" %
                 (name, "Empty: nothing in this message needs a call."
                  if not slots else "One slot per field that could not ride in the group."))
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_evt_%s {" % name)
        if not slots:
            o.append("    /// Reserved. An empty struct has no defined size in C, so a vtable")
            o.append("    /// for a message that needs no call still carries one slot.")
            o.append("    pub _reserved: *const c_void,")
        for path, f in slots:
            o.append("    pub loop_%s: Option<ak_loop_f>," % slot_name(path))
            et = elem_type(f)
            if et and loop_slots(ir, et):
                o.append("    /// The element type has loop slots of its own, so the codec")
                o.append("    /// needs its vtable to reach them (ABI v1 section 6).")
                o.append("    pub elem_%s: *const ak_evt_%s," % (slot_name(path), et))
        o.append("}")
        o.append("")

        o.append("/// Decode vtable for `%s` (the push family, ABI v1 section 7.1)." % name)
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_dvt_%s {" % name)
        o.append("    pub apply: Option<")
        o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, *const ak_dfix_%s)," % name)
        o.append("    >,")
        for path, f in slots:
            sn = slot_name(path)
            dty, _ = slot_elem_rust(f)
            et = elem_type(f)
            batchable = not (et and not ir.msg(et).leaf)
            if batchable:
                o.append("    /// Batchable: the element type is a leaf, so a run crosses once")
                o.append("    /// per chunk. Append; never size to the count you were handed.")
                o.append("    pub add_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const %s, i32)," % dty)
                o.append("    >,")
            else:
                o.append("    /// NOT batchable: `%s` carries repeated or map fields of its own," % et)
                o.append("    /// so there would be nothing to attach the inner elements to")
                o.append("    /// (ABI v1 section 7.2). Two calls per element, `new` then")
                o.append("    /// `apply`, plus one run per inner field that occurred.")
                o.append("    pub new_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void) -> i64,")
                o.append("    >,")
                o.append("    pub apply_%s: Option<" % sn)
                o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const ak_dfix_%s)," % et)
                o.append("    >,")
                for ipath, iff in loop_slots(ir, et):
                    idty, _ = slot_elem_rust(iff)
                    iet = elem_type(iff)
                    if iet and not ir.msg(iet).leaf:
                        raise NotImplementedError(
                            "a non-leaf element inside a non-leaf element (%s.%s): the "
                            "schema has no instance, so this is refused rather than "
                            "emitted untested" % (et, slot_name(ipath)))
                    o.append("    pub add_%s_%s: Option<" % (sn, slot_name(ipath)))
                    o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, i64, *const %s, i32)," % idty)
                    o.append("    >,")
        o.append("}")
        o.append("")

    o.append("// ABI v1 section 6: what a host calls in the codec are PLAIN EXPORTS, not a")
    o.append("// table, so a missing symbol is a load failure, which is loud.")
    o.append("unsafe extern \"C\" {")
    for root in ir.roots:
        o.append("    pub fn ak_encode_%s(" % root)
        o.append("        obj: *const c_void,")
        o.append("        ctx: *mut ak_enc_ctx,")
        o.append("        vt: *const ak_evt_%s," % root)
        o.append("        fix: *const ak_efix_%s," % root)
        if direct_fields(ir, root):
            o.append("        // ABI v1 section 8: the one direct-argument field of this tree.")
            o.append("        direct: *const u8,")
            o.append("        direct_len: usize,")
        o.append("    ) -> isize;")
        o.append("    pub fn ak_decode_%s(" % root)
        o.append("        ctx: *mut ak_dec_ctx,")
        o.append("        obj: *mut c_void,")
        o.append("        buf: *const u8,")
        o.append("        len: usize,")
        o.append("        vt: *const ak_dvt_%s," % root)
        o.append("    ) -> i32;")
    for et in sorted(element_types(ir)):
        leaf = ir.msg(et).leaf
        if leaf:
            o.append("    /// Leaf form: `%s` is transitively free of repeated and map fields," % et)
            o.append("    /// so the codec makes no reverse call during a run.")
            o.append("    pub fn ak_elem_%s(ctx: *mut ak_enc_ctx, elems: *const ak_efix_%s, n: i32) -> i32;"
                     % (et, et))
        else:
            o.append("    /// Unrestricted form: names element i as `tok0 + i` from a contiguous")
            o.append("    /// token range the host allocated, because the codec has to call back")
            o.append("    /// into the host mid-run for `%s`'s own repeated fields." % et)
            o.append("    pub fn ak_elemu_%s(" % et)
            o.append("        ctx: *mut ak_enc_ctx,")
            o.append("        elems: *const ak_efix_%s," % et)
            o.append("        n: i32,")
            o.append("        tok0: i64,")
            o.append("    ) -> i32;")
    o.append("    /// A run of strings or bytes under the repeated field the codec has open.")
    o.append("    /// `n == 1` is the unbatched call, exactly as for elements.")
    o.append("    pub fn ak_blob_run(ctx: *mut ak_enc_ctx, elems: *const ak_str, n: i32) -> i32;")
    o.append("    /// A packed repeated scalar is the host's own array, handed over whole: one")
    o.append("    /// symbol per host layout, and the wire encoding comes from the schema and")
    o.append("    /// lives in the context, so bool and enum need no cases (ABI v1 section 6).")
    for ty in ("i32", "i64", "f64", "u8"):
        o.append("    pub fn ak_run_%s(ctx: *mut ak_enc_ctx, p: *const %s, n: usize) -> i32;" % (ty, ty))
    o.append("}")
    o.append("")
    o.append("/// What each length-prefix site of the core is, in site order, so a miss count")
    o.append("/// can name the field it came from (ABI v1 open decision 5). A descriptor fact,")
    o.append("/// so it lives in the header both sides compile against.")
    o.append("pub const SITE_NAMES: [&str; %d] = [" % len(SITE_NAMES))
    for n in SITE_NAMES:
        o.append("    \"%s\"," % n)
    o.append("];")
    o.append("")
    return "\n".join(o)


def element_types(ir):
    out = set()
    for name in ir.abi_order:
        for _, f in loop_slots(ir, name):
            et = elem_type(f)
            if et:
                out.add(et)
    return out


def oneof_message_members(ir):
    """A message-typed oneof member is reached through a group encoder of its own rather
    than inlined, because a oneof writes exactly one member and inlining all of them would
    duplicate every member's walk into every arm."""
    out = set()
    for name in ir.abi_order:
        for _, members in ir.msg(name).oneofs.items():
            for g in members:
                if g.kind == "message":
                    out.add(g.of)
    return out


# ============================================================== the core

def has_slots(ir, name):
    return bool(loop_slots(ir, name))


def _site(sites, key):
    return sites.id(key)


SAVE_LINES = """    // ABI v1: an element entry point must leave the codec's open-field state as it found
    // it. The host drives iteration over its own container and calls this once per chunk;
    // encoding an element sets the open state for the element's OWN repeated fields, so
    // without this the second chunk reads whatever the first element left behind. It was
    // found as a length-prefix site that would not converge, but the failure is worse than
    // that: `open_tag` is read here too, so a host that chunks would write the later chunks
    // under the inner field's tag. It did not corrupt this payload set only because
    // `ListTasksDetailedResponse.tasks` and `TaskOptions.options` are both tag 1.
    let saved = ((*cx).open_tag, (*cx).open_site, (*cx).open_kind, (*cx).open_vt, (*cx).open_obj);
""".rstrip("\n").split("\n")
