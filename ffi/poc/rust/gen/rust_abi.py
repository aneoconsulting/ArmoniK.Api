"""The C ABI of design/ABI-v1.md, the core behind it, and the host binding.

Three emitted files, one generator pass, so a group layout cannot be restated differently
on the two sides of the boundary (ABI v1 section 10). In C this pass is the generated
header plus two generated .c files.

Section 6's rules, applied:
  - the group carries the whole singular subtree, every singular child inlined whatever its
    size, with a presence word;
  - a string or bytes field rides in the group as `ak_str`, never as a call;
  - a repeated or map field keeps a loop slot in the vtable -- INCLUDING one that lives on
    an inlined child, which is reached through the parent, so `TaskOptions` never appears in
    the ABI as a message with a vtable of its own;
  - a map has no case: it is a repeated field of a pair message (section 11);
  - one element entry point taking a count, `n == 1` being the unbatched call. The leaf form
    `ak_elem_X` where the element type is transitively free of repeated and map fields, the
    unrestricted form `ak_elemu_X` with a token range otherwise.

Section 7.2's batching predicate on the decode side: a repeated field is handed over as a
run if and only if its element type is a leaf. `ListResultsResponse.results` qualifies and a
thousand rows arrive in a handful of calls; `ListTasksDetailedResponse.tasks` does not, and
keeps two calls per element plus one per repeated field it carries.
"""
from ir import direct_fields, loop_slots, slot_name
from rustnames import SCALAR

HEAD = "// @generated by ffi/poc/rust/gen/generate.py from ffi/schema/shapes.json. Do not edit.\n"

CSCALAR = {"int32": "i32", "int64": "i64", "bool": "u8", "double": "f64", "enum": "i32"}
ZERO = {"i32": "0", "i64": "0", "u8": "0", "f64": "0.0"}


def _camel(snake_name):
    return "".join(p.capitalize() for p in snake_name.split("_"))


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def presence_bits(m):
    """One bit per field whose presence its value cannot carry: a singular message child,
    and an explicit-presence scalar or string."""
    bits = {}
    for f in m.plain:
        if f.oneof:
            continue
        if (f.kind == "message" and f.card == "singular") or f.explicit:
            bits[f.name] = len(bits)
    return bits


def group_fields(m, enc):
    """The group's fields, in tag order.

    A oneof becomes a `<name>_case` discriminant carrying the ACTIVE MEMBER'S TAG, plus every
    member inlined beside it. Not a union: ABI v1 section 6 says a group needs a fixed shape
    and not a size bound, and a union would make the group's layout depend on which member is
    largest, which is a thing a host reproducing offsets by hand can get wrong silently. The
    cost is the size of the group; a union is an unmeasured alternative and is recorded as
    such rather than assumed equivalent.

    `<name>_case == 0` means no member is set. A value the codec does not recognise is
    refused with AK_ERR_ABI rather than encoded as nothing, because a host generated against
    a newer descriptor sending an unknown case is exactly the skew that must be loud.
    """
    out = []
    for f in m.plain:
        if f.oneof or f.card != "singular":
            continue
        if f.kind in ("string", "bytes"):
            out.append((f.name, "ak_str" if enc else "ak_span"))
        elif f.kind == "message":
            out.append((f.name, "ak_%sfix_%s" % ("e" if enc else "d", f.of)))
        else:
            out.append((f.name, CSCALAR[f.kind]))
    for oname, members in m.oneofs.items():
        out.append(("%s_case" % oname, "u32"))
        for g in members:
            n = "%s_%s" % (oname, g.name)
            if g.kind in ("string", "bytes"):
                out.append((n, "ak_str" if enc else "ak_span"))
            elif g.kind == "message":
                out.append((n, "ak_%sfix_%s" % ("e" if enc else "d", g.of)))
            else:
                out.append((n, CSCALAR[g.kind]))
    return out


ZERO["u32"] = "0"


def _zero_of(ty):
    if ty == "ak_str":
        return "ak_str { data: ::core::ptr::null(), len: 0, tc: None }"
    if ty == "ak_span":
        return "ak_span { off: 0, len: 0, coder: 0 }"
    if ty in ZERO:
        return ZERO[ty]
    return "%s::ZERO" % ty


def slot_elem_rust(f):
    """What one element of a loop slot looks like in a run."""
    if f.card == "map":
        return "ak_dfix_%s" % f.entry, "ak_efix_%s" % f.entry
    if f.kind in ("string", "bytes"):
        return "ak_span", "ak_str"
    if f.card == "packed":
        return CSCALAR[f.kind], CSCALAR[f.kind]
    if f.kind == "message":
        return "ak_dfix_%s" % f.of, "ak_efix_%s" % f.of
    raise NotImplementedError("slot %s %s" % (f.card, f.kind))


def elem_type(f):
    if f.card == "map":
        return f.entry
    if f.kind == "message":
        return f.of
    return None


def vtable_messages(ir):
    """Messages that get a vtable: every root, and every element type of a repeated-message
    or map slot. A message that only ever appears as an inlined child does not."""
    out = list(ir.roots)
    for name in ir.abi_order:
        for _, f in loop_slots(ir, name):
            et = elem_type(f)
            if et and et not in out:
                out.append(et)
    return out


