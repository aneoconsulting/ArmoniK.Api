"""The C ABI surface of design/ABI-v1.md, the core behind it, and the host binding.

Three emitted files, one generator pass, so the group layout cannot be restated differently
on the two sides of the boundary (ABI v1 section 10: "Group layouts are exported and
asserted at load"). In C this pass is the generated header plus two generated .c files.

Everything per-message here derives from the descriptor. Section 6's rules, applied:
  - the group carries the whole singular subtree, every singular child inlined whatever
    its size, with a presence word;
  - a string or bytes field rides in the group as `ak_str`, never as a call;
  - a repeated field keeps a loop slot in the vtable, and its elements cross as runs
    through one element entry point taking a count;
  - what the host calls are plain exports, not a table.
"""
from rustnames import SCALAR

HEAD = "// @generated by ffi/poc/rust/gen/generate.py from ffi/schema/shapes.json. Do not edit.\n"

CSCALAR = {"int32": "i32", "int64": "i64", "bool": "u8", "double": "f64", "enum": "i32"}
ZERO = {"i32": "0", "i64": "0", "u8": "0", "f64": "0.0"}


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def presence_bits(m):
    """One bit per field whose presence the group cannot infer from its value: a singular
    message child, and an explicit-presence scalar or string."""
    bits = {}
    for f in m.plain:
        if f.oneof:
            continue
        if (f.kind == "message" and f.card == "singular") or f.explicit:
            bits[f.name] = len(bits)
    return bits


def group_fields(m, enc):
    """(name, rust type) of the group, in tag order. `enc` picks ak_str against ak_span."""
    out = []
    for f in m.plain:
        if f.oneof:
            continue
        if f.card != "singular":
            continue                      # a repeated or map field keeps a loop slot instead
        if f.kind in ("string", "bytes"):
            out.append((f.name, "ak_str" if enc else "ak_span"))
        elif f.kind == "message":
            out.append((f.name, "ak_%sfix_%s" % ("e" if enc else "d", f.of)))
        else:
            out.append((f.name, CSCALAR[f.kind]))
    return out


def _zero_of(ty):
    if ty == "ak_str":
        return "ak_str { data: ::core::ptr::null(), len: 0, tc: None }"
    if ty == "ak_span":
        return "ak_span { off: 0, len: 0, coder: 0 }"
    if ty in ZERO:
        return ZERO[ty]
    return "%s::ZERO" % ty


def emit_abi(ir):
    o = [HEAD,
         "//! The per-message part of the C ABI: section 6's groups and vtables, section 7's",
         "//! decode fixes. Both the core and the host binding compile against this file.",
         "#![allow(non_camel_case_types, non_upper_case_globals)]",
         "use super::super::{ak_dec_ctx, ak_enc_ctx, ak_span, ak_str};",
         "use core::ffi::c_void;",
         "",
         "/// A host-driven loop over one repeated field. The context is the first argument of",
         "/// every host-facing callback (ABI v1 section 5), so a failure always has somewhere",
         "/// to go.",
         "pub type ak_loop_f =",
         "    unsafe extern \"C\" fn(ctx: *mut ak_enc_ctx, obj: *const c_void) -> i32;",
         ""]

    for name in ir.order:
        m = ir.msg(name)
        bits = presence_bits(m)
        for enc in (True, False):
            pre = "e" if enc else "d"
            sname = "ak_%sfix_%s" % (pre, name)
            o.append("/// %s group for `%s`%s" %
                     ("Encode" if enc else "Decode", name,
                      ": the whole singular subtree, inlined, with a presence word."
                      if enc else ": spans are offsets into the buffer the host handed in."))
            o.append("#[repr(C)]")
            o.append("#[derive(Clone, Copy)]")
            o.append("pub struct %s {" % sname)
            fields = group_fields(m, enc)
            for fname, ty in fields:
                o.append("    pub %s: %s," % (fname, ty))
            o.append("    /// Bit per field whose presence its value cannot carry.")
            o.append("    pub presence: u32,")
            o.append("}")
            o.append("impl %s {" % sname)
            o.append("    pub const ZERO: Self = %s {" % sname)
            for fname, ty in fields:
                o.append("        %s: %s," % (fname, _zero_of(ty)))
            o.append("        presence: 0,")
            o.append("    };")
            o.append("}")
            for fname, b in bits.items():
                o.append("pub const %s_PRESENT_%s: u32 = 1 << %d;"
                         % (sname.upper(), fname.upper(), b))
            o.append("")

        # vtables, for the fields that could not ride in the group
        loops = [f for f in m.plain if not f.oneof and f.card in ("repeated", "packed", "map")]
        o.append("/// Encode vtable for `%s`. %s" %
                 (name, "Empty: nothing in this message needs a call." if not loops
                  else "One slot per field that could not ride in the group."))
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_evt_%s {" % name)
        for f in loops:
            o.append("    pub loop_%s: Option<ak_loop_f>," % f.name)
        o.append("}")
        o.append("")
        o.append("/// Decode vtable for `%s` (the push family, ABI v1 section 7.1)." % name)
        o.append("#[repr(C)]")
        o.append("#[derive(Clone, Copy)]")
        o.append("pub struct ak_dvt_%s {" % name)
        o.append("    pub apply: Option<")
        o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, *const ak_dfix_%s),"
                 % name)
        o.append("    >,")
        for f in loops:
            if f.kind != "message":
                continue
            o.append("    /// A batched add may be called more than once per field: append,")
            o.append("    /// never size to the count you were handed (ABI v1 section 7.4).")
            o.append("    pub add_%s: Option<" % f.name)
            o.append("        unsafe extern \"C\" fn(*mut ak_dec_ctx, *mut c_void, *const ak_dfix_%s, i32),"
                     % f.of)
            o.append("    >,")
        o.append("}")
        o.append("")

    o.append("unsafe extern \"C\" {")
    for root in ir.roots:
        o.append("    /// Encode. The host filled the root group before calling, so a failure")
        o.append("    /// there needs no channel: the host simply does not call.")
        o.append("    pub fn ak_encode_%s(" % root)
        o.append("        obj: *const c_void,")
        o.append("        ctx: *mut ak_enc_ctx,")
        o.append("        vt: *const ak_evt_%s," % root)
        o.append("        fix: *const ak_efix_%s," % root)
        o.append("    ) -> isize;")
        o.append("    /// Decode, push family: the arena is a local of this function, so it is")
        o.append("    /// per decode rather than per thread.")
        o.append("    pub fn ak_decode_%s(" % root)
        o.append("        ctx: *mut ak_dec_ctx,")
        o.append("        obj: *mut c_void,")
        o.append("        buf: *const u8,")
        o.append("        len: usize,")
        o.append("        vt: *const ak_dvt_%s," % root)
        o.append("    ) -> i32;")
    for name in ir.order:
        m = ir.msg(name)
        if not m.leaf:
            continue
        if not any(f.kind == "message" and f.of == name
                   for n2 in ir.order for f in ir.msg(n2).plain if f.card == "repeated"):
            continue
        o.append("    /// One element entry point taking a count, not two symbols: `n == 1`")
        o.append("    /// is the unbatched call (ABI v1 section 6). The leaf form, because")
        o.append("    /// `%s` is transitively free of repeated and map fields." % name)
        o.append("    pub fn ak_elem_%s(ctx: *mut ak_enc_ctx, elems: *const ak_efix_%s, n: i32) -> i32;"
                 % (name, name))
    o.append("}")
    o.append("")
    return "\n".join(o)


# ============================================ backend: the core behind the C ABI

def _upper(sname):
    return sname.upper()


def emit_codec(ir):
    from rust_core import Sites, walk_encode, walk_decode
    sites = Sites()

    class GroupEnc:
        """Reads an `ak_efix_*` group the host filled. Same field walk as the native
        backend; only the source of a value differs."""

        def blob(self, m, f, o):
            s = sites.id(("blob", m.name, f.name))
            cond = "g.%s.tc.is_some()" % f.name
            if not f.explicit:
                # implicit presence: absent and empty are the same thing on the wire
                cond += " && g.%s.len != 0" % f.name
            o.append("    if %s {" % cond)
            o.append("        if !enc_blob(cx, %d, %d, &g.%s) { return false; }" % (f.tag, s, f.name))
            o.append("    }")

        def scalar(self, m, f, o):
            n = "g.%s" % f.name
            if f.kind == "bool":
                o.append("    if %s != 0 { (*cx).e.varint_field(%d, 1); }" % (n, f.tag))
            elif f.kind in ("int32", "enum"):
                o.append("    if %s != 0 { (*cx).e.varint_field(%d, %s as i64 as u64); }" % (n, f.tag, n))
            else:
                o.append("    if %s != 0 { (*cx).e.varint_field(%d, %s as u64); }" % (n, f.tag, n))

        def double(self, m, f, o):
            o.append("    if g.%s != 0.0 { (*cx).e.f64_field(%d, g.%s); }" % (f.name, f.tag, f.name))

        def child(self, m, f, o):
            s = sites.id(("child", m.name, f.name))
            bit = "AK_EFIX_%s_PRESENT_%s" % (m.name.upper(), f.name.upper())
            o.append("    if g.presence & %s != 0 {" % bit)
            o.append("        let mk = (*cx).e.begin(%d, %d);" % (f.tag, s))
            o.append("        if !enc_%s_group(&g.%s, cx) { return false; }" % (snake(f.of), f.name))
            o.append("        (*cx).e.end(mk);")
            o.append("    }")

        def repeated_message(self, m, f, o):
            # Handled by the root entry point, which opens the field and calls the host's
            # loop: the codec drives and the host supplies the elements (ABI v1 rule 2).
            pass

    class FixDec:
        def blob(self, m, f, o):
            o.append("            %d if wire == 2 => {" % f.tag)
            o.append("                let (off, n) = d.len_body();")
            o.append("                out.%s = ak_span { off: (base + off) as u32, len: n as u32, coder: 0 };"
                     % f.name)
            o.append("            }")

        def scalar(self, m, f, o):
            if f.kind == "bool":
                o.append("            %d if wire == 0 => out.%s = (d.varint() != 0) as u8," % (f.tag, f.name))
            elif f.kind in ("int32", "enum"):
                o.append("            %d if wire == 0 => out.%s = d.varint() as i32," % (f.tag, f.name))
            else:
                o.append("            %d if wire == 0 => out.%s = d.varint() as i64," % (f.tag, f.name))

        def double(self, m, f, o):
            o.append("            %d if wire == 1 => out.%s = d.f64()," % (f.tag, f.name))

        def child(self, m, f, o):
            bit = "AK_DFIX_%s_PRESENT_%s" % (m.name.upper(), f.name.upper())
            o.append("            %d if wire == 2 => {" % f.tag)
            o.append("                let (off, n) = d.len_body();")
            o.append("                let mut sub = Dec::new(&buf[off..off + n]);")
            o.append("                out.%s = dec_%s_fix(&mut sub, base + off);" % (f.name, snake(f.of)))
            o.append("                if sub.err != 0 { d.err = sub.err; }")
            o.append("                out.presence |= %s;" % bit)
            o.append("            }")

        def repeated_message(self, m, f, o):
            pass

    body = []
    for name in ir.order:
        m = ir.msg(name)
        body.append("#[inline]")
        body.append("unsafe fn enc_%s_group(g: &ak_efix_%s, cx: *mut EncCtxImpl) -> bool {"
                    % (snake(name), name))
        walk_encode(ir, m, GroupEnc(), body)
        body.append("    true")
        body.append("}")
        body.append("")

    # One element entry point per element type, taking a count. `n == 1` is the unbatched call.
    elem_types = []
    for name in ir.order:
        for f in ir.msg(name).plain:
            if f.card == "repeated" and f.kind == "message" and f.of not in elem_types:
                elem_types.append(f.of)
    for et in elem_types:
        body.append("/// Leaf form: `%s` is transitively free of repeated and map fields, so the" % et)
        body.append("/// codec makes no reverse call during a run and a host failure cannot happen")
        body.append("/// mid-run (ABI v1 section 6).")
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_elem_%s(" % et)
        body.append("    ctx: *mut ak_enc_ctx,")
        body.append("    elems: *const ak_efix_%s," % et)
        body.append("    n: i32,")
        body.append(") -> i32 {")
        body.append("    let cx = ctx as *mut EncCtxImpl;")
        body.append("    ak_rt::bump!((*cx).e.c, forward);")
        body.append("    let (tag, site) = ((*cx).open_tag, (*cx).open_site);")
        body.append("    for i in 0..n as usize {")
        body.append("        let mk = (*cx).e.begin(tag, site);")
        body.append("        if !enc_%s_group(&*elems.add(i), cx) { return (*cx).e.err; }" % snake(et))
        body.append("        (*cx).e.end(mk);")
        body.append("    }")
        body.append("    AK_OK")
        body.append("}")
        body.append("")

    for root in ir.roots:
        m = ir.msg(root)
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_encode_%s(" % root)
        body.append("    obj: *const c_void,")
        body.append("    ctx: *mut ak_enc_ctx,")
        body.append("    vt: *const ak_evt_%s," % root)
        body.append("    fix: *const ak_efix_%s," % root)
        body.append(") -> isize {")
        body.append("    let cx = ctx as *mut EncCtxImpl;")
        body.append("    ak_rt::bump!((*cx).e.c, forward);")
        body.append("    let g = &*fix;")
        for f in m.plain:
            if f.card == "repeated" and f.kind == "message":
                s = sites.id(("elem", root, f.name))
                body.append("    if let Some(lp) = (*vt).loop_%s {" % f.name)
                body.append("        (*cx).open_tag = %d;" % f.tag)
                body.append("        (*cx).open_site = %d;" % s)
                body.append("        ak_rt::bump!((*cx).e.c, reverse);")
                body.append("        let rc = lp(ctx, obj);")
                body.append("        if rc < 0 { (*cx).e.fail(rc); return rc as isize; }")
                body.append("        if (*cx).e.err != 0 { return (*cx).e.err as isize; }")
                body.append("    }")
            elif f.card == "singular" and f.kind in ("int32", "int64", "bool", "enum"):
                GroupEnc().scalar(m, f, body)
            elif f.card == "singular" and f.kind in ("string", "bytes"):
                GroupEnc().blob(m, f, body)
            elif f.card == "singular" and f.kind == "message":
                GroupEnc().child(m, f, body)
            else:
                raise NotImplementedError("root field %s.%s" % (root, f.name))
        body.append("    (*cx).e.buf.len() as isize")
        body.append("}")
        body.append("")

    # ---- decode
    for name in ir.order:
        m = ir.msg(name)
        body.append("#[inline]")
        body.append("unsafe fn dec_%s_fix(d: &mut Dec, base: usize) -> ak_dfix_%s {"
                    % (snake(name), name))
        body.append("    let mut out = ak_dfix_%s::ZERO;" % name)
        body.append("    #[allow(unused_variables)]")
        body.append("    let buf = d.buf;")
        body.append("    while !d.at_end() {")
        body.append("        let k = d.varint();")
        body.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        body.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
        body.append("        match tag {")
        walk_decode(ir, m, FixDec(), body)
        body.append("            _ => d.skip(wire),")
        body.append("        }")
        body.append("    }")
        body.append("    out")
        body.append("}")
        body.append("")

    for root in ir.roots:
        m = ir.msg(root)
        reps = [f for f in m.plain if f.card == "repeated" and f.kind == "message"]
        body.append("#[no_mangle]")
        body.append("pub unsafe extern \"C\" fn ak_decode_%s(" % root)
        body.append("    ctx: *mut ak_dec_ctx,")
        body.append("    obj: *mut c_void,")
        body.append("    buf: *const u8,")
        body.append("    len: usize,")
        body.append("    vt: *const ak_dvt_%s," % root)
        body.append(") -> i32 {")
        body.append("    let dcx = ctx as *mut DecCtxImpl;")
        body.append("    ak_rt::bump!((*dcx).c, forward);")
        body.append("    let slice = ::core::slice::from_raw_parts(buf, len);")
        body.append("    let mut d = Dec::new(slice);")
        body.append("    let mut fx = ak_dfix_%s::ZERO;" % root)
        for f in reps:
            body.append("    // ABI v1 7.3: the arena is a local of THIS function, so it is per decode")
            body.append("    // rather than per thread; a byte budget divided by the group size, so the")
            body.append("    // scratch is the same 32 KB whatever the schema does.")
            body.append("    const N_%s: usize = ak_rt::arena_n(::core::mem::size_of::<ak_dfix_%s>());"
                        % (f.name.upper(), f.of))
            body.append("    let mut a_%s: [::core::mem::MaybeUninit<ak_dfix_%s>; N_%s] ="
                        % (f.name, f.of, f.name.upper()))
            body.append("        [const { ::core::mem::MaybeUninit::uninit() }; N_%s];" % f.name.upper())
            body.append("    let mut n_%s: usize = 0;" % f.name)
        body.append("    macro_rules! flush {")
        body.append("        () => {")
        for f in reps:
            body.append("            if n_%s > 0 {" % f.name)
            body.append("                if let Some(add) = (*vt).add_%s {" % f.name)
            body.append("                    ak_rt::bump!((*dcx).c, reverse);")
            body.append("                    add(ctx, obj, a_%s.as_ptr() as *const ak_dfix_%s, n_%s as i32);"
                        % (f.name, f.of, f.name))
            body.append("                }")
            body.append("                n_%s = 0;" % f.name)
            body.append("            }")
        body.append("        };")
        body.append("    }")
        body.append("    while !d.at_end() {")
        body.append("        let k = d.varint();")
        body.append("        let (tag, wire) = ((k >> 3) as u32, (k & 7) as u32);")
        body.append("        if tag == 0 { d.err = ak_rt::ERR_MALFORMED; break; }")
        body.append("        match tag {")
        for f in m.plain:
            if f in reps:
                body.append("            %d if wire == 2 => {" % f.tag)
                body.append("                if n_%s == N_%s { flush!(); }" % (f.name, f.name.upper()))
                body.append("                let (off, n) = d.len_body();")
                body.append("                let mut sub = Dec::new(&slice[off..off + n]);")
                body.append("                a_%s[n_%s].write(dec_%s_fix(&mut sub, off));"
                            % (f.name, f.name, snake(f.of)))
                body.append("                if sub.err != 0 { d.err = sub.err; }")
                body.append("                n_%s += 1;" % f.name)
                body.append("            }")
            elif f.card == "singular" and f.kind in ("int32", "int64", "bool", "enum"):
                body.append("            // ABI v1 7.3: the arena is flushed whenever a tag arrives that")
                body.append("            // does not belong to the open batch. Correctness, not tidiness:")
                body.append("            // protobuf permits A B A B and prost's contiguity is a property")
                body.append("            // of prost, not of the format.")
                if f.kind == "bool":
                    body.append("            %d if wire == 0 => { flush!(); fx.%s = (d.varint() != 0) as u8; }" % (f.tag, f.name))
                elif f.kind in ("int32", "enum"):
                    body.append("            %d if wire == 0 => { flush!(); fx.%s = d.varint() as i32; }" % (f.tag, f.name))
                else:
                    body.append("            %d if wire == 0 => { flush!(); fx.%s = d.varint() as i64; }" % (f.tag, f.name))
            else:
                raise NotImplementedError("root decode %s.%s" % (root, f.name))
        body.append("            _ => { flush!(); d.skip(wire); }")
        body.append("        }")
        body.append("    }")
        body.append("    flush!();")
        body.append("    if let Some(apply) = (*vt).apply {")
        body.append("        ak_rt::bump!((*dcx).c, reverse);")
        body.append("        apply(ctx, obj, &fx);")
        body.append("    }")
        body.append("    if d.err != 0 { d.err } else { AK_OK }")
        body.append("}")
        body.append("")

    o = [HEAD,
         "//! The core behind the C ABI. Same traversal emitter as `core-native`, and the only",
         "//! difference is that a value comes from a group the host filled rather than from a",
         "//! facade object directly.",
         "#![allow(non_snake_case, non_camel_case_types, unused_unsafe, unused_variables,",
         "    unused_assignments, unused_mut, clippy::all)]",
         "use crate::{enc_blob, DecCtxImpl, EncCtxImpl};",
         "use ak_abi::*;",
         "use ak_rt::dec::Dec;",
         "use core::ffi::c_void;",
         "",
         "/// One learned length-prefix slot per site. Per context, never process-global.",
         "pub const SITES: usize = %d;" % len(sites),
         ""]
    o += body
    return "\n".join(o)


# ==================================================== backend: the host binding

def emit_binding(ir):
    """Arm `core-ffi-rust`: the generated binding.

    This is the code a generator emits into each host language, and it is the thing the
    interface-cost decomposition prices. Two invariants from ABI v1 are load-bearing here
    and both are generated rather than left to a binding author's discipline:

      - section 6, "the fill must be total": every scalar, every count and all three words
        of every `ak_str` are assigned unconditionally, and the presence word is assigned
        rather than OR-ed. In exchange the codec does not reset the element group between
        elements. A partial fill does not fail, it silently inherits the previous element's
        value, which is why the group is built by a constructor here and not by a sequence
        of stores into a reused slot.
      - section 5, the guard: an accessor that cannot fail is a process abort, because a
        panic crossing `extern "C"` aborts. Every reverse-call accessor is wrapped so that
        a panic becomes `ak_fail` plus a return.
    """
    o = [HEAD,
         "//! Arm `core-ffi-rust`: the generated host binding.",
         "#![allow(non_snake_case, non_camel_case_types, clippy::all)]",
         "use ak_abi::*;",
         "use core::ffi::c_void;",
         "use facade::*;",
         "",
         "/// ABI v1 section 5. Rust's analogue of the managed guard: a panic crossing",
         "/// `extern \"C\"` aborts the process, so the binding catches it and reports it",
         "/// through the context it was handed. On by default; the `no-guard` build exists",
         "/// only to price it, because every published managed figure was taken without it.",
         "#[inline]",
         "fn guard<F: FnOnce() -> i32>(ctx: *mut ak_enc_ctx, f: F) -> i32 {",
         "    #[cfg(feature = \"guard\")]",
         "    {",
         "        match ::std::panic::catch_unwind(::std::panic::AssertUnwindSafe(f)) {",
         "            Ok(rc) => rc,",
         "            Err(_) => unsafe {",
         "                let m = b\"host panic in a reverse call\";",
         "                ak_fail(ctx as *mut c_void, AK_ERR_HOST, m.as_ptr(), m.len() as u32);",
         "                AK_ERR_HOST",
         "            },",
         "        }",
         "    }",
         "    #[cfg(not(feature = \"guard\"))]",
         "    {",
         "        let _ = ctx;",
         "        f()",
         "    }",
         "}",
         "",
         "#[inline]",
         "fn dguard<F: FnOnce()>(f: F) {",
         "    #[cfg(feature = \"guard\")]",
         "    {",
         "        let _ = ::std::panic::catch_unwind(::std::panic::AssertUnwindSafe(f));",
         "    }",
         "    #[cfg(not(feature = \"guard\"))]",
         "    {",
         "        f()",
         "    }",
         "}",
         "",
         "/// ABI v1 section 7.4: resolve spans against the base pointer you already hold.",
         "/// Indexing a copy of the buffer instead measures 14 percent worse on .NET and it is",
         "/// the obvious thing to write, so the generator writes the other one.",
         "#[inline(always)]",
         "unsafe fn s_of(base: *const u8, s: ak_span) -> String {",
         "    // A zero-length span is the common case on the absent path (P1.3, P2.5), and",
         "    // it must not go through the transcode-and-validate path at all.",
         "    if s.len == 0 {",
         "        return String::new();",
         "    }",
         "    let b = ::core::slice::from_raw_parts(base.add(s.off as usize), s.len as usize);",
         "    String::from_utf8_lossy(b).into_owned()",
         "}",
         "",
         "#[inline(always)]",
         "unsafe fn b_of(base: *const u8, s: ak_span) -> ::bytes::Bytes {",
         "    if s.len == 0 {",
         "        return ::bytes::Bytes::new();",
         "    }",
         "    ::bytes::Bytes::copy_from_slice(",
         "        ::core::slice::from_raw_parts(base.add(s.off as usize), s.len as usize),",
         "    )",
         "}",
         "",
         "/// The transcoders, resolved once. `ak_tc_utf8_trusted` rather than `ak_tc_utf8`",
         "/// because a Rust `String` is UTF-8 by construction: validating it is the core",
         "/// re-checking what the host's type system already proved. ABI v1 open decision 3",
         "/// is about which of the two the specification should name, and the harness",
         "/// measures both.",
         "pub struct Tcs {",
         "    pub utf8: ak_transcode_fn,",
         "    pub bytes: ak_transcode_fn,",
         "}",
         "",
         "impl Tcs {",
         "    pub fn trusted() -> Self {",
         "        unsafe { Tcs { utf8: ak_tc_utf8_trusted(), bytes: ak_tc_bytes() } }",
         "    }",
         "    pub fn validating() -> Self {",
         "        unsafe { Tcs { utf8: ak_tc_utf8(), bytes: ak_tc_bytes() } }",
         "    }",
         "}",
         "",
         "thread_local! {",
         "    // Only the transcoder choice, which the loop callback cannot be handed: the",
         "    // callback's arguments are the ABI's, not ours. Nothing else in this binding is",
         "    // a thread-local.",
         "    static TCS: ::std::cell::Cell<(Option<ak_transcode_fn>, Option<ak_transcode_fn>)> =",
         "        const { ::std::cell::Cell::new((None, None)) };",
         "}",
         "",
         "#[inline(always)]",
         "fn tcs() -> (ak_transcode_fn, ak_transcode_fn) {",
         "    let (a, b) = TCS.with(|c| c.get());",
         "    (a.unwrap(), b.unwrap())",
         "}",
         ""]

    # ---- group constructors (encode)
    for name in ir.order:
        m = ir.msg(name)
        bits = presence_bits(m)
        o.append("/// Total fill: every field assigned, presence assigned and not OR-ed.")
        o.append("#[inline(always)]")
        o.append("fn make_%s(o: &%s, tc: (ak_transcode_fn, ak_transcode_fn)) -> ak_efix_%s {"
                 % (snake(name), name, name))
        o.append("    ak_efix_%s {" % name)
        pres = []
        for f in m.plain:
            if f.card != "singular":
                continue
            if f.kind == "string":
                o.append("        %s: ak_str { data: o.%s.as_ptr() as *const c_void, len: o.%s.len(), tc: Some(tc.0) },"
                         % (f.name, f.name, f.name))
            elif f.kind == "bytes":
                o.append("        %s: ak_str { data: o.%s.as_ptr() as *const c_void, len: o.%s.len(), tc: Some(tc.1) },"
                         % (f.name, f.name, f.name))
            elif f.kind == "message":
                o.append("        %s: match &o.%s {" % (f.name, f.name))
                o.append("            Some(c) => make_%s(c, tc)," % snake(f.of))
                o.append("            None => ak_efix_%s::ZERO," % f.of)
                o.append("        },")
                pres.append("((o.%s.is_some() as u32) << %d)" % (f.name, bits[f.name]))
            elif f.kind == "enum":
                o.append("        %s: o.%s.to_i32()," % (f.name, f.name))
            elif f.kind == "bool":
                o.append("        %s: o.%s as u8," % (f.name, f.name))
            else:
                o.append("        %s: o.%s," % (f.name, f.name))
        o.append("        presence: %s," % (" | ".join(pres) if pres else "0"))
        o.append("    }")
        o.append("}")
        o.append("")

    # ---- loop callbacks and the encode entry
    for root in ir.roots:
        m = ir.msg(root)
        for f in m.plain:
            if not (f.card == "repeated" and f.kind == "message"):
                continue
            o.append("/// Batched element runs are host-driven and chunked at 32 KB: the host fills")
            o.append("/// an array of element groups from objects it is already walking and hands")
            o.append("/// over extracted data. The codec never names a host object, never")
            o.append("/// dereferences one, and nothing is pinned.")
            o.append("const CHUNK_%s: usize = ak_rt::arena_n(::core::mem::size_of::<ak_efix_%s>());"
                     % (f.of.upper(), f.of))
            o.append("")
            o.append("unsafe extern \"C\" fn loop_%s(ctx: *mut ak_enc_ctx, obj: *const c_void) -> i32 {"
                     % f.name)
            o.append("    guard(ctx, || {")
            o.append("        let o = &*(obj as *const %s);" % root)
            o.append("        let tc = tcs();")
            o.append("        let mut chunk: [::core::mem::MaybeUninit<ak_efix_%s>; CHUNK_%s] ="
                     % (f.of, f.of.upper()))
            o.append("            [const { ::core::mem::MaybeUninit::uninit() }; CHUNK_%s];" % f.of.upper())
            o.append("        let mut i = 0usize;")
            o.append("        for r in &o.%s {" % f.name)
            o.append("            chunk[i].write(make_%s(r, tc));" % snake(f.of))
            o.append("            i += 1;")
            o.append("            if i == CHUNK_%s {" % f.of.upper())
            o.append("                let rc = ak_elem_%s(ctx, chunk.as_ptr() as *const ak_efix_%s, i as i32);"
                     % (f.of, f.of))
            o.append("                if rc < 0 { return rc; }")
            o.append("                i = 0;")
            o.append("            }")
            o.append("        }")
            o.append("        if i > 0 {")
            o.append("            let rc = ak_elem_%s(ctx, chunk.as_ptr() as *const ak_efix_%s, i as i32);"
                     % (f.of, f.of))
            o.append("            if rc < 0 { return rc; }")
            o.append("        }")
            o.append("        AK_OK")
            o.append("    })")
            o.append("}")
            o.append("")

        o.append("/// Encode into a context the caller owns, so the learned length widths survive")
        o.append("/// between calls and the allocation is not inside what is timed.")
        o.append("pub fn encode_into(ctx: *mut ak_enc_ctx, o: &%s, t: &Tcs) -> Result<usize, i32> {" % root)
        o.append("    unsafe {")
        o.append("        TCS.with(|c| c.set((Some(t.utf8), Some(t.bytes))));")
        o.append("        ak_enc_reset(ctx);")
        o.append("        let vt = ak_evt_%s {" % root)
        for f in m.plain:
            if f.card == "repeated" and f.kind == "message":
                o.append("            loop_%s: Some(loop_%s)," % (f.name, f.name))
        o.append("        };")
        o.append("        let fix = make_%s(o, (t.utf8, t.bytes));" % snake(root))
        o.append("        let rc = ak_encode_%s(o as *const _ as *const c_void, ctx, &vt, &fix);" % root)
        o.append("        if rc < 0 { Err(rc as i32) } else { Ok(rc as usize) }")
        o.append("    }")
        o.append("}")
        o.append("")
        o.append("pub unsafe fn encoded<'a>(ctx: *mut ak_enc_ctx) -> &'a [u8] {")
        o.append("    let mut p: *const u8 = ::core::ptr::null();")
        o.append("    let mut n: usize = 0;")
        o.append("    ak_enc_take(ctx, &mut p, &mut n);")
        o.append("    ::core::slice::from_raw_parts(p, n)")
        o.append("}")
        o.append("")

    # ---- decode: fix -> facade, and the vtable
    for name in ir.order:
        m = ir.msg(name)
        bits = presence_bits(m)
        o.append("#[inline(always)]")
        o.append("unsafe fn from_%s(f: &ak_dfix_%s, base: *const u8) -> %s {"
                 % (snake(name), name, name))
        o.append("    %s {" % name)
        for f in m.plain:
            if f.card == "repeated":
                o.append("        %s: Vec::new()," % f.name)
                continue
            if f.kind == "string":
                o.append("        %s: s_of(base, f.%s)," % (f.name, f.name))
            elif f.kind == "bytes":
                o.append("        %s: b_of(base, f.%s)," % (f.name, f.name))
            elif f.kind == "message":
                o.append("        %s: if f.presence & AK_DFIX_%s_PRESENT_%s != 0 {"
                         % (f.name, name.upper(), f.name.upper()))
                o.append("            Some(from_%s(&f.%s, base))" % (snake(f.of), f.name))
                o.append("        } else {")
                o.append("            None")
                o.append("        },")
            elif f.kind == "enum":
                o.append("        %s: %s::from_i32(f.%s)," % (f.name, f.of, f.name))
            elif f.kind == "bool":
                o.append("        %s: f.%s != 0," % (f.name, f.name))
            else:
                o.append("        %s: f.%s," % (f.name, f.name))
        o.append("    }")
        o.append("}")
        o.append("")

    for root in ir.roots:
        m = ir.msg(root)
        reps = [f for f in m.plain if f.card == "repeated" and f.kind == "message"]
        o.append("/// What the host hands the codec as `obj` on decode: the destination, plus the")
        o.append("/// base pointer the spans are offsets into (ABI v1 section 7.4).")
        o.append("pub struct Sink<'a> {")
        o.append("    pub out: &'a mut %s," % root)
        o.append("    pub base: *const u8,")
        o.append("}")
        o.append("")
        o.append("unsafe extern \"C\" fn apply_%s(" % snake(root))
        o.append("    _ctx: *mut ak_dec_ctx,")
        o.append("    obj: *mut c_void,")
        o.append("    fx: *const ak_dfix_%s," % root)
        o.append(") {")
        o.append("    dguard(|| {")
        o.append("        let s = &mut *(obj as *mut Sink);")
        o.append("        let f = &*fx;")
        for f in m.plain:
            if f.card == "repeated":
                continue
            if f.kind == "enum":
                o.append("        s.out.%s = %s::from_i32(f.%s);" % (f.name, f.of, f.name))
            elif f.kind == "bool":
                o.append("        s.out.%s = f.%s != 0;" % (f.name, f.name))
            elif f.kind == "string":
                o.append("        s.out.%s = s_of(s.base, f.%s);" % (f.name, f.name))
            elif f.kind == "bytes":
                o.append("        s.out.%s = b_of(s.base, f.%s);" % (f.name, f.name))
            elif f.kind == "message":
                o.append("        s.out.%s = if f.presence & AK_DFIX_%s_PRESENT_%s != 0 {"
                         % (f.name, root.upper(), f.name.upper()))
                o.append("            Some(from_%s(&f.%s, s.base))" % (snake(f.of), f.name))
                o.append("        } else { None };")
            else:
                o.append("        s.out.%s = f.%s;" % (f.name, f.name))
        o.append("    })")
        o.append("}")
        o.append("")
        for f in reps:
            o.append("unsafe extern \"C\" fn add_%s(" % f.name)
            o.append("    _ctx: *mut ak_dec_ctx,")
            o.append("    obj: *mut c_void,")
            o.append("    elems: *const ak_dfix_%s," % f.of)
            o.append("    n: i32,")
            o.append(") {")
            o.append("    dguard(|| {")
            o.append("        let s = &mut *(obj as *mut Sink);")
            o.append("        // ABI v1 7.4: a batched add may be called more than once per field.")
            o.append("        // Append; never size to the count you were handed.")
            o.append("        s.out.%s.reserve(n as usize);" % f.name)
            o.append("        for i in 0..n as usize {")
            o.append("            s.out.%s.push(from_%s(&*elems.add(i), s.base));" % (f.name, snake(f.of)))
            o.append("        }")
            o.append("    })")
            o.append("}")
            o.append("")
        o.append("pub fn decode_with(ctx: *mut ak_dec_ctx, b: &[u8]) -> Result<%s, i32> {" % root)
        o.append("    let mut out = %s::default();" % root)
        o.append("    let rc = unsafe {")
        o.append("        let mut sink = Sink { out: &mut out, base: b.as_ptr() };")
        o.append("        let vt = ak_dvt_%s {" % root)
        o.append("            apply: Some(apply_%s)," % snake(root))
        for f in reps:
            o.append("            add_%s: Some(add_%s)," % (f.name, f.name))
        o.append("        };")
        o.append("        ak_decode_%s(ctx, &mut sink as *mut _ as *mut c_void, b.as_ptr(), b.len(), &vt)" % root)
        o.append("    };")
        o.append("    if rc < 0 { Err(rc) } else { Ok(out) }")
        o.append("}")
        o.append("")
    return "\n".join(o)
