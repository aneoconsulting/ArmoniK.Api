"""The payload builder, emitted over the facade types.

It mirrors the rules of `ffi/schema/emit/payloads.py` -- which value goes in which field,
which fields the absent-path modes remove, how explicit presence cycles -- and calls the
value rules in `crates/shapes-values`. Generated rather than written so that the arms'
objects and the manifest's bytes cannot drift, and so that arm `prost` (whose builder is
the hand-written one in crates/stage1-validate) and the facade arms construct their values
by two independent routes.
"""
from rustnames import camel, facade_type, oneof_type

HEAD = "// @generated by ffi/poc/rust/gen/generate.py from ffi/schema/shapes.json. Do not edit.\n"

PRE = '''//! Build any payload of shapes.json as facade values.
#![allow(unused_variables, clippy::all)]
use super::types::*;
use shapes_values as v;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mode {
    Full,
    /// P1.3: `absent()` drops every field, so an element is the proto zero throughout.
    AllAbsent,
    /// P2.5: half the map values emptied, the adapter child removed, half the timestamps absent.
    HalfAbsent,
}

/// `explicit_present()`: presence cycles per field, and one element in seven is present
/// AND zero, which a by-value group cannot tell from absent unless it is designed to.
#[inline]
#[allow(dead_code)]
fn explicit_present(tag: i64, idx: i64) -> bool {
    idx % (tag + 1) != 0
}

/// `adapter_state()`: which of the Output facade's three states element `idx` carries.
///
/// The adapter maps ONE facade type onto two wire forms and the map is not injective, so
/// reaching the shape at all requires the payload to carry all three states. Cycled Error,
/// Ok, Invalid so that element 0 is Error, because `half_absent` removes the nested site
/// and P2.5 keeps a written one first.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[allow(dead_code)]
pub enum AdapterState {
    Error,
    Ok,
    Invalid,
}

#[inline]
#[allow(dead_code)]
pub fn adapter_state(idx: i64) -> AdapterState {
    match idx % 3 {
        0 => AdapterState::Error,
        1 => AdapterState::Ok,
        _ => AdapterState::Invalid,
    }
}
'''

VALUE_FN = {"guid": "v::guid", "word": "v::word", "sentence": "v::sentence"}


def _string_expr(f, path_expr, idx="idx"):
    return "%s(&%s, %s)" % (VALUE_FN[f.value_rule], path_expr, idx)


def _scalar_expr(f, path_expr, idx="idx"):
    fn = {"int32": "v::scalar_i32", "int64": "v::scalar_i64",
          "bool": "v::scalar_bool", "double": "v::scalar_f64"}[f.kind]
    return "%s(&%s, %s)" % (fn, path_expr, idx)


def absent_expr(f):
    """`absent()` in emit/payloads.py, as a Rust bool.

    The precedence matters and getting it wrong is how this generator first produced a
    P1.3 that was seven times too large: `all_absent` drops EVERY field, and the
    `half_absent` rules are checked only after that. One helper, applied to every field of
    every kind, rather than a check inside the branches that happened to need it.
    """
    half = []
    if f.adapter_site == "nested":
        half.append("true")
    if f.kind == "message" and f.of == "Timestamp" and f.tag % 2 == 0:
        half.append("true")
    if half:
        return "mode == Mode::AllAbsent || mode == Mode::HalfAbsent"
    return "mode == Mode::AllAbsent"


def zero_expr(f):
    """The proto zero of a field's facade type: what an absent field holds."""
    if f.card == "map":
        return "::std::collections::BTreeMap::new()"
    if f.card in ("repeated", "packed"):
        return "Vec::new()"
    if f.kind == "message" or f.explicit:
        return "None"
    if f.kind == "string":
        return "String::new()"
    if f.kind == "bytes":
        return "Default::default()"
    if f.kind == "enum":
        return "Default::default()"
    return {"int32": "0", "int64": "0", "bool": "false", "double": "0.0"}[f.kind]


def _value(ir, m, f):
    """The field's value when it is NOT absent, as a Rust expression."""
    fp = 'format!("{path}.%s")' % f.name

    if f.card == "map":
        n = f.raw.get("entries", 4)
        return ("{\n"
                "            let kp = format!(\"{path}.%s.key\");\n"
                "            let vp = format!(\"{path}.%s.value\");\n"
                "            let mut m = ::std::collections::BTreeMap::new();\n"
                "            for k in 0..%di64 {\n"
                "                let key = format!(\"k{:02}-{}\", k, v::word(&kp, idx * 31 + k));\n"
                "                let val = if mode == Mode::HalfAbsent && k %% 2 == 0 {\n"
                "                    String::new()\n"
                "                } else {\n"
                "                    v::word(&vp, idx * 31 + k)\n"
                "                };\n"
                "                m.insert(key, val);\n"
                "            }\n"
                "            m\n"
                "        }" % (f.name, f.name, n))

    if f.card == "packed":
        n = f.raw.get("count", 30)
        if f.kind == "enum":
            # `oneof_member`-style cycling by the same rule the singular enums use, so a
            # packed run reaches the large value too.
            table = {"ResultStatus": "RESULT_STATUS", "TaskStatus": "TASK_STATUS"}[f.of]
            return ("(0..%di64).map(|j| %s::from_i32(v::enum_value(&v::%s, idx * 97 + j))).collect()"
                    % (n, f.of, table))
        return "(0..%di64).map(|j| %s).collect()" % (n, _scalar_expr(f, fp, "idx * 97 + j"))

    if f.card == "repeated":
        if f.kind == "string":
            return "(0..repeats).map(|j| %s).collect()" % _string_expr(f, fp, "idx * 211 + j")
        if f.kind == "message":
            return "(0..repeats).map(|j| %s).collect()" % _msg_call(ir, f, fp, idx="j")
        raise NotImplementedError("repeated %s" % f.kind)

    if f.kind == "string":
        if f.explicit:
            return ("explicit_present(%d, idx).then(|| if idx %% 7 == 0 { String::new() } else { %s })"
                    % (f.tag, _string_expr(f, fp)))
        return _string_expr(f, fp)
    if f.kind == "bytes":
        return ("::bytes::Bytes::from(v::bulk(bulk))" if f.value_rule == "bulk"
                else "::bytes::Bytes::from(v::blob(&%s, idx, 16))" % fp)
    if f.kind == "enum":
        table = {"ResultStatus": "RESULT_STATUS", "TaskStatus": "TASK_STATUS"}[f.of]
        return "%s::from_i32(v::enum_value(&v::%s, idx))" % (f.of, table)
    if f.kind == "message":
        e = _msg_call(ir, f, fp)
        return "Some(%s)" % e
    if f.is_scalar_leaf:
        if f.explicit:
            zero = {"int32": "0", "int64": "0", "bool": "false", "double": "0.0"}[f.kind]
            return ("explicit_present(%d, idx).then(|| if idx %% 7 == 0 { %s } else { %s })"
                    % (f.tag, zero, _scalar_expr(f, fp)))
        return _scalar_expr(f, fp)
    raise NotImplementedError(f.kind)


def _field(ir, m, f, o):
    if f.adapter_site == "nested":
        # One facade type, two wire forms. Invalid is no child at all; Ok is success with
        # no error; Error is an error with success left at its zero.
        o.append("        %s: if %s {" % (f.name, absent_expr(f)))
        o.append("            None")
        o.append("        } else {")
        o.append("            match adapter_state(idx) {")
        o.append("                AdapterState::Invalid => None,")
        o.append("                AdapterState::Ok => Some(%s { success: true, error: String::new(), unknown_fields: Vec::new() }),"
                 % f.of)
        o.append("                AdapterState::Error => Some(%s {" % f.of)
        o.append("                    success: false,")
        o.append("                    error: v::sentence(&format!(\"{path}.%s.error\"), idx)," % f.name)
        o.append("                    unknown_fields: Vec::new(),")
        o.append("                }),")
        o.append("            }")
        o.append("        },")
        return
    if f.adapter_site == "plain":
        # The other wire form: a plain string, where Ok and Invalid BOTH flatten to empty.
        o.append("        %s: if %s || adapter_state(idx) != AdapterState::Error {"
                 % (f.name, absent_expr(f)))
        o.append("            String::new()")
        o.append("        } else {")
        o.append("            %s" % _string_expr(f, 'format!("{path}.%s")' % f.name))
        o.append("        },")
        return
    o.append("        %s: if %s { %s } else { %s }," %
             (f.name, absent_expr(f), zero_expr(f), _value(ir, m, f)))


def _msg_call(ir, f, path_expr, idx="idx"):
    if f.of == "Timestamp":
        return "{ let (s, n) = v::timestamp(%s); Timestamp { seconds: s, nanos: n, unknown_fields: Vec::new() } }" % idx
    if f.of == "Duration":
        return "{ let (s, n) = v::duration(%s); Duration { seconds: s, nanos: n, unknown_fields: Vec::new() } }" % idx
    return "build_%s(&%s, %s, mode, repeats, bulk)" % (snake(f.of), path_expr, idx)


def snake(camel):
    out = []
    for i, c in enumerate(camel):
        if c.isupper() and i:
            out.append("_")
        out.append(c.lower())
    return "".join(out)


def _oneof_value(ir, msg, g):
    """`oneof_member()` builds its value at path "<Msg>.<field>", not at the element path."""
    path = '"%s.%s"' % (msg, g.name)
    if g.kind == "string":
        return "v::word(%s, idx)" % path
    if g.kind == "bytes":
        return "::bytes::Bytes::from(v::blob(%s, idx, 16))" % path
    if g.kind == "int64":
        return "v::scalar_i64(%s, idx)" % path
    if g.kind == "int32":
        return "v::scalar_i32(%s, idx)" % path
    if g.kind == "message" and g.of == "Empty":
        return "Empty { unknown_fields: Vec::new() }"
    if g.kind == "message":
        return "{ let (s, n) = v::timestamp(idx); Timestamp { seconds: s, nanos: n, unknown_fields: Vec::new() } }"
    raise NotImplementedError("oneof member %s" % g.kind)


def emit(ir):
    o = [HEAD, PRE]
    for name in ir.order:
        m = ir.msg(name)
        o.append("pub fn build_%s(path: &str, idx: i64, mode: Mode, repeats: i64, bulk: usize) -> %s {"
                 % (snake(name), name))
        o.append("    %s {" % name)
        for f in m.plain:
            _field(ir, m, f, o)
        for oname, members in m.oneofs.items():
            # `oneof_member()` in emit/payloads.py: exactly one member, cycled by element
            # index so that every variant including the payload-free one is reached.
            ty = oneof_type(name, oname)
            o.append("        %s: Some(match idx %% %d {" % (oname, len(members)))
            for i, g in enumerate(members):
                arm = "%d" % i if i < len(members) - 1 else "_"
                o.append("            %s => %s::%s(%s)," % (arm, ty, camel(g.name),
                                                            _oneof_value(ir, name, g)))
            o.append("        }),")
        o.append("        // Decision 11's bag: a built payload has no unknown fields, by\n        //   construction -- it was built from this build's own descriptor.")
        o.append("        unknown_fields: Vec::new(),")
        o.append("    }")
        o.append("}")
        o.append("")
    o.append(emit_payloads(ir))
    return "\n".join(o)


def emit_payloads(ir):
    """One constructor per payload whose root is in this generator's closure.

    Mirrors `build()` in emit/payloads.py: elements first, then the `page` and `total`
    fields, which that function writes unconditionally.
    """
    o = ["", "// ---- payloads ----------------------------------------------------------", ""]
    ids = []
    for pid, spec in ir.payloads.items():
        root = spec["root"]
        if root not in ir.messages:
            continue
        m = ir.msg(root)
        fn = "payload_" + pid.replace(".", "_").lower()
        ids.append((pid, fn, root))
        if spec.get("interleaved"):
            # No canonical writer can produce P7.1: it interleaves two repeated fields on
            # purpose, and every writer here emits a field contiguously. So there is no
            # builder for it, and M7 is validated by DECODE (design/SHAPES.md, P7.1's row).
            o.append("/// %s has no builder: no canonical writer can produce it." % pid)
            o.append("pub const %s_DECODE_ONLY: bool = true;" % fn.upper())
            o.append("")
            ids.pop()
            continue
        o.append("/// %s: %s, %s" % (pid, root, spec.get("mode", "full")))
        o.append("pub fn %s() -> %s {" % (fn, root))
        if "bulk" in spec:
            f = m.plain[0]
            o.append("    %s {" % root)
            o.append("        %s: Some(build_%s(\"%s\", 0, Mode::Full, 3, %d)),"
                     % (f.name, snake(f.of), f.of, spec["bulk"]))
            o.append("        unknown_fields: Vec::new(),")
            o.append("    }")
            o.append("}")
            o.append("")
            continue
        field = next(f for f in m.plain if f.name == spec["field"])
        reps = spec.get("repeats", 3)
        reps = reps if isinstance(reps, list) else [reps]
        mode = {"all_absent": "Mode::AllAbsent", "half_absent": "Mode::HalfAbsent"}.get(
            spec.get("mode"), "Mode::Full")
        o.append("    const REPEATS: [i64; %d] = %s;" % (len(reps), "[" + ", ".join(str(r) for r in reps) + "]"))
        o.append("    %s {" % root)
        o.append("        %s: (0..%di64)" % (field.name, spec["count"]))
        o.append("            .map(|j| build_%s(\"%s\", j, %s, REPEATS[(j as usize) %% REPEATS.len()], 0))"
                 % (snake(field.of), field.of, mode))
        o.append("            .collect(),")
        for f in m.plain:
            if f.name == "page":
                o.append("        page: 1,")
            elif f.name == "total":
                o.append("        total: %d," % spec["count"])
        o.append("        unknown_fields: Vec::new(),")
        o.append("    }")
        o.append("}")
        o.append("")
    o.append("/// Every payload this build covers, by the id design/SHAPES.md uses.")
    o.append("pub const COVERED: [&str; %d] = [%s];" % (len(ids), ", ".join('"%s"' % p for p, _, _ in ids)))
    return "\n".join(o)
